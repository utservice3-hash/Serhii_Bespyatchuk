/**
 * ⚠️ Перевіряється ЗНАЧЕННЯ, а не наявність файлу — і це не дрібниця. Заміряно, що
 * `loadEnv("production", …)` бере змінну і з shell: `VITE_API_URL=… npm run build`
 * працює БЕЗ `.env.production`, і це законний шлях. Вимога «файл мусить існувати»
 * зламала б його на рівному місці.
 *
 * ⚠️ І перевірка лише для `production`: у dev-режимі `.env.production` не читається
 * взагалі (заміряно — там `undefined` навіть коли файл лежить поруч), тож будь-яка
 * перевірка, не привʼязана до режиму, вбила б `npm run dev` усім.
 */
export function requireApiBase(mode: string, env: Record<string, string | undefined>): void {
  if (mode !== "production") return;
  const url = env.VITE_API_URL?.trim();
  if (url) return;
  throw new Error(
    "🔴 ЗБІРКА ЗУПИНЕНА: у продакшн-режимі немає VITE_API_URL.\n" +
    "   Без нього vite запече фолбек `http://localhost:4000/api` з frontend/src/api.ts:\n" +
    "   сторінка намалюється, а кожен запит піде в нікуди. CSS при цьому збігається\n" +
    "   байт-у-байт, тож CSS-guard і buildStale цього НЕ побачать.\n" +
    "   Джерело значення — frontend/.env.production, і його НЕМАЄ В GIT (у git лише\n" +
    "   .env.example). Тобто у свіжому клоні чи на збірковому стенді його треба\n" +
    "   покласти руками або передати змінною: VITE_API_URL=… npm run build",
  );
}
