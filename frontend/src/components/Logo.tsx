/**
 * Фірмовий знак UTS (файли від власника, 05.08.2026).
 *
 * 🔴 ЄДИНЕ МІСЦЕ, ДЕ ЗНАК ЗАДАНО. Якщо в маркетингу знайдеться SVG-оригінал —
 * міняється рівно цей файл (шляхи в `SRC`), і більше ніде. Саме заради цього
 * знак не інлайниться в JS і не розкиданий по компонентах.
 *
 * ВАРІАНТИ (рішення власника):
 *  • `white` — темний сайдбар. Червоний на темному має нижчий контраст і
 *    конкурує з червоним акцентом активного пункту меню: на екрані виходило б
 *    ДВА різні червоні.
 *  • `red` — світлі поверхні (сторінка входу, друк).
 *
 * ⚠️ Розмір задається СТИЛЕМ (height), ширина — `auto`. Атрибутами width/height
 * не масштабуємо: вихідні 445×334, і жорсткий width дав би або мило, або
 * спотворення пропорцій.
 */
const SRC: Record<"white" | "red", string> = {
  white: "/uts-logo-white.png",
  red: "/uts-logo-red.png",
};

export function Logo({ size = 26, variant = "red" }: { size?: number; variant?: "white" | "red" }) {
  return (
    <img
      src={SRC[variant]}
      alt="UTS"
      style={{ height: size, width: "auto", display: "block", flex: "none" }}
    />
  );
}
