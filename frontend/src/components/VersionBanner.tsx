import { useEffect, useState } from "react";
import { fetchClientStale } from "../api";

/**
 * 🖥 МОДАЛЬНЕ ВІКНО «ВИЙШЛА НОВА ВЕРСІЯ». Зʼявляється ТІЛЬКИ тоді, коли ця вкладка
 * справді крутить стару збірку.
 *
 * 📐 Куплено 04.09.2026, ціна — пів дня трьох людей. Кнопку «Подати план»
 * полагодили 02.09 і викотили; о 14:51 користувачка написала «кнопка сіра, ніхто
 * не може» — і була права щодо того, що бачила: її вкладка крутила стару збірку.
 * Симптому не існувало: сайт відкривається, health 200, версія правильна — просто
 * НЕ ТА, що в браузері. Підтверджено власником 05.09: `Cmd+Shift+R` полагодив.
 *
 * 🔴 ЧОМУ МОДАЛКА, А НЕ СМУЖКА (рішення власника 05.09.2026). Перша редакція була
 * банером угорі екрана — його можна не помітити й працювати далі у старій версії,
 * тобто рівно те, від чого ми лікуємось. Вікно на весь екран не помітити не можна.
 * Ціна — воно перекриває роботу, і саме тому «Закрити» є ОБОВʼЯЗКОВОЮ частиною
 * рішення, а не поступкою: людина мусить мати змогу дописати абзац і оновитись сама.
 *
 * 🔴 НЕ ПЕРЕЗАВАНТАЖУЄМО САМІ: у полі може бути недописане обґрунтування плану чи
 * коментар. Автоперезавантаження стерло б роботу — тобто лікувало б наш недогляд
 * її даними. Кнопка є, натискає людина.
 *
 * 🔔 «ОДИН РАЗ» — і це про ВІКНО, не про опитування. Спокуса прочитати «один раз»
 * як «спитати на завантаженні й забути» вбиває фічу цілком: у момент відкриття
 * вкладки збірка СВІЖА, тож єдина перевірка завжди сказала б «усе гаразд». А
 * потрібна вона рівно тому, хто тримає вкладку відкритою ЧЕРЕЗ викат — відповідь
 * мусить прийти ПІЗНІШЕ за завантаження. Тому: показали → опитування спиняється;
 * закрив → не повертається до перезавантаження сторінки.
 */
const POLL_MS = 2 * 60 * 1000;

/**
 * 🧱 ШАР — 4000, і число куплене власною помилкою.
 *
 * 🔴 Перший замір дав «найвищі діалоги 2100», і на ньому стояло Z=2500. Замір був
 * НЕПОВНИЙ: я взяв `zIndex` по всьому фронту, відсортував ЗА ЧАСТОТОЮ і подивився
 * перші десять — а рідкісні значення саме тому й не потрапили у видачу. Це той
 * самий клас, що «порожній результат при просторі, заданому здогадом»: простір
 * обрізали, а висновок зробили про весь.
 *
 * 📐 Повний перелік того, що ВИЩЕ за 2100 (перевірено поіменно):
 *   TasksSection.tsx:727  підкладка картки задачі — 2500  ← рівно стільки ж, скільки було тут
 *   TasksSection.tsx:733  сама панель задачі        — 2600
 *   CommandPalette.tsx:59 палітра команд            — 3000
 *   Dashboard.tsx:849     тости                     — 9999
 *
 * Отже 2500 ховало вікно про версію ПІД карткою задачі. 4000 — вище за все, крім
 * тостів: їх перекривати не треба, вони транзитні й нічого не блокують.
 */
const Z = 4000;

export function VersionBanner() {
  const [stale, setStale] = useState(false);
  const [serverSha, setServerSha] = useState<string | null>(null);
  /**
   * 🔴 ЗАКРИТТЯ ПРИВʼЯЗАНЕ ДО SHA СЕРВЕРА, А НЕ ДО БУЛЕВОГО «closed» — і опитування
   * НЕ ЗУПИНЯЄТЬСЯ після першого «застарів».
   *
   * 📐 АВАРІЯ, ЯКА ЦЕ КУПИЛА (15.09.2026). Було: `if (stale) return;` спиняв
   * опитування назавжди після першого вердикту, а `closed=true` після Escape/✕
   * ніколи не скидалось. Одне рефлекторне закриття — і тиша ДО ПЕРЕЗАВАНТАЖЕННЯ,
   * скільки б викатів не пройшло далі (14.09 їх було шість). Людина працювала на
   * бандлі без «Спільних задач», а плашка мовчала — і всі три ланки (sha бандла,
   * health, сервер) були справні: заміряно поіменно.
   *
   * Тепер: закрив на sha X — на X більше не турбуємо; сервер став Y ≠ X — показуємо
   * знову. Тримає `#414`.
   */
  const [dismissedSha, setDismissedSha] = useState<string | null>(null);
  const open = stale && serverSha != null && dismissedSha !== serverSha;

  useEffect(() => {
    let alive = true;
    const load = async () => {
      const r = await fetchClientStale();
      if (!alive) return;
      if (r.serverSha) setServerSha(r.serverSha);
      // `null` (не знаю) НЕ гасить уже показане вікно: версія від «не знаю» назад
      // не помолодшала. `false` гасить — це відповідь «ти вже на актуальній».
      if (r.stale === true) setStale(true);
      else if (r.stale === false) setStale(false);
    };
    void load();
    const t = setInterval(load, POLL_MS);
    return () => { alive = false; clearInterval(t); };
  }, []);
  const dismiss = () => setDismissedSha(serverSha);

  if (!open) return null;

  /**
   * 🔔 СПОВІЩЕННЯ, А НЕ ВІКНО НА ВЕСЬ ЕКРАН (07.10.2026, Роман: «хочеться його взагалі прибрати, щоб він був як
   * сповіщення», за зразком нової системи сповіщень). Вікно на весь екран (рішення 05.09) перекривало роботу на кожному
   * викаті — а їх буває по 8 на день. Тепер — картка внизу праворуч у стилі решти сповіщень (`app-toast`):
   *  · НЕ ПЕРЕКРИВАЄ роботу (немає підкладки й `aria-modal`), тож і Esc не перехоплюємо — він лишається відкритим діалогам;
   *  · САМА НЕ ЗНИКАЄ (немає таймера) — пропустити її важче, ніж смужку, від якої відмовились 05.09;
   *  · ✕ — мовчить до НАСТУПНОГО викату (`dismissedSha`, `#414`), «Оновити» — перезавантаження.
   * Без `autoFocus` — з тієї самої причини, що й раніше: монтує картку таймер опитування, посеред набору тексту, і
   * фокус на «Оновити» перезавантажив би сторінку наступним пробілом.
   */
  return (
    <div role="status" aria-live="polite" style={{ position: "fixed", right: 16, bottom: 16, zIndex: Z, width: "min(400px, calc(100vw - 32px))" }}>
      <div className="app-toast ev t-info">
        <span className="app-toast-icon" aria-hidden>⟳</span>
        <div className="app-toast-body">
          <span className="app-toast-src">Дашборд</span>
          <b style={{ fontSize: 13.5 }}>Вийшла нова версія</b>
          <span style={{ fontSize: 12.5, opacity: 0.9 }}>Оновіть сторінку, щоб працювати з актуальними цифрами й кнопками. Незбережений текст — спершу збережіть.</span>
        </div>
        <button className="app-toast-act" onClick={() => location.reload()}>
          Оновити
        </button>
        <button className="app-toast-x" onClick={() => dismiss()} title="Закрити до наступної версії" aria-label="Закрити до наступної версії">×</button>
      </div>
    </div>
  );
}
