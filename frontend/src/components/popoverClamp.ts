/** Відступ від краю екрана, щоб поповер не липнув до нього впритул. */
export const POPOVER_EDGE_MARGIN = 8;

export interface PopoverClampInput {
  /** `getBoundingClientRect().left` кнопки-якоря, у координатах вікна. */
  anchorLeft: number;
  /** Ширина поповера в пікселях. */
  popWidth: number;
  /** Ширина вікна (`window.innerWidth`). */
  viewportWidth: number;
  /** Відступ від краю; за замовчуванням `POPOVER_EDGE_MARGIN`. */
  margin?: number;
}

/**
 * Скільки пікселів додати до `left` поповера ВІДНОСНО ЯКОРЯ.
 *
 * `0` — нічого не змінюємо (поповер уміщається, поведінка та сама, що була).
 * Відʼємне — тягнемо ліворуч, бо не влазить праворуч.
 * Додатне — тягнемо праворуч, бо якір сам стоїть за лівим краєм.
 *
 * 🔴 Порядок обмежень має значення: спершу прибираємо правий виліт, ПОТІМ не даємо
 * зайти за лівий край. Зворотний порядок на екрані, вужчому за поповер, притиснув би
 * його до правого краю — тобто сховав би початок вмісту замість кінця.
 */
export function clampPopoverLeft({
  anchorLeft, popWidth, viewportWidth, margin = POPOVER_EDGE_MARGIN,
}: PopoverClampInput): number {
  // Скільки місця бракує праворуч (відʼємне число = виліт).
  const spare = viewportWidth - margin - (anchorLeft + popWidth);
  // Ніколи не зсуваємо ПРАВОРУЧ заради правого краю — лише прибираємо виліт.
  const shift = Math.min(0, spare);
  // Лівий край сильніший: краще показати початок поповера, ніж його середину.
  const minShift = margin - anchorLeft;
  return Math.max(shift, minShift);
}
