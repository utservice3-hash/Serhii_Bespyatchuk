export function FirstTouchRules({ onClose }: { onClose: () => void }) {
  useEffect(() => {
    const k = (e: KeyboardEvent) => { if (e.key === "Escape") onClose(); };
    window.addEventListener("keydown", k);
    return () => window.removeEventListener("keydown", k);
  }, [onClose]);
  const list = (xs: readonly string[]) => <ol style={{ margin: "6px 0 14px", paddingLeft: 20, lineHeight: 1.5 }}>{xs.map((x) => <li key={x} style={{ marginBottom: 6 }}>{x}</li>)}</ol>;
  return (
    <div className="hr-overlay" onClick={onClose}>
      <div className="hr-drawer" role="dialog" aria-label="Правила роботи · Перший дотик" onClick={(e) => e.stopPropagation()}>
        <div style={{ display: "flex", justifyContent: "space-between", alignItems: "center", gap: 8 }}>
          <h2 style={{ margin: 0, fontSize: 17 }}>📘 Правила роботи · Перший дотик</h2>
          <button type="button" className="ftd-pill" onClick={onClose} aria-label="Закрити правила">✕</button>
        </div>
        <h3 style={{ margin: "16px 0 0", fontSize: 14 }}>Для менеджера</h3>
        {list(RULES_MANAGER)}
        <h3 style={{ margin: "4px 0 0", fontSize: 14 }}>Для тімліда</h3>
        {list(RULES_LEAD)}
      </div>
    </div>
  );
}
