export function PlannedTabCard({ tab }: { tab: PlannedTab }) {
  const p = PLANNED[tab];
  const list = (items: string[]) => <ul style={{ margin: "6px 0 0", paddingLeft: 18, lineHeight: 1.55 }}>{items.map((x) => <li key={x}>{x}</li>)}</ul>;
  return (
    <div className="hr-card">
      <div className="hd">
        <div><h3>{p.title}</h3><div className="hr-muted">замість {p.replaces}</div></div>
        <span className="hr-pill wn">ще не зроблено</span>
      </div>
      <div className="hr-sect" style={{ borderTop: 0 }}><h4>Що тут буде</h4>{list(p.will)}</div>
      <div className="hr-sect"><h4>Чому цього ще немає</h4>{list(p.why)}</div>
      <div className="hr-sect"><h4>Що для цього потрібно</h4>{list(p.needs)}</div>
      <div className="hr-sect"><h4>Коли</h4><div>{p.stage} Макет цієї вкладки вже затверджено.</div></div>
    </div>
  );
}

