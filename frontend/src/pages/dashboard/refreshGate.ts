/** Скільки часу дані вважаються достатньо свіжими, щоб не перемальовувати. */
export const RECEIVABLES_MIN_AGE_MS = 5 * 60 * 1000;

export interface BusyState {
  /** Скільки редакторів/поповерів відкрито в секції ЗАРАЗ. */
  openEditors: number;
  /**
   * Тег елемента у фокусі (`document.activeElement`), у нижньому регістрі.
   * `null` — фокуса немає або він поза секцією.
   */
  activeTag: string | null;
}

/**
 * Чи зайнята людина прямо зараз.
 *
 * 🔴 ДВІ ОЗНАКИ, А НЕ ОДНА, І ЖОДНОЇ ДОСИТЬ ОКРЕМО. Відкритий поповер ловить
 * редагування домовленості, ліміту, відповідального; фокус у полі ловить
 * набір коментаря до рахунка, який живе ПРЯМО В РЯДКУ і поповера не відкриває.
 * Лишити тільки перше — і текст у рядку знову зникатиме.
 */
export function isBusy(s: BusyState): boolean {
  if (s.openEditors > 0) return true;
  const t = (s.activeTag ?? "").toLowerCase();
  return t === "input" || t === "textarea" || t === "select";
}

export interface RefreshDecision {
  apply: boolean;
  /** Чому НЕ застосовано — щоб причина була видима, а не вгадувалась. */
  reason: "busy" | "fresh" | null;
}

/**
 * Чи застосовувати свіжі дані.
 *
 * Два рубежі, обидва названі:
 *   ① людина зайнята → НЕ застосовуємо (нічого не рухаємо під руками);
 *   ② дані молодші за `minAgeMs` → НЕ застосовуємо (повернення на вкладку саме
 *      по собі не привід перемальовувати те, що щойно завантажили).
 *
 * 🔴 ДЗЕРКАЛО ОБОВʼЯЗКОВЕ, І ВОНО ТУТ НЕ ФОРМАЛЬНІСТЬ. Одностороння перевірка
 * («не застосовувати, коли зайнято») зеленіє й на екрані, що НЕ ОНОВЛЮЄТЬСЯ
 * ВЗАГАЛІ, — тобто ми полікували б смикання, зламавши свіжість, і не помітили.
 */
export function shouldApplyRefresh(o: {
  busy: boolean;
  ageMs: number;
  minAgeMs?: number;
}): RefreshDecision {
  if (o.busy) return { apply: false, reason: "busy" };
  const min = o.minAgeMs ?? RECEIVABLES_MIN_AGE_MS;
  if (o.ageMs < min) return { apply: false, reason: "fresh" };
  return { apply: true, reason: null };
}

/**
 * Тихий підпис свіжості — ознака оновлення БЕЗ руху таблиці.
 * Рух рядків замість підпису і є те, від чого власник просив позбутись.
 */
export function freshnessLabel(ageMs: number): string {
  if (!Number.isFinite(ageMs) || ageMs < 0) return "оновлено щойно";
  const min = Math.floor(ageMs / 60000);
  if (min < 1) return "оновлено щойно";
  if (min === 1) return "оновлено хвилину тому";
  if (min < 5) return `оновлено ${min} хвилини тому`;
  return `оновлено ${min} хвилин тому`;
}
