/**
 * 🔀 ЗВУЖЕННЯ РЯДКА МЕНЕДЖЕРА ДО ЗРІЗУ — ОДНЕ МІСЦЕ НА ВСІ П'ЯТЬ ЧИСЕЛ.
 *
 * Звужуються РІВНО ті числа, склад яких пояснює розкриття «Створено»: саме
 * `created`, розклад новизни (`new`/`rep`) і ПАРТИЦІЯ джерела (чотири колонки).
 * Решта рядка — гроші, дзвінки, відправлені авто, плани — не залежить від
 * новизни й лишається як є.
 *
 * 🔴 ЧОМУ НЕ В `val` КОЖНОЇ КОЛОНКИ. Там це чотири незалежні місця, і забути одне
 * — питання одного рядка: тоді «зі створених: реклама» показувала б зріз, а
 * «Створено» над нею — усе. Рівно та розбіжність «число проти складу», якої цей
 * перемикач і не має допускати.
 *
 * ⚠️ Повертається НОВИЙ обʼєкт; вхідний не мутується — інакше «усі» після
 * перемикання показувало б залишки звуження, і причину шукали б у бекенді.
 */
export function narrowToSlice<T extends {
  created: number; new: number; rep: number;
  srcAd: number; srcLeadgen: number; srcOther: number; srcNoChannel: number;
  srcByKlass?: Record<"new" | "rep" | "undef", {
    created: number; adCount: number; leadgenCount: number; otherCount: number; noChannelCount: number;
  }>;
}>(m: T, slice: Slice): T {
  if (slice === "all") return m;
  const s = m.srcByKlass?.[slice];
  // Зріз не приїхав (старий бекенд / менеджера немає в розкладі) — НЕ вигадуємо
  // числа: показуємо нулі, а не повний рядок під звуженим підписом.
  const z = { created: 0, adCount: 0, leadgenCount: 0, otherCount: 0, noChannelCount: 0 };
  const v = s ?? z;
  return {
    ...m,
    created: v.created,
    new: slice === "new" ? v.created : 0,
    rep: slice === "rep" ? v.created : 0,
    srcAd: v.adCount, srcLeadgen: v.leadgenCount,
    srcOther: v.otherCount, srcNoChannel: v.noChannelCount,
  };
}
