/**
 * 🧩 ЗЛИТТЯ ФОНОВОГО РЕФЕТЧУ З НЕЗБЕРЕЖЕНИМИ ПРАВКАМИ.
 *
 * 🔴 ПРИВІД — БАГ, ЯКИЙ КОШТУВАВ КОРИСТУВАЧЕВІ ТЕКСТУ. Задачник тримає правки
 * поля в ЛОКАЛЬНОМУ стані (`patchTaskLocal`) і відправляє їх на сервер аж по
 * `onBlur`. Паралельно фоновий поллер щокілька десятків секунд робив
 * `fetchTasks().then(setTasks)` — тобто ЗАМІНЮВАВ увесь масив відповіддю
 * сервера. Усе, що людина набрала й ще не встигла зафіксувати, зникало.
 *
 * ⚠️ І це не «раз на 45 секунд». `usePolling` має джитер ±25% (тобто вікно від
 * ~34 с) І додатково стріляє на КОЖНЕ повернення фокуса вкладки: перемкнувся
 * скопіювати номер рахунку, повернувся — коментаря немає. Довгий коментар у
 * Задачнику (а вони там багаторядкові, «1. …\n2. …») пережити це вікно не мав
 * шансів.
 *
 * 🔴 ДВА СИМПТОМИ, ОДНА ПРИЧИНА — і саме тому це читалось як «не зберігається»:
 *   • поллер спрацював ДО `onBlur` → текст зник, на сервер не пішов ЖОДНОГО разу;
 *   • поллер вистрілив ДО того, як PATCH закомітився, а відповідь прийшла ПІСЛЯ
 *     → значення на екрані відкотилось, хоча в базі воно вже лежало.
 * Перший — втрата даних, другий — брехня екрана. Обидва зникають, щойно рефетч
 * перестає затирати те, чого сервер ще не бачив.
 *
 * ✅ ЩО ПЕРЕВІРЕНО ПЕРЕД ФІКСОМ (щоб не лікувати не те): шар БД і SQL роуту
 * справні — прогін проти ЖИВОЇ бази в транзакції з ROLLBACK записав коментар і
 * прочитав його назад байт-у-байт. У проді 232 задачі мають коментар,
 * доданий ПІСЛЯ створення, тобто `PATCH /tasks/:id` працює. Ламався саме показ.
 */

/** Поля, які людина редагує руками; лише вони й бережуться від затирання. */
export type TaskDirtyFields = Map<number, Set<keyof Task>>;

/**
 * Зливає свіжу відповідь сервера з локальними правками.
 *
 * Правило одне: якщо поле позначене «редагується» — на екрані лишається
 * ЛОКАЛЬНЕ значення, доки сервер не наздожене. Щойно сервер віддав те саме
 * значення (PATCH доїхав), позначка знімається САМА, і задача повертається під
 * звичайне оновлення.
 *
 * 🔴 ЗНІМАЄМО ПОЗНАЧКУ ЗА ЗБІГОМ ЗНАЧЕНЬ, А НЕ ЗА ФАКТОМ ВІДПРАВКИ. Інакше
 * довелось би повідомляти контейнер про кожен успішний `updateTask` із півтора
 * десятка місць секції — і те єдине, яке забули б підключити, знову тихо
 * втрачало б текст. Збіг значень перевіряє РЕЗУЛЬТАТ, а не намір.
 *
 * ⚠️ СВІДОМИЙ НАСЛІДОК: якщо збереження ВПАЛО (403/500), значення лишиться на
 * екрані незбереженим замість зникнути. Це навмисно — мовчки втрачений текст
 * гірший за текст, який видно. Окремо треба показувати саму помилку: зараз
 * `onCommit` — проміс без `catch`, і про невдачу не дізнається ніхто. Це інша
 * ланка й інша задача (див. звіт), тут вона НЕ лікується.
 */
export function mergeTasksPreservingEdits(
  prev: Task[],
  incoming: Task[],
  dirty: TaskDirtyFields
): Task[] {
  if (dirty.size === 0) return incoming;
  const byId = new Map(prev.map((t) => [t.id, t]));

  return incoming.map((srv) => {
    const keys = dirty.get(srv.id);
    if (!keys || keys.size === 0) return srv;
    const local = byId.get(srv.id);
    // Задачі більше немає локально (перший показ) — берегти нічого.
    if (!local) { dirty.delete(srv.id); return srv; }

    const merged = { ...srv };
    for (const k of [...keys]) {
      if (Object.is(local[k], srv[k])) {
        keys.delete(k);              // сервер наздогнав — правка більше не «в польоті»
      } else {
        (merged as Record<string, unknown>)[k as string] = local[k];
      }
    }
    if (keys.size === 0) dirty.delete(srv.id);
    return merged;
  });
}
