/**
 * 🚦 ТРИ ВІДПОВІДІ НА ПРОБУ ДОСТУПУ, А НЕ ДВІ (31.08.2026, рішення власника).
 *
 * `#5.3` питає сервер «чи пустиш цю роль», і донедавна вмів рівно два висновки:
 * пустив (2xx) або відмовив (усе інше). Третього стану — «сервер не відповів по
 * суті» — не існувало, тож 5xx роздавався по цих двох кошиках, і ОБИДВА рази
 * неправильно:
 *
 *   · ДОЗВОЛЕНІЙ ролі 503 читався як «пробита межа доступу» і давав червоне з
 *     текстом «МАЄ доступ → отримав 503». Заміряно на приймання 28.08.2026: гейт
 *     упав саме так, поки прод просто не встигав відповісти;
 *   · 🔴 НЕДОЗВОЛЕНІЙ ролі 503 зараховувався як ЗАКОННА ВІДМОВА — і проба
 *     проходила МОВЧКИ. Це небезпечніша половина: перевірка звітує про успіх,
 *     не перевіривши нічого. Той самий клас, що «успіх за 0 мс» і «порожній
 *     результат = pass»: недобір читається як норма.
 *
 * 🔴 «НЕ ВИМІРЯНО» — ЦЕ ПРОВАЛ, А НЕ ПРОПУСК. Спокуса зробити третій стан тихим
 * велика й хибна: гейт, що мовчить, коли не зміг перевірити, нічим не
 * відрізняється від гейта, якого немає, — але виглядає як робочий.
 *
 * ⚠️ ЦІНА, НАЗВАНА ВГОЛОС: у вікні, коли прод віддає 5xx, `#5.3` тепер червоніє
 * ТАМ, ДЕ РАНІШЕ ЧАСТКОВО ЗЕЛЕНІВ. Це не регрес — це і є предмет правки: зелений
 * прогін, який нічого не зміряв, гірший за червоний, який чесно сказав чому.
 *
 * МЕЖА СВІДОМА: третім станом вважається ЛИШЕ 5xx. Коди 4xx поза 401/403
 * (400, 404) трактуються як і досі — відмовою; звузити «законну відмову» до
 * 401/403 означало б змінити те, що гейт ловить, а це окрема зміна поведінки з
 * власним прийманням, не причіп.
 */

/** Що сервер відповів по суті питання «чи пустиш цю роль». */
export type MatrixAnswer =
  /** Пустив того, кому можна; або відмовив тому, кому не можна. */
  | "ok"
  /** Відмовив тому, КОМУ МОЖНА — межа стоїть занадто вузько. */
  | "wrongly-refused"
  /** Пустив того, КОМУ НЕ МОЖНА — межа пробита. */
  | "wrongly-allowed"
  /** Сервер не відповів по суті (5xx) — про доступ НЕ ДІЗНАЛИСЬ НІЧОГО. */
  | "not-measured";

/**
 * Чиста функція: код відповіді + чи мала роль доступ → висновок.
 *
 * 🔴 Живе окремим модулем, а не в тілі тесту, СВІДОМО: гейт, що порівнює дві
 * копії, написані поруч, доводить рівність двох рядків, а не поведінку продукту.
 * `#5.3` і `#24r`/`#24s` кличуть ОДНУ функцію, тож розійтись їм нема де.
 */
export function classifyMatrixAnswer(status: number, shouldAllow: boolean): MatrixAnswer {
  if (status >= 500) return "not-measured";
  const ok2xx = status >= 200 && status < 300;
  if (shouldAllow) return ok2xx ? "ok" : "wrongly-refused";
  return ok2xx ? "wrongly-allowed" : "ok";
}

/** Чи цей висновок мусить валити прогін. «Не виміряно» — мусить. */
export const isMatrixProblem = (a: MatrixAnswer): boolean => a !== "ok";

/** Текст порушення для звіту — кожен стан називає СЕБЕ, а не сусіда. */
export function matrixProblemText(
  a: MatrixAnswer, role: string, path: string, status: number, note: string,
): string {
  switch (a) {
    case "not-measured":
      return `⚪ НЕ ВИМІРЯНО: ${role} × ${path} → сервер віддав ${status}. `
        + `Про доступ це не каже НІЧОГО — ні «дозволено», ні «заборонено» (${note})`;
    case "wrongly-refused":
      return `${role} МАЄ доступ до ${path} → отримав ${status} (${note})`;
    case "wrongly-allowed":
      return `🔴 ${role} НЕ має доступу до ${path} → сервер віддав ${status} (${note})`;
    case "ok":
      return "";
  }
}
