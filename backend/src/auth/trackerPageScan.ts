/** Що знайшов розбір у джерелі сторінки. */
export interface PageScan {
  /** Скільки разів у файлі будується URL. 0 = розбір зламався або сторінка переписана. */
  urlCount: number;
  /** Скільки з них мають ЗАШИТИЙ loopback-хост і рівно одну підстановку. */
  hardcoded: number;
  /** Ідентифікатор, який підставляють у ціль (`port`). null = підстановки немає. */
  interpolated: string | null;
  /** Ім'я умови, якою закрито перехід (`usable`). null = переходу нічим не закрито. */
  guardName: string | null;
  /** Чи обмежено `interpolated` числом ЗНИЗУ і ЗВЕРХУ в тілі цієї умови. */
  boundedBelow: boolean;
  boundedAbove: boolean;
}

const HARD_URL = /new URL\(`http:\/\/127\.0\.0\.1:\$\{(\w+)\}\/callback`\)/g;

export function scanTrackerPage(src: string): PageScan {
  const urlCount = [...src.matchAll(/new URL\(/g)].length;
  const hard = [...src.matchAll(HARD_URL)];
  const interpolated = hard[0]?.[1] ?? null;

  // Умова, якою закрито ефект: `if (!<імʼя> ...) return;` — саме вона вирішує, чи дійде
  // сторінка до переходу. Шукаємо ЇЇ, а не слово «usable»: імʼя береться з коду.
  const guardName = src.match(/if\s*\(\s*!(\w+)\s*(?:\|\||\))/)?.[1] ?? null;

  // Обидві межі шукаємо в ОГОЛОШЕННІ цієї умови, і саме для того ідентифікатора, який
  // потрапляє в URL. Порівняння з іншою змінною тут нічого не варте.
  let boundedBelow = false, boundedAbove = false;
  if (guardName && interpolated) {
    const decl = src.match(new RegExp(`const\\s+${guardName}\\s*=([^;]*);`))?.[1] ?? "";
    boundedBelow = new RegExp(`${interpolated}\\s*>=?\\s*\\d+`).test(decl);
    boundedAbove = new RegExp(`${interpolated}\\s*<=?\\s*\\d+`).test(decl);
  }
  return { urlCount, hardcoded: hard.length, interpolated, guardName, boundedBelow, boundedAbove };
}

/**
 * Вирок: чим саме сторінка небезпечна. Порожній масив = все гаразд.
 * 🔴 Твердження і текст ідуть з ОДНОГО набору (урок S1 від 31.08.2026).
 */
export function pageFaults(s: PageScan): string[] {
  const out: string[] = [];
  // Порожній скоуп = ПРОВАЛ: без цього «порушень нуль» зійшлось би на нерозібраному файлі.
  if (s.urlCount === 0) return ["🔴 у файлі не знайдено ЖОДНОГО `new URL(` — розбір зламався або сторінку переписано"];
  if (s.hardcoded !== s.urlCount)
    out.push(`🔴 адрес переходу ${s.urlCount}, із зашитим хостом лише ${s.hardcoded} — решта будується з чогось іншого`);
  if (!s.interpolated) out.push("🔴 у ціль переходу нічого не підставляють — шаблон не той, що очікує гейт");
  if (!s.guardName) out.push("🔴 перехід не закритий жодною умовою `if (!…) return`");
  if (s.interpolated && s.guardName && !s.boundedBelow)
    out.push(`🔴 «${s.interpolated}» не обмежений числом ЗНИЗУ — привілейовані порти пройдуть`);
  if (s.interpolated && s.guardName && !s.boundedAbove)
    out.push(`🔴 «${s.interpolated}» не обмежений числом ЗВЕРХУ — значення поза діапазоном порту пройде`);
  return out;
}
