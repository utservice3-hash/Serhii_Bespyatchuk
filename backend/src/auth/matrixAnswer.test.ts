import { test } from "node:test";
import assert from "node:assert/strict";
import { classifyMatrixAnswer, isMatrixProblem, matrixProblemText } from "./matrixAnswer.js";

/**
 * Пара гейтів на класифікатор проб доступу. Вони перевіряють РІЗНІ твердження,
 * і це навмисно — інакше другий був би переказом першого:
 *   #24r — 5xx не є ВІДПОВІДДЮ про доступ (і в обидва боки, і в тексті);
 *   #24s — дзеркало: справжні порушення далі ловляться, тобто фікс не проковтнув
 *          усе в «не виміряно».
 * Без #24s правка «завжди повертати not-measured» зробила б `#5.3` вічно
 * червоним, але БЕЗЗУБИМ — він перестав би відрізняти пробиту межу від таймауту.
 */

test("#24r ТРИ ВІДПОВІДІ, НЕ ДВІ: 5xx не каже про доступ НІЧОГО", () => {
  for (const status of [500, 502, 503, 504]) {
    // 🔴 Обидва боки. Дозволеній ролі 5xx давав фальшиве ЧЕРВОНЕ («МАЄ доступ →
    // отримав 503»); недозволеній — фальшиве ЗЕЛЕНЕ, і саме друга половина
    // небезпечніша: перевірка проходила, не перевіривши нічого.
    for (const shouldAllow of [true, false]) {
      const v = classifyMatrixAnswer(status, shouldAllow);
      assert.equal(v, "not-measured",
        `🔴 ${status} для ${shouldAllow ? "ДОЗВОЛЕНОЇ" : "НЕДОЗВОЛЕНОЇ"} ролі класифіковано як «${v}» — `
        + "сервер, що не відповів по суті, не свідчить ні про дозвіл, ні про заборону");
      assert.equal(isMatrixProblem(v), true,
        `🔴 ${status} не валить прогін — «не виміряно» мовчки зарахувалось як успіх; `
        + "це той самий клас, що «успіх за 0 мс»");
    }
  }
  // 🏷 Стан мусить НАЗИВАТИ СЕБЕ. Підпис «МАЄ доступ → отримав 503» був
  // правдоподібний і неправдивий: він стверджував причину, якої не встановив.
  const txt = matrixProblemText("not-measured", "manager", "/api/settings", 503, "n/a");
  assert.match(txt, /НЕ ВИМІРЯНО/, "🔴 текст не називає стан — читач вирішить, що це порушення доступу");
  assert.doesNotMatch(txt, /МАЄ доступ|НЕ має доступу/,
    "🔴 текст «не виміряно» говорить про доступ — це підпис не до тієї величини");
});

test("#24s ДЗЕРКАЛО: справжні порушення далі ловляться в ОБИДВА боки", () => {
  // Пустив того, кому не можна.
  assert.equal(classifyMatrixAnswer(200, false), "wrongly-allowed",
    "🔴 2xx недозволеній ролі перестав бути порушенням — гейт осліп на пробиту межу");
  // Відмовив тому, кому можна.
  for (const status of [401, 403]) {
    assert.equal(classifyMatrixAnswer(status, true), "wrongly-refused",
      `🔴 ${status} дозволеній ролі перестав бути порушенням`);
  }
  // Законні випадки лишились законними — інакше гейт червонів би завжди.
  assert.equal(classifyMatrixAnswer(200, true), "ok", "🔴 дозволена роль із 2xx оголошена порушенням");
  assert.equal(classifyMatrixAnswer(403, false), "ok", "🔴 законна відмова оголошена порушенням");
  // ⚠️ МЕЖА, ЯКУ ТРИМАЄМО СВІДОМО: 4xx поза 401/403 і далі рахується відмовою.
  // Звузити «законну відмову» до 401/403 — окрема зміна поведінки, не причіп.
  assert.equal(classifyMatrixAnswer(404, false), "ok",
    "🔴 404 недозволеній ролі змінив трактування — це вихід за межі правки");
  assert.equal(isMatrixProblem("ok"), false, "🔴 «ok» валить прогін — гейт червонів би на здоровому проді");
});
