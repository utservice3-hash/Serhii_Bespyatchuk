/**
 * 🔒 ХТО КОГО МОЖЕ ЗЛИВАТИ — чиста функція рішення (рішення власника 04.08.2026).
 *
 * Тімлід дістав право обʼєднувати клієнтів, але ЛИШЕ коли ОБИДВА боки належать
 * його команді. Міжкомандні випадки лишились там, де були — КВП/ОД/адмін.
 *
 * 🔴 ЧОМУ ОКРЕМА ФУНКЦІЯ, А НЕ `if` У РОУТІ. Рішення про доступ треба вміти
 * перевірити БЕЗ мережі й БЕЗ бази — інакше єдиний доказ його правильності живе
 * у прод-прогоні, і саботаж (єдиний спосіб довести, що тест справді ловить) стає
 * неможливим без другого сервера. Тут вона перевіряється в кожному `npm test`.
 *
 * ⚠️ Це рішення, а не перевірка даних: обидві команди мусить порахувати той, хто
 * кличе (по КЛІЄНТУ, а не по угоді), і передати сюди. `null` = команду визначити
 * не вдалося — і це ЗАБОРОНА для тімліда, а не «мабуть, своя»: невідомий бік у
 * реєстрі псевдонімів гірший за відмову, бо злиття доводиться відкочувати руками.
 */
export interface MergePairScope {
  /** Роль має право `merge_clients` (КВП/ОД/адмін) — міжкомандні злиття теж. */
  canAll: boolean;
  /** Команда тімліда; `null`, якщо він не тімлід або команди немає. */
  leadTeamId: number | null;
  /** Команда власника ключа-псевдоніма (`null` — не визначилась). */
  aliasTeamId: number | null;
  /** Команда власника канонічного ключа. */
  canonicalTeamId: number | null;
}

export function mergePairAllowed(s: MergePairScope): boolean {
  if (s.canAll) return true;
  if (s.leadTeamId == null) return false;
  return s.aliasTeamId === s.leadTeamId && s.canonicalTeamId === s.leadTeamId;
}

/** Причина відмови — щоб у відповіді стояло, ЩО саме поза межею, а не голий 403. */
export function mergeDenyReason(s: MergePairScope): string {
  if (s.leadTeamId == null) return "Обʼєднання доступне КВП, Опер. директору та адміну";
  const bad: string[] = [];
  if (s.aliasTeamId !== s.leadTeamId) bad.push("той, кого приєднують");
  if (s.canonicalTeamId !== s.leadTeamId) bad.push("основний");
  return `Поза вашою командою: ${bad.join(" і ")}. Міжкомандне обʼєднання робить КВП або Опер. директор`;
}

