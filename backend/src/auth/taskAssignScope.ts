export interface TaskAssignAuth {
  role: "admin" | "team_lead" | "manager" | "company";
  teamId: number | null;
}

/** Чи може ця роль ставити задачу іншій людині (хоч комусь). */
export function canAssignTaskToOthers(auth: TaskAssignAuth): boolean {
  if (auth.role === "manager") return false;
  // `company` — рівень СЕО/опердира/КВП/фінансиста після scope-compat: вони
  // ставлять задачі й сьогодні (`POST /tasks` пускає всіх, крім менеджера).
  if (auth.role === "team_lead") return auth.teamId != null;
  return true;
}

/**
 * Чи може ця роль ставити задачу ПРО цього клієнта.
 *
 * Тімлід — лише коли клієнт веде хтось із його команди. Без цієї частини
 * «в межах своєї команди» перетворилось би на «будь-який клієнт компанії»,
 * і тімлід ставив би задачі про чужих боржників.
 */
export function canRequestLimitFor(auth: TaskAssignAuth, clientTeamId: number | null): boolean {
  if (!canAssignTaskToOthers(auth)) return false;
  if (auth.role !== "team_lead") return true;
  return clientTeamId != null && clientTeamId === auth.teamId;
}
