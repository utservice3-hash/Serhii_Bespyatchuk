  // 617 з 1330 одним суцільним вікном, чужий викат). Вердикт про ДОСТУП у такому
  // прогоні не має сенсу взагалі, і видавати його — гірше, ніж не видати.
  const BROKEN_OUTAGE_SHARE = 0.05;
  if (broken.length > checked * BROKEN_OUTAGE_SHARE) {
    assert.fail(`🔴 ПРОБА НЕ ЗМОГЛА СУДИТИ: ${broken.length} з ${checked} пар відповіли 5xx `
      + `навіть після ${RETRY_BACKOFF_MS.length} повторів. Це не політика — це сервер, який `
      + "лежав або перезапускався під час обходу (наприклад, чужий викат). Дочекайся тиші й "
      + "повтори; вердикт про доступ у такому прогоні недійсний.");
  }

  assert.deepEqual(broken, [],
    `🔴 РОУТ ВІДПОВІДАЄ 5xx — ПРО ДОСТУП ЦЕ НЕ КАЖЕ НІЧОГО (і саме так 500 у «Регламентах» `
    + "два місяці стояв під зеленим гейтом: стара проба читала будь-що, крім 403, як "
    + `«дозволено»). Стійких після повторів: ${broken.length}\n  ` + broken.join("\n  "));

