/**
 * 🔴 СЛІПА ЗОНА ЦЬОГО ПЕРЕЛІЧУВАЧА — ЧИТАЙ ДО ТОГО, ЯК ПОВІРИТИ ЗЕЛЕНОМУ.
 *
 * Зелене означає **«сиріт немає серед тих, кого я вмію бачити»**, а не «сиріт немає».
 * Розділ живий: пункти зникають, коли їх закривають гейтом, і біля кожного стоїть, чим
 * саме закрито або скільки таких форм у коді сьогодні.
 *
 * ✅ 1. **Роут прямо на `app` в `index.ts`** — ЗАКРИТО 02.09.2026 цим же файлом.
 *    Заміряно до закриття: таких було три, і **всі три сироти** — `GET /api/health`,
 *    `/api/health/alerts`, `/api/health/reconciliation`, тобто гейт був зелений при
 *    трьох живих дірках. Тепер `declaredRoutes()` читає ще й `dist/index.js`.
 * ✅ 2. **Модуль, змонтований в `index.ts`, але не вписаний у `MOUNTS`** — ЗАКРИТО
 *    гейтом `#281` нижче. ⚠️ І не «це не звіряв ніхто»: заміряно, що видалення запису з
 *    `MOUNTS` червонить `#11c` само по собі. Сліпим лишався ІНШИЙ випадок — модуль
 *    змонтовано під префіксом, якого немає у зліпку (перевірено підміною `/api/bank`
 *    на `/api/bank2`: `#11c` і `#280` обидва зелені). Подробиці — біля `#281`.
 * ⏳ 3. **Шлях не рядковим літералом** — змінна, шаблон, масив, регулярка. Такий виклик
 *    у перелік не потрапляє. Але тепер він хоча б РАХУЄТЬСЯ: `appDeclared()` віддає
 *    `nonLiteral`, і `#280` друкує це число у власному вироку. 📐 Сьогодні в `index.ts`
 *    таких **два** — обидва не-API (`["/favicon.svg","/icons.svg"]` і SPA-фолбек
 *    регуляркою), тож поза доменом зліпка за побудовою; у `routes/` — нуль.
 * ⏳ 4. **Вкладений роутер** — `xRouter.use("/sub", subRouter)`. Не видно ні його, ні
 *    шляхів усередині. 📐 Сьогодні всі `*.use(` у `routes/` безшляхові (`requireAuth`).
 * ⏳ 5. **Це ТЕКСТ, а не рантайм.** `routeInventory.ts` у власному доккоментарі
 *    попереджає саме про це: статичний розбір колись показав `kvp-report` відкритим,
 *    хоча там 403.
 *
 * ⚠️ ЧОМУ ТОДІ НЕ `allRoutes()`, яка обходить `router.stack` і бреше менше: вона робить
 * живий `import` модулів роутів, тобто тягне конфіг. 📐 Заміряно 02.09.2026: щоб вона
 * просто ПЕРЕЛІЧИЛА роути, знадобилось **чотири** змінні оточення (`JWT_SECRET`,
 * `DATABASE_URL`, `KOMMO_BASE_URL`, `KOMMO_API_TOKEN`) — тобто гейт на ній скіпався б
 * саме там, де потрібен: у швидкому наборі на кожен деплой. Обмін свідомий: **дешевий і
 * трохи сліпий щодня** замість «чесного, але раз на матричний прогін».
 *
 * 📐 І РОЗМІР СЛІПОТИ ЗАМІРЯНО, А НЕ ПРИПУЩЕНО. Того ж дня я звірив текстовий перелік
 * модулів із рантайм-обходом `allRoutes()` під тими чотирма змінними: **217 проти 217,
 * розбіжність нуль в обидва боки**. Пункти 3-5 порожні ЗА ЗБІГОМ поточного коду, а не
 * за побудовою, і цей замір треба ПОВТОРИТИ, а не успадкувати.
 */
test("#280 кожен оголошений роут має рядок у ACCESS_MATRIX", () => {
  const routes = declaredRoutes();
  // Порожній скоуп = ПРОВАЛ: без цього «нуль непокритих» зійшовся б на порожньому переліку.
  assert.ok(routes.length > 150,
    `🔴 розбір дав ${routes.length} роутів — він зламався, і гейт нічого не перевіряє`);

  // 🔴 ДРУГА ПОЛОВИНА СКОУПУ — index.ts. Її теж треба довести окремо: якщо шлях до
  // dist/index.js зміниться, catch вище проковтне помилку, перелік лишиться >150 за
  // рахунок модулів, і три роути на app тихо випадуть із поля зору знову.
  const app = appDeclared(readIndex());
  assert.ok(app.api.length > 0,
    "🔴 в index.ts не знайдено ЖОДНОГО app.<дієслово>(\"/api…\") — розбір зламався або "
    + "файл не той. Саме ця половина перелічувача колись і була сліпою.");

  const covered = matrixKeys(ACCESS_MATRIX);
  const missing = uncovered(routes, covered);
  // Твердження і текст — з ОДНОГО набору (урок S1 від 31.08.2026).
  assert.deepEqual(missing, [],
    `🔴 роути є, а рядка у зліпку доступу НЕМАЄ: ${missing.join(", ")}.\n`
    + "   Зникнення рядка не ловить ні #17 (він дивиться в ROUTE_BOUNDARY_EXEMPTIONS), ні\n"
    + "   швидкий набір: #11 працює лише в test:matrix. Саме так три роути SSO трекера\n"
    + "   поїхали в прод узагалі без запису у зліпку.\n"
    + `   ⚠️ І пам'ятай про сліпу зону: в index.ts ${app.nonLiteral} виклик(ів) app.<дієслово>(\n`
    + "   перелічувач прочитати НЕ зміг (масив/регулярка/змінна) — вони не в цьому числі.");
});

/**
 * 🗺 #281–#281b — `MOUNTS` Є ДЗЕРКАЛОМ `app.use(...)`, А НЕ ПАРАЛЕЛЬНИМ СПИСКОМ.
 *
 * 🔴 НАВІЩО, І ТУТ ВАЖЛИВО НЕ ПЕРЕБІЛЬШИТИ. `MOUNTS` — ручний реєстр, з якого
 * починають троє: `#17` (межі роутів), `#11c` (формат шляхів) і `#280` вище.
 * Заміряно саботажем 02.09.2026, ДВА РІЗНІ ВИПАДКИ, і вони поводяться по-різному:
 *
 *   • ЗАПИС ПРИБРАЛИ з `MOUNTS`, а модуль монтується → `#11c` ЧЕРВОНІЄ сам, бо в зліпку
 *     лишаються рядки з префіксом, якого він більше не знає. Тобто цей бік прикритий
 *     і без `#281` — так і запишемо, замість зручнішого «не звіряє ніхто».
 *   • МОДУЛЬ ЗМОНТУВАЛИ ПІД ІНШИМ ПРЕФІКСОМ (або додали новий, ще не описаний у зліпку)
 *     → `#11c` ЗЕЛЕНИЙ і `#280` ЗЕЛЕНИЙ. Заміряно: замінив `app.use("/api/bank", …)` на
 *     `"/api/bank2"` — обидва мовчать, бо в зліпку немає рядків із `/api/bank2`, а
 *     `/api/bank` у `MOUNTS` на місці. Модуль живий, роути без меж і без зліпка,
 *     жоден гейт не заперечує. **Ось цю дірку й закриває `#281`.**
 *
 * Зворотний бік — запис у `MOUNTS` про модуль, який більше не монтують: тоді `#280`
 * вимагає рядків зліпка для роутів, яких у застосунку немає, а `#11` іде пробувати
 * неіснуючі URL і читає 404 як «дозволено».
 * 📐 Заміряно перед закриттям: 22 проти 22, дрейфу нуль. Тобто гейт додається НЕ по
 * слідах аварії — саме тому й додається, поки ціна нульова.
 */
test("#281 MOUNTS і app.use в index.ts описують той самий набір модулів", () => {
  const mounted = mountedInIndex(readIndex());
  const known = MOUNTS.map((m) => `${m.mount}|${m.export}`).sort();
  // Обидві сторони мусять бути НЕПОРОЖНІ: інакше «дрейфу нуль» зійшлось би на нулі.
  assert.ok(mounted.length > 0, "🔴 в index.ts не знайдено жодного app.use(\"/api/…\") — розбір зламався");
  assert.ok(known.length > 0, "🔴 MOUNTS порожній — звіряти нема з чим");

  assert.deepEqual(drift(mounted, known), [],
    "🔴 модуль ЗМОНТОВАНО в index.ts, але його немає в MOUNTS. Він невидимий для #17, "
    + "#11c і #280 одночасно — тобто його роути без меж і без зліпка, і всі гейти зелені.");
  assert.deepEqual(drift(known, mounted), [],
    "🔴 у MOUNTS є модуль, якого index.ts НЕ монтує. #280 вимагатиме рядків зліпка для "
    + "роутів, яких у застосунку немає, а #11 піде пробувати неіснуючі URL.");
});

test("#281b 🪞 ДЗЕРКАЛО: предикат дрейфу розрізняє обидва боки, а на цілому мовчить", () => {
  const mounted = mountedInIndex(readIndex());
  const known = MOUNTS.map((m) => `${m.mount}|${m.export}`).sort();

  assert.deepEqual(drift(mounted, known), [], "🔴 на цілому наборі дрейф мусить бути порожній");

  // Забули вписати змонтований модуль → #281 мусить назвати саме його.
  const victim = mounted[0];
  assert.deepEqual(drift(mounted, known.filter((x) => x !== victim)), [victim],
    "🔴 зниклий запис MOUNTS не спіймано — предикат не розрізняє напрям");
  // Лишили в MOUNTS модуль, якого вже не монтують → інший бік мусить назвати його.
  const ghost = "/api/ПРИВИД|ghostRouter";
  assert.deepEqual(drift([...known, ghost], mounted), [ghost],
    "🔴 мертвий запис MOUNTS не спіймано — другий бік предиката сліпий");
});

test("#280b 🪞 ДЗЕРКАЛО: гейт ловить ПІДКИНУТЕ зникнення, а на цілому зліпку мовчить", () => {
  const routes = declaredRoutes();
  const full = matrixKeys(ACCESS_MATRIX);

  // На цілому — порожньо. Інакше гейт червонів би завжди й його почали б гортати очима.
  assert.deepEqual(uncovered(routes, full), [], "🔴 на цілому зліпку гейт мусить мовчати");

  // Приберемо ОДИН реальний рядок — гейт мусить назвати саме його, і лише його.
  const victim = routes[0];
  const holed = new Set(full); holed.delete(victim);
  assert.deepEqual(uncovered(routes, holed), [victim],
    "🔴 підкинуте зникнення не спіймано або спіймано не те — предикат не розрізняє покриття");

  // І навпаки: зайвий рядок у зліпку гейт НЕ вважає порушенням (мертві записи ловить #19h).
  const extra = matrixKeys([...ACCESS_MATRIX, { method: "GET", path: "/api/НЕМАЄ" }]);
  assert.deepEqual(uncovered(routes, extra), [],
    "🔴 зайвий рядок зробив гейт червоним — це не його предмет");
});
