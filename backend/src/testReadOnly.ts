/**
 * 🔒 ПРИМУСОВИЙ READ-ONLY ДЛЯ ТЕСТОВОГО ХАРНЕСУ.
 *
 * Підвантажується через `--import` ПЕРЕД будь-яким тестом (див. package.json) і
 * робить так, що КОЖНЕ з'єднання набору відкривається вже в ролі `test_readonly`.
 * Наслідок: будь-який помилковий запис із тестів — хоч прямим SQL, хоч викликом
 * обробника роуту напряму, хоч через джобу — падає на правах, а не виконується.
 *
 * 🔴 ЧОМУ САМЕ ТАК, А НЕ «БУДЕМО УВАЖНІШЕ». Юніт-тест гейтів обійшов middleware і
 * виконав справжній `DELETE FROM monthly_goals` проти ПРОДА. Не зачепило лише тому,
 * що id не існував. Це третій поспіль випадок, коли рятує випадковість — тож межу
 * переносимо в БД, де вона не залежить від уважності того, хто пише запит.
 *
 * ⚙️ ЧОМУ PGOPTIONS, А НЕ `pool.on("connect") → SET ROLE`. Обробник події `connect`
 * у pg НЕ очікується: `SET ROLE` пішов би в чергу паралельно з першим запитом тесту
 * і міг би програти гонку — тобто запобіжник спрацьовував би ЧЕРЕЗ РАЗ, а виглядав
 * би завжди зеленим. `PGOPTIONS=-c role=…` їде в СТАРТОВОМУ ПАКЕТІ з'єднання: до
 * першого запиту роль уже діє, гонки не існує в принципі.
 *
 * ⚠️ Якщо роль недоступна — процес ПАДАЄ, а не працює далі. «Не зміг обмежити» не
 * може означати «ну тоді поїхали з повними правами»: це рівно той хибно-зелений,
 * від якого ми йдемо. Краще червоний набір, ніж набір із правом на запис.
 *
 * Діє ЛИШЕ в прод-режимі (`TEST_SCOPE=prod`): локально БД може не бути взагалі.
 */
const ROLE = "test_readonly";

/**
 * 🔴 НЕМАЄ DATABASE_URL У ПРОД-РЕЖИМІ = ПАДІННЯ, А НЕ ТИХИЙ ПРОПУСК (02.08.2026).
 *
 * Тут стояло `TEST_SCOPE === "prod" && process.env.DATABASE_URL` — тобто без змінної
 * увесь preload мовчки нічого не робив. Реальний наслідок: приймання після деплою
 * надрукувало «100 тестів, 0 падінь», а насправді **72 тести пропустились**, бо я
 * подав env як `../.env`, тоді як він лежить у `backend/.env`. Вивід був так само
 * зелений, як справжній, і за ним поїхав би висновок «прод перевірено».
 *
 * Це ТРЕТІЙ випадок хибно-зеленого за спринт (перші два: порожній результат = pass,
 * і тест, якого немає у наборі). Форма одна: «нічого не сталось» читається як «усе
 * гаразд». Тому змінна названа ПОІМЕННО в повідомленні — щоб діагноз був у першому
 * рядку, а не після години читання скіпів.
 */
if (process.env.TEST_SCOPE === "prod" && !process.env.DATABASE_URL) {
  console.error("🔴 TEST_SCOPE=prod, але DATABASE_URL порожній. Без нього прод-тести "
    + "ПРОПУСТЯТЬСЯ, а прогін надрукує «0 падінь» — це хибно-зелене приймання, а не успіх.\n"
    + "   Оточення береться з backend/.env (НЕ ../.env). Правильно:\n"
    + "   cd backend && set -a && . ./.env && set +a && API_BASE=… npm run test:prod");
  process.exit(1);
}

if (process.env.TEST_SCOPE === "prod" && process.env.DATABASE_URL) {
  // `options=` всередині DATABASE_URL має пріоритет над PGOPTIONS і мовчки скасував
  // би запобіжник. Це не «малоймовірно» — це саме той тихий обхід, який ми ловимо.
  if (/[?&]options=/.test(process.env.DATABASE_URL)) {
    console.error(`🔴 DATABASE_URL містить власний options= — він перекриє PGOPTIONS і `
      + `набір пішов би в прод із правом на запис. Прибери options= з рядка підключення.`);
    process.exit(1);
  }
  process.env.PGOPTIONS = `-c role=${ROLE}`;

  // САМОПЕРЕВІРКА. Без неї «запобіжник увімкнено» означало б лише «ми виставили
  // змінну оточення» — а це і є та сама віра замість доказу. Top-level await у
  // preload-модулі блокує старт тестів, тож перевірка відбувається ДО першого тесту.
  const { pool } = await import("./db/pool.js");
  try {
    const who = (await pool.query<{ u: string }>("SELECT current_user AS u")).rows[0]?.u;
    if (who !== ROLE) {
      console.error(`🔴 ХАРНЕС НЕ ПІД ${ROLE}, а під «${who}» — зупиняюсь, щоб не отримати `
        + `право на запис у прод. Прогнати npm run migrate (роль + GRANT ... WITH SET TRUE).`);
      process.exit(1);
    }
    console.log(`🔒 харнес під роллю ${ROLE}: запис у БД неможливий`);
  } catch (err) {
    console.error(`🔴 ХАРНЕС НЕ ЗМІГ ПІДКЛЮЧИТИСЬ ПІД ${ROLE} — зупиняюсь, щоб не поїхати `
      + `з повними правами:`, err instanceof Error ? err.message : err);
    process.exit(1);
  }
}
