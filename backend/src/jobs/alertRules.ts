import type { Alert } from "../health/alerts.js";

/** Повтор чинної тривоги — не частіше ніж раз на стільки хвилин. */
export const REPEAT_AFTER_MIN = 360;

/**
 * 🔴 `build:stale` ПОВТОРЮЄТЬСЯ ЧАСТІШЕ — і це не «важливіше», а ІНША ФОРМА
 * інциденту. Вікно між збіркою й рестартом коротке (рестарт прода — зовнішня
 * залежність, чужий час відповіді), тож нагадування раз на 6 год прийшло б уже
 * після того, як усе минуло, — тобто марно. Наполегливість дає інтервал, а не
 * підвищений рівень тривоги.
 */
const REPEAT_OVERRIDE: { match: RegExp; min: number }[] = [
  { match: /^build:stale$/, min: 30 },
];

export function repeatAfterMin(id: string): number {
  return REPEAT_OVERRIDE.find((r) => r.match.test(id))?.min ?? REPEAT_AFTER_MIN;
}

/**
 * 🤫 ТИХА ФОРА ДЛЯ ШУМУ ВИКАТУ (рішення власника 21.08.2026).
 *
 * `build:stale` і `version:mismatch` — це НОРМАЛЬНИЙ проміжний стан кожного викату:
 * між `npm run build` і рестартом прод хвилину-дві крутить старий код при новому
 * `dist`. Заміряно на власному викаті 1592eaf: обидві тривоги прилетіли, обидві
 * були ПРАВДИВІ, і обидві отримали відбій за кілька хвилин — тобто чотири
 * повідомлення за один плановий викат.
 *
 * 🔴 ЧОМУ ЦЕ НЕ ДРІБНИЦЯ. Канал, який передбачувано шумить на кожну планову дію,
 * глушать — і разом із шумом глухнуть справжні тривоги. Це рівно та втрата
 * сигналізації, від якої весь цей код і заводився; спам тут не незручність, а
 * тихий спосіб опинитись без гудка.
 *
 * ⚠️ ФОРА НЕ СКАСОВУЄ ТРИВОГУ, А ВІДКЛАДАЄ ЇЇ. Справжній випадок «зібрав і не
 * перезапустив» тривав 49 хвилин (05.08.2026) — він переживе фору й приїде. Тобто
 * ми не робимо перевірку слабшою, ми прибираємо з неї передбачуваний перехідний
 * стан. Різниця та сама, що «послабити поріг» проти «полагодити вимір».
 *
 * Стосується ЛИШЕ цих двох подій: решта шле з першого ж тіку, як шле зараз.
 */
export const DEPLOY_GRACE_MIN = 10;

/** Чи належить подія до тих, кому дано тиху фору на час викату. */
export function hasDeployGrace(id: string): boolean {
  return id === "build:stale" || id === "version:mismatch";
}

/**
 * Чи треба ПРИДУШИТИ перше повідомлення: подія з форою і молодша за поріг.
 *
 * ⚠️ Вік рахується від `first_seen_at` — моменту, коли поштар УПЕРШЕ побачив умову,
 * а не від `since` перевірки: `since` є не в кожної події, і фора, що залежить від
 * необовʼязкового поля, мовчки не працювала б саме там, де його не заповнили.
 */
export function suppressedByGrace(id: string, ageMin: number): boolean {
  return hasDeployGrace(id) && ageMin < DEPLOY_GRACE_MIN;
}

/**
 * ТОЧКОВІ ПОДІЇ — ті, що НЕ «тривають», а сталися. Для них відбій не шлеться:
 * «✅ несподіваний рестарт відновився» — беззмістовна фраза, а канал, у якому
 * трапляються беззмістовні фрази, читають гірше.
 */
export function isPointEvent(id: string): boolean {
  return id.startsWith("app:restart:");
}

/** Людське «скільки тривало» — без бібліотек і без «0 хв» для миттєвих подій. */
export function humanDuration(ms: number): string {
  const min = Math.max(1, Math.round(ms / 60000));
  if (min < 60) return `${min} хв`;
  const h = Math.floor(min / 60), m = min % 60;
  if (h < 24) return m ? `${h} год ${m} хв` : `${h} год`;
  const d = Math.floor(h / 24);
  return `${d} дн ${h % 24} год`;
}

const ICON = (s: string) => (s === "critical" ? "🔴" : "🟡");

/**
 * Текст тривоги. `action` обовʼязковий і мусить ДОЇХАТИ В ТЕКСТ — тривогу без
 * «що робити» читають один раз, далі ігнорують. Тримає `#112`.
 */
export function formatAlert(a: Alert, repeat: { since: Date; count: number } | null): string {
  const head = repeat
    ? `${ICON(a.severity)} <b>ВСЕ ЩЕ: ${a.title}</b>\nТриває ${humanDuration(Date.now() - repeat.since.getTime())}`
      + ` (нагадування #${repeat.count}).`
    : `${ICON(a.severity)} <b>${a.title}</b>`;
  return `${head}\n${a.detail}\n\n▶️ <b>Що робити:</b> ${a.action}`;
}

export function formatResolved(title: string, since: Date): string {
  return `✅ <b>Відновилось:</b> ${title}\nІнцидент тривав ${humanDuration(Date.now() - since.getTime())}.`;
}

export type BootKind = "first" | "deploy" | "crash" | "deploy-intent";

/** Заявлений намір викату, ЗАБРАНИЙ цим стартом. `null` — забирати не було чого. */
export interface ClaimedIntent {
  /** Стеля часу. Намір без стелі — це прапорець, що застряг (урок «успіх за 0 мс»). */
  expiresAt: Date;
}

/**
 * 🔴 КРАХ І ВИКАТ РОЗРІЗНЯЮТЬСЯ ЗА sha (рішення власника 21.08.2026). Рестарт із
 * НОВИМ sha — плановий викат, який ми щойно зробили самі; кричати про нього
 * означало б слати фальшиву аварію на КОЖЕН деплой, а алерт, що регулярно бреше,
 * вимикають — і разом із ним вимикають справжні.
 *
 * 🔴 НАШ ВЛАСНИЙ МЕТОД ДЕПЛОЮ sha НЕ МІНЯЄ (рішення власника 23.08.2026). Ми
 * збираємо на місці й перезапускаємо процес (`kill -TERM` → респавн конвеєром),
 * тож `prevSha === sha` — і кожен наш викат приходив як «АВАРІЯ». Тому ДРУГИЙ
 * сигнал: заявлений НАМІР (`deploy_intent`), який ставиться ПЕРЕД kill.
 *
 * 🔴 НАМІР ЗАБИРАЄ РІВНО ОДИН СТАРТ — і це не деталь реалізації, а суть рішення.
 * «Вікно, всередині якого мовчимо» мало б дірку: петля рестартів, що почалась у
 * вікні викату, була б невидима — рівно те, що ми щойно пережили (16 рестартів
 * поспіль). Забирає перший старт → другий і далі у тому самому вікні знову
 * `crash`. Тобто лічильник, а не таймер.
 *
 * ⚠️ `now` — параметр, а не `new Date()` усередині: інакше гейт на протермінований
 * намір довелося б писати очікуванням у реальному часі, тобто не писати взагалі.
 */
export function classifyBoot(
  prevSha: string | null | undefined,
  sha: string,
  claimed?: ClaimedIntent | null,
  now: Date = new Date(),
): BootKind {
  if (!prevSha) return "first";
  if (prevSha !== sha) return "deploy";
  if (claimed && claimed.expiresAt.getTime() > now.getTime()) return "deploy-intent";
  return "crash";
}

/** Скільки хвилин вважаємо старт «свіжим» — рівно стільки тривога й видима. */
export const BOOT_FRESH_MIN = 60;

/** Скільки хвилин живе намір викату за замовчуванням. */
export const DEPLOY_INTENT_MIN = 15;

/** Від скількох рестартів у вікні це вже ПЕТЛЯ, а не окремі падіння. */
export const BOOT_LOOP_MIN = 3;

export type BurstKind = "single" | "repeat" | "loop";

export interface RestartBurst {
  count: number;
  spanMin: number;
  kind: BurstKind;
  /** Частота між подіями, разів/год. `null`, коли подія одна — в однієї точки частоти немає. */
  perHour: number | null;
}

/**
 * 🔴 «ВПАЛО РАЗ» І «ПАДАЄ ЩОХВИЛИНИ ВЖЕ 16 ХВИЛИН» — РІЗНІ АВАРІЇ (рішення
 * власника 23.08.2026). Досі банер брав ОСТАННІЙ старт і тільки його, тож петля
 * з 16 рестартів виглядала точно так само, як одиничний рестарт: той самий
 * заголовок, той самий текст. Заміряно на проді 23.08: `app_boot` id 9…24 —
 * 16 стартів за 16 хвилин, рівно раз на хвилину, і жодного слова про це на екрані.
 *
 * ⚠️ `perHour` рахується по ІНТЕРВАЛАХ (`count - 1`), а не по подіях: 16 подій за
 * 16 хв — це 15 проміжків, тобто 56/год, а не 60. Різниця мала, але «частота»,
 * порахована по точках, завищує тим сильніше, чим коротше вікно.
 */
export function summarizeRestarts(count: number, spanMin: number): RestartBurst {
  const kind: BurstKind = count >= BOOT_LOOP_MIN ? "loop" : count === 2 ? "repeat" : "single";
  const perHour = count >= 2 && spanMin > 0 ? Math.round(((count - 1) / spanMin) * 60) : null;
  return { count, spanMin, kind, perHour };
}
