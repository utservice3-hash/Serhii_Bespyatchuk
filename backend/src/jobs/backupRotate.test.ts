import { test } from "node:test";
import assert from "node:assert/strict";
import { plannedDeletions, copyWithRetry, MIN_KEPT_COMPLETE, COPY_ATTEMPTS } from "./backupRotateRule.js";

/**
 * #70 — РОТАЦІЯ НЕ ЗНИЩУЄ ОСТАННІ ПРИДАТНІ КОПІЇ.
 *
 * 🔴 ЩО МАЛО СТАТИСЬ. На 10.08.2026 у каталозі лежало 26 папок бекапу, а
 * `MANIFEST.txt` мали ТРИ: 20.07, 25.07, 29.07 (решта — обірвані або порожні).
 * Ротація, що рахує папки за датою й тримає «14 найновіших», зітерла б саме
 * найстаріші — тобто дві з трьох єдиних придатних копій, лишивши чотирнадцять
 * порожніх. Наявність папки виглядала б як наявність бекапу.
 *
 * 🔒 ПРАВИЛО ВЛАСНИКА: каталог із маніфестом не видаляється, поки не існує
 * щонайменше ДВОХ новіших каталогів із маніфестом. Це підлога, незалежна від
 * `KEEP`: зменшить хтось `KEEP` до 1 — остання копія все одно вціліє.
 *
 * Гейт на фікстурі й на ЧИСТІЙ функції: «прогнати й подивитись, що зникло» —
 * не спосіб перевіряти видалення.
 */

const NOW = Date.parse("2026-08-10T12:00:00Z");
const d = (name: string, complete: boolean) =>
  ({ name, status: (complete ? "complete" : "broken") as "complete" | "partial" | "broken" });
const partial = (name: string) => ({ name, status: "partial" as const });

/**
 * Реальний стан каталогу на момент інциденту: **26 папок**, придатних три.
 *
 * 🔴 РОЗМІР ФІКСТУРИ ТУТ — ЧАСТИНА ПЕРЕВІРКИ, А НЕ ДЕКОРАЦІЯ. Перша редакція мала
 * вісім папок, і саботаж «рахувати ВСІ папки замість придатних» (тобто первинний
 * баг) її НЕ червонив: при восьми каталогах `8 − KEEP(14)` дає нуль, і ротація не
 * видаляла нічого незалежно від помилки. Небезпека виникає лише коли папок БІЛЬШЕ
 * за `KEEP`. Спіймано власним саботажем — рівно те, заради чого саботаж і роблять.
 */
const REAL = [
  // 16.07-19.07, 21.07-24.07, 26.07-28.07, 30.07-09.08 — неповні (обірвані/порожні)
  ...["07-16", "07-17", "07-18", "07-19", "07-21", "07-22", "07-23", "07-24",
      "07-26", "07-27", "07-28", "07-30", "07-31", "08-01", "08-02", "08-03",
      "08-04", "08-05", "08-06", "08-07", "08-08", "08-09", "08-10"]
    .map((s) => d(`uts_2026-${s}_00-00-00`, false)),
  d("uts_2026-07-20_00-00-00", true),  // ← придатна
  d("uts_2026-07-25_00-00-00", true),  // ← придатна
  d("uts_2026-07-29_00-00-00", true),  // ← придатна
];

test("#70 РОТАЦІЯ НЕ ЧІПАЄ ОСТАННІ ПРИДАТНІ КОПІЇ", () => {
  const del = plannedDeletions(REAL, NOW);
  assert.ok(del.length > 0,
    "🔴 ротація не видалила нічого — фікстура містить старі неповні папки, тож "
    + "порожній план це ПРОВАЛ, а не «нічого не треба»");
  for (const name of ["uts_2026-07-20_00-00-00", "uts_2026-07-25_00-00-00", "uts_2026-07-29_00-00-00"])
    assert.ok(!del.includes(name),
      `🔴 ротація зносить ПРИДАТНУ копію ${name} — саме так ми лишились би без жодної`);
  // Старі неповні прибираються — інакше каталог росте без меж.
  assert.ok(del.includes("uts_2026-07-16_00-00-00"),
    "🔴 стара НЕПОВНА папка не прибирається — місце тектиме, а користі з неї немає");
  // Свіжі неповні лишаються для розбору.
  assert.ok(!del.includes("uts_2026-08-10_00-00-00"),
    "🔴 сьогоднішню неповну папку знесли — слідів для розбору не лишиться");
  assert.equal(REAL.length, 26, "🔴 фікстура має відтворювати РЕАЛЬНИЙ розмір каталогу (26): при меншому KEEP маскує баг");
});

/**
 * 🔒 ПІДЛОГА СИЛЬНІША ЗА `KEEP`. Це головна перевірка: при `keep = 1` звичайна
 * логіка лишила б ОДНУ копію, а правило вимагає щонайменше двох.
 */
test("#70b ПІДЛОГА ТРИМАЄТЬСЯ НАВІТЬ ПРИ KEEP=1", () => {
  const five = [1, 2, 3, 4, 5].map((i) => d(`uts_2026-08-0${i}_00-00-00`, true));
  const del = plannedDeletions(five, NOW, 1);
  const kept = five.map((x) => x.name).filter((n) => !del.includes(n));
  assert.equal(kept.length, MIN_KEPT_COMPLETE,
    `🔴 при KEEP=1 лишилось ${kept.length} придатних копій замість ${MIN_KEPT_COMPLETE} — підлога не тримає`);
  assert.deepEqual(kept, ["uts_2026-08-04_00-00-00", "uts_2026-08-05_00-00-00"],
    "🔴 лишились не НАЙНОВІШІ копії — ротація видаляє не з того кінця");
});

/**
 * 🪞 ДЗЕРКАЛО. Без нього #70 зеленів би й тоді, якби функція не видаляла НІЧОГО
 * ніколи — тобто якби ротації фактично не було, а каталог ріс без меж (рівно те,
 * з чого почалась ця історія: 26 папок при KEEP=14).
 */
test("#70c ДЗЕРКАЛО: зайві придатні копії ВИДАЛЯЮТЬСЯ", () => {
  const twenty = Array.from({ length: 20 }, (_, i) =>
    d(`uts_2026-07-${String(i + 1).padStart(2, "0")}_00-00-00`, true));
  const del = plannedDeletions(twenty, NOW, 14);
  assert.equal(del.length, 6,
    `🔴 з 20 придатних при KEEP=14 мали піти 6, пішло ${del.length} — ротація не працює`);
  assert.ok(del.includes("uts_2026-07-01_00-00-00") && !del.includes("uts_2026-07-20_00-00-00"),
    "🔴 видаляються не найстаріші — порядок ротації перевернутий");
});

/**
 * 🔴 #70d — ЧАСТКОВА КОПІЯ НЕ ЗАХИЩАЄ І НЕ РАХУЄТЬСЯ (рішення власника 10.08.2026).
 *
 * Раніше «придатна» = «має MANIFEST.txt», тож копія на 72 таблиці важила стільки ж,
 * скільки на 78. Через тиждень ми мали б шість часткових копій, формально придатних,
 * і жодної цілої — та сама пастка «артефакт є, придатність невідома», лише поверхом
 * вище за порожні папки.
 */
test("#70d ЧАСТКОВА КОПІЯ НЕ ЗАМІНЮЄ ЦІЛУ", () => {
  // ⚠️ ДВАДЦЯТЬ часткових, а не шість — і це знову про розмір фікстури. З шістьма
  // саботаж «часткові рахуються цілими» НЕ червонив: 7 каталогів мінус KEEP(14) дає
  // нуль, і ротація нічого не видаляла попри помилку. Той самий механізм маскування
  // вже ловив мене годиною раніше на #70. Записано, щоб не наступити втретє.
  const dirs = [
    d("uts_2026-07-01_00-00-00", true),
    ...Array.from({ length: 20 }, (_, i) => partial(`uts_2026-08-${String(i + 1).padStart(2, "0")}_00-00-00`)),
  ];
  const del = plannedDeletions(dirs, NOW, 14);
  assert.ok(!del.includes("uts_2026-07-01_00-00-00"),
    "🔴 ЄДИНУ цілу копію знесли, бо поруч лежать свіжі часткові — саме цього ми й уникаємо");
  // Дзеркало: часткові НЕ рахуються цілими, тож підлога їх не боронить —
  // старі часткові прибираються за віком, як і обірвані.
  const old = [partial("uts_2026-06-01_00-00-00"), d("uts_2026-08-09_00-00-00", true), d("uts_2026-08-10_00-00-00", true)];
  assert.ok(plannedDeletions(old, NOW, 14).includes("uts_2026-06-01_00-00-00"),
    "🔴 стара ЧАСТКОВА копія не прибирається — каталог наповнюватиметься мотлохом");
});

/**
 * #71 — РЕТРАЙ: ТРЕТЯ СПРОБА ЦЕ УСПІХ, А НЕ ПРОВАЛ.
 *
 * 🔴 Заміряно трьома прогонами проти прода: падає 2-6 таблиць із 78, і набори
 * падінь майже не перетинаються (`deal_stage_events` упала двічі, але раз пройшла;
 * `statistics_values` навпаки). Рветься з'єднання до Neon посеред COPY, а не
 * таблиця й не бібліотека — обидві версії `pg-copy-streams` на локальній базі
 * тягнуть 98 МБ за секунду. При частоті ~2/78 три спроби дають цілу копію.
 */
test("#71 РЕТРАЙ: таблиця, що вдалась із третьої спроби, — це УСПІХ", async () => {
  let calls = 0;
  const reconnects: number[] = [];
  const used = await copyWithRetry(
    async () => { calls++; if (calls < 3) throw new Error("Cannot read properties of null (reading 'push')"); },
    async (n) => { reconnects.push(n); },
  );
  assert.equal(used, 3, "🔴 не повернуто номер вдалої спроби — «з третьої» має читатись як успіх");
  assert.equal(calls, 3, `🔴 спроб було ${calls}, а не 3`);
  assert.deepEqual(reconnects, [1, 2],
    "🔴 перепідключення НЕ відбулось між спробами — повтор по отруєному з'єднанню впаде так само");
});

test("#71b РЕТРАЙ НЕ ХОВАЄ СПРАВЖНЮ ПОМИЛКУ", async () => {
  let calls = 0;
  await assert.rejects(
    () => copyWithRetry(async () => { calls++; throw new Error("завжди падає"); }, async () => {}),
    /завжди падає/,
    "🔴 після вичерпання спроб помилка мусить летіти далі, інакше провал стане тихим успіхом");
  assert.equal(calls, COPY_ATTEMPTS, `🔴 зроблено ${calls} спроб замість ${COPY_ATTEMPTS}`);
  // 🪞 Дзеркало: успіх із ПЕРШОЇ спроби не робить зайвих викликів.
  let once = 0;
  assert.equal(await copyWithRetry(async () => { once++; }, async () => {}), 1,
    "🔴 успішна з першого разу таблиця не має вважатись повтореною");
  assert.equal(once, 1, "🔴 зайвий виклик при успіху — ретрай спрацьовує там, де не треба");
});

/**
 * 🔒 #70e — НУЛЬ ЦІЛИХ КОПІЙ → РОТАЦІЯ МОВЧИТЬ.
 *
 * 🔴 РЕАЛЬНИЙ СТАН ПІСЛЯ ВИКАТУ `89f1e65`. Маркер `status:` пише лише новий код,
 * тож усі шість наявних копій стали `partial`, а цілих не лишилось жодної. Підлога
 * `MIN_KEPT_COMPLETE` боронить ЦІЛІ — боронити стало нічого, і найстаріша копія
 * (20.07, двадцять перший день) підпадала під видалення за віком. Нічний прогін
 * зніс би її сам, і ми втратили б єдине, з чого можна відновитись.
 *
 * Правило: не можна викидати останнє, що є, лише тому, що воно неідеальне.
 *
 * ⚠️ ФІКСТУРА РОЗМІРУ РЕАЛЬНОСТІ (26+). Сьогодні маска `KEEP = 14` двічі ховала
 * помилку на дрібних фікстурах: при `N < KEEP` вираз `N − KEEP` дає нуль, і
 * ротація не видаляє нічого НЕЗАЛЕЖНО від того, правильна вона чи зламана.
 */
test("#70e НУЛЬ ЦІЛИХ — НЕ ВИДАЛЯЄМО НІЧОГО", () => {
  // 26 каталогів, ЖОДНОГО complete: 3 старі часткові (липень) + 23 свіжі.
  const dirs = [
    partial("uts_2026-07-20_00-00-00"), partial("uts_2026-07-25_00-00-00"),
    partial("uts_2026-07-29_00-00-00"),
    ...Array.from({ length: 23 }, (_, i) =>
      d(`uts_2026-06-${String(i + 1).padStart(2, "0")}_00-00-00`, false)),
  ];
  assert.equal(dirs.length, 26, "🔴 фікстура має бути розміру реальності — інакше KEEP маскує баг");
  assert.equal(dirs.filter((x) => x.status === "complete").length, 0, "🔴 у фікстурі не має бути цілих копій");
  assert.deepEqual(plannedDeletions(dirs, NOW, 14), [],
    "🔴 при НУЛІ цілих копій ротація видалила щось — так ми лишимось узагалі без нічого");

  // 🪞 ДЗЕРКАЛО: щойно з'явилась бодай одна ціла — ротація знову працює, інакше
  // правило означало б «ніколи нічого не видаляти», і каталог ріс би без меж.
  const withOne = [...dirs, d("uts_2026-08-10_00-00-00", true)];
  assert.ok(plannedDeletions(withOne, NOW, 14).length > 0,
    "🔴 з'явилась ціла копія, а ротація й далі мовчить — старі часткові накопичуватимуться вічно");
});
