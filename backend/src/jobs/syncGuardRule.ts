/** Стеля тривалості проходу. Реальний прохід — 26 с; нічний reconcile — хвилини. */
export const MAX_RUN_MS = 15 * 60_000;

/**
 * `run` — вільно; `skip` — попередній прохід законно працює; `seize` — попередній
 * висить довше за стелю, перехоплюємо. Перехоплення це АВАРІЯ, але дані компанії
 * важливіші за акуратність: одна зависла обіцянка не має зупиняти синк назавжди.
 */
export function guardDecision(
  running: boolean, since: number, now: number, maxMs = MAX_RUN_MS
): "run" | "skip" | "seize" {
  if (!running) return "run";
  return now - since < maxMs ? "skip" : "seize";
}
