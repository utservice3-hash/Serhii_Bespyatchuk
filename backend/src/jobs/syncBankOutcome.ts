export interface SyncBankTally {
  /** Рахунки, що впали на отриманні чи записі виписки (є токен, адаптер відповів помилкою). */
  failed: { label: string; error: string }[];
  /** Рахунки, пропущені свідомо: немає токена в env / не привʼязано рахунок. */
  noToken: string[];
}

export type SyncBankOutcome = { ok: true } | { ok: false; error: string };

export function syncBankOutcome(t: SyncBankTally): SyncBankOutcome {
  if (t.failed.length === 0) return { ok: true };
  const list = t.failed.map((f) => `«${f.label}»: ${f.error}`).join("; ");
  return { ok: false, error: `syncBank: не синкнулись ${t.failed.length} рах. — ${list}` };
}
