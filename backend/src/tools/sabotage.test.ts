import test from "node:test";
import assert from "node:assert/strict";
import { decideSabotage, countHits } from "./sabotage.js";

/**
 * 🧨 #234e–#234f — ОБГОРТКА САБОТАЖУ.
 *
 * 📐 Заміряна частота відмови, а не побоювання: за одну добу ТРИ саботажі в двох
 * чатах не застосувались і дали зелений прогін. Два стани виглядають однаково —
 * «гейт беззубий» і «саботажу не було», — і розрізняє їх лише доказ зміни файла.
 */
test("#234e САБОТАЖ БЕЗ ЗБІГУ — ВІДМОВА, а не тихий зелений прогін", () => {
  const src = "const A = 1;\n";
  const v = decideSabotage(src, "ЦЬОГО РЯДКА НЕМАЄ", "X", 1);
  assert.equal(v.ok, false, "🔴 обгортка дозволила саботаж, який нічого не змінить");
  assert.equal(v.hits, 0);
  assert.match(v.lines.join("\n"), /ЗЕЛЕНЕ/,
    "🔴 не сказано ГОЛОВНОГО: що зелений колір після цього означав би «нічого не ламали»");
  // Кілька збігів — теж відмова: саботаж, що влучає в кілька місць, доводить не те.
  assert.equal(decideSabotage("a\na\n", "a", "b", 1).ok, false, "🔴 два збіги прийнято за один");
  assert.equal(decideSabotage("a\na\n", "a", "b", 2).ok, true, "🔴 свідомий --expect=2 не приймається");
  // find == replace: файл не зміниться, а прогін виглядатиме саботованим.
  assert.equal(decideSabotage("a\n", "a", "a", 1).ok, false, "🔴 порожня заміна прийнята");
});

test("#234f ДЗЕРКАЛО: справжній саботаж ПРОХОДИТЬ, інакше обгортка забороняє все", () => {
  // Без цієї пари #234e зеленів би й на обгортці, яка відмовляє ЗАВЖДИ — і тоді
  // саботажі просто перестали б робитись, а ми читали б це як надійність.
  const src = 'return /\\.neon\\.tech$/i.test(host);\n';
  const v = decideSabotage(src, "neon", "example", 1);
  assert.equal(v.ok, true, "🔴 звичайний саботаж заборонено — інструментом ніхто не користуватиметься");
  assert.match(v.lines.join("\n"), /застосується/);
  // Підрахунок — по ПІДРЯДКУ, без регулярок: саме екранування й ламало заміни.
  assert.equal(countHits("a.b.c", "."), 2, "🔴 крапку прийнято за регулярку — знову екранування");
  assert.equal(countHits("$PATH $PATH", "$PATH"), 2);
  assert.equal(countHits("", "x"), 0);
});
