/**
 * 🛑 #316b/#317/#317b — TTL МІРЯЄ БЕЗДІЯЛЬНІСТЬ, А ДОТИК FAIL-CLOSED.
 *
 * 📐 Рішення власника 02.09.2026, і воно з заміру: прохід `run` триває ~18 хв (з них
 * 16 хв самого прогріву) при TTL 20 хв, тож НОРМАЛЬНЕ коло впритул підходило до
 * порогу — і замок, що активно працював, називався покинутим. Того ж дня в журналі:
 * `take-after-ttl` у чату, який саме працював, і холд 184 хв в іншого.
 */
test("#317 прострочення рахується від ОСТАННЬОГО ДОТИКУ, а не від взяття", () => {
  const now = new Date();
  // Узято 100 хв тому, але дотик хвилину тому — це ЖИВИЙ прохід, не покинутий замок.
  const live = viewLock({ ...claim("Основний", 100), touchedAt: at(1) }, now);
  assert.equal(live.expired, false,
    "🔴 живий прохід визнано простроченим — саме через це замки й перехоплювали посеред роботи");
  assert.equal(live.ageMin >= 100, true, "🔴 вік від взяття загублено — його показують людині");
  assert.equal(live.idleMin <= 2, true, "🔴 бездіяльність порахована не від дотику");

  // Узято щойно, але дотику не було довше за TTL — це покинутий замок.
  const dead = viewLock({ ...claim("Основний", 5), touchedAt: at(TTL_MIN + 5) }, now);
  assert.equal(dead.expired, true,
    "🔴 замок без жодного дотику понад TTL не визнано покинутим — тоді поріг не стереже нічого");

  // 🔴 СТАРА ЗАЯВКА БЕЗ `touchedAt` ПОВОДИТЬСЯ РІВНО ЯК РАНІШЕ — інакше зміна
  // потребувала б міграції файлів на диску, а її немає.
  assert.equal(viewLock(claim("Основний", TTL_MIN + 1), now).expired, true);
  assert.equal(viewLock(claim("Основний", 1), now).expired, false);
});

test("#317b 🪞 ДЗЕРКАЛО: дотик продовжує ЛИШЕ свій замок і не пише в журнал", () => {
  const repo = scratch();
  assert.equal(cli(["--take", "--who=Допоміжний", "--reason=викат"], repo).code, 0);
  const before = readEvents(repo).length;

  // ① Свій — продовжується, і `touchedAt` зʼявляється у claim.
  assert.equal(cli(["--touch", "--who=Допоміжний"], repo).code, 0, "🔴 власний замок не продовжується");
  const c = JSON.parse(readFileSync(claimPath(repo), "utf8")) as Claim;
  assert.ok(c.touchedAt, "🔴 дотик не записав `touchedAt` — TTL і далі рахується від взяття");
  assert.equal(c.who, "Допоміжний", "🔴 дотик переписав тримача");
  assert.equal(c.reason, "викат", "🔴 дотик стер причину — саме її читає той, хто прийде");

  // ② 🔴 FAIL-CLOSED (#316b): чужий замок дотиком НЕ продовжується, і це не мовчазний no-op.
  const alien = cli(["--touch", "--who=Основний"], repo);
  assert.notEqual(alien.code, 0,
    "🔴 чужий дотик прийнято — ланцюг поїхав би далі під ЧУЖИМ замком, і крадіжка лишилась би невидимою");
  assert.match(alien.out.join("\n"), /не твій/i, "🔴 відмова не називає причини");

  // ③ Дотик до ПОРОЖНЬОГО замка — теж відмова: працювати без замка не можна.
  const free = scratch();
  assert.notEqual(cli(["--touch", "--who=Допоміжний"], free).code, 0,
    "🔴 дотик до порожнього замка «успішний» — ланцюг вважав би, що замок у нього");

  // ④ 🔴 ЖУРНАЛ НЕ РОСТЕ ВІД ДОТИКІВ. Він append-only й читається як історія;
  // сотні рядків за коло зробили б його марним саме тоді, коли по ньому відновлюють хід.
  for (let i = 0; i < 5; i++) cli(["--touch", "--who=Допоміжний"], repo);
  assert.equal(readEvents(repo).length, before,
    "🔴 дотик пише подію в журнал — за одне коло він потоне в шумі, і `lossFor` почне брехати");
});

