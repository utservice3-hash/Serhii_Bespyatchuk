export interface Artifact { branchSha: string; prodSha: string; mode: Mode; at: string }

/**
 * 🔴 СВІЖІСТЬ АРТЕФАКТА — ЗА ОБОМА sha, І ЦЕ НЕ ПРИДИРКА. «Той самий sha гілки»
 * недостатньо: перевірка, знята три години тому, могла звіряти базу проти прода,
 * який відтоді зрушив ВІСІМ разів (заміряно 25.08.2026 — саме стільки й було).
 * Записане число старіє разом із тим, що воно описувало.
 */
export function verifyArtifact(
  a: Artifact | null, liveBranchSha: string, liveProdSha: string,
): { ok: true } | { ok: false; reason: string } {
  if (!a) return { ok: false, reason: "артефакта немає — спершу `npm run deploy:check`" };
  if (a.branchSha !== liveBranchSha)
    return { ok: false, reason: `протух БІК ГІЛКИ: перевіряли ${a.branchSha}, зараз ${liveBranchSha} — перевір заново` };
  if (a.prodSha !== liveProdSha)
    return { ok: false, reason: `протух БІК ПРОДА: перевіряли проти ${a.prodSha}, зараз ${liveProdSha} — базу треба звірити заново` };
  return { ok: true };
}

/**
 * 🔴 ОБІРВАНИЙ ПРОГІН МУСИТЬ НАЗВАТИ СТАН ПРОДА СЛОВАМИ.
 *
 * Ручний ритуал має властивість, якої скрипт легко позбувається: людина бачить, де
 * саме зупинилась. Скрипт, що впав на кроці 9 із 15, лишає прод у стані, якого ніхто
 * не назве вголос — а **не сказане вголос читається як благополуччя** (той самий клас,
 * що «успіх за 0 мс» і «папка бекапу є, копії немає»).
 *
 * Стан ВИВОДИТЬСЯ з переліку виконаних кроків, а не вгадується: `copy` вже пройшов —
 * докрут несе новий бандл; `healthVersion` пройшов — сервер уже новий; `pushBranch` ні
 * — гілка ще не знає про те, що крутиться.
 */
export type AbortState = "prod-untouched" | "docroot-ahead" | "server-ahead";

export interface AbortReport { state: AbortState; exitCode: number; lines: string[] }

export function abortState(
  failedStep: string, doneOk: readonly string[],
  ctx: { prodSha: string; targetSha: string; branch: string; intentMinutes?: number },
): AbortReport {
  const did = (id: string) => doneOk.includes(id);
  const intent = did("markDeploy")
    ? [`Намір markDeploy виставлено — спливе через ~${ctx.intentMinutes ?? 15} хв і сам себе скасує.`]
    : [];
  /**
   * 🔒 ЗАМОК ПРИ АВАРІЙНОМУ ВИХОДІ ЛИШАЄТЬСЯ ВЗЯТИМ — НАВМИСНО. Саме недороблений
   * викат і є той стан, заради якого замок існує: наступний мусить упертися, а не
   * зайти в мішаний чекаут. Але мовчазний замок за годину читається як забуте сміття,
   * тому вихід каже про нього ВГОЛОС і дає команду звільнення.
   */
  const lock = did("lockTake") && !did("lockRelease")
    ? ["🔒 ЗАМОК ЧЕКАУТУ ЛИШАЄТЬСЯ ВЗЯТИМ — це не забуте сміття, а сигнал «тут недороблено».",
       "   Звільнити свідомо: npm run lock -- --release --who=<ти> --reason=\"…\""]
    : [];

  if (did("healthVersion")) {
    return { state: "server-ahead", exitCode: 13, lines: [
      `Зупинено на «${failedStep}». СЕРВЕР УЖЕ КРУТИТЬ НОВИЙ КОД (${ctx.targetSha}), докрут теж новий.`,
      `Розходження лише в тому, що ГІЛКА ${ctx.branch} про це не знає — а поки вона відстає,`,
      "«повернути як було» повернуло б НЕ те, що працює.",
      ...intent,
      `Щоб завершити: git push origin HEAD:${ctx.branch} && git fetch origin -q && git rev-list --left-right --count origin/${ctx.branch}...HEAD`,
      "Відкочувати НЕ треба: прод справний, бракує лише запису.",
      ...lock,
    ] };
  }
  if (did("copy")) {
    return { state: "docroot-ahead", exitCode: 12, lines: [
      `Зупинено на «${failedStep}». Прод крутить СТАРИЙ код (${ctx.prodSha}), але докрут уже несе НОВИЙ бандл.`,
      "Сторінка й сервер розійшлись: банер «АВАРІЯ» спрацює, і спрацює ПРАВИЛЬНО.",
      ...intent,
      "Щоб завершити: npm run deploy:run -- --mode=<той самий> (кроки ідемпотентні, пройде з місця обриву).",
      "Щоб відкотити: git merge --ff-only <старий sha> у прод-чекауті, перезібрати фронт і повторити копію з CSS-guard.",
      ...lock,
    ] };
  }
  return { state: "prod-untouched", exitCode: 11, lines: [
    `Зупинено на «${failedStep}». ПРОД НЕ ЗМІНЕНО: ні докрут, ні сервер не чіпали.`,
    ...intent,
    "Нічого відкочувати не треба. Полагодь причину й запусти deploy:run заново.",
    ...lock,
  ] };
}

/**
 * 🧬 ЧИ НЕСЕ ЦЕЙ ВИКАТ МІГРАЦІЮ — ВИВОДИТЬСЯ З ДІФУ, А НЕ З ПРАПОРЦЯ.
 *
 * 🔴 ДЕФЕКТ, ЯКИЙ ЦЕ ЗАМІНЯЄ, І ЧОМУ ВІН БУВ НАЙГІРШИМ ІЗ МОЖЛИВИХ. У першій редакції
 * `hasMigrations` був зашитим літералом `false`, і скрипт НЕ дивився в диф узагалі
 * (нуль згадок). Крок `migrate` не виконався б ніколи — а звіт щоразу друкував би
 * «міграцій у діфі немає», тобто **стверджував факт про диф, якого ніхто не перевіряв**.
 * Речення було бездоганно чесне за формою і порожнє за змістом: механізм звітував про
 * роботу, якої не робив. Це «успіх за 0 мс» у новому корпусі, і воно небезпечніше за
 * падіння, бо написане впевнено й правильними словами.
 *
 * Ціна пропуску записана в `docs/INFRASTRUCTURE.md` §7: новий код звернеться до колонки,
 * якої ще немає, і роут упаде з 500.
 *
 * ⚠️ Тому разом із поверненням обчислення змінено й ТЕКСТ пропуску: він тепер несе
 * ПІДСТАВУ («переглянуто N файлів проти <sha>»), а не голе твердження.
 */
export const MIGRATION_GLOB = /(^|\/)src\/db\/.*\.sql$/;

export function migrationsInDiff(changedFiles: readonly string[]): string[] {
  return changedFiles.filter((f) => MIGRATION_GLOB.test(f.trim()));
}

/**
 * 🛑 `deploy:check` РУЙНІВНИЙ У ПРОД-ЧЕКАУТІ — І ЦЕ ВЖЕ СТАЛОСЬ.
 *
 * Фаза `check` робить `rm -rf dist && npm run build`. Запущена в прод-чекауті, вона
 * перезбирає `dist` ПРОДА з тієї гілки, що там зараз лежить — 26.08.2026 це зробили
 * з чужої незапушеної гілки: прод лишився на старому sha, а на диску опинився бандл
 * ІНШОГО коду. Рестарт підняв би не те, що всі думають.
 *
 * ⚠️ Ознака прод-чекауту — НЕ шлях, а ДОКРУТ: Apache віддає корінь репозиторію, тож
 * там лежать `index.html` і `assets/` поруч із `backend/`. Заміряно 27.08.2026: у
 * докруті обидва є, і **в git не відстежується жоден із них** — отже жоден клон їх
 * не дістане, і ознака не вироджується.
 *
 * 🔴 ДРУГИЙ СИГНАЛ ЗВУЖЕНО З ХОСТА ДО САМОГО ДОКРУТА (27.08.2026), і це виправлення,
 * а не послаблення. Було `/home/evraziat/` — «будь-що на прод-хості». Поки на хості
 * жило ОДНЕ дерево, воно збігалося з істиною; щойно поруч став стенд
 * (`/home/evraziat/fwt`), та сама умова почала блокувати САМЕ ТЕ дерево, заради якого
 * збірку й виносили: `deploy:check` у стенді відмовляв із кодом 3.
 * Тобто гейт спирався на інваріанту «на проді одне дерево», якої більше немає.
 * Тепер порівнюємо з `docRoot` — тим самим значенням, куди ланцюг реально доставляє.
 */
export function isProdCheckout(o: { rootIndexHtml: boolean; rootAssets: boolean; path: string; docRoot: string }): boolean {
  const norm = (p: string) => p.replace(/\/+$/, "");
  // 🔴 Порожній docRoot не сміє означати «збігається з усім»: без цієї умови
  // невиставлена змінна перетворила б гейт на глухий блок для будь-якого шляху.
  const sameTree = norm(o.docRoot) !== "" && norm(o.path) === norm(o.docRoot);
  return (o.rootIndexHtml && o.rootAssets) || sameTree;
}

