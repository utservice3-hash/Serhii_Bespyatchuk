import { test } from "node:test";
import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { clientStale } from "./version.js";

/**
 * #330 — ВКЛАДКА НА СТАРІЙ ЗБІРЦІ МУСИТЬ БУТИ ВИДИМОЮ.
 *
 * 📐 Куплено 04.09.2026. Кнопку «Подати план» полагодили 02.09 і викотили; бандл
 * на проді зібрано 04.09 об 11:47. О 14:51 користувачка написала «кнопка сіра,
 * ніхто не може» — і була права щодо того, що бачила: її вкладка крутила стару
 * збірку. Пів дня трьох людей пішло на пошук бага, якого в коді вже два дні не
 * було. Симптому не існувало: сайт відкривається, health 200, версія правильна —
 * просто НЕ ТА, що в браузері.
 *
 * 🔴 ЧОМУ ГЕЙТ НА ЧИСТІЙ ФУНКЦІЇ, А НЕ НА ЗАПИТІ. Твердження про ПРАВИЛО, а не
 * про мережу: гейт, що ходить по HTTP, червоніє від завантаження Neon і мовчить
 * від дефекту (правило 14). Тут фікстура задає обидва боки межі в одному прогоні
 * і саботується ВХОДОМ.
 *
 * 🪞 Три гейти, а не один, і це не надмірність: у правила ТРИ результати, а
 * фікстура з одного значення не перевіряє властивості (правило 11). #330 — що
 * розбіжність помічається; #330b — що збіг НЕ помічається (без нього плашка,
 * яка висить завжди, була б зеленою); #330c — що невідоме лишається невідомим.
 */

const A = "8c11d08b5d2e87f58b1f17bbb330db6df2d18f06";
const B = "03a3f448fb116849494c5ad12a88f1fa2fc14fbe";

test("#330 РІЗНІ ЗБІРКИ — ВКЛАДКА СТАРА", () => {
  assert.equal(clientStale(A, B), true,
    "🔴 розбіжність збірок не помічена — саме так людина півдня бачить старий "
    + "продукт і повідомляє про баги, яких у коді вже немає");
  // Симетрія: неважливо, хто «старший» — важливо, що це РІЗНИЙ код.
  assert.equal(clientStale(B, A), true, "🔴 порівняння залежить від порядку аргументів");
  // Регістр — не різниця версій. git віддає нижній, але вшити могли й верхній.
  assert.equal(clientStale(A.toUpperCase(), A), false,
    "🔴 та сама sha в іншому регістрі прочиталась як інша збірка — плашка висіла б вічно");
});

test("#330b 🪞 ДЗЕРКАЛО: ОДНАКОВІ ЗБІРКИ — ПЛАШКИ НЕМАЄ", () => {
  assert.equal(clientStale(A, A), false,
    "🔴 збіг збірок помічено як розбіжність. Плашка «оновіть сторінку», що висить "
    + "завжди, гірша за її відсутність: її перестають читати рівно тоді, коли вона права");
  assert.equal(clientStale(B, B), false, "🔴 те саме на другій фікстурі");
});

test("#330c НЕВІДОМЕ ЛИШАЄТЬСЯ НЕВІДОМИМ, А НЕ СТАЄ «ЗБІГАЄТЬСЯ»", () => {
  /**
   * 🔴 Тут ловиться найтихіший спосіб убити фічу: `define` у vite-конфізі загубили,
   * фронт шле порожнечу — і `false` прочитався б як «версія збігається». Плашка
   * померла б назавжди, а гейти #330/#330b лишились би зеленими. Порожній скоуп,
   * виражений через `false`, — та сама діра під іншим числом (правило 7).
   */
  for (const bad of [undefined, null, "", "   ", "unknown", "8c11d08", A + "0", "zz" + A.slice(2)]) {
    assert.equal(clientStale(bad as string | null | undefined, A), null,
      `🔴 «${String(bad)}» прочитано як версію — невідоме мусить лишатись невідомим`);
  }
  // Дзеркало по другому боку: сервер без версії теж «не знаю», а не «збігається».
  assert.equal(clientStale(A, "unknown"), null,
    "🔴 сервер без sha дав визначену відповідь — порівнювати не було з чим");
});

test("#1720 ВКЛАДКА НА ЗБІРЦІ З ДИСКА (новішій за процес) — НЕ СТАРА; стара — і далі стара; без збірки на диску — як було", () => {
  /**
   * 📐 14.10.2026: між «фронт скопійовано» і «процес перезапущено» браузер вантажив новий бандл, а сервер звав себе
   * старою sha — плашка «оновіть» не зникала після «Оновити». Обидва боки межі в одній фікстурі: вкладка на A
   * (збірка на диску) — не стара; вкладка на C (третя, ще старша) — стара; диска не знаємо — правило як до правки.
   */
  const C = "1111111111111111111111111111111111111111";
  assert.equal(clientStale(A, B, A), false, "🔴 вкладка на НОВІЙ збірці з диска отримала «оновіть» — «Оновити» вантажить той самий бандл, петля");
  assert.equal(clientStale(C, B, A), true, "🔴 справді стара вкладка перестала бачити плашку");
  assert.equal(clientStale(B, B, A), false, "🔴 вкладка на збірці процесу стала «старою», бо на диску новіша");
  assert.equal(clientStale(A, B, null), true, "🔴 без відомостей про диск правило змінилось");
  assert.equal(clientStale(A, B, "unknown"), true, "🔴 «unknown» на диску прочитано як збіг");
  // Проводка: /api/health передає збірку з диска в ОБОХ гілках (звичайній і аварійній) — інакше правило мертве.
  const idx = readFileSync(fileURLToPath(new URL("./index.ts", import.meta.url).href.replace("/dist/", "/src/")), "utf8");
  const calls = idx.match(/clientStale\(\s*typeof req\.query\.loaded === "string" \? req\.query\.loaded : null,\s*buildVersion\(\)\.sha,\s*onDiskVersion\(\)\.sha,\s*\)/g) ?? [];
  assert.equal(calls.length, 2, "🔴 /api/health не передає збірку з диска в обох гілках — петля «оновіть» повернеться");
});
