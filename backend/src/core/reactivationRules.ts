/**
 * 🔀 ЧИ НАЛЕЖИТЬ КЛІЄНТ ВКЛАДЦІ «РЕАКТИВАЦІЯ» — чиста функція, ОДНА на екран і гейт.
 *
 * 🔴 ВИКЛЮЧНІСТЬ ВКЛАДОК (рішення власника 27.08.2026). До неї фільтра стану тут не
 * було ВЗАГАЛІ: `clientStates` віддавав усіх кваліфікованих, і 134 клієнти, які
 * замовляють ПРЯМО ЗАРАЗ, висіли в реактивації — 21% її складу. «Вихід» не був
 * зламаний, його не існувало: стан рахувався (`stateOf`), а у видачу не входив.
 *
 * ⚙️ Вихід тепер автоматичний і ТИМ САМИМ виразом: замовив → `daysSince` обнулився →
 * `state = 'active'` → рядок зник. Окремої дії немає й не треба.
 *
 * ⚠️ `qualified` бере `payments` — УСІ оплачені угоди, включно з недатованими
 * (рішення власника: «неоплачена дата не має значення для кваліфікації»). Дати
 * годують лише «коли востаннє». Вирівнювати це вниз, на `paymentsDated`, ЗАБОРОНЕНО:
 * заміряно 27.08.2026 — перевернуло б 10 клієнтів, «Активних» 142 → 136.
 */
/**
 * Хто взагалі належить розділу «Клієнти»: кваліфікований постійний і не телефонний
 * дженерик. Спільний знаменник обох половин екрана — активних і тих, хто не замовляє.
 */
export function inClientsScreen(f: {
  qualified: boolean; phoneKey: boolean; paymentType: string | null;
}): boolean {
  return f.qualified && keepInReactivation(f);
}

/**
 * 🔴 ВКЛАДКА РЕАКТИВАЦІЇ — ЦЕ ЕКРАН КЛІЄНТІВ МІНУС АКТИВНІ, І ЦЕ ВИВОДИТЬСЯ, А НЕ
 * ПОВТОРЮЄТЬСЯ. Дві множини живуть на одному екрані (обʼєднання 05.09.2026), тож
 * умова належності мусить бути ОДНА: інакше «схожі» предикати розійдуться, і
 * клієнт зникне з обох списків або зʼявиться в обох — рівно те, що вже коштувало
 * 134 рядків у двох вкладках водночас (виправлено 27.08.2026).
 */
export function inReactivationTab(f: {
  qualified: boolean; phoneKey: boolean; paymentType: string | null; state: ClientState;
}): boolean {
  return inClientsScreen(f) && f.state !== "active";
}

/**
 * 📵 ТЕЛЕФОННІ ДЖЕНЕРИКИ — геть із реактивації, КРІМ безготівкових
 * (рішення власника 05.08.2026, записане в CLAUDE.md).
 *
 * Клієнт із ключем-телефоном («380685263085») — це переважно разовий фізик, а не
 * клієнт із історією. Але серед них є й реальні фірми з кривим ключем — їх видає
 * форма оплати «Безнал з ПДВ / без ПДВ».
 *
 * 🟢 СТРАХОВКА ЗАМІРЯНА (прод, 05.08.2026): прибирається 294 із 388, лишається 94.
 * Топ-10 прибраних за грошима — усі з ПОРОЖНЬОЮ формою оплати і давністю
 * 1 034-2 246 днів, тобто легасі до появи поля. Цінного не викинули.
 * (Повторний замір 05.08.2026 на списку реактивації: 1 137 → 842, тобто 295.)
 *
 * 🔴 ПЕРЕЇХАЛА СЮДИ 27.08.2026 З `clientSegments`, І ЦЕ НЕ ПОРЯДОК ЗАРАДИ ПОРЯДКУ. Умова потрібна
 * `inReactivationTab`; лишити її в `clientSegments` означало б або тягти сюди `db/pool`
 * (модуль перестав би бути чистим і впав би на імпорті без `DATABASE_URL`), або
 * написати ДРУГУ копію поруч — рівно те, проти чого стоїть увесь цей прохід.
 * `clientSegments` її ре-експортує, тож жоден виклик не змінився.
 */
export function keepInReactivation(f: { phoneKey: boolean; paymentType: string | null }): boolean {
  return !f.phoneKey || (f.paymentType ?? "").toLowerCase().includes("езнал");
}
