/** Пороги — рішення власника 03.08.2026. Тут, бо на них стоїть гейт #23. */
export const SLEEPING_DAYS = 60;
export const LOST_DAYS = 180;

export type ClientState = "active" | "sleeping" | "lost";

/**
 * 🧭 СЕГМЕНТ ЗА ЧАСТОТОЮ ЗАМОВЛЕНЬ (рішення власника 05.08.2026, CLAUDE.md).
 * Рахується з МЕДІАННОГО інтервалу між оплатами по канонічному ключу.
 *
 * 🔴 МІНІМУМ 3 ОПЛАТИ — і це не обережність, а замір. При порозі «2+» медіана
 * рахується по ОДНОМУ інтервалу: дві оплати з різницею 3 дні робили клієнта
 * «ВІП» назавжди. На проді таких 488 із 1 135, і ВІП роздувався з 232 до 393.
 * Тому <3 оплат — це `unknown` («недостатньо історії»), а не вгаданий сегмент.
 */
export type ClientSegment = "vip" | "regular" | "episodic" | "unknown";
export const SEGMENT_MIN_PAYMENTS = 3;
export const VIP_MAX_GAP_DAYS = 10;
export const REGULAR_MAX_GAP_DAYS = 28;

/**
 * 🎯 ХТО ВЗАГАЛІ Є ПОСТІЙНИМ — ДВОШЛЯХОВА КВАЛІФІКАЦІЯ
 * (рішення власника 05.08.2026, записане в CLAUDE.md).
 *
 * · **БЕЗНАЛ:** 2+ оплати в межах 30 днів **АБО** 3+ за всю історію;
 * · **ГОТІВКА:** 3+ оплати в межах 30 днів **АБО** 3+ за історію;
 * · **ЗМІШАНІ форми — за БЕЗНАЛЬНИМ правилом** (м'якшим);
 * · хто не проходить — **РАЗОВИЙ**: ні в плануванні, ні в реактивації.
 *
 * 🔴 ЧОМУ КОД КОРОТШИЙ ЗА ПРАВИЛО — І ЦЕ НЕ СПРОЩЕННЯ. Готівкова гілка «3+ у
 * межах 30 днів» цілком **вкладається** в «3+ за історію»: три оплати всередині
 * 30-денного вікна — це три оплати. Тобто для готівки правило зводиться рівно до
 * `3+ lifetime`, і окремої перевірки вікна воно не потребує. Виписувати її окремо
 * означало б завести мертву гілку, яку ніхто ніколи не зможе довести тестом.
 * Реально розрізняє форми оплати ЛИШЕ випадок «рівно 2 оплати»: безналу вистачає
 * ритму (інтервал ≤30 дн.), готівці — ні.
 *
 * ⛔️ **НЕ «ПОВЕРТАТИ» ГОТІВКОВУ ГІЛКУ ЯК ЗАГУБЛЕНУ** (зафіксовано на вимогу
 * власника 05.08.2026). Вона не загублена — вона доведено надлишкова. Якщо колись
 * здасться, що правило реалізоване не повністю: доказ вкладеності вище, а не
 * недогляд. Додавати `maxInWindow(30) >= 3` можна ЛИШЕ якщо зміниться саме
 * правило (напр. поріг історії стане більшим за 3) — тоді гілка перестане бути
 * надлишковою, і це буде нове рішення власника, а не відновлення старого.
 *
 * 🔴 КВАЛІФІКАЦІЯ ≠ СЕГМЕНТ. Кваліфікація каже «чи він узагалі наш постійний»,
 * сегмент — «з якою частотою він замовляє». Клієнт із 2 оплатами може
 * кваліфікуватись, але сегмент у нього `unknown` («недостатньо історії»), бо
 * медіана по ОДНОМУ інтервалу — це не частота. Тримає гейт #25g.
 */
export const QUALIFY_LIFETIME_MIN = 3;
export const QUALIFY_RHYTHM_DAYS = 30;
export type ClientPayMode = "cash" | "cashless";

/**
 * Форма розрахунку клієнта для КВАЛІФІКАЦІЇ (не для показу).
 * `cash` — лише коли готівка є, а безготівкових оплат немає ЖОДНОЇ: змішані й
 * невідомі йдуть за безнальним правилом, як вирішив власник.
 */
export function payModeOf(hasCash: boolean, hasCashless: boolean): ClientPayMode {
  return hasCash && !hasCashless ? "cash" : "cashless";
}

export function qualifiesAsRepeat(f: {
  payments: number; minGapDays: number | null; payMode: ClientPayMode;
  /**
   * ⭐ РУЧНИЙ ВИНЯТОК КВП («вважати постійним попри правило», рішення власника
   * 05.08.2026). Стоїть ПЕРШИМ і коротким замиканням — це і є сенс винятку:
   * правило без винятків жорсткіше за реальність, і після двошляхової
   * кваліфікації 342 клієнти стали разовими автоматично.
   *
   * 🔴 ЧОМУ ВИНЯТОК ЖИВЕ ТУТ, А НЕ НА ЕКРАНІ. Прапорець `force_regular` існував
   * у БД і впливав ЛИШЕ на легасі-сегментацію старого `/loyalty`; нова
   * кваліфікація його не бачила ВЗАГАЛІ. Тобто вхід у UI без цього рядка дав би
   * рівно «брехливу кнопку», яку ми щойно прибрали: КВП тисне «вважати
   * постійним», а клієнт як був разовим у плануванні й реактивації, так і
   * лишається — 200 у відповідь і нуль змін на екрані.
   */
  forcedRegular?: boolean;
}): boolean {
  if (f.forcedRegular) return true;
  if (f.payments >= QUALIFY_LIFETIME_MIN) return true;
  if (f.payMode === "cash") return false;
  return f.payments >= 2 && f.minGapDays != null && f.minGapDays <= QUALIFY_RHYTHM_DAYS;
}

export function segmentOf(medianGapDays: number | null, payments: number): ClientSegment {
  if (payments < SEGMENT_MIN_PAYMENTS || medianGapDays == null) return "unknown";
  if (medianGapDays <= VIP_MAX_GAP_DAYS) return "vip";
  if (medianGapDays <= REGULAR_MAX_GAP_DAYS) return "regular";
  return "episodic";
}

/**
 * 🔴 ПОРІГ «ПОРА В РЕАКТИВАЦІЮ» ЗАЛЕЖИТЬ ВІД СЕГМЕНТА
 * (рішення власника 05.08.2026, записане в CLAUDE.md).
 * Сенс: ВІП, що замовляв щотижня і мовчить два тижні, — головний кандидат;
 * епізодичного чіпати через два тижні безглуздо, у нього такий ритм.
 *
 * `unknown` іде за епізодичним (60) — свідомий дефолт власника: клієнт без
 * історії не має зависати взагалі без правила, а 60 днів це той поріг, за яким
 * екран жив досі. Робити для нього окремий поріг означало б вигадати четверте
 * правило під сегмент, якого ми навмисне не визначили.
 */
export const SEGMENT_SLEEPING_DAYS: Record<ClientSegment, number> = {
  vip: 14, regular: 30, episodic: 60, unknown: 60,
};

/**
 * 🗄 МЕЖА «АРХІВУ» — втрачені понад рік (рішення власника 05.08.2026 + замір).
 * З 628 втрачених: 180-269 дн. — 142, 270-364 — 102, 365-547 — 100, 548+ — 284.
 * Тобто рік ділить список майже навпіл (244 свіжих / 384 архівних) і відрізає
 * саме той хвіст, де давність рахується роками. Архів не ховає клієнта — він
 * прибирає його з головної сцени, щоб свіжі не тонули.
 */
export const LONG_LAPSED_DAYS = 365;

/**
 * Чиста функція: стан із кількості днів без замовлення.
 * `segment` не обовʼязковий — без нього поводиться як раніше (60/180), тож старі
 * виклики й гейт #23 лишаються чинними без правок.
 */
export function stateOf(daysSinceLastOrder: number, segment?: ClientSegment): ClientState {
  if (daysSinceLastOrder >= LOST_DAYS) return "lost";
  const sleep = segment ? SEGMENT_SLEEPING_DAYS[segment] : SLEEPING_DAYS;
  if (daysSinceLastOrder >= sleep) return "sleeping";
  return "active";
}

/**
 * ЦІННІСТЬ = виручка за життя × свіжість. Свіжість спадає гіперболічно від
 * місяців простою: 12 міс. без замовлення важать удесятеро менше за свіжого.
 *
 * 🔴 Формула НАЗВАНА і живе в ядрі, а не в сортуванні на фронті: інакше два
 * екрани відсортують «за цінністю» по-різному, і жоден не буде неправильним.
 */
export function valueScore(lifetimeRevenue: number, daysSinceLastOrder: number): number {
  const months = Math.max(0, daysSinceLastOrder) / 30;
  return lifetimeRevenue / (1 + months);
}

