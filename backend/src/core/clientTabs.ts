export type TabGroup = "regular" | "yellow" | "react";

/** Скільки днів без замовлення робить активного клієнта «жовтим». */
export const YELLOW_DAYS = 30;

/** Порядок у вкладці «Всі»: постійні → жовті → реактивація. */
export const TAB_GROUP_RANK: Record<TabGroup, number> = { regular: 0, yellow: 1, react: 2 };

/** `inReact` — 3 повні місяці без рахунку (`reactCycleRules.inReact`), рахується на сервері. */
export function clientTabGroup(inReact: boolean, lastOrderDays: number | null): TabGroup {
  if (inReact) return "react";
  if (lastOrderDays != null && lastOrderDays >= YELLOW_DAYS) return "yellow";
  return "regular";
}

/** Вкладка, у якій рядок видно (крім «Всі», де видно всіх). */
export function tabOf(group: TabGroup): "regular" | "react" {
  return group === "react" ? "react" : "regular";
}
