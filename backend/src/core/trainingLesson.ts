/** Умова «рядок — це урок, а не частина». Для SQL із псевдонімом таблиці — `lessonOnly("m")`. */
export const LESSON_ONLY = "lesson_id IS NULL";
export const lessonOnly = (alias: string): string => `${alias}.lesson_id IS NULL`;

export type PartRole = "main" | "attachment";
export const PART_ROLES: readonly PartRole[] = ["main", "attachment"];

/** Урок, до якого належить рядок: сам рядок, якщо він урок, інакше той, на кого він вказує. */
export const lessonOf = (row: { id: number; lessonId: number | null }): number => row.lessonId ?? row.id;
