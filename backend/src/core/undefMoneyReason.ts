/** Названі причини. Список РОСТЕ лише свідомо: нова причина = нове рішення власника. */
export type UndefMoneyReason = "storno-no-key";

export interface UndefMoneyDeal {
  kommoId: number;
  /** Сума, що потрапила в касу періоду (та сама, що в `receivedByMgrKlass`). */
  revenue: number;
  /** Канонічний ключ клієнта; порожній рядок і `null` — те саме «ключа немає». */
  clientKey: string | null;
}

/**
 * `null` = причина НЕВІДОМА, тобто саме той випадок, заради якого будильник існує.
 *
 * 🔴 ОБИДВІ УМОВИ ОБОВʼЯЗКОВІ. Відʼємна сума з ключем — це звичайне сторно, воно
 * має клас і сюди не потрапляє взагалі; додатна сума без ключа — це НЕ сторно, а
 * невідомий вид, і його треба побачити. Послабити до однієї умови означає
 * зробити гейт беззубим: він зеленітиме майже на чому завгодно (`#102c`).
 */
export const explainUndefMoney = (d: UndefMoneyDeal): UndefMoneyReason | null =>
  d.revenue < 0 && (d.clientKey == null || d.clientKey.trim() === "") ? "storno-no-key" : null;

/** Людський підпис причини — для повідомлення гейта й для екрана. */
export const UNDEF_REASON_LABEL: Record<UndefMoneyReason, string> = {
  "storno-no-key": "сторно без ключа клієнта",
};

/**
 * Ті, чию появу ніхто не пояснив. Порожній масив — норма; непорожній — тривога.
 *
 * ⚙️ Дженерик, а не `UndefMoneyDeal[]`: рішення приймається за двома полями, але
 * повідомлення гейта мусить назвати й решту (канал, менеджера), інакше людина
 * дізнається «щось зʼявилось» без жодної зачіпки, де це шукати.
 */
export const unexplainedUndef = <T extends UndefMoneyDeal>(deals: readonly T[]): T[] =>
  deals.filter((d) => explainUndefMoney(d) === null);
