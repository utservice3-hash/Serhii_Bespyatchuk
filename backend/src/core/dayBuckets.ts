/** Київ — і для меж періоду, і для меж доби. Без цього 23:59 31.12 їде в 01.01. */
const KY = "AT TIME ZONE 'Europe/Kyiv'";

/**
 * Порядок НЕ алфавітний і не випадковий: так відра стоять на екрані Звіту, і так
 * само вони мають стояти скрізь, де з'являться. Порядок показу — теж означення.
 */
export const DAY_BUCKETS = ["work", "evening", "weekend", "night"] as const;
export type DayBucket = (typeof DAY_BUCKETS)[number];

/**
 * 🔴 ВИХІДНІ ПЕРЕВІРЯЮТЬСЯ ПЕРШИМИ, І ЦЕ ЗМІСТОВНО, А НЕ ПОРЯДОК РЯДКІВ.
 * Субота об 11:00 — це `weekend`, а не `work`. Переставиш дві перші гілки — і
 * вихідні мовчки розчиняться в робочому часі: число `work` виросте, `weekend`
 * впаде до нуля, а сума лишиться тією самою, тож інваріант Σ нічого не помітить.
 *
 * ⚠️ `company_holidays` тут НЕ враховується — таблиця порожня, календар робочих
 * днів свят не бачить (борг власника №2 у CLAUDE.md). Отже «вихідні» означає
 * РІВНО Сб/Нд, і це має бути написано на екрані виноскою, а не матись на увазі.
 */
export const dayBucketCase = (dow = "dow", hr = "hr"): string =>
  `CASE WHEN ${dow} IN (0,6) THEN 'weekend'`
  + ` WHEN ${hr} >= 9 AND ${hr} < 18 THEN 'work'`
  + ` WHEN ${hr} >= 18 AND ${hr} < 21 THEN 'evening'`
  + ` ELSE 'night' END`;

/**
 * Два доданки `SELECT`, з яких `dayBucketCase` бере `dow`/`hr`. Віддаються разом
 * саме тому, що нарізно їх легко розвести по часових поясах: порахувати день за
 * Києвом, а годину за UTC — і вечір поїде на три години, не зачепивши жодної суми.
 */
export const dayBucketParts = (ts: string): string =>
  `EXTRACT(DOW  FROM (${ts} ${KY})) AS dow, EXTRACT(HOUR FROM (${ts} ${KY})) AS hr`;

/**
 * 🪞 ДЗЕРКАЛО ТОГО САМОГО ПРАВИЛА В JS — для фікстур, які мусять червоніти в будь-який
 * день тижня і без бази. Гейт на живих даних питає «скільки рядків у відрі»; це
 * питання істинне лише тоді, коли в базі щось є, і мовчить у порожньому вікні.
 *
 * ⚠️ Дзеркало живе рівно доти, доки його звіряють із `dayBucketCase`. Саме тому
 * обидва стоять в ОДНОМУ файлі за пʼять рядків один від одного: розійтись вони
 * можуть лише в редакторі, де видно обидва.
 */
export const dayBucketOf = (dow: number, hr: number): DayBucket =>
  dow === 0 || dow === 6 ? "weekend"
    : hr >= 9 && hr < 18 ? "work"
      : hr >= 18 && hr < 21 ? "evening"
        : "night";
