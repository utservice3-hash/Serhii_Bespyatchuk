import { test } from "node:test";
import assert from "node:assert/strict";
import { packRows, PACK_CHILD_SQL, PACK_PARENT_SQL } from "./reactivationPack.js";

/**
 * #335 — ПАЧКА ДАЄ РЯДОК НА КОЖНОГО КЛІЄНТА, І КЛЮЧ У НЬОМУ НЕ ПОРОЖНІЙ.
 *
 * 📐 Куплено заміром 05.09.2026: 37 пачок, 347 елементів усередині, `client_key`
 * заповнений у НУЛЯ. Через це (а) автозакриття «клієнт повернувся» не бачило жодного
 * клієнта в пачці, (б) задачі по клієнту читались двома різними запитами.
 *
 * 🔴 ФІКСТУРА ПО ОБИДВА БОКИ НОРМАЛІЗАЦІЇ (правило 11): один ключ уже чистий, другий —
 * із подвійними пробілами. Якби перевіряли лише чистий, гейт зеленів би й тоді, коли
 * нормалізацію викинули, — а саме на пробілах свого часу розійшлись 16 із 94 елементів.
 */
test("#335 пачка → рядок на клієнта з непорожнім, нормалізованим ключем", () => {
  const { title, children } = packRows("Іваненко", [
    { clientKey: "ТОВ АЛЬФА", clientName: "ТОВ АЛЬФА" },
    { clientKey: "ТОВ   БЕТА  ", clientName: "ТОВ БЕТА", orders: 7 },
  ]);
  assert.equal(children.length, 2, "🔴 клієнтів двоє — рядків має бути двоє");
  assert.ok(children.every((c) => c.clientKey.trim().length > 0),
    "🔴 порожній client_key — це рівно той стан, у якому пачка була невидимою для картки клієнта");
  assert.equal(children[1].clientKey, "ТОВ БЕТА",
    "🔴 ключ не нормалізувався: у базі він розійдеться з ключем із синку, і клієнт не зіставиться");
  assert.match(title, /\(2\)/, "🔴 у заголовку пачки має стояти кількість клієнтів");
});

/**
 * #336 — 🪞 ДЗЕРКАЛО: статус дитини є ПАРАМЕТРОМ запиту.
 *
 * Без цього перенесення старих пачок мусило б підміняти текст запиту рядковою заміною —
 * тобто тримати другу, невидиму редакцію того самого SQL. Гейт стереже саме параметр:
 * поверни в запит літерал `'not_started'` — і перенесення мовчки зітре стан кожного
 * вже опрацьованого клієнта (заміряно: таких 59 із 347).
 */
test("#336 🪞 статус дитини — параметр, а не літерал у тексті запиту", () => {
  assert.match(PACK_CHILD_SQL, /VALUES \(\$1,\$8,/,
    "🔴 статус став літералом — перенесення старих пачок сплощить прогрес у «не почато»");
  assert.doesNotMatch(PACK_CHILD_SQL, /'not_started'/,
    "🔴 у запиті лишився літерал статусу — значить є два джерела правди про стан дитини");
  assert.match(PACK_CHILD_SQL, /client_key/, "🔴 запит дитини без client_key не має сенсу взагалі");
  assert.doesNotMatch(PACK_PARENT_SQL, /client_key/,
    "🔴 у батька client_key стояти не може: у пачці клієнтів багато, і один ключ там збрехав би");
});
