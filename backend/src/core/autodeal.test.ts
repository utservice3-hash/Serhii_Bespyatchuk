import { test } from "node:test";
import assert from "node:assert/strict";
import { notAutodealSql, AUTODEAL_PREFIX } from "./dealFilters.js";

/**
 * #34 — «АВТОСДЕЛКА» НЕ ЗʼЯВЛЯЄТЬСЯ В СПИСКАХ УГОД.
 *
 * 🔴 ЧОМУ ЧИСТИЙ ТЕСТ, А НЕ ПРОТИ БАЗИ. Перевіряти тут треба РІВНО ОДНЕ: що
 * предикат існує в ОДНОМУ місці й ловить ті написання, які реально трапляються.
 * Підняти базу й переконатись, що рядок не повернувся, означало б перевіряти
 * PostgreSQL, а не наше правило. Те, що предикат ДІЙСНО стоїть у запитах, тримає
 * окремий гейт (#34b) — він читає джерела, а не результат.
 *
 * 🟢 Виключення безпечне для грошей ① — доведено заміром на проді 04.08.2026:
 * у Повному циклі 1 019 автосделок, виграна ОДНА за всю історію, за 12 міс — 0.
 */

test("#34 предикат «Автосделка» ловить реальні написання і не чіпає звичайні угоди", () => {
  const sql = notAutodealSql("d");
  assert.ok(sql.includes("NOT ILIKE"),
    "🔴 порівняння чутливе до регістру — «автосделка:» з малої літери пройшла б повз");
  assert.ok(sql.includes(AUTODEAL_PREFIX),
    "🔴 префікс у предикаті не той, що оголошений константою — дві редакції правила");
  assert.ok(sql.includes("COALESCE("),
    "🔴 без COALESCE угода з NULL-назвою дає NULL і випадає з ОБОХ гілок — тиха втрата рядків");
  // Аліас підставляється, а не зашитий: списки використовують різні аліаси.
  assert.ok(notAutodealSql("x").includes("x.name"), "🔴 аліас ігнорується");
});

test("#34b ПРЕДИКАТ СПРАВДІ СТОЇТЬ У СПИСКАХ, а не лише існує", async () => {
  // 🔴 Без цього #34 зеленів би й тоді, якби функцію ніхто не викликав, — тобто
  // рівно в тому стані, який ми виправляємо. Читаємо ДЖЕРЕЛА, а не результат.
  const { readFileSync } = await import("node:fs");
  const path = await import("node:path");
  // 🔴 Читаємо ЗІБРАНИЙ код (`dist/**.js`), а не джерела: саме він їде на прод.
  // Перша версія дивилась у `.ts` поруч із собою — а поруч лежить `dist`, тож
  // тест падав на відсутньому файлі. Помилка корисна: вона ж показала, що
  // перевіряти треба те, що виконується.
  const root = path.join(import.meta.dirname, "..");
  const must: [string, string][] = [
    ["routes/dashboard.js", "картка клієнта (список останніх угод)"],
    ["core/metrics.js", "застряглі угоди"],
  ];
  for (const [file, what] of must) {
    const src = readFileSync(path.join(root, file), "utf8");
    assert.ok(src.includes("notAutodealSql("),
      `🔴 ${what} (${file}) не викликає notAutodealSql — «Автосделка» там і далі видима`);
  }
});
