/**
 * 📞 УСПІШНИЙ ДЗВІНОК — ВИХІДНИЙ, РОЗМОВА ДОВША ЗА 8 СЕКУНД (`billsec > 8`, межа НЕвключна).
 *
 * 30.09.2026: межа — як у фільтрі Ringostat, яким рахує Ярослав («тривалість більше 00:08»).
 * Із включною межею (`>= 8`) Сердюк за вересень мав 1 106 проти 1 102 у Ringostat — рівно 4
 * дзвінки тривалістю 8 с. Від дзвінків залежить зарплата, тож число мусить збігатися з Ringostat.
 *
 * Рішення власника 29.09.2026. До нього стояло 20 с — поріг, підібраний під ручну
 * таблицю лідгенів (серпень: 3 604 проти 3 627). Тепер означення задає власник, а не
 * таблиця, тож із таблицею число свідомо НЕ збігається: серпень ≥8 с = 5 558, +54 %.
 * Тримаємо в одному місці, щоб не розповзлось копіями.
 */
export const LEADGEN_CALL_MIN_SEC = 8;

/**
 * 🎯 ЦІЛІ КОНВЕРСІЙ — бізнес-правило власника, а не число на екрані.
 */
export const LEADGEN_CONVERSION_TARGETS = { oprOfLeads: 40, quotesOfOpr: 50, machinesOfQuotes: 10 } as const;

/** Конверсія у відсотках; `null`, коли знаменник нульовий — «—» на екрані, а не «0 %». */
export function pct(part: number, whole: number): number | null {
  return whole > 0 ? Math.round((part / whole) * 1000) / 10 : null;
}

/**
 * 🧾 ПОКРИТТЯ ПОЛЯ «ЛИДОГЕНЕРАТОР» — ЖИВЕ ЧИСЛО ЗАМІСТЬ ЗАШИТОГО «11 зі 103».
 * Розріз доходу по особах лідгенів у ТЗ «показники, яких не вистачає» (17.09.2026)
 * неможливий, поки поле порожнє: заміряно 17.09 — 36 497 із 38 534 лідоген-угод 2026
 * без особи (95 %). Підпис називає ОБИДВА числа й відсоток; порожній період каже
 * «лідів немає», а не «0 %», щоб порожнеча не читалась як нуль покриття.
 */
export function leadGeneratorFillNote(withPerson: number, total: number): string {
  if (total <= 0) return "поле «Лидогенератор»: лідоген-угод у періоді немає";
  const p = pct(withPerson, total);
  return `поле «Лидогенератор» заповнене в ${withPerson.toLocaleString("uk-UA")} із ${total.toLocaleString("uk-UA")} `
    + `лідоген-угод періоду (${p} %) — розріз доходу по особах зʼявиться, коли поле заповнюватимуть у CRM`;
}
