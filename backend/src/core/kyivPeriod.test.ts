/**
 * 🇺🇦🈳 #237–#237d — ЧАС ПО-КИЇВСЬКИ І ПОРОЖНІЙ ПЕРІОД, НА ШТУЧНИХ ДАНИХ.
 *
 * 🔴 ЧОМУ ФІКСТУРА, А НЕ ЖИВИЙ ПРОД. Обидві властивості треба перевірити САМЕ НА
 * МЕЖІ МІСЯЦЯ і САМЕ НА ПОРОЖНЕЧІ, а живі дані такого стану на замовлення не дають:
 * чекати 30 днів до наступної межі — це не приймання. Тут межа підставляється
 * аргументом, тож обидва стани відтворювані в будь-який день.
 */

test("#237 МЕЖА МІСЯЦЯ: `to` — справжній останній день, а не зашите 31", () => {
  /**
   * 🔴 САМЕ ЦЕ ВБИЛО ПʼЯТЬ ГЕЙТІВ 01.09.2026. Вони будували період як `${ym}-31`;
   * у вересні 30 днів, тож у SQL їхав `2026-09-31` і Postgres відповідав
   * `DateTimeParseError`. Читалось як «щось із даними», а це була арифметика.
   */
  assert.equal(kyivMonthBounds("2026-09-15").to, "2026-09-30", "🔴 вересень отримав 31-й день");
  assert.equal(kyivMonthBounds("2026-02-10").to, "2026-02-28", "🔴 лютий отримав зайві дні");
  assert.equal(kyivMonthBounds("2024-02-10").to, "2024-02-29", "🔴 високосний лютий обрізано");
  assert.equal(kyivMonthBounds("2026-08-31").to, "2026-08-31", "🔴 31-денний місяць укорочено");
  // 🪞 Дзеркало: `from` теж від того самого місяця, інакше «межі» були б із різних.
  assert.deepEqual(kyivMonthBounds("2026-09-15"), { ym: "2026-09", from: "2026-09-01", to: "2026-09-30" });
  assert.equal(monthEndOf("2026-09"), "2026-09-30");
});

test("#237b ВІКНО ЗАВЕДЕННЯ ПЛАНІВ — рівно 2 РОБОЧІ дні, і воно закінчується", () => {
  // Вересень 2026: 1-е — вівторок. Отже 01 і 02 у вікні, 03 уже ні.
  assert.equal(withinPlanGrace("2026-09-01"), true, "🔴 перший день місяця вже поза вікном");
  assert.equal(withinPlanGrace("2026-09-02"), true);
  assert.equal(withinPlanGrace("2026-09-03"), false,
    "🔴 вікно не закінчується — тоді «плани забули завести» ніколи не стане червоним");
  // Вихідні НЕ їдять вікно: серпень 2026 починається в суботу, отже 1-2 не робочі,
  // і два робочі дні це 3-є та 4-е.
  assert.equal(withinPlanGrace("2026-08-04"), true, "🔴 вихідні порахувались як робочі дні");
  assert.equal(withinPlanGrace("2026-08-05"), false);
});

test("#237c ПОРОЖНЬО → ПРИЧИНА З МАРКЕРОМ І ЧИСЛОМ; Є ДАНІ → ГЕЙТ БІЖИТЬ", () => {
  const skip = emptyPeriodSkip("угод у касі", 0, "2026-09");
  assert.ok(skip, "🔴 нуль не дав скіпу — гейт упаде там, де мав промовчати");
  assert.ok(skip!.includes(EMPTY_PERIOD_MARK), "🔴 причина без маркера — вартовий її не зарахує");
  assert.ok(skip!.includes("угод у касі") && skip!.includes("2026-09"),
    "🔴 причина не називає ПРЕДМЕТ і ПЕРІОД — це «немає даних», тобто тихий скіп");
  /**
   * 🪞 ДРУГА СТОРОНА МЕЖІ, і вона головна: скіп, що ковтає справжній дефект, гірший
   * за падіння. Одна одиниця даних — і гейт зобовʼязаний бігти.
   */
  assert.equal(emptyPeriodSkip("угод у касі", 1, "2026-09"), null,
    "🔴 гейт скіпнувся ПРИ НАЯВНИХ даних — саме так скіп ковтає дефект");
});

test("#237d ПЛАНИ: у вікні — скіп, ПІСЛЯ вікна — падіння (а не тихий скіп)", () => {
  assert.ok(planGraceSkip("менеджерів із планом", 0, "2026-09-01"), "🔴 у вікні заведення не скіпнулось");
  /**
   * 🔴 РІВНО ТЕ, ЧОГО ВИМАГАВ ВЛАСНИК: після вікна нуль планів — це аварія «плани
   * забули завести», і глухий скіп сховав би саме її. `null` тут означає «не
   * скіпаю», тобто гейт біжить далі й падає власним вироком.
   */
  assert.equal(planGraceSkip("менеджерів із планом", 0, "2026-09-03"), null,
    "🔴 після вікна нуль планів усе одно скіпнувся — аварію сховано");
  // 🪞 І дані б'ють вікно: якщо плани Є, скіпу немає навіть у перший день.
  assert.equal(planGraceSkip("менеджерів із планом", 7, "2026-09-01"), null,
    "🔴 скіп при НАЯВНИХ планах — вікно стало важливішим за дані");
});

/**
 * 📉 #238–#238b — ЗАМАЛА ВИБІРКА: СКІП, АЛЕ НЕ ЦІНОЮ ПРОҐАВЛЕНОГО ДЕФЕКТУ.
 *
 * 🔴 Рішення власника, дослівно: «може бути і 2 ліди, це не проблема». Отже `#89`
 * падав на ЗАКОННОМУ стані світу. Але перетворити це на скіп можна лише разом із
 * доказом другої половини — інакше ми обміняли б хибне червоне на хибне зелене.
 */
test("#238 ЗАМАЛА ВИБІРКА → скіп, і текст називає межу ПЕРЕВІРКИ, а не вимогу до людини", () => {
  const skip = smallSampleSkip("лідів у найактивнішого", 2, NEED_LEADS, "2026-09");
  assert.ok(skip, "🔴 два ліди дали падіння — а власник сказав, що це норма");
  assert.ok(skip!.includes(EMPTY_PERIOD_MARK), "🔴 без маркера вартовий скіп не зарахує");
  assert.ok(skip!.includes("придатності"), "🔴 текст не називає, що поріг — про ГЕЙТ");
  assert.ok(/НЕ вимога|не вимога/.test(skip!),
    "🔴 через півроку це прочитають як «менеджеру треба 20 лідів» — саме цього ми й уникаємо");
  // 🪞 Досить вибірки — скіпу немає, гейт зобовʼязаний бігти.
  assert.equal(smallSampleSkip("лідів", NEED_LEADS, NEED_LEADS, "2026-09"), null,
    "🔴 гейт скіпнувся при ДОСТАТНІЙ вибірці — це вже хибне зелене");
});

test("#238b 🔴 ДЗЕРКАЛО: ДОСТАТНЯ вибірка + порушена властивість = ЧЕРВОНЕ", () => {
  /**
   * Живі дані такого стану сьогодні не дають (лідів мало), а чекати місяць не є
   * прийманням — тож порушення підставляється фікстурою. Саме тут доводиться, що
   * скіп НЕ ковтає дефект.
   */
  const want = new Map([[1, { n: 40, slow: 10 }]]);
  const good: RtRow[] = [{ managerId: 1, n: 40, slow: 10, pctSlow: 25 }];
  assert.deepEqual(responseViolations(good, want), [], "🔴 гейт червоніє на СХОДНИХ числах");
  assert.equal(smallSampleSkip("лідів", 40, NEED_LEADS, "x"), null, "🔴 40 лідів визнано замалою вибіркою");

  for (const [label, row] of [
    ["лідів", { managerId: 1, n: 39, slow: 10, pctSlow: 25 }],
    ["повільних", { managerId: 1, n: 40, slow: 11, pctSlow: 25 }],
    ["частки", { managerId: 1, n: 40, slow: 10, pctSlow: 26 }],
  ] as [string, RtRow][]) {
    assert.equal(responseViolations([row], want).length, 1, `🔴 порушення «${label}» не спіймано`);
  }
  // Менеджер, якого немає в контролі, — теж порушення, а не тиша.
  assert.equal(responseViolations([{ managerId: 99, n: 40, slow: 1, pctSlow: 2.5 }], want).length, 1,
    "🔴 зайвий менеджер у розрізі пройшов мовчки");
  // 🔴 І порожній знаменник: `null` не має дорівнювати нулю.
  assert.deepEqual(responseViolations([{ managerId: 2, n: 0, slow: 0, pctSlow: 0 }],
    new Map([[2, { n: 0, slow: 0 }]])), ["менеджер 2: частка 0 не дорівнює slow/n = null"],
    "🔴 «0%» прийнято за відсутню відповідь — саме та підміна, від якої ми лікували Звіт");
});

/**
 * 🛡 #238c — РОДИНА НЕ МОЖЕ СТАТИ ВСЯ-СКІПОМ: у кожної пари «живе дзеркало + вирок»
 * той, ХТО ТРИМАЄ ВИРОК, у реєстрі скіпів відсутній.
 *
 * 🔴 НАВІЩО ОКРЕМЕ ТВЕРДЖЕННЯ. Цього тижня ми перевели в скіпи чотирнадцять гейтів,
 * і кожен раз доказом було «правило стереже хтось інший». Це трималось на моєму
 * слові в коментарі — а слово не гейт. Тут воно стає перевіркою: якщо колись у
 * реєстр потрапить `#58` (джерельний вирок про знаменник) або `#46b` (грошова
 * тотожність), правило лишиться без ЖОДНОГО охоронця, і ніхто цього не помітить.
 */
test("#238c ВИРОК НЕ СКІПАЄТЬСЯ: джерельні гейти родин відсутні в реєстрі порожнього періоду", () => {
  const named = EMPTY_PERIOD_SKIPS.map((x) => x.name);
  for (const guard of ["#58 сер.чек дня ділить гроші на УГОДИ, а не на авто",
    "#46b факт місяця == успішно + оплачено (розклад ②)"]) {
    assert.equal(named.some((n) => n === guard), false,
      `🔴 «${guard}» опинився серед дозволених скіпів — правило лишилось без охоронця, `
      + "а його живе дзеркало має право мовчати");
  }
  // 🪞 Дзеркало: перевірка не вироджена — дзеркала в реєстрі БУТИ мають.
  assert.ok(named.some((n) => n.startsWith("#58b ")), "🔴 живе дзеркало #58b не в реєстрі — тоді воно й далі падатиме");
  assert.ok(named.length >= 14, `🔴 у реєстрі лише ${named.length} записів — перевірка дивиться не туди`);
});

/**
 * #775 — ПОЧАТОК МІСЯЦЯ: «ЗАМАЛО» СКІПАЄТЬСЯ ЛИШЕ В ПЕРШІ 2 РОБОЧІ ДНІ ПОТОЧНОГО МІСЯЦЯ (01.10.2026, рішення Романа).
 * Межа підставляється аргументом, тож обидва боки відтворювані в будь-який день (правило 11).
 * 🧨 Червоніє, якщо скіп спрацює після вікна, на минулому місяці чи при достатніх даних — тобто почне ковтати дефект.
 */
test("#775 ПОЧАТОК МІСЯЦЯ: скіп «замало» лише у вікні 2 робочих днів і лише для поточного місяця", () => {
  const sk = monthStartSkip("менеджерів із планом", 2, 3, "2026-10", "2026-10-01");
  assert.ok(sk && sk.includes(EMPTY_PERIOD_MARK), "🔴 1-ше число з недобором не скіпнулось із маркером порожнього періоду");
  assert.match(sk!, /= 2.*треба 3/, "🔴 причина не називає скільки є і скільки треба");
  assert.ok(monthStartSkip("x", 0, 1, "2026-10", "2026-10-02"), "🔴 другий робочий день — ще вікно");
  assert.equal(monthStartSkip("x", 3, 3, "2026-10", "2026-10-01"), null, "🔴 даних досить, а гейт скіпнувся");
  assert.equal(monthStartSkip("x", 0, 1, "2026-09", "2026-10-01"), null, "🔴 порожній МИНУЛИЙ місяць сховано скіпом — це аварія");
  assert.equal(monthStartSkip("x", 0, 1, "2026-10", "2026-10-05"), null, "🔴 вікно минуло, а недобір усе ще скіпається");
  // Вихідні не їдять вікно: 01.08.2026 — субота, тож 04.08 (вівторок) — лише другий робочий день.
  assert.ok(monthStartSkip("x", 0, 1, "2026-08", "2026-08-04"), "🔴 вихідні з’їли вікно заведення");
});

/**
 * #775b — КОЖЕН ГЕЙТ, ЩО КЛИЧЕ `monthStartSkip`, НАЗВАНИЙ У `EMPTY_PERIOD_SKIPS`. Без запису його скіп у test:prod
 * рахується ПАДІННЯМ (`testRunGate.ts`), тобто помічник тихо не працював би. Перелік — від предмета (правило 12):
 * усі тест-файли з викликом, а не «файли, які я пам'ятаю».
 * 🧨 Червоніє, якщо підключити `monthStartSkip` у новий гейт і забути реєстр.
 */
test("#775b ПОЧАТОК МІСЯЦЯ: кожен гейт із monthStartSkip — у реєстрі порожнього періоду", () => {
  const SRC = path.join(import.meta.dirname, "..", "..", "src");
  const callers: string[] = [];
  const walk = (d: string) => {
    for (const e of readdirSync(d, { withFileTypes: true })) {
      const p = path.join(d, e.name);
      if (e.isDirectory()) walk(p);
      else if (e.name.endsWith(".test.ts") && e.name !== "kyivPeriod.test.ts") {
        const src = readFileSync(p, "utf8");
        let at = src.indexOf("monthStartSkip(");
        while (at >= 0) {
          const head = src.slice(0, at);
          const m = [...head.matchAll(/\btest\("([^"]+)"/g)].at(-1);
          assert.ok(m, `🔴 ${path.relative(SRC, p)}: виклик monthStartSkip поза тестом`);
          callers.push(m![1]);
          at = src.indexOf("monthStartSkip(", at + 1);
        }
      }
    }
  };
  walk(SRC);
  const named = new Set(EMPTY_PERIOD_SKIPS.map((x) => x.name));
  const uniq = [...new Set(callers)];
  assert.ok(uniq.length >= 8, `🔴 гейтів із monthStartSkip знайдено ${uniq.length} — підключено вісім, перелік осліп`);
  assert.deepEqual(uniq.filter((n) => !named.has(n)), [], "🔴 гейт кличе monthStartSkip, але не названий у EMPTY_PERIOD_SKIPS");
});
