import { test } from "node:test";
import assert from "node:assert/strict";
import { kyivMonthBounds, withinPlanGrace, monthEndOf } from "./dates.js";
import { emptyPeriodSkip, planGraceSkip } from "../testMode.js";
import { EMPTY_PERIOD_MARK } from "../testRunGate.js";

/**
 * 🇺🇦🈳 #237–#237d — ЧАС ПО-КИЇВСЬКИ І ПОРОЖНІЙ ПЕРІОД, НА ШТУЧНИХ ДАНИХ.
 *
 * 🔴 ЧОМУ ФІКСТУРА, А НЕ ЖИВИЙ ПРОД. Обидві властивості треба перевірити САМЕ НА
 * МЕЖІ МІСЯЦЯ і САМЕ НА ПОРОЖНЕЧІ, а живі дані такого стану на замовлення не дають:
 * чекати 30 днів до наступної межі — це не приймання. Тут межа підставляється
 * аргументом, тож обидва стани відтворювані в будь-який день.
 */

test("#237 МЕЖА МІСЯЦЯ: `to` — справжній останній день, а не зашите 31", () => {
  /**
   * 🔴 САМЕ ЦЕ ВБИЛО ПʼЯТЬ ГЕЙТІВ 01.09.2026. Вони будували період як `${ym}-31`;
   * у вересні 30 днів, тож у SQL їхав `2026-09-31` і Postgres відповідав
   * `DateTimeParseError`. Читалось як «щось із даними», а це була арифметика.
   */
  assert.equal(kyivMonthBounds("2026-09-15").to, "2026-09-30", "🔴 вересень отримав 31-й день");
  assert.equal(kyivMonthBounds("2026-02-10").to, "2026-02-28", "🔴 лютий отримав зайві дні");
  assert.equal(kyivMonthBounds("2024-02-10").to, "2024-02-29", "🔴 високосний лютий обрізано");
  assert.equal(kyivMonthBounds("2026-08-31").to, "2026-08-31", "🔴 31-денний місяць укорочено");
  // 🪞 Дзеркало: `from` теж від того самого місяця, інакше «межі» були б із різних.
  assert.deepEqual(kyivMonthBounds("2026-09-15"), { ym: "2026-09", from: "2026-09-01", to: "2026-09-30" });
  assert.equal(monthEndOf("2026-09"), "2026-09-30");
});

test("#237b ВІКНО ЗАВЕДЕННЯ ПЛАНІВ — рівно 2 РОБОЧІ дні, і воно закінчується", () => {
  // Вересень 2026: 1-е — вівторок. Отже 01 і 02 у вікні, 03 уже ні.
  assert.equal(withinPlanGrace("2026-09-01"), true, "🔴 перший день місяця вже поза вікном");
  assert.equal(withinPlanGrace("2026-09-02"), true);
  assert.equal(withinPlanGrace("2026-09-03"), false,
    "🔴 вікно не закінчується — тоді «плани забули завести» ніколи не стане червоним");
  // Вихідні НЕ їдять вікно: серпень 2026 починається в суботу, отже 1-2 не робочі,
  // і два робочі дні це 3-є та 4-е.
  assert.equal(withinPlanGrace("2026-08-04"), true, "🔴 вихідні порахувались як робочі дні");
  assert.equal(withinPlanGrace("2026-08-05"), false);
});

test("#237c ПОРОЖНЬО → ПРИЧИНА З МАРКЕРОМ І ЧИСЛОМ; Є ДАНІ → ГЕЙТ БІЖИТЬ", () => {
  const skip = emptyPeriodSkip("угод у касі", 0, "2026-09");
  assert.ok(skip, "🔴 нуль не дав скіпу — гейт упаде там, де мав промовчати");
  assert.ok(skip!.includes(EMPTY_PERIOD_MARK), "🔴 причина без маркера — вартовий її не зарахує");
  assert.ok(skip!.includes("угод у касі") && skip!.includes("2026-09"),
    "🔴 причина не називає ПРЕДМЕТ і ПЕРІОД — це «немає даних», тобто тихий скіп");
  /**
   * 🪞 ДРУГА СТОРОНА МЕЖІ, і вона головна: скіп, що ковтає справжній дефект, гірший
   * за падіння. Одна одиниця даних — і гейт зобовʼязаний бігти.
   */
  assert.equal(emptyPeriodSkip("угод у касі", 1, "2026-09"), null,
    "🔴 гейт скіпнувся ПРИ НАЯВНИХ даних — саме так скіп ковтає дефект");
});

test("#237d ПЛАНИ: у вікні — скіп, ПІСЛЯ вікна — падіння (а не тихий скіп)", () => {
  assert.ok(planGraceSkip("менеджерів із планом", 0, "2026-09-01"), "🔴 у вікні заведення не скіпнулось");
  /**
   * 🔴 РІВНО ТЕ, ЧОГО ВИМАГАВ ВЛАСНИК: після вікна нуль планів — це аварія «плани
   * забули завести», і глухий скіп сховав би саме її. `null` тут означає «не
   * скіпаю», тобто гейт біжить далі й падає власним вироком.
   */
  assert.equal(planGraceSkip("менеджерів із планом", 0, "2026-09-03"), null,
    "🔴 після вікна нуль планів усе одно скіпнувся — аварію сховано");
  // 🪞 І дані б'ють вікно: якщо плани Є, скіпу немає навіть у перший день.
  assert.equal(planGraceSkip("менеджерів із планом", 7, "2026-09-01"), null,
    "🔴 скіп при НАЯВНИХ планах — вікно стало важливішим за дані");
});
