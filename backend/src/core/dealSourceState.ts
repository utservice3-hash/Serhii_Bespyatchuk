/**
 * ЧОТИРИ СТАНИ ДЖЕРЕЛА + `null`, і жоден не зводиться в інший.
 *
 * 🔴 ЩО ТУТ БУЛО ДО 24.08.2026. Стояло `'undef' → null`, «як і невизначена
 * новизна». Разом із тим, що чип малювався лише для `ad`/`leadgen`, це давало
 * таке: `other` (43.2% створених угод) і `undef` обидва лишались БЕЗ ПОЗНАЧКИ й
 * ставали нерозрізненними — і між собою, і з рядками, де джерело незастосовне
 * (дзвінки). Розкриття вміло показати два кошики з чотирьох, тимчасом як колонка
 * над ним рахувала всі чотири. Рівно та розбіжність «число проти складу», що вже
 * коштувала нам 12.6% угод серпня на мітці «новий/постійний».
 *
 * ⚠️ «без джерела» ≠ «канал не вказано»: перше — дотику НЕ БУЛО, друге — ми НЕ
 * ЗНАЄМО. Зводити їх в одну позначку означає видати незнання за факт.
 *
 * `null` лишається РІВНО ЗА ОДНИМ сенсом: рядок — не угода (дзвінок), тож питання
 * про джерело до нього не стосується. Незнайоме значення теж дає `null` — краще
 * «не показали», ніж «показали не тим станом»: нове значення в ядрі має спершу
 * зламати `#174c` (catch-all), а не тихо прикинутись відомим.
 */
export type DealSourceState = "ad" | "leadgen" | "other" | "undef" | null;

export const sourceOf = (v: string | null): DealSourceState =>
  v === "ad" ? "ad"
    : v === "leadgen" ? "leadgen"
      : v === "other" ? "other"
        : v === "undef" ? "undef"
          : null;
