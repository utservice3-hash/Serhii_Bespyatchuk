/**
 * SQL-предикат «менеджер активний за ОБОМА джерелами».
 *
 * `alias` — псевдонім таблиці `managers` у запиті.
 *
 * Логіка навмисно НЕ «немає активного користувача»: менеджер може взагалі не
 * мати логіна (його не заводили) — такий лишається АКТИВНИМ. Виключаємо лише
 * того, у кого логін Є і ЖОДЕН з них не активний. Інакше половина ростера
 * зникла б через те, що людям просто не створювали доступ.
 */
export function activeManagerSql(alias = "m"): string {
  return `${alias}.is_active
    AND NOT (
      EXISTS (SELECT 1 FROM users u WHERE u.manager_id = ${alias}.id)
      AND NOT EXISTS (SELECT 1 FROM users u WHERE u.manager_id = ${alias}.id AND u.is_active)
    )`;
}

/** Чиста двійня предиката — для гейтів без БД і для читабельності на боці JS. */
export function isActiveManager(f: { kommoActive: boolean; loginStates: boolean[] }): boolean {
  if (!f.kommoActive) return false;
  if (f.loginStates.length === 0) return true;      // логіна немає — це не звільнення
  return f.loginStates.some((x) => x);
}
