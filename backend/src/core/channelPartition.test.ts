import { test } from "node:test";
import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { needsApi } from "../testMode.js";

/**
 * 🧺 #174 — ТРИ КАНАЛИ ВЗАЄМНО ВИКЛЮЧНІ Й ПОКРИВАЮТЬ УСЕ (рішення власника 24.08.2026).
 *
 * Модель: походження угоди — це **партиція** `Створено` на реклама · лідген ·
 * без джерела (+ «невизначено», сьогодні порожнє). Новизна (новий/постійний/
 * невизначено) — ДРУГА, незалежна партиція того самого набору. Складати їх між
 * собою заборонено; кожна окремо мусить давати рівно `Створено`.
 *
 * 🔴 ЧОМУ ЦЕЙ ГЕЙТ НАПИСАНО ПЕРШИМ, ЩЕ ДО КОЛОНКИ (вимога власника). Кошики
 * починають перетинатись ТИХО: досить, щоб одна угода потрапила у два, і кожне
 * окреме число лишиться правдоподібним — сума перевищить ціле, а нікому не спаде
 * на думку її скласти. Рівно так прожили «12 із 31 менеджера, у кого тиждень
 * більший за місяць»: обидві метрики окремо правильні, зламана рівність МІЖ ними.
 * Тому інваріант заводиться РАНІШЕ за те, що він стереже.
 *
 * 🔴 І ЦЕ НЕ «ЩЕ ОДИН РОЗКЛАД». Поруч на тому самому екрані живуть колонки
 * «Прийнято реклами» / «Прийнято лідоген» — це KPI-факт із Задачника, ІНША
 * множина (заміряно: 248 проти 228 за тиждень, 8.8%). Їх у цю суму включати не
 * можна, і `#96` стереже саме межу між двома сімʼями.
 */

const src = (rel: string): string => {
  for (const p of [
    fileURLToPath(new URL(`../../src/${rel}`, import.meta.url)),
    fileURLToPath(new URL(`../../../backend/src/${rel}`, import.meta.url)),
  ]) { try { return readFileSync(p, "utf8"); } catch { /* далі */ } }
  assert.fail(`не знайдено джерело ${rel} — гейт не має права мовчки пропускатись`);
};

const MONTH = { from: "2026-07-01", to: "2026-07-31" };

/**
 * #174 — ПАРТИЦІЯ ПО МЕНЕДЖЕРУ, ПО КОМАНДІ Й ПО ВІДДІЛУ.
 *
 * 🧨 САБОТАЖ: зробити кошики перетинними (щоб угода рахувалась двічі) → сума
 * перевищує `Створено`, гейт червоніє з іменем менеджера.
 */
test("#174 Σ каналів (реклама+лідген+без джерела+невизн.) == Створено", { ...needsApi() }, async () => {
  const m = await import("./metrics.js");
  const rows = await m.createdSplitByManager(MONTH);

  // ⚠️ `undefCount` — це НЕВИЗНАЧЕНА НОВИЗНА (`klass='undef'`), а не канал.
  // Канальний аналог зветься `noChannelCount` (`source='undef'`, тобто
  // `lead_channel IS NULL`). Перша редакція цього гейта склала їх в одну суму —
  // дві різні речі під схожими іменами, рівно той клас, що ловить `#96`.
  const bad: string[] = [];
  let sumCreated = 0, sumChannels = 0;
  for (const r of rows) {
    const ch = r.adCount + r.leadgenCount + r.otherCount + r.noChannelCount;
    sumCreated += r.created; sumChannels += ch;
    if (ch !== r.created) {
      bad.push(`${r.name}: канали ${r.adCount}+${r.leadgenCount}+${r.otherCount}+${r.noChannelCount}=${ch} проти створено ${r.created}`);
    }
  }
  assert.deepEqual(bad, [],
    "🔴 кошики каналів перетинаються або не покривають усе — партиція зламана");
  assert.equal(sumChannels, sumCreated,
    "🔴 по відділу Σ каналів ≠ Σ створених");

  // 🪞 Дзеркало: без нього «0 == 0» на порожній вибірці зеленіло б завжди.
  assert.ok(sumCreated > 0,
    "🔴 за період нуль створених угод — рівність тривіальна, перевіряти нема чого");
  assert.ok(rows.some((r) => r.otherCount > 0),
    "🔴 кошик «без джерела» порожній у ВСІХ менеджерів — або він не рахується, або "
    + "предикат вироджений; заміряно 25.07-24.08: 1137 угод (43.2%), нулем бути не може");
});

/**
 * #174b — НОВИЗНА — ДРУГА ПАРТИЦІЯ ТОГО САМОГО НАБОРУ, а не продовження першої.
 *
 * 🔴 НАВІЩО ОКРЕМИМ ТВЕРДЖЕННЯМ. Обидві сімʼї дають у сумі те саме `Створено`,
 * тож на екрані вони виглядають однорідно — і саме тому їх складуть. Гейт
 * фіксує, що це ДВА РІЗНІ розрізи: кожен сходиться сам із собою, і при цьому
 * вони НЕ є копією один одного.
 *
 * 🔴 ДРУГА ПОЛОВИНА ОБОВʼЯЗКОВА. Якби хтось помилково завів канал ЧЕРЕЗ новизну
 * (або навпаки), перша рівність лишилась би зеленою — обидві партиції сходились
 * би, бо це були б ті самі числа. Ловить лише вимога, що вони РІЗНІ хоч десь.
 * 📐 Заміряно: 84% лідген-угод і 73% «іншого» — постійні клієнти, тобто розрізи
 * розходяться масово, і збіг тут означав би поломку, а не природу даних.
 *
 * 🧨 САБОТАЖ: підмінити канальні лічильники новизною → друга половина червоніє.
 */
test("#174b новизна — ОКРЕМА партиція, і вона не копія каналів", { ...needsApi() }, async () => {
  const m = await import("./metrics.js");
  const rows = await m.createdSplitByManager(MONTH);

  const bad: string[] = [];
  for (const r of rows) {
    const nv = r.newCount + r.repeatCount + r.undefCount;
    if (nv !== r.created) bad.push(`${r.name}: новизна ${nv} проти створено ${r.created}`);
  }
  assert.deepEqual(bad, [], "🔴 партиція новизни зламана");

  const differ = rows.filter((r) => r.adCount !== r.newCount || r.leadgenCount !== r.repeatCount);
  assert.ok(differ.length > 0,
    "🔴 канальні лічильники поменеджерно збігаються з новизною — два розрізи стали одним; "
    + "заміряно, що вони мусять масово розходитись (84% лідгену — постійні клієнти)");
});

/**
 * #174c — ДЖЕРЕЛО КАНАЛУ — ТОТАЛЬНА ФУНКЦІЯ, БЕЗ ДІРКИ.
 *
 * 🔴 ЧОМУ ЧИТАЄМО ДЖЕРЕЛО, А НЕ ЛИШЕ ЧИСЛА. Партиція тримається на тому, що
 * `dealSourceCase` має **catch-all** гілку: прибрав `ELSE` — і угода з незнайомим
 * значенням `lead_channel` дістає `NULL`, тобто випадає з УСІХ кошиків. Сума
 * зійдеться (бо `COUNT(*) FILTER` просто не порахує), а рядок зникне з екрана
 * мовчки. Це той самий клас, що операційні статуси, перелічені поштучно «без
 * catch-all, бо catch-all зробив би гейт беззубим» — лише дзеркально.
 *
 * 🧨 САБОТАЖ: прибрати `ELSE 'other'` → червоніє.
 */
test("#174c dealSourceCase покриває всі значення каналу (є catch-all)", () => {
  const met = src("core/metrics.ts");
  const fn = /export function dealSourceCase[\s\S]*?\n\}/.exec(met)?.[0] ?? "";
  assert.ok(fn, "🔴 не знайдено `dealSourceCase` — гейт втратив предмет");

  for (const v of ["'ad'", "'leadgen'", "'undef'", "'other'"])
    assert.ok(fn.includes(v), `🔴 у розкладі каналу зникло значення ${v}`);
  assert.match(fn, /ELSE\s+'other'/,
    "🔴 зник catch-all: угода з незнайомим `lead_channel` дістане NULL і випаде з УСІХ кошиків мовчки");
  assert.match(fn, /IS NULL THEN 'undef'/,
    "🔴 порожній канал більше не читається як «невизначено» — невідоме має лишатись невідомим");
});

/**
 * #174d — ЕКРАН ПОКАЗУЄ ТУ САМУ ПАРТИЦІЮ, ЩО Й ЯДРО.
 *
 * 🔴 ДЗЕРКАЛЬНА ПАСТКА, НА ЯКУ МИ ВЖЕ НАСТУПАЛИ: поле лишається у відповіді й
 * зникає з екрана (або навпаки). Тому гейт дивиться І в контракт роуту, І в
 * набір колонок — саме так `#56` ловить Задачник.
 *
 * 🧨 САБОТАЖ: прибрати колонку «без джерела» з `REPORT_COLS` → червоніє.
 */
/**
 * #174e — 🔔 БУДИЛЬНИК: «канал не вказано» сьогодні НУЛЬ, і поки він нуль — мовчить.
 *
 * 🔴 ЧОМУ БУДИЛЬНИК, А НЕ ХОВАННЯ КОЛОНКИ. Заміряно 24.08.2026: `lead_channel IS NULL`
 * немає в жодної угоди. Колонка, що завжди показує нуль, — це шпалери: її перестають
 * читати, і перша ж справжня одиниця пройде непоміченою. Механізм «ховати, поки нуль»
 * вимагав би нового рантайм-правила у верстці; будильник дає те саме за нуль рядків
 * UI — і, на відміну від верстки, його не можна не помітити.
 *
 * ⚠️ Коли він задзвонить — це НЕ привід його глушити. Це привід зʼясувати, чому
 * `reclassifyAdChannel` лишив угоду без каналу, і показати її людям. Той самий
 * договір, що з `#59` (звільнені з грішми).
 *
 * 🧨 САБОТАЖ: підкинути ненульовий лічильник у чисту перевірку → червоніє.
 */
test("#174e жодної угоди без заповненого каналу (інакше — розібратись, а не глушити)",
  { ...needsApi() }, async () => {
    const m = await import("./metrics.js");
    const rows = await m.createdSplitByManager(MONTH);
    const withNo = rows.filter((r) => r.noChannelCount > 0)
      .map((r) => `${r.name}: ${r.noChannelCount}`);
    assert.deepEqual(withNo, [],
      "🔔 зʼявились угоди з НЕзаповненим `lead_channel`. Це не поломка гейта: "
      + "увімкніть колонку «зі створених: канал не вказано» й зʼясуйте, чому "
      + "`reclassifyAdChannel` їх не покрив. Глушити заборонено.");
  });

