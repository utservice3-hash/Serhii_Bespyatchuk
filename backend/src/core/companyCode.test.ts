import { test } from "node:test";
import assert from "node:assert/strict";
import { normalizeCompanyCode, codeKind, splitCompanyCodes } from "./companyCode.js";

/**
 * #41 — КОД ПІДПРИЄМСТВА: ЩО ВВАЖАЄМО КОДОМ, А ЩО НІ.
 *
 * 🔴 ЧОМУ ЦЕ ВАРТЕ ГЕЙТА. Правило вирішує, які пари клієнтів колись буде
 * ЗАПРОПОНОВАНО ЗЛИТИ. Помилка тут коштує не кривого рядка, а злиття двох різних
 * фірм, яке потім розплітати руками. Усі числа нижче — з живого заміру по 10 000
 * компаній Kommo (05.08.2026), а не з уяви.
 */

test("#41 НОРМАЛІЗАЦІЯ КОДУ: беремо лише осмислені довжини", () => {
  // ✅ реальні формати: ЄДРПОУ 8, РНОКПП 10, ІПН платника ПДВ 12
  assert.equal(normalizeCompanyCode("35705178"), "35705178");
  assert.equal(normalizeCompanyCode("3567397012"), "3567397012");
  assert.equal(normalizeCompanyCode("357051705818"), "357051705818");
  // сміття навколо цифр прибирається — у Kommo трапляється «ЄДРПОУ 35705178»
  assert.equal(normalizeCompanyCode(" 35-70-51-78 "), "35705178");

  // ❌ 🔴 ВІДКИДАЄМО, І ЦЕ ГОЛОВНЕ. Пропущений дубль — робота, яку не зробили;
  // вигаданий — робота, яку доведеться СКАСОВУВАТИ. Тому за сумнівів — null.
  for (const bad of ["1057", "3567397", "123456789", "12345678901", "", null, undefined, "—"])
    assert.equal(normalizeCompanyCode(bad as string), null,
      `🔴 «${bad}» зійшло за код — правило вигадує тотожність там, де її немає`);

  // ❌ провідні нулі = внутрішній обліковий код із поля «Код» (000000882, 000002599).
  // Заміряно: із 517 компаній, де заповнені й «Код», і «ЕДРПОУ», РІЗНІ — 513.
  assert.equal(normalizeCompanyCode("00000882"), null, "🔴 обліковий код 1С зійшов за ЄДРПОУ");
});

test("#41b КЛАС КОДУ: ЄДРПОУ й ІПН — РІЗНІ ключі, не зводяться в один", () => {
  assert.equal(codeKind("35705178"), "edrpou");
  assert.equal(codeKind("357051705818"), "ipn");

  // 🔴 ЧОМУ НЕ ЗВОДИМО. Гіпотезу «ІПН містить ЄДРПОУ» перевірено на 506 компаніях,
  // де заповнені обидва поля: перші 7 цифр збігаються у 96%, перші 8 — лише у 15%
  // (8-ма цифра ЄДРПОУ контрольна, в ІПН на її місці інша). Зрізання до 7 цифр
  // колізій на тих даних не дало, але 7 цифр — це вже здогад, а не ідентифікатор.
  const edrpou = "35705178", ipn = "357051705818";
  assert.notEqual(edrpou, ipn.slice(0, 8),
    "🔴 якби ЄДРПОУ дорівнював першим 8 цифрам ІПН, це був би один ключ — заміряно, що ні");
  assert.equal(edrpou.slice(0, 7), ipn.slice(0, 7),
    "🔴 перші 7 цифр РОЗІЙШЛИСЬ — тоді й приклад у коментарі неправильний");
});

test("#41c ПОЛЕ НЕ ВИЗНАЧАЄ КЛАС — вирішує довжина значення", () => {
  // Заміряно: у полі «ЕДРПОУ» лежить 10-значний ІПН 61 раз, у полі «ИНН» —
  // 8-значний ЄДРПОУ 15 разів. Якби ми вірили назві поля, то звіряли б ЄДРПОУ з
  // ІПН і не знаходили б збігів там, де вони є.
  const swapped = splitCompanyCodes("3567397012", "35705178");   // поля переплутані
  assert.equal(swapped.edrpou, "35705178", "🔴 8 цифр не розпізнались як ЄДРПОУ через назву поля");
  assert.equal(swapped.ipn, "3567397012", "🔴 10 цифр не розпізнались як ІПН через назву поля");

  const normal = splitCompanyCodes("35705178", "357051705818");
  assert.deepEqual(normal, { edrpou: "35705178", ipn: "357051705818" });

  // 🪞 ДЗЕРКАЛО: сміття в обох полях дає ДВА null, а не «щось одне про всяк випадок».
  assert.deepEqual(splitCompanyCodes("1057", "—"), { edrpou: null, ipn: null },
    "🔴 із сміття зʼявився код — саме так і народжуються фальшиві злиття");
});
