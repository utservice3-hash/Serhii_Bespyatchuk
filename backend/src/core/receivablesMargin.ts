/** Стан клітинки маржинальності. `null` там, де рахувати нема з чого. */
export interface MarginCell {
  /** Скільки заробили, ₴. `null` — жодної угоди з лінком. */
  earned: number | null;
  /** Повна сума угод (знаменник), ₴. `null` — немає «Приход 1». */
  base: number | null;
  /** Відсоток. `null` означає «—», і це НЕ нуль. */
  pct: number | null;
  /** Чому «—». Порожнє місце читається як «нічого немає», а не «не знаємо». */
  why: MarginUnknown | null;
}

export type MarginUnknown = "no_deal" | "no_base";

export const MARGIN_UNKNOWN_LABEL: Record<MarginUnknown, string> = {
  no_deal: "немає звʼязку з угодою",
  no_base: "у CRM не вказана сума угоди",
};

/** Підпис колонки. Слово «PnL» тут заборонене — див. `#199f`. */
export const MARGIN_LABEL = "маржинальність, % від суми рахунків";

/**
 * 🔴 ДІЛЕННЯ НА НУЛЬ ТУТ НЕ ПАДАЄ ГОЛОСНО — воно дає `Infinity` або `NaN`, і на
 * екрані зʼявляється порожнеча чи «∞» без пояснення. Тому нуль і `null` у
 * знаменнику — це ОДИН стан «рахувати нема з чого», названий словами.
 *
 * Заміряно: угод із `price = 0` — 2, тобто нулі в чисельнику реальні й мусять
 * давати чесні 0%, а не «—». Плутати нуль у чисельнику з нулем у знаменнику
 * не можна: перший означає «не заробили», другий — «не знаємо, з чого рахувати».
 */
export function marginCell(earned: number | null, base: number | null): MarginCell {
  if (earned == null) return { earned: null, base, pct: null, why: "no_deal" };
  if (base == null || base === 0) return { earned, base: base ?? null, pct: null, why: "no_base" };
  return { earned, base, pct: (earned / base) * 100, why: null };
}

/**
 * Формат відсотка для екрана. Відʼємні показуються ЯК Є: заміряно 3 угоди з
 * відʼємним `price`, і всі 3 мають `is_minus = true` — це коректне сторно, знак
 * дає поле CRM. Ховати правильне число, бо воно негарне, ми не будемо.
 */
export function marginPctText(c: MarginCell): string {
  if (c.pct == null) return "—";
  return `${c.pct.toFixed(1)}%`;
}
