/** Один запис нотатки з набору «канонічний ∪ псевдоніми». */
export interface RowNote {
  /** Ключ, на якому ЛЕЖИТЬ запис — канонічний або псевдонім. */
  clientKey: string;
  /** Назва юрособи цього ключа; `null` — не знайшлась у рахунках. */
  counterpartyName: string | null;
  comment: string | null;
  dueDate: string | null;
  /** Канонічний ISO з `Z` — той самий формат, що вже їде на екран. */
  updatedAt: string | null;
  isCanonical: boolean;
}

export interface PickedNote {
  /** Запис, який займає рядок. `null` — нотаток немає взагалі. */
  primary: RowNote | null;
  /** Решта записів набору — назви юросіб, у тому самому порядку. */
  otherNames: string[];
  othersCount: number;
}

const hasText = (s: string | null): boolean => (s ?? "").trim() !== "";

/**
 * Мить запису як число. Нерозбірна або відсутня дата — НАЙСТАРІША (`-Infinity`),
 * а не «зараз»: інакше зіпсований рядок витіснив би справжній свіжий запис.
 */
function stamp(v: string | null): number {
  if (!v) return -Infinity;
  const t = Date.parse(v);
  return Number.isNaN(t) ? -Infinity : t;
}

/** Повний порядок — див. шапку модуля. Відʼємне = `a` попереду. */
export function compareRowNotes(a: RowNote, b: RowNote): number {
  const byTime = stamp(b.updatedAt) - stamp(a.updatedAt);
  if (byTime !== 0) return byTime;
  const byText = Number(hasText(b.comment)) - Number(hasText(a.comment));
  if (byText !== 0) return byText;
  const byCanon = Number(b.isCanonical) - Number(a.isCanonical);
  if (byCanon !== 0) return byCanon;
  return a.clientKey < b.clientKey ? -1 : a.clientKey > b.clientKey ? 1 : 0;
}

/**
 * Обирає запис для рядка й називає решту набору.
 *
 * 🔴 РЕШТА НАЗИВАЄТЬСЯ, А НЕ ХОВАЄТЬСЯ. «Ще 2» без назв — це та сама хвороба,
 * з якої почалась заявка: людина бачить, що чогось не видно, і не знає чого.
 */
export function pickRowNote(notes: readonly RowNote[]): PickedNote {
  if (notes.length === 0) return { primary: null, otherNames: [], othersCount: 0 };
  const sorted = [...notes].sort(compareRowNotes);
  const [primary, ...rest] = sorted;
  return {
    primary,
    otherNames: rest.map((r) => (r.counterpartyName ?? "").trim() || r.clientKey),
    othersCount: rest.length,
  };
}
