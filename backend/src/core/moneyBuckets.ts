/** Порядок перевірки — від «гроші вже наші» до «ще ні». Корзини диз'юнктні (гейт #45b). */
const BUCKETS: [MoneyBucket, readonly number[]][] = [
  ["closed", CLOSED_STATUSES],
  ["received", RECEIVED_STATUSES],
  ["awaiting", AWAITING_STATUSES],
  ["operational", OPERATIONAL_STATUSES],
  ["lost", LOST_STATUSES],
];

/**
 * Корзина статусу. `null` = статус не належить ЖОДНІЙ корзині — це і є сигнал
 * «наступний Антипенко», а не дрібниця для фолбека. Свідомо БЕЗ дефолту:
 * невідоме має читатись як невідоме.
 */
export function bucketOfStatus(statusId: number): MoneyBucket | null {
  for (const [name, list] of BUCKETS) if (list.includes(statusId)) return name;
  return null;
}

/** Усі корзини, до яких належить статус — для перевірки диз'юнктності (#45b). */
export function bucketsOfStatus(statusId: number): MoneyBucket[] {
  return BUCKETS.filter(([, list]) => list.includes(statusId)).map(([n]) => n);
}

export interface FcStatus { pipelineId: number; statusId: number; name: string }

/** Усі статуси обох FC-воронок: з довідника назв + «провал», якого там немає. */
export function allFcStatuses(): FcStatus[] {
  const out: FcStatus[] = Object.keys(STAGE_NAMES).map((k) => {
    const [p, s] = k.split(":");
    return { pipelineId: Number(p), statusId: Number(s), name: STAGE_NAMES[k] };
  });
  for (const p of FC_PIPELINE_IDS) out.push({ pipelineId: p, statusId: STATUS_LOST, name: FC_LOST_STAGE_NAME });
  return out;
}

/** Статуси без корзини — порожньо в нормі; непорожньо = поломка, яку видно поіменно. */
export function unbucketedStatuses(): FcStatus[] {
  return allFcStatuses().filter((x) => bucketOfStatus(x.statusId) === null);
}
