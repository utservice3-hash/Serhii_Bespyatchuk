/**
 * Рахунок ЖИВИЙ, якщо по ньому немає чинного списання.
 *
 * ⚠️ Ключ — `COALESCE(client_key_raw, client_key)`, той самий, що й на записі
 * списання: касова вставка `client_key_raw` не заповнює (заміряно: 12 рахунків
 * МГЕР, `raw` у нуля з них), і NULL мусить вироджуватись симетрично з обох
 * боків. Голий `client_key_raw` тут зробив би списання готівкового невидимим.
 */
export const INVOICE_ALIVE_SQL = `
  NOT EXISTS (SELECT 1 FROM receivable_writeoffs w
               WHERE w.client_key_raw = COALESCE(ri.client_key_raw, ri.client_key)
                 AND w.invoice_no = COALESCE(ri.invoice_no, '')
                 AND w.revoked_at IS NULL)`;

/**
 * Вік боргу по клієнту = найстаріший ЖИВИЙ рахунок.
 *
 * 🔴 `MAX(...) FILTER`, А НЕ `WHERE`, І ЦЕ НЕ СТИЛЬ. З `WHERE` клієнт, у якого
 * списані ВСІ рахунки, зникає з результату взагалі — і `UPDATE ... FROM` просто
 * не оновлює його рядок, лишаючи ТОРІШНЄ значення. Тобто «списали все» дало б
 * не «віку немає», а «вік застиг», і виглядало б це бездоганно. З `FILTER`
 * такий клієнт дає рядок із `NULL` — і `overdue_days` чесно занулюється.
 */
export const CLIENT_DEBT_AGE_SQL = `
  SELECT ri.client_key,
         MAX((CURRENT_DATE - ri.invoice_date)) FILTER (WHERE ${INVOICE_ALIVE_SQL})::int AS max_age
    FROM receivable_invoices ri
   GROUP BY ri.client_key`;

/**
 * Те саме правило для фронта: вік у днях за найстарішою датою з переданих.
 *
 * ⚠️ Фронт отримує ВЖЕ відфільтрований список (роут не віддає списані рахунки),
 * тож фільтрувати тут нема чого — небезпека інша: рахувати вік у ДВОХ місцях
 * різними виразами. Ця функція існує, щоб шапка розкриття не мала власного
 * `Math.floor((Date.now() - min) / 86400000)`, який одного дня розійдеться з
 * `CURRENT_DATE - invoice_date` у SQL (наприклад, на межі доби чи в іншій зоні).
 *
 * `null` — «рахунків немає», а не «нуль днів»: нуль означав би «виставлений
 * сьогодні», і це різні відповіді.
 */
export function debtAgeDays(dates: ReadonlyArray<Date | null>, now: Date): number | null {
  const t = dates.filter((d): d is Date => d != null).map((d) => d.getTime());
  if (!t.length) return null;
  // Порівнюємо КАЛЕНДАРНІ дати, як `CURRENT_DATE - invoice_date` у SQL, а не
  // різницю моментів: інакше рахунок від учора о 23:00 давав би 0 днів зранку.
  const day = (ms: number) => Math.floor(ms / 86400000);
  return Math.max(0, day(now.getTime()) - day(Math.min(...t)));
}
