export interface TeamOverride {
  /** Команда дашборда або `null` = примусово без команди. */
  teamId: number | null;
  note: string | null;
}

/** Ефективна команда: перевизначення бʼє групу Kommo; відсутність рядка — група. */
export function effectiveTeamId(crmTeamId: number | null, override: TeamOverride | undefined | null): number | null {
  if (override === undefined || override === null) return crmTeamId;
  return override.teamId;
}

/** Підпис для журналу й екрана. */
export function overrideLabel(o: TeamOverride | null, teamName: (id: number) => string | undefined): string {
  if (!o) return "з CRM";
  if (o.teamId == null) return "без команди (примусово)";
  return teamName(o.teamId) ?? `Команда #${o.teamId}`;
}

