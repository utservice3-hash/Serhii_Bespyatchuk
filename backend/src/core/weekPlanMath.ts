/**
 * 🗓 ЧИСТА АРИФМЕТИКА ДИНАМІЧНОГО ПЛАНУ ТИЖНЯ — БЕЗ доступу до БД.
 *
 * 🔴 НАВІЩО ОКРЕМИЙ ФАЙЛ. `core/weekPlan.ts` тягне `db/pool.js` → `config.js`,
 * який кидає без `DATABASE_URL` ще НА ІМПОРТІ — тобто раніше, ніж спрацює `skip`.
 * Перша версія гейтів `#48` саме на цьому й упала: тест про чисте ділення вимагав
 * живої БД. Той самий урок, що з `reactivationRules.ts` і `moneyBuckets.ts`, і він
 * повторюється рівно тому, що формула завжди «на хвилинку» лежить поруч із даними.
 *
 * ФОРМУЛА (рішення власника 06.08.2026):
 *
 *     planWeek = залишок × (робочих днів у цьому тижні)
 *                        ÷ (робочих днів від початку тижня до кінця місяця)
 *     залишок  = план місяця − факт ② на ПОЧАТОК тижня
 *
 * 🔴 БАЗИС — РОБОЧІ ДНІ, А НЕ «ТИЖНІ, ЩО ЛИШИЛИСЬ». Це різниця між досяжною й
 * недосяжною ціллю: останній «тиждень» серпня 2026 — це ОДИН день (31.08). Поділ
 * залишку на кількість тижнів дав би цьому дню ПОВНУ тижневу норму. Поділ на
 * робочі дні дає його одноденну частку.
 *
 * Спостережний наслідок, на якому й стоїть гейт `#48b`: за робочими днями ДЕННИЙ
 * ТЕМП цілі однаковий у всіх тижнях місяця, за тижнями — вилітає саме на
 * обрізаному тижні.
 */

export interface WeekPlanInput {
  monthPlan: number;
  /** Факт ② від 1-го числа до дня ПЕРЕД початком тижня. */
  factBefore: number;
  /** Робочі дні цього тижня (перетин блоку з місяцем). */
  wdWeek: number;
  /** Робочі дні від початку тижня до кінця місяця. */
  wdRest: number;
}
export interface WeekPlanResult {
  plan: number;
  /** Перевиконання: залишок ≤ 0 → план 0, а на екрані «понад план +N ₴». */
  overPlan: number;
}

/**
 * `Math.max(0, …)` на залишку — це і є правило перевиконання власника: плану
 * більше немає, ділення на нуль не стається, шкала не лишається порожньою.
 */
export function weekPlanOf(i: WeekPlanInput): WeekPlanResult {
  const remaining = i.monthPlan - i.factBefore;
  // `|| 0` прибирає `-0`: `Math.round(-0)` дає саме `-0`, і воно доїхало б до JSON
  // як `-0`, а на екран — як «-0 ₴». Дрібниця, яка виглядає як поломка даних.
  if (remaining <= 0) return { plan: 0, overPlan: Math.round(-remaining) || 0 };
  if (i.wdRest <= 0 || i.wdWeek <= 0) return { plan: 0, overPlan: 0 };
  return { plan: Math.round((remaining * i.wdWeek) / i.wdRest), overPlan: 0 };
}

/** Скільки робочих днів у тижні (межі блоку вже обрізані по місяцю). */
export function weekWorkingDays(w: { from: string; to: string }): number {
  return workingDaysBetween(w.from, w.to);
}

/**
 * 🧊 ЧИ ФІКСУВАТИ ТИЖДЕНЬ ЗНІМКОМ ЗАРАЗ (задача 5202, 07.10.2026).
 *
 * Фіксуємо лише тиждень, що ВЖЕ почався, і лише коли місячний план менеджера ВЖЕ заведено.
 *
 * 📐 ЧОМУ ДРУГА УМОВА. Знімок незмінний (`ON CONFLICT DO NOTHING`), тож нуль, зафіксований ДО заведення
 * планів, лишається нулем на весь тиждень. Заміряно 07.10.2026: T2 жовтня в команді Дмитрука заморожено
 * 05.10 о 01:35 з місячним планом 0 у шести людей — «план тижня 21 тис при місячному 900 тис»; T1
 * (01.10, 00:17) — так само в 33 менеджерів усіх команд. Нуль тут означає «плану ще немає», а не «ціль 0».
 * Тиждень без плану лишається живим і фіксується на першому перегляді після заведення плану — з позначкою
 * `backfill`, бо зафіксовано вже заднім числом.
 *
 * ⚠️ Зміна плану ПІСЛЯ фіксації знімок не рухає — і це правило власника від 06.08, а не дефект.
 */
export function shouldFreezeWeek(i: { weekStart: string; today: string; monthPlan: number }): boolean {
  return i.weekStart <= i.today && i.monthPlan > 0;
}

/**
 * 🧊 ЧИ ВІРИТИ ЗНІМКУ (ТЗ Юлі 05.10.2026, «минулі тижні — план, який був на початку тижня»).
 *
 * Знімок із місячним планом 0 у менеджера, чий план ТЕПЕР заведено, — це не «ціль була 0», а «плану ще не
 * завели, коли тиждень зафіксувався» (так застигли T1/T2 жовтня, задача 5202; в історії таких рядків сотні).
 * Показувати його як план минулого тижня означало б намалювати нуль, якого ніхто не ставив. Тоді план тижня
 * відновлюється тією самою формулою від залишку на початок того тижня — і рядок позначений «відновлено».
 */
export function snapshotUsable(snapMonthPlan: number, monthPlan: number): boolean {
  return !(snapMonthPlan === 0 && monthPlan > 0);
}

/**
 * 📅 ПЛАН МАЙБУТНЬОГО ТИЖНЯ — НЕВИКОНАНЕ ПЕРЕНОСИТЬСЯ (ТЗ Юлі 05.10.2026, Звіт КВП).
 *
 * Той самий залишок і той самий денний темп, що в ПОТОЧНОГО тижня: `залишок на початок поточного тижня ×
 * дні цього тижня ÷ дні від початку поточного тижня до кінця місяця`. Тобто майбутні тижні не повзуть
 * усередині тижня (база зафіксована знімком поточного) і оновлюються в понеділок, коли новий тиждень стає
 * поточним і бере свіжий залишок.
 *
 * Приклад з ТЗ: план 400 000, T1 (5 дн) факт 30 000 → у T2 залишок 370 000 на 15 днів → T2 = T3 = T4 = 123 333.
 */
export function futureWeekPlan(cur: { monthPlan: number; factBefore: number; wdRest: number }, wdWeek: number): number {
  return weekPlanOf({ monthPlan: cur.monthPlan, factBefore: cur.factBefore, wdWeek, wdRest: cur.wdRest }).plan;
}
