/**
 * Службові акаунти Kommo. Поповнювати СВІДОМО, як lock-файл.
 * `904923` — «Операційний директор», у `syncKommo` він же має NAME_OVERRIDES із
 * позначкою `was "Admin"`. За ним ~344 клієнти й мільйони гривень, які через це
 * не видно жодному тімліду й не входять у розріз по командах.
 */
export const SERVICE_KOMMO_USER_IDS: readonly string[] = ["904923"];

export type OrphanReason = "service" | "inactive";

/**
 * SQL-предикат «основний відповідальний робить клієнта нічийним».
 * @param alias алиас таблиці `managers` у запиті
 */
export function orphanManagerSql(alias = "m"): string {
  const ids = SERVICE_KOMMO_USER_IDS.map((x) => `'${x}'`).join(",");
  return `(${alias}.kommo_user_id::text IN (${ids}) OR NOT ${alias}.is_active)`;
}

/** Причина, за якою клієнт потрапив у пул. Порядок перевірки = порядок у типі. */
export function orphanReason(m: { kommoUserId: string | number | null; isActive: boolean }): OrphanReason | null {
  if (m.kommoUserId != null && SERVICE_KOMMO_USER_IDS.includes(String(m.kommoUserId))) return "service";
  if (!m.isActive) return "inactive";
  return null;
}

export const ORPHAN_REASON_LABEL: Record<OrphanReason, string> = {
  service: "службовий акаунт",
  inactive: "звільнений менеджер",
};

