/**
 * 🏢 ВИД КЛІЄНТА ДЛЯ ПОРЯДКУ В ПУЛІ (05.10.2026, Роман): «юр особи та ФОПи зверху, фіз особи знизу».
 *
 * Окремого поля «тип клієнта» в CRM НЕМАЄ — заміряно 05.10 на пулі (371 клієнт за 18 міс). Компанія
 * Kommo сама по собі НЕ ознака: її заводять і на фізосіб (297 із 371 мають компанію). Тому вид —
 * це обʼєднання трьох прямих свідчень, будь-якого з них досить:
 *   • хоч одна БЕЗГОТІВКОВА оплата — готівкою фізособа платить, рахунком платить юрособа чи ФОП;
 *   • код у компанії Kommo — ЄДРПОУ (8 цифр) або ІПН (10 цифр);
 *   • організаційна форма в назві («ТОВ», «ФОП», «ПП», «ДП», «ПрАТ», «LLC»…).
 * Решта — «фіз». Заміряно 05.10: 43 зверху, 328 знизу.
 * ⚠️ Межовий випадок, названий заздалегідь: назва без форми й без коду на готівці («АГРОПРОД
 * ІНВЕСТ») іде вниз — свідчення немає, а вигадувати його з «схоже на компанію» ми не беремось.
 * Вид ЛИШЕ сортує й підписує рядок пулу: у гроші, сегменти й кваліфікацію він не входить.
 */
export type ClientKind = "legal" | "person";
export type ClientKindWhy = "cashless" | "code" | "name" | "none";

/**
 * Організаційна форма окремим словом (межі слова — щоб «ТОВАР» чи «ПППП» не рахувались) або повним
 * словом форми («товариство», «підприємство», «підприємець»). Короткі «АТ»/«СК» свідомо НЕ беремо:
 * вони збігаються з ініціалами й частинами прізвищ («Остапенко Ат») — хибне «юр» гірше за пропуск.
 */
const LEGAL_FORM_RE = /(^|[\s"'«(,.])(тов|тзов|ооо|фоп|флп|спд|пп|дп|кп|пкп|фг|прат|пат|зат|ват|ltd|llc|gmbh|uab|sia)(?=$|[\s"'»),.])|товариств|підприємств|підприємець|підприємця/iu;

export function clientKind(c: { name: string | null; anyCashless: boolean; hasCode: boolean }): { kind: ClientKind; why: ClientKindWhy } {
  if (c.anyCashless) return { kind: "legal", why: "cashless" };
  if (c.hasCode) return { kind: "legal", why: "code" };
  if (LEGAL_FORM_RE.test(c.name ?? "")) return { kind: "legal", why: "name" };
  return { kind: "person", why: "none" };
}

/** Порядок у групі пулу: спершу «юр/ФОП», усередині виду — за сумою за весь час (як було). */
export function orphanRowOrder<T extends { kind: ClientKind; revenueAll: number }>(a: T, b: T): number {
  if (a.kind !== b.kind) return a.kind === "legal" ? -1 : 1;
  return b.revenueAll - a.revenueAll;
}

/**
 * 🧭 ХТО І ЩО МОЖЕ В ПУЛІ. Керівники (будь-яка роль, крім scope-ролі `manager`) — увесь пул і
 * закріплення за будь-ким (тімлід — у межах своєї команди, це перевіряє роут). Менеджер — лише з
 * прапорцем `users.orphan_pool`, і лише «взяти собі»: пул для нього — пошук клієнта, а не розподіл.
 * Без прапорця менеджер пулу не бачить (рішення власника 05.08.2026 лишається правилом за замовчуванням).
 */
export type OrphanPoolAccess = "full" | "self" | "none";
export function orphanPoolAccess(a: { role: string; orphanPoolFlag: boolean }): OrphanPoolAccess {
  if (a.role !== "manager") return "full";
  return a.orphanPoolFlag ? "self" : "none";
}
