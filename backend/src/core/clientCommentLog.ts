/**
 * 💬 ЗАДАЧА РЕАКТИВАЦІЇ ПИШЕ В СТРІЧКУ КЛІЄНТА (задача 9224, ТЗ Юлі 16.11.2026).
 *
 * 🔴 ПРИВІД. Менеджери писали коментар по клієнту в трьох місцях: «План місяця», «З ким говорити» і задачник.
 * Перші два вже пишуть в одну стрічку `client_comments`; задачник жив окремо — коментар із постановки задачі
 * (`tasks.description`) і пояснення закриття (`tasks.close_reason`) на екрани «Клієнтів» не потрапляли
 * (заміряно 18.11: 58 задач із власним текстом, 273 закриття з поясненням). Головне місце — стрічка клієнта
 * (Роман у задачі 16.11), тож задача тепер дописує туди свій запис, а в задачнику стрічка лише читається.
 *
 * 🔴 ПОЗНАЧКА ПОПЕРЕДУ ТЕКСТУ — НЕ ПРИКРАСА. За нею «Робота з клієнтом» відрізняє запис задачі від слів
 * людини: постановка задачі тімлідом — це ще не розмова з клієнтом, і колонка «працюють · коментар» не має
 * загорятись від неї (`TASK_LOG_LIKE` нижче). Тому і запис, і фільтр беруть позначки ЗВІДСИ, а не з копії.
 *
 * Чиста: без БД, без імпорту `db/pool` — гейт `#9224` ганяє її без оточення.
 */

/** Позначка запису «поставлено задачу на дзвінок». */
export const TASK_SET_MARK = "📞";
/** Позначка запису «задачу реактивації закрито». */
export const TASK_CLOSED_MARK = "📋";

/** Текст, який діалог «Задача на дзвінок» підставляє, коли людина нічого не написала. Це не коментар по клієнту. */
export const DEFAULT_TASK_NOTE = "Подзвонити клієнту";

/** `2026-11-20` → `20.11`. Інше (порожньо, сміття) → null: дати, якої немає, не вигадуємо. */
function dayMonth(iso: string | null | undefined): string | null {
  const m = /^\d{4}-(\d{2})-(\d{2})$/.exec(String(iso ?? ""));
  return m ? `${m[2]}.${m[1]}` : null;
}

/**
 * Запис у стрічку клієнта при постановці задачі на дзвінок. `null` — писати НІЧОГО: людина коментаря не
 * залишила (порожньо або підставлене «Подзвонити клієнту»), і рядок «📞 … Подзвонити клієнту» в стрічці лише
 * затер би справжній останній коментар у рядку списку.
 */
export function taskSetComment(deadline: string | null | undefined, note: string | null | undefined): string | null {
  const text = String(note ?? "").trim();
  if (!text || text === DEFAULT_TASK_NOTE) return null;
  const d = dayMonth(deadline);
  return `${TASK_SET_MARK} Задача на дзвінок${d ? ` до ${d}` : ""}: ${text}`;
}

/**
 * Запис у стрічку клієнта при закритті задачі з причиною. Пишемо ЗАВЖДИ: навіть без пояснення причина
 * («Ціна», «Конкурент») — це те, що тімлід хоче бачити біля клієнта. Невідомий ключ показуємо як є, а не
 * підміняємо «Іншим»: словник міг поповнитись, і тоді «Інше» збрехало б про причину.
 */
export function taskClosedComment(reasonLabel: string, note: string | null | undefined): string {
  const text = String(note ?? "").trim();
  return `${TASK_CLOSED_MARK} Задачу реактивації закрито — ${reasonLabel}${text ? `: ${text}` : ""}`;
}

/** Шаблони `LIKE` для записів задачі — параметр `ANY($n)` у SQL «Роботи з клієнтом». */
export const TASK_LOG_LIKE: readonly string[] = [`${TASK_SET_MARK} %`, `${TASK_CLOSED_MARK} %`];

/** Чи це запис задачі, а не слова людини (та сама межа, що `TASK_LOG_LIKE`, для коду поза SQL). */
export function isTaskLogComment(body: string): boolean {
  return body.startsWith(`${TASK_SET_MARK} `) || body.startsWith(`${TASK_CLOSED_MARK} `);
}
