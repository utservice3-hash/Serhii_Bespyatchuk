/**
 * 🏢 КОД ПІДПРИЄМСТВА (ЄДРПОУ / ІПН) — ЧИСТЕ ПРАВИЛО НОРМАЛІЗАЦІЇ.
 *
 * 🔴 ЧОМУ ОКРЕМИМ ЯДРОМ, А НЕ `replace(/\D/g,'')` У СИНКУ. Правило вирішує, що
 * ВВАЖАТИ кодом, а отже — які пари клієнтів колись буде запропоновано злити.
 * Помилка тут коштує не «кривого рядка в таблиці», а неправильного злиття двох
 * різних фірм, яке потім розплітати руками. Тому воно чисте, назване й під тестом.
 *
 * 📐 ЗАМІРЯНО НА 10 000 КОМПАНІЙ KOMMO (05.08.2026) — довжини реальних значень:
 *   · «ЕДРПОУ» (466493): 8 цифр — 855, 10 — 61, 7 — 7, 9 — 4, 12 — 4, 6 — 1;
 *   · «ИНН»    (463931): 12 цифр — 616, 10 — 39, 8 — 15, 11 — 13, решта одиниці.
 * Тобто в полі «ЕДРПОУ» люди пишуть і 10-значний ІПН, і навпаки. Саме тому
 * ДОВЖИНА, а не назва поля, вирішує, чим є значення.
 *
 * ⚠️ ЩО МИ СВІДОМО ВІДКИДАЄМО:
 *   · 7 і менше цифр — обрізаний або чужий код (напр. «1057»);
 *   · 9, 11 цифр — не існує таких форматів; це помилка вводу;
 *   · значення з провідними нулями типу `000000882` — це внутрішній обліковий
 *     код із поля «Код», і його ми не беремо взагалі (див. `schema.sql`).
 * Відкинути краще, ніж вгадати: пропущений дубль — це робота, яку не зробили,
 * а вигаданий — робота, яку доведеться скасовувати.
 */

/** Валідні довжини українських кодів: ЄДРПОУ — 8, ІПН/РНОКПП — 10, ІПН платника ПДВ — 12. */
export const CODE_LENGTHS = [8, 10, 12] as const;

/**
 * Витягує цифри й повертає код, лише якщо довжина осмислена.
 * `null` = «це не код», а не «код порожній» — різниця важлива: у першому випадку
 * ми НЕ маємо права використати значення як доказ тотожності.
 */
export function normalizeCompanyCode(raw: string | null | undefined): string | null {
  if (raw == null) return null;
  const digits = String(raw).replace(/\D/g, "");
  if (!(CODE_LENGTHS as readonly number[]).includes(digits.length)) return null;
  // 🔴 Провідні нулі відсікаємо ОКРЕМО: `00000882` формально має 8 цифр, але це
  // обліковий номер із 1С, а не ЄДРПОУ. Жоден реальний ЄДРПОУ не починається з
  // двох нулів (діапазон видачі починається з 00000001, але такі не зустрічаються
  // у ринкових контрагентів — заміряно: у вибірці 853 унікальних ЄДРПОУ таких 0).
  if (/^00/.test(digits)) return null;
  return digits;
}

/**
 * Яким КЛАСОМ коду є значення. Потрібне не для краси: ЄДРПОУ й ІПН — РІЗНІ
 * ключі, і зводити їх в один заборонено (перші 7 цифр збігаються у 96%, перші
 * 8 — лише у 15%, бо 8-ма цифра ЄДРПОУ контрольна). Клас дозволяє звіряти
 * «ЄДРПОУ з ЄДРПОУ», а не «код із кодом».
 */
export type CompanyCodeKind = "edrpou" | "ipn";
export function codeKind(code: string): CompanyCodeKind {
  return code.length === 8 ? "edrpou" : "ipn";
}

/**
 * Розкладає пару полів компанії у два нормалізовані коди.
 *
 * 🔴 ПОЛЕ НЕ ВИЗНАЧАЄ КЛАС. У полі «ЕДРПОУ» трапляється 10-значний ІПН (61 раз
 * у вибірці), у полі «ИНН» — 8-значний ЄДРПОУ (15 разів). Якби ми вірили назві
 * поля, то порівнювали б ЄДРПОУ з ІПН і не знаходили б збігів там, де вони є.
 */
export function splitCompanyCodes(
  edrpouField: string | null | undefined,
  ipnField: string | null | undefined,
): { edrpou: string | null; ipn: string | null } {
  const out: { edrpou: string | null; ipn: string | null } = { edrpou: null, ipn: null };
  for (const raw of [edrpouField, ipnField]) {
    const code = normalizeCompanyCode(raw);
    if (!code) continue;
    const kind = codeKind(code);
    // Перше знайдене значення виграє: другий такий самий клас — або дубль, або
    // помилка вводу, і мовчки перезаписувати його на «останнє» ми не хочемо.
    if (out[kind] == null) out[kind] = code;
  }
  return out;
}
