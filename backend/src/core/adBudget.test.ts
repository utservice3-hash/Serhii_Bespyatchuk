import { test } from "node:test";
import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { monthStartOf } from "./dates.js";

/**
 * 💰 #374–#374c — МІСЯЧНИЙ ПЛАН РЕКЛАМИ: ОДНЕ ДЖЕРЕЛО, І «НЕ ЗАДАНО» ≠ НУЛЬ.
 *
 * 🔴 ЩО САМЕ СТЕРЕЖЕТЬСЯ. Рішення власника 09.09.2026 — «скрізь один план»: ручне
 * число замінює табличне і на екрані «Реклама», і в звіті КВП, звідки рахується ROMI.
 * Два запити до плану означали б два плани на той самий місяць, і розійшлися б вони
 * ТИХО — кожне число окремо виглядало б правильним. Тому джерело одне (`core/adBudget`),
 * і що обидва екрани беруть саме його, перевіряється ДЖЕРЕЛОМ, а не домовленістю.
 *
 * 🔴 ЧОМУ «НЕ ЗАДАНО» МУСИТЬ БУТИ `null`, А НЕ 0. Нуль falsy, тож місяць без плану
 * читався б як «план нуль»: виконання плану дало б ділення на нуль, а перевитрата —
 * 100% там, де плану просто не ставили. Це рівно той сентинел, від якого застерігає
 * правило 5 («заповнене поле, яке не означає значення»), і рівно та дірка, про яку
 * каже правило 7: нуль відтворює її під іншим числом, лишаючи гейт зеленим.
 */

// ⚠️ Шляхи від DIST: тест біжить як `dist/core/…`, тож джерело на два рівні вище й у `src`.
const CORE = fileURLToPath(new URL("../../src/core/adBudget.ts", import.meta.url));
const ROUTE = fileURLToPath(new URL("../../src/routes/dashboard.ts", import.meta.url));

test("#374 МІСЯЦЬ БЕРЕТЬСЯ З БУДЬ-ЯКОГО ДНЯ — і не зсувається на межі", () => {
  assert.equal(monthStartOf("2026-09-17"), "2026-09-01");
  assert.equal(monthStartOf("2026-09-01"), "2026-09-01", "перше число лишається собою");
  assert.equal(monthStartOf("2026-09-30"), "2026-09-01", "останній день місяця — той самий місяць");
  // 🪞 ДЗЕРКАЛО: сусідні місяці НЕ склеюються. Без цієї половини гейт зеленів би
  // на функції, що завжди повертає той самий місяць.
  assert.equal(monthStartOf("2026-08-31"), "2026-08-01");
  assert.equal(monthStartOf("2026-10-01"), "2026-10-01");
  assert.equal(monthStartOf("2026-01-31"), "2026-01-01", "січень не перетікає в лютий");
});

test("#374b «НЕ ЗАДАНО» — це null, і код НЕ підмінює його нулем", () => {
  const src = readFileSync(CORE, "utf8");

  // Порожня мапа мусить давати null, а не 0 — інакше «виконання плану» ділитиметься
  // на нуль, а «перевитрата» покаже 100% там, де плану не ставили.
  assert.match(src, /if \(byMonth\.size === 0\) return null;/,
    "🔴 порожній період більше не віддає null — місяць без плану почне читатись як «план нуль»");

  // Мапа не має містити місяців без плану: «немає запису» ≠ «запис із нулем».
  assert.doesNotMatch(src, /plan:\s*0\b/,
    "🔴 у джерелі зʼявився нуль як значення плану — це сентинел, що читається як дані");
});

test("#374c 🪞 ДЖЕРЕЛО ПЛАНУ ОДНЕ — роут «Реклами» кличе саме ядро, а не свій SQL", () => {
  const route = readFileSync(ROUTE, "utf8");

  assert.match(route, /adPlanForPeriod\(from, to\)/,
    "🔴 роут /ads більше не кличе adPlanForPeriod — план поїхав із другого джерела");

  // 🔴 І ГОЛОВНЕ: у роуті НЕ МАЄ бути власного запиту до плану. Саме так зʼявляється
  // друга копія — не як свідоме рішення, а як «тут швидше дописати SELECT».
  const adsBlock = route.slice(route.indexOf('dashboardRouter.get("/ads"'),
                               route.indexOf('dashboardRouter.get("/lead-quality"'));
  assert.ok(adsBlock.length > 200, "не знайшов тіла роуту /ads — перевірка стала б порожньою");
  assert.doesNotMatch(adsBlock, /budget_plan/,
    "🔴 роут /ads читає budget_plan напряму — це другий план поруч із ручним, і вони розійдуться");
});
