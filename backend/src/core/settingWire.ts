/**
 * 🔌 ТРИ СТАНИ НАЛАШТУВАННЯ НА ДРОТІ (рішення власника 02.09.2026).
 *
 * Та сама форма, що в `core/managerState.ts`: **відсутність — це стан**, а не «нуль».
 * Там «активний» = немає рядка в `manager_work_state`; тут «діє дефолт» = немає значення
 * в тілі запиту. Один упізнаваний зразок, а не два винаходи.
 *
 * | що прийшло    | стан     | що робимо        | навіщо |
 * |---------------|----------|------------------|--------|
 * | поля немає    | `absent` | лишити ПОТОЧНЕ   | часткове збереження безпечне: екран, що шле не всі поля, не стирає решту |
 * | `null` / `""` | `reset`  | повернути ДЕФОЛТ | «очистити поле» це «як було з коробки», а не «нуль» |
 * | число         | `value`  | клампнуте число  | 0 тут ЗАКОННЕ: «межу свідомо знято» |
 *
 * 🔴 ЧОМУ `clampInt` ДЛЯ ЦЬОГО НЕ ГОДИТЬСЯ — це не стиль, а тихий дефект.
 * `clampInt` робить `Math.round(Number(v))`, а `Number("")` дорівнює **0**. Тобто
 * порожній інпут, надісланий як `""`, означав би «межа 0» — МОВЧКИ знімав би поріг
 * усім, хто просто стер поле. Три стани цього не допускають за побудовою: `""` це
 * `reset`, а нуль треба ввести ЯВНО.
 *
 * 🔴 І ЧОМУ ЦЕ СТАЛО ТЕРМІНОВИМ САМЕ ЗАРАЗ. Доки поля не було на екрані, «не задано»
 * жило вічно. Щойно екран почне слати його ЗАВЖДИ, цей стан стане недосяжним — після
 * першого збереження він зникне назавжди. Тому трьом станам потрібні три представлення
 * на дроті, а не два.
 *
 * ⚠️ Сміття (рядок «абв», NaN) лишається `absent` — поведінка та сама, що була в
 * `clampInt`. Свідомо не робимо з нього помилку в цьому проході: це змінило б контракт
 * роуту, а обсяг закритий. Названо, щоб не читалось як недогляд.
 */

export interface Bounds { min: number; max: number }

/**
 * Дефолт межі плану — ТУТ, а не в роуті. Причина та сама, що прибирає `COALESCE(…, 30000)`
 * з міграції: правда про це число мусить бути в ОДНОМУ місці, звідки її може прочитати і
 * роут, і гейт. Імпорт роуту в тест тягне `config`, який кидає без ENV, — тобто зашите
 * число в роуті було ще й неперевірюваним.
 */
export const DEFAULT_PLAN_MIN = 30000;

/** Дозволений діапазон межі. 0 = «межу свідомо знято», стеля — щоб хибний ввід не заблокував подачу. */
export const PLAN_MIN_BOUNDS: Bounds = { min: 0, max: 1_000_000 };


export type WireState = "absent" | "reset" | "value";

/** Що саме прийшло по дроту. Чиста функція — гейт не мусить піднімати роут. */
export function wireState(raw: unknown): WireState {
  if (raw === undefined) return "absent";
  if (raw === null) return "reset";
  if (typeof raw === "string" && raw.trim() === "") return "reset";
  const n = Number(raw);
  return Number.isFinite(n) ? "value" : "absent";
}

/**
 * Значення після розбору трьох станів.
 * `current` — те, що лежить у налаштуваннях зараз; `byDefault` — дефолт із коду.
 */
export function wireValue(raw: unknown, b: Bounds, current: number, byDefault: number): number {
  switch (wireState(raw)) {
    case "absent": return current;
    case "reset": return byDefault;
    case "value": return Math.min(b.max, Math.max(b.min, Math.round(Number(raw))));
  }
}
