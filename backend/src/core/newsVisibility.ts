export const NEWS_ALIVE = "deleted_at IS NULL";

/** Дописується до `WHERE`, коли інші умови вже є. */
export function andAlive(hasWhere: boolean): string {
  return hasWhere ? `AND ${NEWS_ALIVE}` : `WHERE ${NEWS_ALIVE}`;
}

