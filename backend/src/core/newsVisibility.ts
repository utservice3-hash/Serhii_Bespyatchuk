export const NEWS_ALIVE = "deleted_at IS NULL";

/**
 * 🎯 АДРЕСНІСТЬ: НОВИНА НАЗИВАЄ ВКЛАДКИ, ЧИТАЧ БАЧИТЬ ЇЇ, ЯКЩО МАЄ ХОЧ ОДНУ.
 *
 * 🟢 Рішення власника 09.09.2026: «якщо це статистики для адмінів — їх бачать лише
 * адміни; якщо зміна для менеджерів — бачать усі». Замість другого переліку ролей у
 * кожній новині беремо ТОЙ САМИЙ `screen_access`, який адмін і так крутить щодня:
 * другий перелік розійшовся б із першим мовчки, і при кожній новій ролі довелось би
 * проходити 207 старих новин руками.
 *
 * 🔴 `NULL` = БАЧАТЬ УСІ, І ЦЕ НЕ «ПОРОЖНЬО ЯК FALSY». Два стани, які легко злити в
 * один, тут РІЗНІ:
 *   • `audience_tabs IS NULL` — новина нікого не звужує (у нотатці написано `all`);
 *   • читач без жодної вкладки (порожній кеш ролей, невідома роль) — бачить ЛИШЕ такі
 *     новини, а не «всі». Fail-closed, як `roleHasTab`.
 * Виразити перше нулем чи порожнім масивом означало б, що збій кеша відкриває стрічку
 * цілком — правило проєкту «порожній скоуп не можна виражати нулем» саме про це.
 *
 * 🔴 ОДИН БІЛДЕР ВОЛОДІЄ ВСІМА УМОВАМИ, а не віддає фрагмент, який кожен клеїть сам.
 * Причина технічна й заміряна: у списку новин фільтр за категорією НЕОБОВʼЯЗКОВИЙ, тож
 * параметр аудиторії опиняється то в `$1`, то в `$2`. Сталий рядок такого не вміє —
 * і саме тут народилася б друга умова, яка розійдеться з першою.
 *
 * ⚠️ ЧИТАЧІВ ТАБЛИЦІ ШІСТЬ, ФІЛЬТР НЕСУТЬ ЧОТИРИ. Машинні два — дедуп RSS
 * (`jobs/syncNews.ts`) і перевірка «той самий блок» (`tools/publishReleaseNews.ts`) —
 * лишаються БЕЗ фільтра свідомо: перший почав би заводити дублі статей, другий —
 * публікувати повтори. Це той самий виняток, що вже названий вище для `NEWS_ALIVE`.
 */
export function newsScope(
  tabs: readonly string[],
  conds: readonly string[] = [],
  params: readonly unknown[] = [],
): { where: string; params: unknown[] } {
  const p = [...params];
  p.push([...tabs]);
  const all = [...conds, NEWS_ALIVE, `(audience_tabs IS NULL OR audience_tabs && $${p.length}::text[])`];
  return { where: `WHERE ${all.join(" AND ")}`, params: p };
}

/** Дописується до `WHERE`, коли інші умови вже є. */
export function andAlive(hasWhere: boolean): string {
  return hasWhere ? `AND ${NEWS_ALIVE}` : `WHERE ${NEWS_ALIVE}`;
}

