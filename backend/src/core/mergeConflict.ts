/** Активний рядок реєстру; `null` — активного немає серед тих, що просили. */
export interface ActiveAlias {
  /** Який саме псевдонім конфліктує. Двері дебіторки шлють кілька за раз —
   *  без імені людина не знала б, котрий із них розʼєднувати. */
  aliasKey: string;
  canonicalKey: string;
}

export function aliasConflictText(active: ActiveAlias | null, wantedCanonical: string): string {
  // Активного рядка немає, а вставка все одно конфліктує — часткового індексу не
  // існує або гонка з паралельним злиттям. Чесно кажемо «не записався», а не
  // вигадуємо причину, якої не бачимо.
  if (!active) return "Псевдонім не записався через конфлікт у реєстрі — спробуйте ще раз";
  if (active.canonicalKey === wantedCanonical) return "Ці клієнти вже обʼєднані";
  return `Псевдонім «${active.aliasKey}» уже веде до «${active.canonicalKey}» — спершу розʼєднайте його там`;
}
