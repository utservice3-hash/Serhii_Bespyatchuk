import { test } from "node:test";
import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import path from "node:path";
import { parseReleaseNotes } from "./releaseNotes.js";

/** Читання ДЖЕРЕЛА з кореня репозиторію — той самий прийом, що `#24d`/`#107`. */
const ROOTS = [
  path.join(import.meta.dirname, "..", ".."),
  path.join(import.meta.dirname, "..", "..", ".."),
  path.join(import.meta.dirname, "..", "..", "..", ".."),
];
function readSrc(rel: string): string {
  for (const r of ROOTS) {
    try { return readFileSync(path.join(r, rel), "utf8"); } catch { /* далі */ }
  }
  assert.fail(`не знайдено ${rel} — перевірка не має права мовчки пропускатись`);
}

/**
 * #353 — РОЗБІР ПІДПИСІВ РЕЛІЗУ: ТРИ СТАНИ, А НЕ ДВА.
 *
 * 🔴 «Новини не буде» має ДВІ різні причини, і склеїти їх не можна: файла немає (він
 * загубився при переїзді — це наша поломка) проти «блок порожній» (цього викату немає
 * що сказати людям — штатна тиша). Одна відповідь на обидва означала б, що зниклий
 * файл виглядає як звичайний технічний реліз, і ми не помітимо пропажі роками.
 *
 * ⚠️ Заголовок БЕЗ тіла — теж порожній блок: новина з самою датою нічого не каже, а
 * виглядає як повідомлення. Це гірше за відсутність, бо навчає не читати наступні.
 */
test("#353 верхній блок: є текст · порожньо · файла немає — три різні відповіді", () => {
  const ok = parseReleaseNotes("## Оновлення 07.09\nТімлід бачить архів своєї команди.\n");
  assert.equal(ok.note?.title, "Оновлення 07.09");
  assert.equal(ok.note?.body, "Тімлід бачить архів своєї команди.");
  assert.equal(ok.reason, undefined);

  assert.equal(parseReleaseNotes(null).reason, "no-file",
    "🔴 відсутній файл не названий окремо — його пропажа виглядатиме як тихий реліз");
  assert.equal(parseReleaseNotes("").reason, "empty-block");
  assert.equal(parseReleaseNotes("# Заголовок файла\nбез блоків\n").reason, "empty-block",
    "🔴 текст без жодного блоку `## ` прийнято за новину");
  assert.equal(parseReleaseNotes("## Порожній\n\n").reason, "empty-block",
    "🔴 заголовок без тіла став новиною — це повідомлення, яке нічого не повідомляє");
  assert.equal(parseReleaseNotes(null).note, null);
});

/**
 * #353b — 🪞 ДЗЕРКАЛО: береться САМЕ ВЕРХНІЙ блок, і сусідній у нього не затікає.
 *
 * Без цієї половини `#353` лишався б зеленим на розборі, який склеює весь файл: новина
 * про сьогоднішній викат несла б і всю історію попередніх. Перевіряємо обидва боки межі
 * — верхній блок узято ПОВНІСТЮ (обидва його рядки) і НЕ прихоплено нижчий.
 */
test("#353b 🪞 верхній блок береться цілком і не тягне наступний", () => {
  const r = parseReleaseNotes(
    "## Свіже\nперший рядок\nдругий рядок\n\n## Старе\nминулий реліз\n");
  assert.equal(r.note?.title, "Свіже");
  assert.match(r.note!.body, /перший рядок/);
  assert.match(r.note!.body, /другий рядок/,
    "🔴 з блоку взято лише перший рядок — довгі підписи обріжуться мовчки");
  assert.doesNotMatch(r.note!.body, /минулий реліз/,
    "🔴 у новину затік наступний блок — кожен викат публікуватиме всю історію");
  assert.doesNotMatch(r.note!.body, /## /,
    "🔴 у тілі лишився заголовок наступного блоку");
});

/**
 * ✍️ #374 / #374b — НОВИНА ДОЇЖДЖАЄ ДО ЛЮДИНИ ЗВИЧАЙНИМ ТЕКСТОМ.
 *
 * 📐 ПРИВІД, ПОБАЧЕНИЙ ВЛАСНИКОМ НА ЕКРАНІ 08.09.2026: у стрічці стояли зірочки —
 * `**Виправляємо власне попереднє повідомлення.**`. Джерело зветься `RELEASE_NOTES.md`
 * і пишеться як markdown, а рендер — `<p style={{ whiteSpace: "pre-wrap" }}>{n.body}</p>`,
 * тобто ЗВИЧАЙНИЙ текст: markdown-рендера в проєкті немає жодного. Заміряно: 4 новини
 * з 4 автопублікацій, 26 пар `**`, і помилку зробили ТРИ різні проходи поспіль.
 *
 * 🔴 ГЕЙТ НА ФУНКЦІЮ, А НЕ НА ФАЙЛ. Перевіряти «у `RELEASE_NOTES.md` немає зірочок»
 * означало б забороняти markdown у markdown-файлі, який читають і розробники. Правильна
 * межа — ВИХІД парсера: у файлі пиши як зручно, до людини доїде чисте.
 */
test("#374 парсер віддає ЧИСТИЙ текст — розмітка не доїжджає до стрічки", () => {
  const raw = "# шапка\n\n## Заголовок із **жирним**\n\n"
    + "Текст із **жирним** і `кодом`.\n\n- перший пункт\n- другий пункт\n\n## Старіший блок\nінше";
  const r = parseReleaseNotes(raw);
  assert.ok(r.note, "🔴 блок не розібрався — далі перевіряти нічого");

  assert.equal(r.note!.title, "Заголовок із жирним",
    "🔴 зірочки лишились у ЗАГОЛОВКУ — саме він стоїть найбільшим шрифтом угорі картки");
  assert.doesNotMatch(r.note!.body, /\*\*/,
    `🔴 у тілі лишились зірочки: ${JSON.stringify(r.note!.body.slice(0, 120))}. Стрічка `
    + "рендерить звичайний текст, тож людина побачить їх як символи");
  assert.doesNotMatch(r.note!.body, /(^|\n)- /,
    "🔴 марковані пункти лишились дефісами — у звичайному тексті це читається як тире");
  assert.match(r.note!.body, /• перший пункт\n• другий пункт/,
    "🔴 пункти зникли або злиплись — чистка не має ламати перелік");
  assert.match(r.note!.body, /«кодом»/,
    "🔴 код-лапки лишились зворотними — у стрічці вони виглядають як друкарська помилка");
});

test("#374b 🪞 чистка НЕ їсть зміст і не чіпає одиночну зірочку", () => {
  // Дзеркало: гейт вище зеленів би й тоді, якби `toPlainText` повертав порожній рядок.
  const r = parseReleaseNotes("## Назва\n\nПлан **880 000** ₴ на 5 угод.");
  assert.equal(r.note!.body, "План 880 000 ₴ на 5 угод.",
    "🔴 разом із розміткою зник текст — чистка стала цензурою");

  // Одиночна `*` СВІДОМО лишається: у нас вона частіше множення чи виноска, ніж курсив.
  // Без цього твердження хтось «дочистить» і зіпсує «2 * 3» або зноску.
  const star = parseReleaseNotes("## Назва\n\n2 * 3 = 6, дивись виноску *.");
  assert.match(star.note!.body, /2 \* 3 = 6/,
    "🔴 одиночну зірочку теж почали чистити — це вже не розмітка, а зміст");
});

/**
 * 🎯 #380 / #380b — АДРЕСАТ НОВИНИ НАЗВАНИЙ, І НАЗВАНИЙ ПРАВИЛЬНО.
 *
 * 🟢 Рішення власника 09.09.2026: рядок `Кому:` обовʼязковий, «для всіх» пишеться явно
 * (`all`). Причина — мовчання двозначне: воно однаково означає «вирішив, що всім» і
 * «забув», а це два різні стани.
 *
 * 📐 Що «забуде» станеться — заміряно, а не припущено: у шапці цього ж файла першим
 * абзацом стоїть «пишемо ДЛЯ ЛЮДЕЙ», і попри це ТРИ проходи поспіль написали туди
 * markdown. Вимога у файлі вже одного разу не спрацювала — тому тут гейт.
 */
test("#380 парсер: `all` = всім, перелік = вкладки, відсутність = названий дефект", () => {
  const one = parseReleaseNotes("## Назва\n\nКому: all\n\nТекст новини.");
  assert.equal(one.note!.audience, null, "🔴 `all` має означати «бачать усі», тобто NULL");
  assert.equal(one.note!.audienceMissing, false, "🔴 рядок БУВ — це не «забув»");
  assert.doesNotMatch(one.note!.body, /Кому:/,
    "🔴 службовий рядок доїхав у стрічку — людям він не потрібен, а ще він зламав би "
    + "сторожа «той самий блок», який порівнює саме тіло");
  assert.match(one.note!.body, /Текст новини\./, "🔴 разом із тегом зник і зміст");

  const two = parseReleaseNotes("## Назва\n\nКому: depstats, statistics\n\nТекст.");
  assert.deepEqual(two.note!.audience, ["depstats", "statistics"],
    "🔴 перелік вкладок розібрано неправильно — новина поїде не тим людям");

  const none = parseReleaseNotes("## Назва\n\nТекст без адресата.");
  assert.equal(none.note!.audienceMissing, true,
    "🔴 відсутність рядка не позначена — «забув» і «для всіх» знову нерозрізненні");
  assert.equal(none.note!.audience, null,
    "🔴 без тега новина мусить піти ВСІМ: ховати її від людей через помилку автора гірше, "
    + "ніж показати зайвим (дефект ловить #380b ще до коміту)");
});

test("#380b ФАЙЛ: верхній блок називає адресата, і кожна вкладка існує", () => {
  const raw = readSrc("RELEASE_NOTES.md");
  const parsed = parseReleaseNotes(raw);
  if (parsed.note === null) return;   // штатна тиша — блоків немає, перевіряти нічого

  assert.equal(parsed.note.audienceMissing, false,
    "🔴 у верхньому блоці RELEASE_NOTES.md немає рядка «Кому:». Напиши `Кому: all`, якщо "
    + "новина для всіх, або перелічи вкладки. Це ловиться ЗАРАЗ, поки ти у файлі, — "
    + "а не за пів дня на сервері, де тебе вже немає");

  // 🔴 Друкарська помилка у назві вкладки не звужує аудиторію — вона ховає новину ВІД УСІХ.
  const nav = readSrc(path.join("frontend", "src", "components", "Layout.tsx"));
  for (const tab of parsed.note.audience ?? []) {
    assert.ok(new RegExp(`key: "${tab}"`).test(nav),
      `🔴 вкладки «${tab}» не існує (немає в NAV_GROUPS). Така новина не дійде НІ ДО КОГО, `
      + "і мовчки — перетин із порожнім набором завжди хибний");
  }
});
