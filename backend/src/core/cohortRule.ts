export const COHORT_MIN_ENTERED = 10;

/** Відсоток когорти, або `null` («—»), якщо знаменник менший за поріг. */
export function cohortPct(won: number, entered: number): number | null {
  if (entered < COHORT_MIN_ENTERED) return null;
  return Math.round((won / entered) * 1000) / 10;
}
