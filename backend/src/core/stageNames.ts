/**
 * Підпис стадії однієї угоди.
 *
 * 🔒 Фолбек НАВМИСНО грубий і чесний, а не «найпоширеніша назва»: новий статус
 * у Kommo має виглядати як «ми його ще не назвали», а не тихо вдягати чужу
 * назву — саме так і зʼявився ярлик, що брехав 60 угодам.
 */
export function stageName(pipelineId: number | string, statusId: number | string, funnelStage?: string): string {
  return STAGE_NAMES[`${pipelineId}:${statusId}`] ?? FALLBACK[funnelStage ?? ""] ?? "—";
}

