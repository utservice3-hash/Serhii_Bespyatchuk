/** Поле-якір. Іменоване, щоб «за чим саме рахуємо» не доводилось вишукувати в SQL. */
export const DISPATCH_ANCHOR = "load_at";

const KYIV = "Europe/Kyiv";

/**
 * Місяць когорти («створена у цьому місяці») по-київськи.
 *
 * 🔴 ОДИН ВИРАЗ НА ДВА ВЖИТКИ — і це не економія рядка. Ним визначається І бакет, у
 * який лягає число, І верхня межа якоря. Дві копії розійшлись би тихо: угода лягла б
 * у серпневий бакет, а межу мала б липневу, і ніхто б не помітив.
 */
export const cohortMonth = (a: string): string =>
  `date_trunc('month', (${a}.created_at_kommo AT TIME ZONE '${KYIV}'))`;

/**
 * Умова «ця угода відправлена» — чотири предикати, і кожен ріже свою множину.
 * `receivedParam` — плейсхолдер зі статусами «оплата зайшла» (`STAGE_RECEIVED`);
 * передається ззовні НАВМИСНО, щоб цей файл лишався без `db/pool` і гейти бігли в
 * оточенні без `.env` — той самий урок, що `core/cohortRule.ts`.
 */
/**
 * ① + ② «ПОЇХАЛА»: якір проставлений і не пізніше за min(кінець свого місяця, сьогодні).
 *
 * 🔴 ВИНЕСЕНО ОКРЕМО НЕ ЗАРАДИ КРАСИ. Інваріант приймання — «поїхали == відправлено +
 * оплачені + закриті» — інакше довелося б будувати з ДРУГОЇ копії умови якоря, і
 * рівність перевіряла б копію проти оригіналу замість того, щоб перевіряти розбиття.
 */
export function anchorTravelled(a: string): string {
  const m = cohortMonth(a);
  return `${a}.${DISPATCH_ANCHOR} IS NOT NULL
      AND (${a}.${DISPATCH_ANCHOR} AT TIME ZONE '${KYIV}')::date`
    + ` <= LEAST((${m} + interval '1 month - 1 day')::date, (now() AT TIME ZONE '${KYIV}')::date)`;
}

/**
 * Умова «ця угода відправлена»: «поїхала» ∧ оплата ще не зайшла ∧ не закрита провалом.
 * `receivedParam` — плейсхолдер зі статусами «оплата зайшла» (`STAGE_RECEIVED`);
 * передається ззовні НАВМИСНО, щоб цей файл лишався без `db/pool` і гейти бігли в
 * оточенні без `.env` — той самий урок, що `core/cohortRule.ts`.
 */
export function dispatchedWhere(a: string, receivedParam: string): string {
  return [
    anchorTravelled(a),
    // ③ оплата ще НЕ зайшла
    `NOT (${a}.status_id = ANY(${receivedParam}))`,
    // ④ і угоду не закрито як провал — рішення власника, див. шапку
    `${a}.status_id <> ${STATUS_LOST}`,
  ].join("\n      AND ");
}
