import { test } from "node:test";
import assert from "node:assert/strict";
import { closeReasonClass, ownerTeamClamp, OWNER_TEAM_CTE, SERVICE_CLOSE_REASONS,
         CLOSE_CLASS_LABEL } from "./reactivationClose.js";
import { CLOSE_REASON_KEYS, RETURNED_CLOSE_REASON } from "./reactivationRules.js";
import { MIGRATED_CLOSE_REASON } from "./reactivationPack.js";

/**
 * #348 — ЗАКРИТТЯ СИСТЕМОЮ НЕ МОЖНА ПОКАЗУВАТИ ЯК РОБОТУ ЛЮДИНИ.
 *
 * 📐 Куплено заміром 07.09.2026 ДО реалізації екрана: у базі «закритих із причиною»
 * 194, а закритих людиною — НУЛЬ. Усі 194 — мітка нашого ж перенесення від 05.09.
 * Реєстр, що не розрізняє класи, показав би 194 опрацьовані клієнти там, де роботи
 * не було, — тобто екран, зроблений заради чесності, збрехав би першим же рядком.
 *
 * 🔴 ФІКСТУРА ПО ВСІХ ЧОТИРЬОХ КЛАСАХ (правило 11), бо саме межі між ними й коштують:
 * ① довідникова причина — робота людини; ② службова мітка — робота коду;
 * ③ порожньо — легально для пачок (CHECK вимагає причину лише поклієнтно);
 * ④ чуже значення — «поза довідником», а НЕ мовчазне зарахування до людських.
 */
test("#348 клас причини розрізняє людину, систему, порожнечу й чуже значення", () => {
  assert.equal(closeReasonClass(CLOSE_REASON_KEYS[0]), "human",
    `🔴 довідникова причина «${CLOSE_REASON_KEYS[0]}» не зарахована людині`);
  assert.equal(closeReasonClass(RETURNED_CLOSE_REASON), "service",
    "🔴 автоповернення зараховане людині — на екрані це виглядатиме як її робота");
  assert.equal(closeReasonClass(MIGRATED_CLOSE_REASON), "service",
    "🔴 мітка перенесення зарахована людині — саме так 194 рядки стануть «опрацьованими»");
  assert.equal(closeReasonClass(null), "none");
  assert.equal(closeReasonClass("   "), "none",
    "🔴 пробіли прочитались як причина — порожнє мусить називати себе порожнім");
  // 📐 Форма, у якій причина СПРАВДІ лежить у базі: `POST /reactivation-task/close`
  // складає «ключ: пояснення». Без цієї половини найдетальніші людські закриття
  // зараховувались би до «поза довідником» — тобто губились би саме найкращі записи.
  assert.equal(closeReasonClass("other: клієнт закрився"), "human",
    "🔴 причина з поясненням не зарахована людині — а саме так її й пише роут закриття");
  assert.equal(closeReasonClass("returned: щось своє"), "unknown",
    "🔴 чужий рядок із службовим префіксом прийнято за службову мітку — префіксне "
    + "порівняння відкрило б клас «система» для будь-кого ззовні");
  assert.equal(closeReasonClass("щось своє"), "unknown",
    "🔴 значення поза довідником зараховане людині — причина, якої ніхто не вибирав");
});

/**
 * #348b — 🪞 ДЗЕРКАЛО: класи беруться з КОНСТАНТ, а не з переписаних префіксів.
 *
 * Без цього `#348` лишався б зеленим після перейменування константи: власний рядок
 * «migrated:» у класифікаторі мовчки перевів би сотні рядків у клас «людська причина».
 * Той самий клас помилки, що друга копія бізнес-правила.
 */
test("#348b 🪞 службові мітки — це самі константи, не їхні копії", () => {
  assert.ok(SERVICE_CLOSE_REASONS.includes(RETURNED_CLOSE_REASON),
    "🔴 позначка автоповернення випала з переліку службових");
  assert.ok(SERVICE_CLOSE_REASONS.includes(MIGRATED_CLOSE_REASON),
    "🔴 позначка перенесення випала з переліку службових");
  for (const s of SERVICE_CLOSE_REASONS) {
    assert.ok(!CLOSE_REASON_KEYS.includes(s),
      `🔴 службова мітка «${s}» потрапила в довідник — людина зможе обрати її руками, `
      + "і ми перестанемо відрізняти дію від механізму");
  }
  assert.equal(new Set(Object.values(CLOSE_CLASS_LABEL)).size, 4,
    "🔴 два класи мають однаковий підпис — на екрані вони зіллються, і різниця зникне");
});

/**
 * #349 — КЛАМП СКОУПУ Є SQL-УМОВОЮ, А НЕ ФІЛЬТРОМ У ВІДПОВІДІ.
 *
 * 🔴 Обидві половини обовʼязкові: тімліду умова МУСИТЬ додатись, адміну — НІ.
 * Односторонній гейт зеленів би на «умова стоїть завжди», тобто адмін перестав би
 * бачити компанію цілком, і це виглядало б як зникнення даних, а не як звуження прав.
 */
test("#349 кламп: тімліду умова додається, адмін-рівню — ні", () => {
  assert.equal(ownerTeamClamp(null, "$2"), "",
    "🔴 адмін-рівень отримав кламп — він побачить лише частину компанії");
  const lead = ownerTeamClamp(7, "$2");
  assert.match(lead, /ot\.team_id = \$2/,
    "🔴 тімліду не додалась умова по команді — у видачу поїде чужа команда");
  assert.ok(lead.trim().startsWith("AND "),
    "🔴 умова не дописується до WHERE — запит або зламається, або мовчки втратить кламп");
  assert.match(OWNER_TEAM_CTE, /COALESCE\(lo\.pinned_manager_id, pm\.manager_id\)/,
    "🔴 формула «менеджер клієнта» розійшлась із рештою екранів — це ДРУГЕ джерело правди "
    + "про відповідального, а їх має бути одне");
});
