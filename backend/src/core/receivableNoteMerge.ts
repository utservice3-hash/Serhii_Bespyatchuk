/**
 * 🗒 ПОРОЖНІЙ КОМЕНТАР НЕ ЗАТИРАЄ ТЕКСТ (17.09.2026).
 *
 * Заміряно на проді 17.09: за 14 днів 14 нотаток дебіторки спорожніли, у 10 з них
 * раніше був текст («оплачено», «чекають на оплату від порту», «частково закрив,
 * лишилось 92к»), і кожна — у мить зміни дати. Механізм: редактор відкривається з полем,
 * звуженим тижневим правилом (`activeNote`), тобто ПОРОЖНІМ для минулотижневого запису;
 * людина ставить дату, тисне «Зберегти», і на сервер летить `comment: ""`, а `ON CONFLICT
 * … SET comment = EXCLUDED.comment` записує порожнечу поверх тексту. Скарга власника:
 * «у нас злітають постійно коментарі».
 *
 * Правило: порожній коментар у запиті означає «не чіпати», стерти можна лише явним
 * `clear: true`. Текст у запиті — замінює. Тижневе правило показу НЕ змінюється.
 */
export function mergeNoteComment(existing: string | null, incoming: string | null | undefined, clear: boolean): string | null {
  const next = (incoming ?? "").trim();
  if (clear) return next || null;
  if (next) return next;
  const prev = (existing ?? "").trim();
  return prev || null;
}
