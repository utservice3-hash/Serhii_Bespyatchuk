import { test } from "node:test";
import assert from "node:assert/strict";
import { stageName, STAGE_NAMES, FUNNEL_STAGE_LABELS } from "./stageNames.js";

/**
 * 🔴 НАВІЩО ЦІ ТЕСТИ. Підпис стадії брався з `funnel_stage` — грубого кошика на
 * 5 значень. У кошику `invoiced` живуть ШІСТЬ статусів Kommo, серед них і
 * «Виставлено рахунок», і «Очікуємо оплату», тож один ярлик обслуговував дві
 * різні стадії. Замір на проді: у наборі застряглих підпис був неправильним у
 * 312 із 313 угод.
 *
 * Пастка, заради якої написаний #28b: «просто перейменувати invoiced в
 * „Очікуємо оплату"» звучить як фікс, але створює ДРУГУ брехню — угоди на
 * 69716304 справді стоять на «Виставлено рахунок». Тому тест фіксує НЕ лише
 * те, що ми перейменували, а й те, що НЕ перейменували.
 */

test("#28 ПІДПИС СТАДІЇ — ЗА СТАТУСОМ, а не за кошиком funnel_stage", () => {
  // те, що брехало: етап 8 підписувався як «Виставлено рахунок»
  assert.equal(stageName(8921932, 69716312, "invoiced"), "Очікуємо оплату");
  assert.equal(stageName(155304, 25044997, "invoiced"), "Очікуємо оплату");
  // дзеркальна брехня поруч: «Виставлення рахунку» лежить в `approved`,
  // тож підписувалось як «Взято в роботу»
  assert.equal(stageName(8921932, 100274340, "approved"), "Виставлення рахунку");
  assert.equal(stageName(8921932, 98470988, "approved"), "Перевезення завершено");
});

test("#28b НЕ ПЕРЕЙМЕНОВАНО ТЕ, ЩО НАЗВАНО ПРАВИЛЬНО (інакше друга брехня)", () => {
  // 69716304 / 42639144 — це САМЕ «Виставлено рахунок» (після розвантаження).
  // Якби ми перейменували весь кошик `invoiced`, ці угоди отримали б чужу назву.
  assert.equal(stageName(8921932, 69716304, "invoiced"), "Виставлено рахунок");
  assert.equal(stageName(155304, 42639144, "invoiced"), "Виставлено рахунок");
  assert.notEqual(stageName(8921932, 69716304, "invoiced"), stageName(8921932, 69716312, "invoiced"));
});

test("#28c ФОЛБЕК ЧЕСНО ГРУБИЙ: невідомий статус не вдягає чужу назву", () => {
  // Новий статус у Kommo має виглядати як «ми його ще не назвали». Саме тихе
  // «вдягання найпоширенішої назви» і породило ярлик, що брехав.
  assert.equal(stageName(8921932, 999999999, "invoiced"), FUNNEL_STAGE_LABELS.invoiced);
  assert.equal(stageName(8921932, 999999999), "—");
  // і фолбек НЕ дорівнює жодній конкретній назві всередині кошика
  assert.notEqual(FUNNEL_STAGE_LABELS.invoiced, "Виставлено рахунок");
  assert.notEqual(FUNNEL_STAGE_LABELS.invoiced, "Очікуємо оплату");
});

test("#28d МАПА ПОКРИВАЄ ОБИДВІ ВОРОНКИ ПОВНОГО ЦИКЛУ", () => {
  // Дірка в мапі = мовчазний фолбек на екрані. Перевіряємо саме ті статуси,
  // які seedKommoMapping.sql кладе в повний цикл.
  const FC = [
    [8921932, [108361876, 69693668, 69693672, 69716252, 69693676, 69716256, 69716260,
      100274340, 69716300, 98470988, 69716304, 69716312, 69716460, 142]],
    [155304, [26010520, 11804491, 10847806, 69500840, 10869081, 10883250, 62940064,
      10937178, 42639144, 42639147, 25044997, 62940068, 60412544, 142]],
  ] as [number, number[]][];
  const missing: string[] = [];
  for (const [pipe, ids] of FC) for (const id of ids) {
    if (!STAGE_NAMES[`${pipe}:${id}`]) missing.push(`${pipe}:${id}`);
  }
  assert.deepEqual(missing, [], `немає назв для: ${missing.join(", ")}`);
  // ⚠️ Порожній результат був би «успіхом» і тоді, коли перевіряти нічого:
  // доводимо, що список НЕ порожній.
  assert.equal(FC[0][1].length + FC[1][1].length, 28);
});
