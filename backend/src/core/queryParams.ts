/**
 * Значення query-параметра як дата або `null`.
 * `""`, `undefined`, `null`, масив (повторений параметр) → `null`.
 */
export function dateParam(v: unknown): string | null {
  if (typeof v !== "string") return null; // включно з масивом: `?from=a&from=b`
  const s = v.trim();
  return s === "" ? null : s;
}
