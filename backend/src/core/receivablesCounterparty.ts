import type { ClientFacts } from "./receivablesFacts.js";

/** Одна юрособа в розкладі: скільки рахунків і на скільки. */
export interface CounterpartyPart {
  /** `client_key_raw`; порожній рядок — юрособи в рахунку не вказано. */
  key: string;
  name: string | null;
  n: number;
  amount: number;
}

/** Підпис для рахунка, у якого юрособи немає. Порожнеча мусить бути відповіддю. */
export const COUNTERPARTY_UNKNOWN = "юрособу не вказано";

/** Як показати назву юрособи, коли її немає. */
export function counterpartyLabel(p: { key: string; name: string | null }): string {
  const n = (p.name ?? "").trim();
  return n === "" ? COUNTERPARTY_UNKNOWN : n;
}

/**
 * Розклад по юрособах, від більшої суми до меншої.
 *
 * 🔴 ПОРЯДОК МУСИТЬ БУТИ ПОВНИЙ, А НЕ «ЗА СУМОЮ». Дві юрособи з однаковою сумою
 * інакше міняються місцями від перезавантаження — і рядок «стрибає» без жодної
 * зміни в даних. Другий ключ сортування (`key`) робить порядок відтворюваним.
 */
export function counterpartyBreakdown(c: ClientFacts | null | undefined): CounterpartyPart[] {
  if (!c) return [];
  return Object.entries(c.counterparty)
    .map(([key, v]) => ({ key, name: v.name, n: v.n, amount: v.amount }))
    .sort((a, b) => (b.amount - a.amount) || (a.key < b.key ? -1 : a.key > b.key ? 1 : 0));
}

/** Копійчана межа рівності — щоб плаваюча арифметика не оголошувала розбіжність. */
export const RECONCILE_EPS = 0.01;

export interface Reconciled {
  parts: CounterpartyPart[];
  /** Скільки з суми рядка НЕ рознесено по юрособах. Може бути й відʼємним. */
  remainder: number;
  /** Розклад сходиться з рядком. */
  ok: boolean;
  /**
   * Чи показувати розклад узагалі. Рішення власника: ЛИШЕ коли юросіб більше
   * однієї — інакше 61 рядок із 63 отримав би зайвий підпис «сам про себе».
   */
  show: boolean;
}

/**
 * Звірка розкладу із сумою рядка.
 *
 * 🔴 ЗАЛИШОК НЕ ХОВАЄТЬСЯ І НЕ ЗАОКРУГЛЮЄТЬСЯ ДО НУЛЯ. Він або 0, або його
 * називають числом. Мовчазне приховання дало б рівно ту помилку, заради якої
 * писався цей модуль: сума, під якою стоять доданки, що їй не дорівнюють.
 */
export function reconcileBreakdown(rowAmount: number, parts: CounterpartyPart[]): Reconciled {
  const sum = parts.reduce((a, p) => a + p.amount, 0);
  const remainder = rowAmount - sum;
  return {
    parts,
    remainder,
    ok: Math.abs(remainder) < RECONCILE_EPS,
    show: parts.length > 1,
  };
}
