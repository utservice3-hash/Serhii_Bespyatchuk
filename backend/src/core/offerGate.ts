/**
 * 🔏 ГЕЙТ ОФЕРА — новий менеджер без підписаного офера бачить лише Навчання й Документи.
 *
 * Рішення власника 15.09.2026: «Без підписаного оферу немає можливості дати повний доступ
 * (правило для нових менеджерів, для поточних у системі не діє)». Уточнення Романа того ж
 * дня: «все закрито окрім навчання і документів».
 *
 * Чиста функція без БД: хто «новий» і що «закрито» — тут, щоб гейт #441b доводив правило
 * фікстурою по обидва боки межі. Чому саме ці межі:
 *  - «новий» = акаунт створений ПІСЛЯ викату цього правила (`OFFER_GATE_SINCE`). Дата,
 *    а не прапорець: поточні менеджери не мають оферів у системі, і будь-який прапорець
 *    довелося б проставляти руками всім, кого правило не стосується.
 *  - лише роль `manager`: тімліди, HR, КВП під правило не потрапляють — власник назвав
 *    менеджерів.
 *  - «підписаний» = є запис підпису на ПОТОЧНІЙ версії (той самий хеш), як у
 *    `signatureState`. Офер із новою версією без підпису знову закриває доступ.
 *
 * Це НЕ блокування «через непідписаний офер» з рішення ③ (там мова про поточних):
 * для поточних менеджерів функція завжди `false`, і саме це стереже дзеркало #441b.
 */

/** Правило діє на акаунти, створені з цієї миті (викат 1 документів v2). */
export const OFFER_GATE_SINCE = new Date("2026-09-17T00:00:00+03:00");

/** Вкладки, відкриті менеджеру до підпису офера. */
export const OFFER_GATE_TABS: readonly string[] = ["training", "documents"];

export interface OfferGateUser {
  roleKey: string;
  createdAt: Date | string;
  hasSignedOffer: boolean;
}

/** Чи чекає користувач підпису офера (і тому обмежений двома вкладками). */
export function offerPending(u: OfferGateUser, since: Date = OFFER_GATE_SINCE): boolean {
  if (u.roleKey !== "manager") return false;
  if (new Date(u.createdAt).getTime() < since.getTime()) return false;
  return !u.hasSignedOffer;
}

/**
 * Чи закритий запит для того, хто чекає офер. `tabs` — вкладки роуту з `tabsForPath`
 * (null = роут поза мапою, проходить). Відкрито, якщо ХОЧ ОДНА вкладка дозволена, як і
 * в основному tab-гейті.
 */
export function offerGateBlocks(pending: boolean, tabs: readonly string[] | null): boolean {
  if (!pending || !tabs) return false;
  return !tabs.some((t) => OFFER_GATE_TABS.includes(t));
}
