/** Один рядок джерела: яка угода і чия вона в цьому вікні. */
export interface DealRef { managerId: number | null; kommoId: number }

/** `managerId|kommoId` — ключ пари, бо та сама угода в різних менеджерів це різні факти. */
const key = (d: DealRef): string => `${d.managerId ?? "—"}|${d.kommoId}`;

/**
 * Порушення включення: що є у ВКЛАДЕНОМУ вікні й чого немає в ОХОПЛЮЮЧОМУ.
 * Порожній масив = включення тримається.
 */
export function subsetViolations(inner: DealRef[], outer: DealRef[]): DealRef[] {
  const have = new Set(outer.map(key));
  const seen = new Set<string>();
  const out: DealRef[] = [];
  for (const d of inner) {
    const k = key(d);
    if (have.has(k) || seen.has(k)) continue;
    seen.add(k); out.push(d);
  }
  return out;
}

/**
 * 🧪 СТАРА ФОРМА — лишена НАВМИСНО, і тільки для дзеркала.
 *
 * Дзеркало мусить довести не лише «нова форма зелена», а й **що стара на тих самих
 * даних була б червона**. Без цього «зелено» не відрізнити від «перевірка нічого не
 * перевіряє»: включення тривіально істинне, якщо вікно порожнє.
 * ⚠️ У продуктовому коді цією функцією не користуватись: вона стверджує монотонність,
 * якої знакова величина не має. Тут вона — предмет досліду, а не правило.
 */
export function sumFormWouldFail(innerSum: number, outerSum: number): boolean {
  return innerSum > outerSum;
}
