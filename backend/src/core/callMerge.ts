/** Вікно склейки. Рішення власника 07.08.2026; не міняти без нового рішення. */
export const CALL_MERGE_WINDOW = "120 seconds";

/**
 * Ключ, за яким два записи вважаються плечима одного дзвінка. Іменований, щоб
 * «за чим ми групуємо» не доводилось вишукувати в трьох різних SQL.
 */
export const callMergeKey = (a: string): string[] =>
  [`${a}.manager_id`, `${a}.client_phone`, `(${a}.billsec > 0)`];

/**
 * ФОРМА ДЛЯ АГРЕГАТІВ: віконна функція. Віддає вираз `gap`; рядок є ПЕРШИМ плечем,
 * коли `gap IS NULL OR gap > вікно` (див. `mergedLagFirst`).
 *
 * 🔴 `ORDER BY calldate, uniqueid` — не для краси: без другого ключа порядок на
 * однакових позначках не визначений, і те саме питання двічі поспіль може дати
 * різні числа.
 */
export const mergedLagGapExpr = (a: string): string =>
  `${a}.calldate - LAG(${a}.calldate) OVER (`
  + `PARTITION BY ${callMergeKey(a).join(", ")} ORDER BY ${a}.calldate, ${a}.uniqueid)`;

/** Умова «це ПЕРШЕ плече» для форми з віконною функцією (по вже обчисленому `gap`). */
export const mergedLagFirst = (gap = "gap"): string =>
  `(${gap} IS NULL OR ${gap} > interval '${CALL_MERGE_WINDOW}')`;

/**
 * ФОРМА ДЛЯ ПОРЯДКОВОГО ВІДБОРУ: корельований `NOT EXISTS`. Потрібна там, де
 * віконну функцію не застосувати — у списку рядків розкриття.
 *
 * 🔴 `(p.calldate, p.uniqueid) < (r.calldate, r.uniqueid)` — рядкове порівняння, а
 * не `p.calldate < r.calldate`. Саме воно і розводить нічию, і не дає рядкові стати
 * власним попередником. Обидві властивості потрібні одночасно.
 */
export const mergedNotExists = (a: string, src = "ringostat_calls"): string =>
  `NOT EXISTS (SELECT 1 FROM ${src} p
                WHERE p.manager_id = ${a}.manager_id
                  AND p.client_phone IS NOT DISTINCT FROM ${a}.client_phone
                  AND (p.billsec > 0) = (${a}.billsec > 0)
                  AND (p.calldate, p.uniqueid) < (${a}.calldate, ${a}.uniqueid)
                  AND ${a}.calldate - p.calldate <= interval '${CALL_MERGE_WINDOW}')`;
