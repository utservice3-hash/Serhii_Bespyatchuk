import { test } from "node:test";
import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import path from "node:path";
import { wireState, wireValue, DEFAULT_PLAN_MIN, PLAN_MIN_BOUNDS } from "./settingWire.js";

/**
 * 🔌 #276–#276c — ТРИ СТАНИ НАЛАШТУВАННЯ, і кожен зі своїм сенсом.
 *
 * 🔴 ЧОМУ ЦЕ НЕ ФОРМАЛЬНІСТЬ. Доки поля не було на екрані, стан «не задано» жив вічно.
 * Щойно екран почав слати його ЗАВЖДИ, цей стан став би недосяжним — після першого
 * збереження зник би назавжди. А нуль ТУТ має власний сенс («межу свідомо знято»), тож
 * зливати його з «порожньо» не можна в жоден бік: зіллємо — або обнулимо межу всім,
 * кому поле не заповнили, або відновимо її там, де її свідомо зняли.
 */

const B = PLAN_MIN_BOUNDS;
const CUR = 30000, DEF = DEFAULT_PLAN_MIN;

test("#276 ТРИ СТАНИ РОЗРІЗНЯЮТЬСЯ: немає / очистити / число", () => {
  assert.equal(wireState(undefined), "absent", "🔴 відсутнє поле перестало бути станом");
  assert.equal(wireState(null), "reset");
  assert.equal(wireState(""), "reset", "🔴 порожній рядок не читається як «очистити»");
  assert.equal(wireState("   "), "reset");
  assert.equal(wireState(0), "value", "🔴 нуль зʼїхав у «порожньо» — межу знімуть непомітно");
  assert.equal(wireState(25000), "value");
  // Три стани мусять бути РІЗНИМИ: якщо два з трьох збіглись, розрізнення немає.
  assert.equal(new Set([wireState(undefined), wireState(null), wireState(0)]).size, 3,
    "🔴 стани злились — саме цього ми й уникаємо");
});

test("#276b ЗНАЧЕННЯ: немає → поточне · очистити → ДЕФОЛТ · число → число (0 законний)", () => {
  assert.equal(wireValue(undefined, B, 25000, DEF), 25000,
    "🔴 відсутнє поле змінило значення — часткове збереження перестало бути безпечним");
  assert.equal(wireValue(null, B, 0, DEF), DEF,
    "🔴 «очистити» не повернуло дефолт — поле стало незворотним");
  assert.equal(wireValue("", B, 0, DEF), DEF);
  assert.equal(wireValue(0, B, CUR, DEF), 0,
    "🔴 нуль клампнувся — «межу знято» стало неможливо задати");
  assert.equal(wireValue(25000, B, CUR, DEF), 25000);
  // Межі: за стелю і під підлогу — клампимо, а не відкидаємо.
  assert.equal(wireValue(9_999_999, B, CUR, DEF), 1_000_000);
  assert.equal(wireValue(-5, B, CUR, DEF), 0);
});

test("#276c 🪞 ПОРОЖНІЙ РЯДОК ≠ НУЛЬ — тихий дефект, який ловить саме цей гейт", () => {
  /**
   * `Number("")` дорівнює 0. Тобто наївний розбір («як у решти полів») означав би:
   * людина стерла поле → межа 0 → поріг знято всім, без жодного рішення.
   */
  assert.notEqual(wireValue("", B, CUR, DEF), 0,
    "🔴 стерте поле дало НУЛЬ — межу знято мовчки, бо `Number(\"\")` це 0");
  assert.equal(wireValue("", B, CUR, DEF), DEF);
  // 🪞 І навпаки: явний нуль НЕ має ставати дефолтом, інакше межу неможливо зняти.
  assert.notEqual(wireValue(0, B, CUR, DEF), DEF,
    "🔴 явний нуль з’їхав у дефолт — рішення власника «межу знято» нездійсненне");
});

/**
 * #276d — ДЕФОЛТ У КОДІ Й ДЕФОЛТ НА ЕКРАНІ — ОДНЕ ЧИСЛО.
 * Гейт `#4.1` знято (див. `RETIRED_GATES`): він стверджував `planMinPerManager === 30000`,
 * а власник тепер може змінити це число з екрана — гейт червонів би на законній дії.
 * Замість «яке саме число» тут стережеться ДІАПАЗОН і те, що дефолт узагалі існує.
 */
test("#276d ДЕФОЛТ ІСНУЄ І ЛЕЖИТЬ У ДОЗВОЛЕНОМУ ДІАПАЗОНІ", () => {
  const d = DEFAULT_PLAN_MIN;
  assert.equal(typeof d, "number", "🔴 дефолт межі зник із коду — «повернути дефолт» нічого не поверне");
  assert.ok(d >= B.min && d <= B.max, `🔴 дефолт ${d} поза межами [${B.min}, ${B.max}]`);
  // ⚠️ Свідомо НЕ стверджуємо «== 30000»: саме це й було в #4.1, і саме тому він знятий.
  assert.equal(wireValue(null, B, 999, d), d, "🔴 «очистити» не повертає той самий дефолт, що в коді");
});

/**
 * #276e — БЕКФІЛ НЕ МАЄ ЗАШИТОГО ПОРОГА.
 * Був `COALESCE(…, 30000)`: зникне рядок `app_settings` — і межа мовчки повернулась би
 * на наступному ж викаті, без чийогось рішення.
 */
test("#276e БЕКФІЛ ЧИТАЄ ПОРІГ ЛИШЕ З НАЛАШТУВАНЬ, без зашитого числа", () => {
  const sql = readFileSync(path.join(import.meta.dirname, "..", "db", "schema.sql"), "utf8");
  const stmt = /UPDATE plan_formation pf[\s\S]*?;/.exec(sql);
  assert.ok(stmt, "🔴 бекфіл `below_min` не знайдено — гейт втратив предмет");
  assert.ok(/planMinPerManager/.test(stmt![0]),
    "🔴 бекфіл більше не читає налаштування — поріг узявся невідомо звідки");
  assert.ok(!/COALESCE[^)]*30000|,\s*30000\s*\)/.test(stmt![0]),
    "🔴 у бекфіл повернувся зашитий поріг — межа відновиться сама, без рішення людини");
});
