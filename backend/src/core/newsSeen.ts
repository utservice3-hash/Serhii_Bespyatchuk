import { NEWS_ALIVE } from "./newsVisibility.js";

/**
 * 🔔 «Є ЩОСЬ НОВЕ ПІСЛЯ МОГО ОСТАННЬОГО ВІЗИТУ» — одна мітка часу на людину.
 *
 * Власник 07.09.2026: «хто відкриває дашборд і бачить новини, які не відкривав — вони
 * мають підсвічуватись, як непрочитані повідомлення… відкрив, подивився — все».
 *
 * 🔴 ЧОМУ МІТКА ЧАСУ, А НЕ ТАБЛИЦЯ `news_reads`. Питання, яке ставить власник, — «чи є
 * нове», а не «хто саме що читав». Таблиця пар (людина × новина) відповідає на друге,
 * коштує рядком на кожен перегляд і потребує чистки; мітка відповідає на перше однією
 * колонкою. Знадобиться друге питання — заведемо таблицю тоді, і це буде видно з потреби,
 * а не з нашого припущення про майбутнє.
 *
 * 🔴 `null` ОЗНАЧАЄ «НІКОЛИ НЕ ВІДКРИВАВ», І ЦЕ НЕ ТЕ САМЕ, ЩО «ДАВНО». Нова людина
 * бачить усе непрочитаним — так і має бути. Але НАЯВНИМ користувачам колонка ставиться
 * зі значенням `now()` у самій міграції: інакше в день викату кожен отримав би десятки
 * непрочитаних за всю історію й навчився б ігнорувати значок із першого дня.
 */
/* 🔴 ВИДАЛЕНЕ НЕ РАХУЄТЬСЯ. Лічильник і список читають ОДНЕ правило видимості: інакше
   значок рахував би те, чого людина не може відкрити, і не згасав би НІКОЛИ — найгірший
   стан для позначки, бо її просто перестають помічати. */

export function isUnread(createdAt: Date | string, seenAt: Date | string | null): boolean {
  if (seenAt == null) return true;
  return new Date(createdAt).getTime() > new Date(seenAt).getTime();
}

/** Скільки новин зʼявилось після візиту. `$1` — мітка часу людини (може бути NULL). */
export const UNREAD_COUNT_SQL = `
  SELECT count(*)::int AS n FROM news
   WHERE ${NEWS_ALIVE}
     AND ($1::timestamptz IS NULL OR created_at > $1::timestamptz)`;

/**
 * ⚠️ ПОЗНАЧАЄМО ЧАСОМ СЕРВЕРА, А НЕ ЧАСОМ КЛІЄНТА. Годинник браузера буває зсунутий на
 * години; узявши його, ми або ховали б нові новини, або показували б давно прочитані.
 */
export const MARK_SEEN_SQL = `UPDATE users SET news_seen_at = now() WHERE id = $1`;

/**
 * 🔔 НЕПРОЧИТАНЕ ПРОТИ МІТКИ БРАУЗЕРА, А НЕ КОЛОНКИ АКАУНТА (08.09.2026).
 *
 * 📐 ПРИВІД, названий власником: «коли хтось один читає новину, вона для всіх перестає
 * підсвічуватися». Заміряно в коді: мітка «побачив» лежала в `users.news_seen_at` —
 * ОДИН рядок на обліковий запис. Там, де кілька людей заходять під спільним логіном,
 * перший, хто відкрив новини, гасив значок усім, хто цим логіном користується. Сам код
 * був per-user коректний; ділив підсвітку саме спільний акаунт.
 *
 * 🔴 ЧОМУ ПО `id`, А НЕ ПО ЧАСУ. Мітку тепер тримає браузер (`localStorage`), тобто вона
 * стає per-device й спільний логін її не поділяє. Але клієнтський ЧАС брати не можна —
 * рівно з тієї причини, що записана над `MARK_SEEN_SQL`: годинник браузера зсунутий.
 * `id` присвоює сервер, монотонно, тож «долистав до id X» не залежить від годинника
 * взагалі. `$1` — найбільший id, який браузер уже бачив (0 = не бачив нічого).
 *
 * 🔴 ВИДАЛЕНЕ НЕ РАХУЄТЬСЯ — той самий `NEWS_ALIVE`, що й у списку та старому лічильнику
 * (див. `newsVisibility.ts`): значок не повинен рахувати те, чого людина не може відкрити.
 */
export const UNREAD_BY_ID_SQL = `
  SELECT count(*)::int AS n FROM news
   WHERE ${NEWS_ALIVE} AND id > $1`;

/** «Долистав досюди» — найбільший ЖИВИЙ id. Береться в ту саму мить, що й лічильник. */
export const MAX_ALIVE_ID_SQL = `SELECT COALESCE(max(id), 0)::int AS max_id FROM news WHERE ${NEWS_ALIVE}`;
