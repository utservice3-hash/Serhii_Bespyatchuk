/**
 * 🔔 «Є ЩОСЬ НОВЕ ПІСЛЯ МОГО ОСТАННЬОГО ВІЗИТУ» — одна мітка часу на людину.
 *
 * Власник 07.09.2026: «хто відкриває дашборд і бачить новини, які не відкривав — вони
 * мають підсвічуватись, як непрочитані повідомлення… відкрив, подивився — все».
 *
 * 🔴 ЧОМУ МІТКА ЧАСУ, А НЕ ТАБЛИЦЯ `news_reads`. Питання, яке ставить власник, — «чи є
 * нове», а не «хто саме що читав». Таблиця пар (людина × новина) відповідає на друге,
 * коштує рядком на кожен перегляд і потребує чистки; мітка відповідає на перше однією
 * колонкою. Знадобиться друге питання — заведемо таблицю тоді, і це буде видно з потреби,
 * а не з нашого припущення про майбутнє.
 *
 * 🔴 `null` ОЗНАЧАЄ «НІКОЛИ НЕ ВІДКРИВАВ», І ЦЕ НЕ ТЕ САМЕ, ЩО «ДАВНО». Нова людина
 * бачить усе непрочитаним — так і має бути. Але НАЯВНИМ користувачам колонка ставиться
 * зі значенням `now()` у самій міграції: інакше в день викату кожен отримав би десятки
 * непрочитаних за всю історію й навчився б ігнорувати значок із першого дня.
 */
export function isUnread(createdAt: Date | string, seenAt: Date | string | null): boolean {
  if (seenAt == null) return true;
  return new Date(createdAt).getTime() > new Date(seenAt).getTime();
}

/** Скільки новин зʼявилось після візиту. `$1` — мітка часу людини (може бути NULL). */
export const UNREAD_COUNT_SQL = `
  SELECT count(*)::int AS n FROM news
   WHERE $1::timestamptz IS NULL OR created_at > $1::timestamptz`;

/**
 * ⚠️ ПОЗНАЧАЄМО ЧАСОМ СЕРВЕРА, А НЕ ЧАСОМ КЛІЄНТА. Годинник браузера буває зсунутий на
 * години; узявши його, ми або ховали б нові новини, або показували б давно прочитані.
 */
export const MARK_SEEN_SQL = `UPDATE users SET news_seen_at = now() WHERE id = $1`;
