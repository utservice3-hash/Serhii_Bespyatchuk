/**
 * Скільки заплачено перевізнику за цією угодою.
 *
 * 📐 Заміряно по 279 угодах дебіторки: тип заповнений у 195 · тип є, а суми
 * немає — **0** · лише «загальна» 126 · лише «готівка» 65 · **обидві 4**.
 *
 * Останні чотири — складена виплата: частину віддали готівкою, частину
 * безготівково. Тому сума — це СУМА ОБОХ, а не «та, що пасує типу»: вибір
 * однієї недорахував би саме там, де платили двома шляхами.
 *
 * `null` означає «не знаємо», а не нуль. Це різні твердження, і плутати їх не
 * можна: угод без типу — 84 із 279, і намалювати їм 0 ₴ означало б заявити,
 * що перевізник не отримав нічого.
 */
export function carrierPaymentFrom(f: {
  type: string | null; cash: number | null; general: number | null;
}): number | null {
  if (f.type == null || f.type.trim() === "") return null;
  const pos = (v: number | null) => (v != null && Number.isFinite(v) && v > 0 ? v : 0);
  const sum = pos(f.cash) + pos(f.general);
  return sum > 0 ? sum : null;
}

/**
 * 🔴 СТЕЛЯ ЗАПИТУ ПО id — ЯВНА, БО ПЕРЕВИЩЕННЯ НЕ ПАДАЄ, А ТИХО НЕДОРАХОВУЄ.
 *
 * Kommo `/leads?limit=250` без пагінації віддає перші 250 і виглядає успішним.
 * Заміряно на собі 25.08.2026: передав 279 id — отримав 250, і мало не порахував
 * частки по обрізаній вибірці. Обрізаний результат гірший за помилку: помилку видно.
 */
export const LEADS_BY_IDS_MAX = 250;

export function assertLeadIdsWithinLimit(count: number): void {
  if (count > LEADS_BY_IDS_MAX) {
    throw new Error(
      `fetchLeadsByIds: ${count} id за раз, а стеля ${LEADS_BY_IDS_MAX} — `
      + "Kommo мовчки віддав би лише перші 250. Дрібніть виклик: ids.slice(i, i + 250)."
    );
  }
}

/**
 * 🔴 «НЕ ЗНАЄМО» І «НУЛЬ» — РІЗНІ ВІДПОВІДІ, І ЖИВУТЬ ВОНИ ТУТ, А НЕ В `client.ts`.
 *
 * Правило винесене в чисту функцію з двох причин, і друга важливіша за першу:
 * (а) `kommo/client.ts` тягне `config.js`, який кидає без `KOMMO_*` ще НА
 *     ІМПОРТІ — гейт не зміг би дістати з нього навіть чисту функцію;
 * (б) поки правило жило рядком усередині екстрактора, воно було НЕВИДИМЕ:
 *     `Number(fieldText(…) ?? "")` виглядає бездоганно, а дає `Number("")` → 0.
 *     Тобто «поля в угоді немає» і «платити перевізнику не треба» лягали в базу
 *     ОДНАКОВИМ значенням, і ре-бекфіл їх уже не розрізнить — ознаки, з якого
 *     боку прийшов нуль, не лишається. Заміряно 26.08.2026: 11 699 нулів проти
 *     1 193 додатних; за серпень 5 754 з 8 672 угод.
 *
 * Нуль тут ЛЕГІТИМНИЙ («перевізник наш, платити нікому»), тому мовчазне
 * перетворення відсутності на нуль не просто неточність — це знищення
 * інформації, що йшло по колу кожні 30 хв разом із синком.
 */
export function carrierObligationFrom(text: string | null | undefined): number | null {
  if (text == null) return null;                 // поля немає → «не знаємо»
  const t = String(text).trim();
  if (!t.length) return null;                    // порожнє → теж «не знаємо»
  const v = Number(t);
  return Number.isFinite(v) ? v : null;          // «абв» → «не знаємо», не нуль
}

/**
 * Повна сума угоди для клієнта («Приход 1») — ЗНАМЕННИК маржинальності.
 *
 * ⚠️ ТУТ НУЛЬ ВІДКИДАЄТЬСЯ, І ЦЕ ІНША ПІДСТАВА, НЕ ТА, ЩО ВИЩЕ. Нуль-знаменник
 * непридатний арифметично, тож `0` і «немає» тут справді один випадок. Сусідній
 * `carrierObligationFrom` уцілів у проді лише тому, що цю умову хтось написав
 * заради ділення, — тобто це ПОБІЧНИЙ ЕФЕКТ, а не сторож. Копіювати його як
 * зразок «як правильно» не можна: правильно те, що вище.
 */
export function clientPaymentFrom(text: string | null | undefined): number | null {
  if (text == null) return null;
  const v = Number(String(text).trim());
  return Number.isFinite(v) && v > 0 ? v : null;
}
