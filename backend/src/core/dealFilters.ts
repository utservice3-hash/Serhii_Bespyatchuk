export const AUTODEAL_PREFIX = "Автосделка:";

/**
 * `alias` — аліас таблиці `deals` у запиті.
 * `COALESCE` обовʼязковий: угода з `NULL`-назвою дала б `NULL`, і рядок випав би
 * з ОБОХ гілок — тиха втрата, яку на екрані не побачити.
 */
export const notAutodealSql = (alias = "d"): string =>
  `COALESCE(${alias}.name, '') NOT ILIKE '${AUTODEAL_PREFIX}%'`;
