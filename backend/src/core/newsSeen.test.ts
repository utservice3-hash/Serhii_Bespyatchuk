import { test } from "node:test";
import assert from "node:assert/strict";
import { isUnread, unreadSinceQuery, MARK_SEEN_SQL } from "./newsSeen.js";

/**
 * #356 — НЕПРОЧИТАНЕ РАХУЄТЬСЯ ВІД ВІЗИТУ, І ОБИДВА БОКИ МЕЖІ ПОТРІБНІ.
 *
 * 🔴 Односторонній гейт («новіша рахується») зеленів би й на коді, що рахує ВСЕ підряд —
 * тобто значок ніколи б не гаснув, а це найгірший із можливих станів: людина навчиться
 * його ігнорувати, і справжня новина потоне разом із рештою.
 *
 * ⚠️ `null` — це «ніколи не відкривав», а не «давно». Для нової людини все нове, і це
 * правильно; наявним користувачам мітку ставить МІГРАЦІЯ (`DEFAULT now()`), інакше в
 * день викату кожен отримав би десятки непрочитаних за всю історію.
 */
test("#356 новіша за візит — непрочитана, старіша — ні, без візиту — усе нове", () => {
  const seen = "2026-09-07T10:00:00Z";
  assert.equal(isUnread("2026-09-07T10:00:01Z", seen), true,
    "🔴 новина, що зʼявилась ПІСЛЯ візиту, не рахується — значок не спрацює ніколи");
  assert.equal(isUnread("2026-09-07T09:59:59Z", seen), false,
    "🔴 стара новина рахується непрочитаною — значок не згасне після відкриття, "
    + "і людина навчиться його ігнорувати");
  assert.equal(isUnread(seen, seen), false,
    "🔴 рівність часів дала непрочитане — власна ж мітка одразу створює нове");
  assert.equal(isUnread("2020-01-01T00:00:00Z", null), true,
    "🔴 без візиту нічого не рахується — нова людина не побачить жодної новини");
});

/**
 * #356b — 🪞 ДЗЕРКАЛО: SQL питає те саме, що чиста функція, і мітку ставить СЕРВЕР.
 *
 * Без цієї половини `#356` доводив би лише свою функцію, тоді як екран рахує запитом —
 * два різні правила під одним підписом розійшлись би тихо. А час клієнта в мітці зсунув
 * би межу на години: браузерний годинник буває неточним, і тоді або нові новини
 * ховаються, або давно прочитані знову спливають.
 */
test("#356b 🪞 запит рахує від тієї самої межі, а мітка — часом сервера", () => {
  // Запит став БІЛДЕРОМ (адресність, 09.09.2026): твердження ті самі, читаємо
  // згенерований текст. Порожні вкладки тут доречні — гейт про межу ЧАСУ, не про аудиторію.
  const UNREAD_COUNT_SQL = unreadSinceQuery(null, []).text;
  assert.match(UNREAD_COUNT_SQL, /created_at > \$1/,
    "🔴 запит рахує не «пізніше за візит» — розійдеться з правилом, яке перевіряє #356");
  assert.match(UNREAD_COUNT_SQL, /\$1::timestamptz IS NULL OR/,
    "🔴 у запиті немає гілки «ніколи не відкривав» — нова людина побачить нуль нового");
  assert.match(MARK_SEEN_SQL, /news_seen_at = now\(\)/,
    "🔴 мітка ставиться не часом сервера — зсунутий годинник браузера або сховає нові "
    + "новини, або поверне давно прочитані");
});
