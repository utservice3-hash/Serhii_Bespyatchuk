import { test } from "node:test";
import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import path from "node:path";
import { monthKeys, expectedSplitByMonth, forecastMonth, paceProjection } from "./forecast.js";

/**
 * K8 — ПРОГНОЗ КВП РАХУЄТЬСЯ ТИМ САМИМ КОДОМ, ЩО ПРОГНОЗ КАРТКИ МЕНЕДЖЕРА.
 *
 * 🔴 ПРИВІД, І ВІН ІСТОРИЧНИЙ. 06.08.2026 власник ухвалив: прогноз = факт ② +
 * очікування з ПЛАНОВОЮ ДАТОЮ цього місяця, добір з формули геть. Рішення доїхало
 * до картки менеджера й **не доїхало** до Звіту КВП, який лишився на
 * `факт + УСЯ зона + добір`. Заміряно на проді 20.08.2026: КВП показував
 * **2 748 167 ₴ (99.6% плану)**, формула картки — **2 306 403 ₴ (84%)**.
 *
 * Це та сама пастка, що «сер.чек ÷ авто»: ухвалене й забуте гірше за неухвалене.
 * Гейта на забуте рішення не буває — буває гейт на ДВІ КОПІЇ формули. Він тут.
 */

const SRC = path.join(import.meta.dirname, "..", "..", "src");
const routes = () => readFileSync(path.join(SRC, "routes", "dashboard.ts"), "utf8");

test("K8 ФОРМУЛА ПРОГНОЗУ — одна, і обидві поверхні кличуть саме її", () => {
  const s = routes();
  // Обидві поверхні — через спільний модуль.
  const calls = (s.match(/forecast\.forecastMonth\(/g) ?? []).length;
  assert.equal(calls, 2,
    `🔴 спільну формулу кличуть ${calls} рази, а поверхонь дві (картка менеджера у `
    + "/report-plan і Звіт КВП). Друга копія — це рівно те, через що рішення 06.08 "
    + "доїхало на один екран і не доїхало на другий");
  const splits = (s.match(/forecast\.expectedSplitByMonth\(/g) ?? []).length;
  assert.equal(splits, 2, `🔴 бакетування планових дат живе не в одному місці (${splits} виклики)`);

  // 🔴 І ЖОДНА з них не рахує старою формулою.
  assert.ok(!/projected: projection\.projected/.test(s),
    "🔴 КВП знову віддає `projection.projected` — це `факт + УСЯ зона + добір` "
    + "(buildProjection), тобто формула, скасована 06.08.2026");
  // Добір лишається ВИДИМИМ, але поруч, а не всередині прогнозу.
  assert.match(s, /dobir: Math\.round\(projection\.dobir\)/,
    "🔴 добір зник з відповіді КВП — його прибрали з ПРОГНОЗУ, а не з екрана");
});

test("K8b ФОРМУЛА: завершений місяць нічого не очікує, добір не додається", () => {
  assert.equal(forecastMonth(1_388_965, 917_438, true), 2_306_403,
    "🔴 прогноз ≠ факт + очікування цього місяця (контрольне число заміру 20.08.2026)");
  // 🔒 Завершений місяць = факт. Додати туди зону означало б домалювати гроші в минуле.
  assert.equal(forecastMonth(1_388_965, 917_438, false), 1_388_965,
    "🔴 у завершений місяць додається очікування — прогноз домальовує минуле");
  // Добір у формулу не входить у принципі: третього аргументу під нього немає.
  assert.equal(forecastMonth.length, 3, "🔴 сигнатура формули змінилась — перевір, чи не заїхав добір");
});

test("K8c БАКЕТУВАННЯ ПЛАНОВИХ ДАТ — за КИЇВСЬКИМ місяцем, чуже не зараховується", () => {
  const { curYm, nextYm } = monthKeys("2026-08-20");
  assert.equal(curYm, "2026-08");
  assert.equal(nextYm, "2026-09");
  // Грудень → січень наступного року: місяць не можна нарощувати простим +1.
  assert.equal(monthKeys("2026-12-31").nextYm, "2027-01", "🔴 перехід через рік зламано");

  const rows = [
    { managerId: 1, day: "2026-08-05", sum: 100 },
    { managerId: 1, day: "2026-08-30", sum: 50 },
    { managerId: 1, day: "2026-09-02", sum: 70 },
    { managerId: 1, day: "2026-07-30", sum: 999 },   // МИНУЛИЙ місяць — у прогноз не йде
    { managerId: 2, day: "2026-08-11", sum: 30 },
  ];
  const m = expectedSplitByMonth(rows, "2026-08-20");
  // ⚠️ Форма розширилась третім числом 07.09.2026, ЗМІСТ гейта — ні: `thisMonth`
  //    і `nextMonth` тут ті самі 150/70 і 30/0, що були до зміни. Саме це і є
  //    доказ, що показ простроченого не зрушив ПРОГНОЗ (рішення власника 06.08).
  assert.deepEqual(m.get(1), { pastMonths: 999, thisMonth: 150, nextMonth: 70 });
  assert.deepEqual(m.get(2), { pastMonths: 0, thisMonth: 30, nextMonth: 0 });
  // 🪞 Дзеркало: прострочене НЕ падає мовчки в поточний місяць — інакше прогноз
  //    обіцяв би гроші за домовленістю, термін якої вийшов (заміряно: 163 записи).
  assert.equal([...m.values()].reduce((a, v) => a + v.thisMonth, 0), 180,
    "🔴 у «цей місяць» затесались дні поза ним");
});

test("K8d ТЕМП — окреме число, і воно не вигадується на порожньому місці", () => {
  // Контрольне число заміру 20.08.2026: 1 388 965 ₴ за 14 із 21 робочого дня.
  assert.equal(paceProjection(1_388_965, 14, 21), 2_083_448);
  // 🔒 Жодного робочого дня не минуло → «—», а не 0 і не ділення на нуль: показувати
  //    «0% плану» першого числа означало б вигадати тривогу.
  assert.equal(paceProjection(0, 0, 21), null);
  assert.equal(paceProjection(100, 5, 0), null);
});

/**
 * 🗓 #357 / #357b / #357c — ТРЕТЄ ЧИСЛО «З МИНУЛИХ МІСЯЦІВ», І ЙОГО МЕЖА.
 *
 * 📐 ПРИВІД, ЗАМІРЯНИЙ 07.09.2026. Яцик: «пише, що очікування на цей місяць 18 450,
 * а в CRM у мене 98 000». У нього 43 угоди зони, з них **37 на 67 274 ₴ із СЕРПНЕВОЮ
 * плановою датою** — не поточний місяць і не наступний, отже не показані НІДЕ. По
 * відділу того ж дня: 301 угода / 747 252 ₴, тобто 67.1% зони.
 *
 * 🔴 МЕЖА — МІСЯЦЬ, А НЕ «СЬОГОДНІ», і це рішення власника, а не зручність. Тому
 * гейтів три, і другий важливіший за перший: він стереже НЕ нову фічу, а те, що
 * вона нічого не зламала.
 */
test("#357 МИНУЛІ МІСЯЦІ — окреме число, і воно не бере з поточного місяця нічого", () => {
  const today = "2026-09-07";   // день заміру у Яцика

  // ① Серпневий день → минулі місяці. До 07.09.2026 він не потрапляв у жодне число.
  const серпень = expectedSplitByMonth([{ managerId: 7, day: "2026-08-29", sum: 67274 }], today);
  assert.deepEqual(серпень.get(7), { pastMonths: 67274, thisMonth: 0, nextMonth: 0 },
    "🔴 дата минулого місяця знову зникла — повернулась фільтрація за НАЗВОЮ місяця");

  // ② 🪞 ДЗЕРКАЛО, І ВОНО ГОЛОВНЕ: день ПОТОЧНОГО місяця, що вже минув, лишається
  //    в «цьому місяці». Саме такі всі 6 вересневих угод Яцика — датовані 01.09 при
  //    «сьогодні» 07.09. Візьми межу «сьогодні» — і його «цей місяць» став би 0
  //    замість 18 453 ₴, тобто зрушив би ПРОГНОЗ, ухвалений окремо 06.08.2026.
  const перше = expectedSplitByMonth([{ managerId: 7, day: "2026-09-01", sum: 18453 }], today);
  assert.deepEqual(перше.get(7), { pastMonths: 0, thisMonth: 18453, nextMonth: 0 },
    "🔴 межу зсунуто на «сьогодні» — прогноз змінився на ВСІХ екранах, а не лише показ");

  // ③ Межі по обидва боки, включно з переходом через рік (правило 11).
  const межі = expectedSplitByMonth([
    { managerId: 8, day: "2026-08-31", sum: 1 },   // останній день минулого
    { managerId: 8, day: "2026-09-01", sum: 2 },   // перший день поточного
    { managerId: 8, day: "2026-09-30", sum: 4 },   // останній день поточного
    { managerId: 8, day: "2026-10-01", sum: 8 },   // перший день наступного
  ], today);
  assert.deepEqual(межі.get(8), { pastMonths: 1, thisMonth: 6, nextMonth: 8 },
    "🔴 межа місяця зсунулась на день");
  const рік = expectedSplitByMonth([{ managerId: 9, day: "2025-12-31", sum: 5 }], "2026-01-10");
  assert.deepEqual(рік.get(9), { pastMonths: 5, thisMonth: 0, nextMonth: 0 },
    "🔴 грудень МИНУЛОГО року не порахований минулим — порівняння втратило рік");
});

test("#357b СУМА НЕ ГУБИТЬСЯ: три відра + далеке майбутнє == усі рядки", () => {
  const today = "2026-09-07";
  const rows = [
    { managerId: 1, day: "2026-06-15", sum: 11 },
    { managerId: 1, day: "2026-08-29", sum: 22 },
    { managerId: 1, day: "2026-09-01", sum: 33 },
    { managerId: 1, day: "2026-10-20", sum: 44 },
    { managerId: 2, day: "2026-12-01", sum: 55 },   // далі за наступний місяць
    { managerId: 2, day: "2026-09-30", sum: 66 },
  ];
  const m = expectedSplitByMonth(rows, today);
  const показано = [...m.values()].reduce((a, v) => a + v.pastMonths + v.thisMonth + v.nextMonth, 0);
  const усі = rows.reduce((a, r) => a + r.sum, 0);
  const далеке = rows.filter((r) => r.day.slice(0, 7) > "2026-10").reduce((a, r) => a + r.sum, 0);

  // 🔴 ІНВАРІАНТ, а не числа: межа їздить щодня, а твердження мусить лишатись тим
  //    самим. Показане + свідомо не показане далеке == усе, що прийшло.
  assert.equal(показано + далеке, усі,
    `🔴 гроші зникли між відрами: показано ${показано} + далеке ${далеке} ≠ ${усі}`);
  // 🪞 І дзеркало: «далеке» не має бути нулем, інакше інваріант вище перевіряє
  //    порожнечу й лишиться зеленим на зламаному коді (правило 11 і «порожній = провал»).
  assert.equal(далеке, 55, "🔴 у фікстурі не лишилось далекого місяця — гейт перевіряє ніщо");
});

test("#357c ДВА ПРАВИЛА РОЗХОДЯТЬСЯ СВІДОМО — і мусять розходитись саме тут", async () => {
  // 🔴 ЦЕ НЕ ДУБЛЬ #357. Там перевіряється НАШЕ правило, тут — що його НЕ звели до
  //    сусіднього. `expectSplit.expectBucketOf` (плитка КВП) міряє від «сьогодні»;
  //    ми — від початку місяця. Об'єднати їх виглядає як прибирання дублювання, а
  //    насправді це зміна прогнозу — тож нехай спроба червоніє тут, а не на екрані.
  const { expectBucketOf } = await import("./expectSplit.js");
  const today = "2026-09-07";
  const день = "2026-09-01";   // у поточному місяці, але вже минув

  assert.equal(expectBucketOf(день, today), "overdue",
    "🔴 плитка КВП перестала звати це простроченим — тоді розходження нижче безпідставне");
  assert.equal(expectedSplitByMonth([{ managerId: 1, day: день, sum: 100 }], today).get(1)?.thisMonth, 100,
    "🔴 картку менеджера звели до межі «сьогодні» — прогноз зрушив; це рішення власника, не рефакторинг");
});

/**
 * 🔌 #357e — ЧИСЛО МУСИТЬ ДОЇХАТИ ДО ВІДПОВІДІ РОУТУ, А НЕ ЛИШЕ ПОРАХУВАТИСЬ.
 *
 * 🔴 ЗНАЙДЕНО РЕЦЕНЗІЄЮ ПЕРЕД ВИКАТОМ, і діра була справжня: `#357`/`#357b`/`#357c`
 * тестують ВИКЛЮЧНО чисту функцію, а `#357d` кличе ядро НАПРЯМУ, обминаючи роут.
 * Тобто проводку не стеріг ніхто — фічу можна було вимкнути (прибрати поле з
 * відповіді), і всі чотири гейти лишились би зеленими. Рівно той клас, що «гейт
 * зелений, бо перевіряє не те місце».
 *
 * Сусідній `K8` стереже проводку прогнозу саме так — рахунком викликів у роуті.
 * Тут те саме твердження для нової величини, обома половинами: JS-розклад (картка
 * менеджера) і SQL-агрегат (КВП).
 */
test("#357e ПРОВОДКА: обидві половини «з минулих місяців» доїжджають у відповідь", () => {
  const s = routes();

  // ① SQL-половина: агрегат кличуть для команд І для менеджерів — дві поверхні КВП.
  const sql = (s.match(/metrics\.expectedPastMonthsByScope\(/g) ?? []).length;
  assert.equal(sql, 2,
    `🔴 агрегат «з минулих місяців» кличуть ${sql} раз(и), а поверхонь дві (рядок команди `
    + "і рядок менеджера у Звіті КВП). Нуль означає, що фічу вимкнули й ніхто не помітив");

  // ② JS-половина: поле рядка менеджера береться саме з `pastMonths`, а не з нуля.
  assert.match(s, /expectPastMonths: Math\.round\(expPlannedM\.get\(m\.id\)\?\.pastMonths \?\? 0\)/,
    "🔴 рядок менеджера більше не бере `pastMonths` з розкладу — число стало сталим нулем, "
    + "і жоден гейт чистої функції цього не побачить");

  // ③ Підсумок відділу — сума саме цього поля, а не чужого.
  assert.match(s, /expectPastMonths: managers\.reduce\(\(s, m\) => s \+ m\.expectPastMonths, 0\)/,
    "🔴 підсумок відділу підсумовує не те поле — Σ рядків перестане дорівнювати кільцю");

  // ④ 🪞 І ГОЛОВНЕ ДЗЕРКАЛО: сусіднє «прострочено» КВП (межа «сьогодні») лишилось
  //    на місці. Якби нове число тихо посіло його поле, два різні питання злились
  //    би в одне — те, від чого ми й розводили назви.
  assert.match(s, /expectedOverdue: delta\(current\.expected\.overdue\.sum/,
    "🔴 зникло ПЕРЕДІСНУЮЧЕ «прострочено» КВП: нове число з межею «місяць» посіло поле "
    + "величини з межею «сьогодні» — два різні питання під одним підписом");
});
