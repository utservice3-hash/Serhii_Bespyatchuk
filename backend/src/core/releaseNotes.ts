/**
 * 📰 ПІДПИСИ ЗМІН ДЛЯ НОВИНИ ПРО ВИКАТ — окремим файлом для ЛЮДЕЙ, не з комітів.
 *
 * 🔴 ЧОМУ НЕ КОМІТ-ПОВІДОМЛЕННЯ. Вони технічні за призначенням: «#352 ланцюг більше не
 * обривається після власного lockRelease» правдиве й нечитабельне для менеджера. Новина
 * адресована людям, які не знають слова «lockRelease», тож джерело тексту має бути
 * окремим — і писати його має той, хто робив зміну, у момент, коли ще памʼятає навіщо.
 *
 * 🔴 ПОРОЖНІЙ БЛОК — ЦЕ ВІДПОВІДЬ «НЕМАЄ ЩО СКАЗАТИ», А НЕ ЗБІЙ. Викат без видимих для
 * людей змін (рефакторинг, гейти, борги) не повинен породжувати новину «оновлено»: така
 * новина за тиждень навчить не читати всі інші. Тому `null` тут — штатний результат, і
 * гейт стверджує саме це, а не «порожньо = зелено».
 *
 * ⚠️ РОЗРІЗНЯЄМО ТРИ СТАНИ, а не два: файла немає · блок порожній · блок є. Перші два
 * дають однакове «новини не буде», але різні ПРИЧИНИ, і склеїти їх означало б не
 * помітити, що файл загубився при переїзді.
 */

/** Верхній блок `RELEASE_NOTES.md`: заголовок `## …` і текст до наступного `## `. */
export type ReleaseNote = {
  title: string;
  body: string;
  /** Вкладки-адресати. `null` = бачать усі (у нотатці написано `Кому: all`). */
  audience: string[] | null;
  /** Рядка `Кому:` не було ЗОВСІМ — це дефект нотатки, а не «для всіх». */
  audienceMissing: boolean;
};

/**
 * 🎯 РЯДОК «Кому:» — ОБОВʼЯЗКОВИЙ, І «ДЛЯ ВСІХ» ТЕЖ ПИШЕТЬСЯ ЯВНО (`all`).
 *
 * 🔴 ЧОМУ НЕ «НЕМАЄ РЯДКА = ДЛЯ ВСІХ». Тоді мовчання означало б одразу два різні стани —
 * «автор вирішив, що це всім» і «автор забув» — а розрізняти їх треба. Рішення власника
 * 09.09.2026: тег обовʼязковий, `all` — його законне значення.
 *
 * 📐 Що «забуде» станеться — не гіпотеза. У шапці `RELEASE_NOTES.md` першим абзацом
 * стоїть «пишемо ДЛЯ ЛЮДЕЙ, без назв файлів і термінів», і попри це ТРИ проходи поспіль
 * написали туди markdown із зірочками. Вимога, що стоїть у файлі, вже одного разу не
 * спрацювала; тому цю тримає гейт, і тримає в момент НАПИСАННЯ, а не публікації.
 */
const AUDIENCE_RE = /^\s*Кому:\s*(.+?)\s*$/m;

/** Чому новини не буде — назване, а не мовчазне `null`. */
export type NoNoteReason = "no-file" | "empty-block";

export type ParsedNotes =
  | { note: ReleaseNote; reason?: undefined }
  | { note: null; reason: NoNoteReason };

/**
 * Розбір верхнього блоку. `raw === null` означає «файла немає» — читання файла
 * лишається викликачу, щоб функція була чистою й гейт не потребував диска.
 */
export function parseReleaseNotes(raw: string | null): ParsedNotes {
  if (raw === null) return { note: null, reason: "no-file" };

  const lines = raw.split("\n");
  const start = lines.findIndex((l) => l.startsWith("## "));
  if (start === -1) return { note: null, reason: "empty-block" };

  const title = lines[start].slice(3).trim();
  const rest = lines.slice(start + 1);
  const end = rest.findIndex((l) => l.startsWith("## "));
  const body = (end === -1 ? rest : rest.slice(0, end)).join("\n").trim();

  // 🔴 Заголовок БЕЗ тіла — теж «порожній блок». Новина з самою датою в назві не каже
  // людині нічого, а виглядає як повідомлення: гірше за відсутність.
  if (!title || !body) return { note: null, reason: "empty-block" };
  const m = AUDIENCE_RE.exec(body);
  const tag = m?.[1]?.trim() ?? null;
  // Рядок-тег прибираємо з тіла: він службовий і людям у стрічці не потрібен.
  const clean = m ? body.replace(m[0], "").replace(/\n{3,}/g, "\n\n").trim() : body;
  const audience = tag === null || tag.toLowerCase() === "all"
    ? null
    : tag.split(",").map((t) => t.trim()).filter(Boolean);
  return {
    note: {
      title: toPlainText(title),
      body: toPlainText(clean),
      audience,
      audienceMissing: m === null,
    },
  };
}

/**
 * ✍️ MARKDOWN → ЗВИЧАЙНИЙ ТЕКСТ, БО СТРІЧКА НОВИН MARKDOWN НЕ РЕНДЕРИТЬ.
 *
 * 📐 ПРИВІД, ПОБАЧЕНИЙ ВЛАСНИКОМ НА ЕКРАНІ 08.09.2026. Джерело новини — файл
 * `RELEASE_NOTES.md`, тобто markdown за розширенням і за звичкою того, хто пише. А
 * рендер — `<p style={{ whiteSpace: "pre-wrap" }}>{n.body}</p>` (`Dashboard.tsx`),
 * тобто ЗВИЧАЙНИЙ ТЕКСТ: markdown-рендера в проєкті немає ЖОДНОГО (перевірено пошуком
 * `markdown|marked|remark|dangerouslySetInnerHTML` — нуль збігів). Тож `**жирний**`
 * доїжджав до людини зірочками. Заміряно: 4 новини з 4 автопублікацій, 26 пар `**`.
 *
 * 🔴 ЧОМУ ЧИСТИМО ТУТ, А НЕ «ПРОСТО НЕ ПИСАТИ MARKDOWN». Файл зветься `.md`, лежить
 * поруч із десятком інших `.md` і читається розробниками — вимагати від кожного автора
 * памʼятати, що ЦЕЙ markdown не markdown, означає покластися на дисципліну там, де
 * можна покластися на код. Помилку зробили три різні проходи поспіль, і всі три були
 * впевнені, що пишуть нормально.
 *
 * ⚠️ ЧИСТИМО ЛИШЕ ТЕ, ЩО ТОЧНО Є РОЗМІТКОЮ. Не пишемо власний markdown-парсер:
 * жирний/курсив, марковані пункти й код-лапки покривають усе, що ми реально вживаємо,
 * а решта (посилання, заголовки всередині тіла) у новинах для людей не має зʼявлятись
 * узагалі. Свідомо НЕ чіпаємо одиночну `*`: вона частіше множення чи виноска, ніж курсив.
 */
export function toPlainText(s: string): string {
  return s
    .replace(/\*\*(.+?)\*\*/gs, "$1")        // **жирний** → жирний
    .replace(/(^|\n)\s*[-*] +/g, "$1• ")     // марковані пункти → •
    .replace(/`([^`\n]+)`/g, "«$1»");        // `код` → «код»
}
