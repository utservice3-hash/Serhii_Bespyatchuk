/**
 * 🔴 ПРИМІТКА ОБОВʼЯЗКОВА, І ЦЕ ПЕРЕВІРЯЄ БД, А НЕ РОУТ.
 *
 * Роут обходить будь-який скрипт; `CHECK` — ні. Той самий прецедент, що
 * `loyalty_overrides.archive_reason` і `client_credit_limits.note`: списання без
 * «чому» через місяць нічим не відрізняється від помилки.
 *
 * Пробіли — не примітка. Умова та сама, що на сервері (`btrim(note) <> ''`).
 */
export const noteIsValid = (note: string): boolean => note.trim().length > 0;

/**
 * Скільки списано і скільки лишилось видимим.
 *
 * 🔴 СПИСАНЕ МУСИТЬ БУТИ ВИДНО. Вимога власника: поруч із сумою — «списано: N на
 * X ₴». Без цього плитка мовчки просідає, і за тиждень ніхто не пояснить, чому
 * борг зменшився. Урок заголовка «Прострочено (понад ліміт)»: число, що
 * змінилось без сліду, читається як поломка.
 */
export interface WriteoffTally {
  /** Скільки рядків списано. */
  n: number;
  /** На яку суму. */
  amount: number;
}

