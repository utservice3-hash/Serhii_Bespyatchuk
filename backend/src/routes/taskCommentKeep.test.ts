import { test } from "node:test";
import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

/**
 * 💬 #138–#139 — КОМЕНТАР ЗАДАЧІ НЕ ЗНИКАЄ ПІД ФОНОВИМ РЕФЕТЧЕМ.
 *
 * 🔴 БАГ, ЩО ЦЕ ПОРОДИВ. У Задачнику правка поля живе в ЛОКАЛЬНОМУ стані
 * (`patchTaskLocal`) і їде на сервер аж по `onBlur`. Паралельно фоновий поллер
 * робив `fetchTasks().then(setTasks)` — ЗАМІНЮВАВ увесь масив відповіддю
 * сервера. Усе набране й ще не зафіксоване зникало.
 *
 * ⚠️ І вікно вужче, ніж «45 секунд»: `usePolling` має джитер ±25% (від ~34 с) і
 * додатково стріляє на КОЖНЕ повернення фокуса вкладки. Багаторядковий коментар
 * («1. …\n2. …», а вони в Задачнику саме такі) це вікно не переживав.
 *
 * 🔴 ЧОМУ ГЕЙТ, ЯКИЙ НАПРОШУЄТЬСЯ, ЦЬОГО БАГУ НЕ ЛОВИТЬ. Перевірка «зберегти
 * коментар → прочитати назад → збігається» тут ЗЕЛЕНА: заміряно проти ЖИВОЇ бази
 * в транзакції з ROLLBACK — `UPDATE`+`SELECT` роута повертають текст байт-у-байт,
 * а в проді 232 задачі мають коментар, доданий ПІСЛЯ створення. Бек справний;
 * ламався показ. Гейт, поставлений не на ту ланку, дав би зелене світло багу.
 *
 * ✅ ТОМУ ТУТ ГАНЯЄТЬСЯ СПРАВЖНІЙ МОДУЛЬ ФРОНТУ, А НЕ ЙОГО ПЕРЕКАЗ: `.ts`
 * транспілюється на льоту й імпортується. Переписати логіку злиття «схоже» в
 * тесті означало б доводити ні про що (урок `#21c`) — саботаж у справжньому
 * файлі мусить червонити цей гейт.
 */

const FE_ROOT = new URL("../../../frontend/src/", import.meta.url);
const MERGE_TS = fileURLToPath(new URL("pages/dashboard/taskMerge.ts", FE_ROOT));
const DASH_TSX = fileURLToPath(new URL("pages/Dashboard.tsx", FE_ROOT));

/**
 * 🔴 КОМЕНТАРІ ВИРІЗАЮТЬСЯ ПЕРЕД ПОШУКОМ. У доках фіксу я цитую САМЕ хибний
 * рядок (`fetchTasks().then(setTasks)`) — без вирізання гейт ловив би цитату,
 * тобто документування помилки робило б перевірку неможливою. Той самий прийом,
 * що в `#58`.
 */
const stripComments = (src: string): string =>
  src.replace(/\/\*[\s\S]*?\*\//g, " ").replace(/(^|[^:])\/\/[^\n]*/g, "$1 ");

/** Транспіляція СПРАВЖНЬОГО модуля фронту → готовий до імпорту JS. */
async function loadMerge(): Promise<
  (prev: unknown[], incoming: unknown[], dirty: Map<number, Set<string>>) => unknown[]
> {
  const ts = (await import("typescript")).default;
  const js = ts.transpileModule(readFileSync(MERGE_TS, "utf8"), {
    compilerOptions: { module: ts.ModuleKind.ESNext, target: ts.ScriptTarget.ES2022 },
  }).outputText;
  const mod = await import(`data:text/javascript,${encodeURIComponent(js)}`);
  return mod.mergeTasksPreservingEdits;
}

const task = (id: number, comments: string | null) =>
  ({ id, title: "t", comments, priority: "medium" }) as unknown as Record<string, unknown>;

/**
 * #138 — НЕЗБЕРЕЖЕНА ПРАВКА ПЕРЕЖИВАЄ ФОНОВИЙ РЕФЕТЧ.
 *
 * 🧨 САБОТАЖ (виконано): повернути в `taskMerge.ts` просте `return incoming` —
 * гейт червоніє першою ж перевіркою, бо на екрані опиняється серверний текст.
 */
test("#138 набраний коментар не затирається відповіддю сервера", async () => {
  const merge = await loadMerge();

  // Людина набрала текст: він у локальному стані, на сервер ще НЕ пішов.
  const prev = [task(1, "новий коментар, ще не збережений"), task(2, "чужа задача")];
  const dirty = new Map([[1, new Set(["comments"])]]);
  // Поллер приносить те, що сервер знав ДО правки.
  const fresh = [task(1, "старий текст"), task(2, "чужа задача")];

  const out = merge(prev, fresh, dirty) as Record<string, unknown>[];
  assert.equal(out[0].comments, "новий коментар, ще не збережений",
    "🔴 фоновий рефетч затер незбережений коментар — це і є той баг");
  assert.equal(out[1].comments, "чужа задача",
    "🔴 постраждала задача, якої ніхто не редагував — злиття б'є занадто широко");

  // 🪞 ДЗЕРКАЛО: поле, якого НЕ чіпали, мусить оновлюватись із сервера. Без цього
  // гейт зеленів би й на «ніколи нічого не оновлювати» — тобто на мертвому екрані.
  const prev2 = [task(1, "локальний")];
  const fresh2 = [{ ...task(1, "серверний"), title: "нова назва з сервера" }];
  const out2 = merge(prev2, fresh2, new Map([[1, new Set(["comments"])]])) as Record<string, unknown>[];
  assert.equal(out2[0].title, "нова назва з сервера",
    "🔴 злиття заморозило ВСЮ задачу — сервер більше не може оновити нічого");
  assert.equal(out2[0].comments, "локальний", "🔴 редаговане поле не збереглось");
});

/**
 * #138b — ПОЗНАЧКА ЗНІМАЄТЬСЯ САМА, КОЛИ СЕРВЕР НАЗДОГНАВ.
 *
 * 🔴 Без цього «бережемо локальне» перетворилось би на «не оновлюємо НІКОЛИ»:
 * задача, яку раз відредагували, назавжди перестала б бачити зміни з інших
 * пристроїв. Тобто фікс багу породив би тихішу поломку за сам баг.
 */
test("#138b коли сервер віддав те саме значення — задача повертається під оновлення", async () => {
  const merge = await loadMerge();
  const dirty = new Map([[1, new Set(["comments"])]]);

  // PATCH доїхав: сервер віддає рівно те, що лежить локально.
  const out = merge([task(1, "збережений текст")], [task(1, "збережений текст")], dirty);
  assert.equal((out as Record<string, unknown>[])[0].comments, "збережений текст");
  assert.equal(dirty.size, 0, "🔴 позначка «редагується» не знялась — задача застрягне назавжди");

  // Далі сервер оновлює вільно.
  const out2 = merge([task(1, "збережений текст")], [task(1, "змінив колега")], dirty);
  assert.equal((out2 as Record<string, unknown>[])[0].comments, "змінив колега",
    "🔴 після зняття позначки оновлення з сервера все одно не проходить");
});

/**
 * #139 — ПОЛЛЕР СПРАВДІ ХОДИТЬ ЧЕРЕЗ ЗЛИТТЯ, А НЕ ПОВЗ НЬОГО.
 *
 * 🔴 Правильна чиста функція нічого не варта, поки виклик іде повз неї. Саме так
 * баг і виглядав: `patchTaskLocal` був бездоганний, а поруч стояв
 * `fetchTasks().then(setTasks)`, який його стирав.
 *
 * 🧨 САБОТАЖ (виконано): повернути `.then(setTasks)` у поллері задач → червоніє.
 */
test("#139 фоновий рефетч задач не замінює стан навпростець", async () => {
  const src = stripComments(readFileSync(DASH_TSX, "utf8"));

  // 🔴 ЦІЛИМОСЬ У ФОНОВИЙ РЕФЕТЧ, А НЕ В УСІ `fetchTasks`. Перша редакція гейта
  // забороняла будь-яке `fetchTasks().then(setTasks)` — і справедливо червоніла на
  // ПЕРВИННОМУ завантаженні секції, де заміна стану правильна: там ще нічого не
  // набрано. Гейт, що вимагає зайвого, з часом вимикають разом із потрібним.
  // Засідку робить саме поллер: він стріляє сам, без дії людини.
  const poll = /usePolling\(([\s\S]{0,600}?)\}?,\s*45000\s*\)/.exec(src)?.[1] ?? "";
  assert.ok(poll.includes("fetchTasks"), "🔴 не знайдено фонового поллера задач — гейт втратив предмет");
  assert.match(poll, /mergeTasksPreservingEdits\s*\(/,
    "🔴 поллер задач не кличе злиття — незбережені правки знову затиратимуться");
  assert.doesNotMatch(poll, /\.then\(\s*setTasks\s*\)/,
    "🔴 у поллері повернувся прямий `.then(setTasks)` — фоновий рефетч затирає набране");

  // Позначка «редагується» мусить ставитись там, де правка й народжується.
  const patchFn = /function patchTaskLocal[\s\S]{0,420}?\n  \}/.exec(src)?.[0] ?? "";
  assert.ok(patchFn, "🔴 не знайдено patchTaskLocal — гейт втратив предмет");
  // 🔴 ПЕРЕВІРЯЄМО ЗАПИС, А НЕ ЗГАДКУ ІМЕНІ. Перша редакція шукала просто
  // `dirtyTaskFields` — і лишалась зеленою, коли я саботажем прибрав САМ запис
  // позначки: ім'я нікуди не дівалось із сусіднього рядка `.get(...)`. Гейт, який
  // не може провалитись, у наборі гірший за відсутній.
  assert.match(patchFn, /dirtyTaskFields\.current\.set\(/,
    "🔴 patchTaskLocal не ЗАПИСУЄ позначку «редагується» — злиттю нічого берегти");
  assert.match(patchFn, /Object\.keys\(patch\)/,
    "🔴 позначаються не ті поля, що прийшли в patch — бережеться не те, що редагують");
});

/**
 * #139b — ЗБЕРЕЖЕННЯ, ЯКЕ ВПАЛО, ВИДНО НА ЕКРАНІ.
 *
 * 🔴 ПРИВІД. Секція кликала `updateTask` напряму — проміс БЕЗ `await` і БЕЗ
 * `.catch()`, у 17 місцях. 403 (немає доступу до задачі) чи 500 не показувались
 * ніяк: значення лишалось на екрані, і людина читала це як «збережено». Мовчазна
 * невдача гірша за видиму помилку — про неї дізнаються тоді, коли текст утрачено.
 *
 * ⚠️ ЦЕ ДРУГА ПОЛОВИНА ФІКСУ, А НЕ ОКРЕМА ОКРАСА. Після `#138` набране лишається
 * на екрані НАВІТЬ якщо PATCH не пройшов — і без тосту це виглядало б як успішне
 * збереження, тобто фікс зробив би брехню переконливішою.
 *
 * 🧨 САБОТАЖ (виконано): повернути в секції прямий `updateTask(` → червоніє;
 * прибрати `catch`/тост із `commitTask` → червоніє.
 */
test("#139b помилка збереження задачі показується, а не ковтається", async () => {
  const dash = stripComments(readFileSync(DASH_TSX, "utf8"));
  const section = stripComments(readFileSync(
    fileURLToPath(new URL("pages/dashboard/sections/TasksSection.tsx", FE_ROOT)), "utf8"));

  // 1) Секція більше не кличе сирий `updateTask` — інакше половина шляхів мовчить.
  assert.doesNotMatch(section, /\bupdateTask\s*\(/,
    "🔴 у Задачнику лишився прямий `updateTask(` — цей шлях знову ковтає 403/500");
  assert.match(section, /\bcommitTask\s*\(/,
    "🔴 секція нічого не зберігає через обгортку — гейт втратив предмет");

  // 2) Обгортка справді ЛОВИТЬ помилку і ПОКАЗУЄ її.
  const fn = /async function commitTask[\s\S]{0,900}?\n  \}/.exec(dash)?.[0] ?? "";
  assert.ok(fn, "🔴 не знайдено commitTask — немає де ловити помилку");
  assert.match(fn, /catch\s*\(/, "🔴 commitTask не має catch — помилка знову тихо зникає");
  assert.match(fn, /setToasts/,
    "🔴 помилку спіймали, але нікому не сказали — мовчазний catch гірший за його відсутність");
  assert.match(fn, /await\s+updateTask/,
    "🔴 без await відхилення промісу пройде повз catch — обгортка стане декорацією");
});
