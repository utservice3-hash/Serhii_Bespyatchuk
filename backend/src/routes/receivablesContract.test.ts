import { test } from "node:test";
import assert from "node:assert/strict";
import { readFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";

/**
 * #134 — КОНТРАКТ «ЮРОСОБИ ОБʼЄДНАНОГО КЛІЄНТА ДОХОДЯТЬ ДО ЕКРАНА».
 *
 * 🔴 НАВІЩО, І ЦЕ НЕ ГІПОТЕЗА — ЦЕ СПІЙМАНИЙ БАГ. Коміт склейки віддавав
 * `entityName`/`entityKey` з роуту, і на цьому все закінчувалось: фронт поле
 * ні типізував, ні рендерив. API був зелений, усі 262 гейти зелені, а обіцянка
 * «у розкритті видно обидві юрособи» на екрані не виконувалась ВЗАГАЛІ.
 * Знайшов скріншот приймання, не тест — тому тест тепер є.
 *
 * Той самий клас, що `#56`: **поле може лишитись у відповіді й зникнути з
 * екрана**, і жоден API-гейт цього не бачить. Тому перевіряються ОБИДВА боки —
 * роут І джерело фронта; жодного з них окремо не досить.
 *
 * 🧾 ЧЕСНА МЕЖА, та сама, що в `#56`: «дійшло до пікселя» вимагає браузера, а на
 * прод-сервері його немає. Тут «доходить до екрана» = поле згадане в компоненті
 * І колонка має свій заголовок. Залишковий розрив: якщо розмітку приберуть, а
 * рядки лишать у мертвому коді, гейт цього не побачить.
 */
const BE = fileURLToPath(new URL("../../src/routes/dashboard.ts", import.meta.url));
const API = fileURLToPath(new URL("../../../frontend/src/api.ts", import.meta.url));
const FE = fileURLToPath(new URL(
  "../../../frontend/src/pages/dashboard/sections/ReceivablesSection.tsx", import.meta.url));

test("#134 ЮРОСОБИ обʼєднаного клієнта доходять від SQL до екрана", async () => {
  const [be, api, fe] = await Promise.all([readFile(BE, "utf8"), readFile(API, "utf8"), readFile(FE, "utf8")]);

  // ── 1 · РОУТ віддає поле. Без цього фронту нема чого показувати.
  assert.ok(/ri\.client_name AS entity_name/.test(be),
    "🔴 роут /receivables/invoices більше не читає юрособу з рахунку");
  assert.ok(/entityName: x\.entity_name/.test(be),
    "🔴 юрособа не потрапляє у відповідь роуту");

  // ── 2 · API-ТИП знає поле. Якщо його нема в типі, фронт не зможе його прочитати
  //        без `any`, і зникнення пройде мовчки на компіляції.
  const iface = api.slice(api.indexOf("export interface ReceivableInvoice"));
  assert.ok(/entityName: string \| null/.test(iface.slice(0, 500)),
    "🔴 `entityName` зник із типу ReceivableInvoice — фронт осліп на це поле");

  // ── 3 · 🔴 ГОЛОВНЕ: ЕКРАН ЙОГО ПОКАЗУЄ. Саме цієї ланки бракувало.
  assert.ok(fe.includes("entityName"),
    "🔴 компонент дебіторки не згадує `entityName` — поле доїжджає в API і ВМИРАЄ ТАМ");
  assert.ok(/>Юрособа</.test(fe),
    "🔴 зник заголовок колонки «Юрособа» — юрособи всередині обʼєднаного клієнта не підписані");
  assert.ok(fe.includes("Обʼєднаний клієнт"),
    "🔴 зник рядок «Обʼєднаний клієнт — усередині N юрособи»: без нього склейка "
    + "читається як ЗНИКНЕННЯ другої компанії, а не як обʼєднання");
});

test("#134b 🪞 ДЗЕРКАЛО: колонка «Юрособа» — лише для ОБʼЄДНАНОГО клієнта", async () => {
  const fe = await readFile(FE, "utf8");
  // Без цього дзеркала `#134` зеленів би від «показувати завжди» — а в звичайного
  // клієнта колонка повторювала б його ж назву в КОЖНОМУ рядку, тобто перетворила
  // б підпис на шпалери. Це той самий урок, що «невідоме має бути видимим ТАМ,
  // де його видно»: підпис у кожному рядку перестають читати.
  assert.ok(/const merged = entities\.length > 1;/.test(fe),
    "🔴 зникло обчислення `merged` — колонка або показується завжди, або не показується ніколи");
  assert.ok(/\{merged && <th/.test(fe),
    "🔴 заголовок «Юрособа» більше не залежить від того, чи клієнт обʼєднаний");
  assert.ok(/\{merged && \(/.test(fe),
    "🔴 клітинка юрособи більше не залежить від `merged`");
});

test("#134c ПІДПИСИ ВІДПОВІДАЛЬНОГО НЕЙТРАЛЬНІ ЗА РОДОМ", async () => {
  const fe = await readFile(FE, "utf8");
  // 🔴 Спіймано тим самим скріншотом. Було «${імʼя} — звільнений» і «замість
  // звільненого ${імʼя}»: для жіночого ПІБ це давало «Гаркушина Юлія — звільненИЙ».
  // Узгодити рід із ПІБ у коді неможливо, тож формулювання мусить лишатись таким,
  // що працює для будь-кого. Перевіряємо ВІДСУТНІСТЬ поламаної форми — рівно як
  // `#56` стереже, щоб не повернувся напис «синхронізовано із Задачником».
  assert.ok(!/звільненого \$\{/.test(fe),
    "🔴 повернулась форма «замість звільненого ${імʼя}» — вона не узгоджується з жіночим ПІБ");
  assert.ok(!/\$\{c\.majorityName\} — звільнений/.test(fe),
    "🔴 повернулась форма «${імʼя} — звільнений» — для жіночого ПІБ читається неправильно");
  assert.ok(fe.includes("мажоритар не в активних"),
    "🔴 зник нейтральний підпис «мажоритар не в активних: …»");
  // 🪞 І сам стан лишається ПІДПИСАНИМ: порожнє місце читається як «нічого немає»,
  // а не як «ми знаємо, чому нікого».
  assert.ok(fe.includes("без відповідального") && fe.includes("немає менеджера в рахунках"),
    "🔴 зник підпис стану «без відповідального» або пояснення «немає менеджера в рахунках»");
});
