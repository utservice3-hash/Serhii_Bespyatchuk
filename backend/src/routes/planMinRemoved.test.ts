import { test } from "node:test";
import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import path from "node:path";

/**
 * 🔓 #275–#275c — МЕЖА 30 000 БІЛЬШЕ НЕ ЗАБОРОНЯЄ ПОДАННЯ, АЛЕ Й НЕ ЗНИКАЄ.
 *
 * Рішення власника 02.09.2026, дослівно: «логіка така що план не може бути менший
 * 30 тисяч, хочу зняти це обмеження».
 *
 * 🔴 ЧОМУ ГЕЙТИ ЧИТАЮТЬ ДЖЕРЕЛО, А НЕ ХОДЯТЬ У БД. Заборона жила у ДВОХ місцях —
 * 400 у роуті й `disabled` на кнопці — і зняти її в одному означало б лишити інше
 * лежати: кнопка ожила б, а подання падало б із 400 (або навпаки). Гейт на живих
 * даних цього не бачить: він перевіряє РЕЗУЛЬТАТ одного шляху, а не те, що обидва
 * шляхи погоджені. Тому твердження — про КОЖНЕ з двох місць поіменно.
 *
 * 📐 Ціна питання, заміряна на проді 02.09.2026: «Подати» була заблокована у
 * 12 із 12 активних менеджерів без вересневого подання; у 9 із них рекомендація = 0
 * не через погану роботу, а тому що виграних угод немає ЗА ПОБУДОВОЮ (лідоген,
 * фінанси). Тобто межа не стримувала від заниження — вона не давала завести план.
 */

const ROOT = path.join(import.meta.dirname, "..", "..");
const SRC = (rel: string): string => readFileSync(path.join(ROOT, rel), "utf8");
const ROUTE = "src/routes/plans.ts";
const FRONT = "../frontend/src/pages/dashboard/sections/PlanFormationSection.tsx";

/** Коментарі вирізаються: у доках ми цитуємо саме те, що заборонено (прийом `#203`). */
const stripComments = (src: string): string =>
  src.replace(/\/\*[\s\S]*?\*\//g, " ").replace(/(^|[^:])\/\/[^\n]*/g, "$1 ");

test("#275 СЕРВЕР більше не відмовляє поданню нижче межі", () => {
  const code = stripComments(SRC(ROUTE));
  /**
   * Твердження ЗМІСТОВЕ: немає гілки, яка порівнює подане значення з порогом і
   * повертає відмову. Не «немає слова 400» — 400 у роуті законно є на інші випадки.
   */
  const rejects = [...code.matchAll(/if\s*\(([^)]*planMinPerManager[^)]*)\)\s*\{[\s\S]{0,240}?status\(4\d\d\)/g)];
  assert.deepEqual(rejects.map((m) => m[1].trim()), [],
    "🔴 у роуті лишилась відмова, зavʼязана на planMinPerManager — кнопка ожила, а подання падатиме");
  // 🪞 Дзеркало: поріг усе ще ЧИТАЄТЬСЯ. Якби його прибрали зовсім, зник би й прапорець.
  assert.ok(/getSettings\(\)/.test(code) && /planMinPerManager/.test(code),
    "🔴 роут більше не читає поріг узагалі — разом із забороною зникне й позначка винятку");
});

test("#275b ФРОНТ більше не блокує кнопку, і попередження ЛИШАЄТЬСЯ", () => {
  const raw = SRC(FRONT);
  const code = stripComments(raw);
  const m = /const\s+blockSubmit\s*=\s*([^;]+);/.exec(code);
  assert.ok(m, "🔴 `blockSubmit` зник — гейт втратив предмет, а не підтвердив зняття");
  assert.equal(m![1].trim(), "false",
    `🔴 кнопка досі блокується виразом «${m![1].trim()}» — власник просив зняти обмеження`);
  /**
   * 🪞 ДРУГА СТОРОНА, І ВОНА ГОЛОВНА: прибрано ЗАБОРОНУ, а не ПІДКАЗКУ. Якби разом
   * із блокуванням зникло попередження, екран перестав би відрізняти виняток від норми.
   */
  assert.ok(/const\s+belowMin\s*=\s*minPer\s*>\s*0\s*&&/.test(code),
    "🔴 обчислення `belowMin` зникло — попередження про виняток більше нічим не показати");
  assert.ok(/Нижче мінімуму/.test(raw),
    "🔴 текст попередження зник з екрана — прибрали підказку замість заборони");
});

test("#275c 🪞 ПРАПОРЕЦЬ below_min І ДАЛІ СТАВИТЬСЯ СЕРВЕРОМ", () => {
  /**
   * Без цього гейта зняття заборони тихо забрало б із собою видимість винятків:
   * подання нижче межі перестали б відрізнятись від звичайних, і `#4.3` (який читає
   * прапорець на живих даних) зеленів би на порожній множині.
   */
  const code = stripComments(SRC(ROUTE));
  assert.ok(/const\s+belowMin\s*=\s*planMinPerManager\s*>\s*0\s*&&[\s\S]{0,80}?<\s*planMinPerManager/.test(code),
    "🔴 сервер більше не обчислює `below_min` — винятки стануть невидимими");
  assert.ok(/below_min/.test(code) && /INSERT INTO plan_formation/.test(code),
    "🔴 прапорець не доїжджає до INSERT — обчислили й викинули");
  // Межа обчислюється ПОРІВНЯННЯМ, а не сталою: інакше він або завжди, або ніколи.
  assert.ok(!/const\s+belowMin\s*=\s*(true|false)\s*;/.test(code),
    "🔴 `below_min` став сталою — прапорець, що завжди однаковий, не позначає нічого");
});
