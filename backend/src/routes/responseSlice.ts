/** Скільки лідів треба, щоб частка `slow/n` перестала збігатися випадково. */
export const NEED_LEADS = 20;

/** `pctSlow` може бути `null` (нуль лідів) — і це РІЗНИЦЯ, а не нуль: див. нижче. */
export interface RtRow { managerId: number; n: number; slow: number; pctSlow: number | null }

/**
 * Розбіжності розрізу з контрольним підрахунком — ЧИСТОЮ функцією.
 *
 * 🔴 НАВІЩО ВИНЕСЕНО. Дзеркало «при ДОСТАТНІЙ вибірці й порушеній властивості гейт
 * лишається ЧЕРВОНИМ» неможливо довести на живих даних у день, коли вибірки мало, —
 * а чекати місяць не є прийманням. Тут порушення підставляється фікстурою, і
 * доводиться саме те, що скіп НЕ ковтає дефект.
 */
export function responseViolations(
  rows: readonly RtRow[], want: ReadonlyMap<number, { n: number; slow: number }>,
): string[] {
  const bad: string[] = [];
  for (const r of rows) {
    const w = want.get(r.managerId);
    if (!w) { bad.push(`менеджер ${r.managerId} є в розрізі, але не в контрольному запиті`); continue; }
    if (r.n !== w.n) bad.push(`менеджер ${r.managerId}: лідів ${r.n} проти ${w.n} у контролі`);
    if (r.slow !== w.slow) bad.push(`менеджер ${r.managerId}: повільних ${r.slow} проти ${w.slow} — поріг «повільно» в ядрі більше не 60 хвилин`);
    /**
     * 🔴 `null` — НЕ нуль. Порожній знаменник не має ставати «0%»: це різні
     * твердження, і саме на такій підміні наш звіт уже одного разу показував
     * упевнений нуль там, де відповіді не існує.
     */
    const pct = w.n > 0 ? Math.round((w.slow / w.n) * 1000) / 10 : null;
    if (r.pctSlow !== pct) bad.push(`менеджер ${r.managerId}: частка ${r.pctSlow} не дорівнює slow/n = ${pct}`);
  }
  return bad;
}
