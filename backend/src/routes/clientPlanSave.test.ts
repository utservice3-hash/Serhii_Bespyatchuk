import { test } from "node:test";
import assert from "node:assert/strict";
import { needsDb } from "../testMode.js";
import { SAVE_SQL, __SAVE_SQL_NO_CAST_FOR_TESTS, SUBMIT_SQL, approveAllSql, RETURN_SQL } from "./clientPlanRules.js";

const load = async () => ({ pool: (await import("../db/pool.js")).pool });

/** Значення-пустушка: клієнта з таким ключем не існує, і транзакція все одно відкочується. */
const VALUES = ["гейт-279-неіснуючий", "2099-01-01", null, 1, "draft", 1];

/** Одна проба на обидва гейти: виконати текст і повернути код помилки, нічого не лишивши. */
const probe = async (sql: string, values: unknown[] = VALUES): Promise<{ code: string; msg: string }> => {
  const { pool } = await load();
  const cl = await pool.connect();
  try {
    await cl.query("BEGIN");
    await cl.query(sql, values);
    return { code: "", msg: "" };
  } catch (e) {
    return { code: String((e as { code?: unknown }).code ?? ""), msg: (e as Error).message };
  } finally { await cl.query("ROLLBACK"); cl.release(); }
};

/**
 * #279i — САМЕ ТОЙ ЗАПИТ, ЩО ВИКОНУЄ РОУТ, ПРОТИ ЖИВОЇ БД.
 *
 * 📐 Куплено аварією на пʼять тижнів. `POST /client-plan` віддавав 500 на КОЖНОМУ
 * збереженні з 29.07.2026: `inconsistent types deduced for parameter $6` — помилка
 * РОЗБОРУ, тобто запит падав завжди, за будь-яких значень і будь-якої ролі. У базі за
 * серпень і вересень нуль рядків, чернеток не існує в принципі, «Подати» сіра назавжди.
 *
 * 🔴 ТЕКСТ БЕРЕТЬСЯ З `SAVE_SQL`, А НЕ З КОПІЇ. Перша редакція гейта тримала власну
 * копію запиту — і копія розійшлась із роутом (`manager_id = COALESCE(...)`), тобто
 * саботаж у роуті лишав гейт зеленим. Урок `#21c`: доказ на переписаному вручну тексті
 * є доказом ні про що.
 *
 * 🔴 ЛІКУЄМО `catch`, А НЕ ПРОБУ — і це куплено власною помилкою 04.09.2026. Спробою
 * обійти `permission denied` я замінив виконання на `PREPARE` — і стало ГІРШЕ: `PREPARE`
 * розбирає, але НЕ планує, а арбітражний індекс для `ON CONFLICT` добирає саме
 * планувальник. Гейт мовчки втратив покриття, яке мав.
 *
 * 📐 ЗАМІРЯНО на проді (PG 18.6, роль `test_readonly`) — три рядки, які й задають межу:
 *   здоровий UPSERT              → 42501  (дійшли до ПРАВ: розбір і планування пройшли)
 *   зниклий арбітражний індекс   → 42P10  (ПЛАНУВАЛЬНИК спрацював раніше за права)
 *   розбіжна арність значень     → 08P01  (BIND спрацював раніше за права)
 *
 * ✅ Тому `42501` — це «дійшли до кінця перевіряного», тобто ЗЕЛЕНЕ. Будь-який інший
 * код — ЧЕРВОНЕ з названим кодом. Так гейт тримає всі три класи і не червоніє від
 * власної ролі. Чого він не доводить: що запис справді відбувається — під read-only ми
 * спиняємось на правах, і це названо, а не замовчано.
 */
test("#279i UPSERT плану клієнта РОЗБИРАЄТЬСЯ живою БД (parse, не дані)", needsDb(), async () => {
  const { code, msg } = await probe(SAVE_SQL);
  assert.ok(code === "" || code === "42501",
    `🔴 UPSERT плану не дійшов до виконання: ${code} ${msg}. `
    + "Саме так екран «Клієнти та реактивація» мовчки не зберігав нічого пʼять тижнів.");
});

/**
 * #279j — ДЗЕРКАЛО: гейт вище ВМІЄ спрацювати.
 *
 * Без нього `#279i` зеленів би й тоді, коли перевіряти нема чого: будь-який справний
 * запит доходить до прав. Тут ТОЙ САМИЙ вираз без приведення — він мусить упасти рівно
 * тим, що ми ловимо.
 *
 * 🔴 Три твердження, і жодне не зайве:
 * ① текст СПРАВДІ інший — інакше дзеркало доводило б щось про запит, у якому нічого не
 *   зняли (той самий клас, що незастосований саботаж);
 * ② код `42P08` — змістова межа; без нього дзеркало зеленіло б на БУДЬ-ЯКІЙ відмові,
 *   зокрема на правах, і саме так воно й було зеленим, коли основний гейт падав із 42501;
 * ③ згадка `$6` — бо `42P08` сам по собі не каже, ЯКИЙ параметр неоднозначний: після
 *   чужого рефакторингу він прилетів би від `$3`, а ми прочитали б це як доказ про `$6`.
 *
 * ⚠️ Якщо приведення приберуть із `SAVE_SQL`, почервоніють ОБИДВА гейти: `#279i` — від
 * бази, `#279j` — від ①. Це не дві поломки, а одна, названа двічі.
 */
test("#279j 🪞 ДЗЕРКАЛО: без ::int той самий запит НЕ розбирається", needsDb(), async () => {
  assert.notEqual(__SAVE_SQL_NO_CAST_FOR_TESTS, SAVE_SQL,
    "🔴 у SAVE_SQL немає `$6::int` — знімати нема чого, а отже дзеркало доводило б порожнечу. "
    + "Це ТОЙ САМИЙ дефект, який ловить #279i: приведення зникло з робочого запиту");
  const { code, msg } = await probe(__SAVE_SQL_NO_CAST_FOR_TESTS);
  assert.equal(code, "42P08",
    `🔴 версія БЕЗ приведення впала не на виводі типів, а з кодом «${code}» («${msg}») — `
    + "дзеркало зеленіло б на будь-якій відмові, зокрема на правах, і не доводило б нічого");
  assert.match(msg, /inconsistent types|parameter \$6/i,
    `🔴 версія БЕЗ приведення пройшла (повідомлення: «${msg}») — отже #279i доводить не те, `
    + "що ми думаємо, і наступний такий дефект пройде повз нього");
});

/**
 * #337 — ТРИ РЕШТА КРОКІВ ЛАНЦЮГА ТЕЖ РОЗБИРАЮТЬСЯ ЖИВОЮ БАЗОЮ.
 *
 * 🔴 ЧОМУ САМЕ ЗАРАЗ. `submit`, `approve-all` і `return` перестали бути простими `UPDATE`:
 * кожен тепер пише слід у `repeat_client_plan_history` ТИМ САМИМ запитом (через CTE), тож
 * кожен параметр у них ужитий ДВІЧІ — раз в `UPDATE`, раз в `INSERT`. Це рівно та
 * конструкція, на якій зламався `$6` і через яку екран мовчав пʼять тижнів: помилка
 * ВИВОДУ ТИПІВ падає на розборі, тобто завжди, за будь-яких значень і будь-якої ролі.
 *
 * ✅ `42501` (права) — зелене: розбір і планування пройшли, ми впершись у read-only роль.
 * Будь-який інший код — червоне з названим кодом. Той самий критерій, що в `#279i`.
 */
test("#337 подання, затвердження й повернення плану РОЗБИРАЮТЬСЯ живою БД", needsDb(), async () => {
  const cases: [string, string, unknown[]][] = [
    ["SUBMIT_SQL", SUBMIT_SQL, ["2099-01-01", -1, 1]],
    ["approveAllSql", approveAllSql(""), ["2099-01-01", 1]],
    ["RETURN_SQL", RETURN_SQL, ["гейт-337-неіснуючий", "2099-01-01", "коментар", 1]],
  ];
  for (const [name, sql, values] of cases) {
    const { code, msg } = await probe(sql, values);
    assert.ok(code === "" || code === "42501",
      `🔴 ${name} не дійшов до виконання: ${code} ${msg}. Крок ланцюга «подав → затвердив» `
      + "упав би на КОЖНОМУ натисканні, як це вже було зі збереженням.");
  }
});

/**
 * #338 — 🪞 ДЗЕРКАЛО ДО #337: слід справді пишеться тим самим запитом.
 *
 * Без нього `#337` зеленів би й на голому `UPDATE` без історії — тобто доводив би, що
 * запит справний, і мовчав би про те, заради чого його міняли. Питання «хто і коли подав»
 * не мало відповіді саме тому, що `UPDATE` був сам по собі.
 */
test("#338 🪞 подання/затвердження/повернення пишуть слід тим самим запитом", () => {
  for (const [name, sql] of [["SUBMIT_SQL", SUBMIT_SQL], ["approveAllSql", approveAllSql("")],
                             ["RETURN_SQL", RETURN_SQL]] as const) {
    assert.match(sql, /INSERT INTO repeat_client_plan_history/,
      `🔴 ${name} не пише історію — отже «хто і коли це зробив» знову не має відповіді`);
    assert.match(sql, /WITH upd AS \(/,
      `🔴 ${name} пише історію ОКРЕМИМ запитом: лишається стан «зроблено, сліду немає»`);
  }
});
