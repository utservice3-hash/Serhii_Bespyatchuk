import { test } from "node:test";
import assert from "node:assert/strict";
import { readFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";

/**
 * #55 — ЖОДЕН ПОКАЗНИК НЕ МАЄ ДВОХ ДЖЕРЕЛ НА ОДНОМУ ЕКРАНІ.
 *
 * 🔴 ПРИВІД, ЗНАЙДЕНИЙ ОЧИМА ВЛАСНИКА НА ПРОДІ 06.08.2026. Під новими плитками
 * лишились старі блоки, які показували ТЕ САМЕ:
 *   · «Команда за місяць» — 12%, а плитка «Виконано · місяць» — 11.8%. Одне число,
 *     два округлення, один екран;
 *   · у тому ж старому блоці стани людей лишались ТРИ (18+1+6 = 25 із 31): помилку
 *     подвійного рахунку виправили в новій плитці, а поруч у старій вона жила далі;
 *   · «Очікуємо за план. датою» дублювало плитку «Ще не надійшли».
 *
 * Це рівно те, з чого почалась уся ця робота: дві правильні величини під одним
 * сенсом читаються як поломка. Тому дубль ловиться не оком, а гейтом.
 *
 * ⚠️ ЧОМУ ЧИТАЄМО ДЖЕРЕЛО, А НЕ HTTP. Дубль — це властивість ВЕРСТКИ: обидва блоки
 * беруть числа з того самого `glance`, тож жоден API-гейт їх не розрізнить. Той
 * самий випадок, що «текст у списку не перевіряє жоден гейт», лише тут перевірка
 * можлива — бо дубль видно за структурою коду.
 */
const FE = (f: string) => fileURLToPath(new URL(
  "../../../frontend/src/pages/dashboard/sections/" + f, import.meta.url));

test("#55 старі блоки-дублі не повернулись у Звіт", async () => {
  const src = await readFile(FE("ReportPlanSection.tsx"), "utf8");

  // ⚠️ Порожній результат = ПРОВАЛ: спершу доводимо, що файл той самий і живий.
  assert.ok(src.includes("function Glance("), "🔴 у файлі нема `Glance` — гейт перевіряє не те, що думає");
  assert.ok(src.includes("Фокус-день"), "🔴 у `Glance` нема фокус-дня — блок вирізали цілком, а мав лишитись");

  for (const [needle, why] of [
    ["Команда за місяць", "дублює плитку «Виконано · місяць» (12% проти 11.8% на одному екрані)"],
    ["Очікуємо за план. датою", "дублює плитку «Ще не надійшли»"],
  ] as const) {
    assert.ok(!src.includes(`>${needle}`),
      `🔴 повернувся блок «${needle}» — ${why}`);
  }

  /**
   * 🔴 СТАНИ ЛЮДЕЙ — НАЙНЕБЕЗПЕЧНІШИЙ ДУБЛЬ, бо він не просто повторює число, а
   * повторює його СТАРОЮ, зламаною формулою (три стани замість чотирьох). Тому
   * окремо вимагаємо, щоб чипи станів малювались РІВНО в одному файлі.
   */
  const summary = await readFile(FE("ReportSummary.tsx"), "utf8");
  assert.ok(summary.includes("collectedNotClosed"),
    "🔴 у зведенні нема стану «гроші є · не закрито» — чотирьох станів більше немає");
  assert.ok(!/statusCounts\.[rag]/.test(src),
    "🔴 `ReportPlanSection` знову малює чипи станів — вони мусять жити ЛИШЕ у зведенні, "
    + "інакше друга копія відстане від першої так само, як відстала минулого разу");
});

/**
 * #55b — ДЗЕРКАЛО: гейт уміє ЛОВИТИ. Без цього він зеленів би й тоді, коли шукає
 * не в тому файлі або коли рядок-маркер змінили — тобто був би декоративним.
 */
test("#55b саботаж: підкинутий дубль ловиться", async () => {
  const src = await readFile(FE("ReportPlanSection.tsx"), "utf8");
  const sabotaged = src.replace("function Glance(", '// >Команда за місяць\nfunction Glance(');
  assert.ok(sabotaged.includes(">Команда за місяць"),
    "🔴 саботаж не застосувався — дзеркало нічого не доводить");
  // саме та перевірка, що в #55, але на зіпсованому джерелі
  assert.ok(!(!sabotaged.includes(">Команда за місяць")),
    "🔴 предикат #55 НЕ помітив підкинутого дубля — він декоративний");
});
