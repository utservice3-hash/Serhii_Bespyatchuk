/**
 * #79 — ВИБІР ПЕРІОДУ У «ЗВІТІ» ДОХОДИТЬ ДО ТІЛА ЕКРАНА.
 *
 * 🔴 ПРИВІД (заміряно 18.08.2026 по коду). Перемикач мав чотири режими
 * (День/Тиждень/Місяць/Період), але тіло Звіту читало `const data = monthData` —
 * тобто ростер, glance, гроші й сортування ЗАВЖДИ показували місяць. Гірше:
 * `mode`/`rangeFrom`/`rangeTo` не стояли в залежностях ефекту, тож режим «Період»
 * не робив ЖОДНОГО запиту — людина клацала дати, а екран не змінювався взагалі.
 * Бекенд при цьому вмів довільний [from,to] увесь час (доведено прогоном: тиждень
 * 11–17.08 → 665 створених і план 656 905 ₴ проти місячних 1 539 / 2 759 000 ₴).
 *
 * 🔴 ЧОМУ ГЕЙТ ЧИТАЄ ДЖЕРЕЛО, А НЕ HTTP. Це поломка ВЕРСТКИ/СТАНУ фронта: API
 * віддавав правильні числа обом режимам. Жодна проба ендпоінта її не бачила — і не
 * бачила пів року. Браузера в прийманні немає (на прод-сервері його теж немає), тож
 * єдине, що можна перевірити машиною, — що в коді стоїть саме той вираз.
 */
const SEC = path.join(import.meta.dirname, "..", "..", "..", "frontend", "src",
  "pages", "dashboard", "sections", "ReportPlanSection.tsx");
const src = (): string => readFileSync(SEC, "utf8");
const RULES = path.join(import.meta.dirname, "..", "..", "..", "frontend", "src",
  "pages", "dashboard", "periodRules.ts");
/** Правило фронту ВИКОНУЄТЬСЯ, а не читається очима (той самий прийом, що в `#370`). */
async function loadRules() {
  const ts = (await import("typescript")).default;
  const js = ts.transpileModule(readFileSync(RULES, "utf8"), {
    compilerOptions: { module: ts.ModuleKind.ESNext, target: ts.ScriptTarget.ES2022 },
  }).outputText;
  return await import(`data:text/javascript,${encodeURIComponent(js)}`);
}

test("#79 ТІЛО ЗВІТУ ЧИТАЄ ОБРАНИЙ ПЕРІОД, А НЕ ЗАВЖДИ МІСЯЦЬ", () => {
  const s = src();
  // ⚠️ Патерн ЯКОРИТЬСЯ НА ПОЧАТОК РЯДКА КОДУ. Перша редакція шукала підрядок будь-де
  // і червоніла на… власному коментарі, де ця сама фраза цитується як опис старої
  // поломки. Гейт, що читає джерело, мусить відрізняти код від прози — інакше він
  // або вічно червоний, або його «полагодять», прибравши пояснення.
  assert.equal(/^\s*const data = monthData/m.test(s), false,
    "🔴 тіло Звіту знову прибите до місяця (`const data = monthData`) — перемикач періоду "
    + "став декорацією, як і був до 18.08.2026");
  assert.ok(/const data = periodData;/.test(s),
    "🔴 немає `const data = periodData` — тіло більше не бере дані за обраним періодом");
  // Мапа режим→дані мусить покривати ВСІ чотири режими, інакше якийсь із них тихо
  // впаде у `monthData` і покаже місяць під чужим підписом.
  const map = s.split("const periodData =")[1]?.slice(0, 240) ?? "";
  for (const m of ["range", "week", "day"])
    assert.ok(map.includes(`"${m}"`), `🔴 режим '${m}' випав із мапи periodData — він показуватиме місяць`);
  assert.ok(/rangeData/.test(map) && /weekData/.test(map) && /focus/.test(map) && /monthData/.test(map),
    "🔴 мапа periodData більше не перевикористовує вже завантажені день/тиждень/місяць");
});

test("#79b РЕЖИМ «ПЕРІОД» РОБИТЬ ЗАПИТ — selectedPeriod у залежностях ефекту", () => {
  const s = src();
  const eff = s.split("if (mode !== \"range\") return;")[1]?.slice(0, 900) ?? "";
  assert.ok(eff.length > 0, "🔴 ефекту завантаження діапазону немає — «Період» знову без запиту");
  assert.ok(/fetchScoped\(\{ from: selectedPeriod\.from, to: selectedPeriod\.to/.test(eff),
    "🔴 діапазон тягнеться не за selectedPeriod");
  /**
   * 🔴 ОНОВЛЕНО 21.08.2026 — І САМЕ ЦЕЙ ГЕЙТ СПІЙМАВ ПОЛОМКУ НА ПРОДІ. З появою
   * мультивибору `teamId` став ПОХІДНИМ: він дорівнює "" щоразу, коли обрано 2+
   * команди. Лишити його в залежностях означало б, що в режимі «Період» зміна
   * набору команд ([5,6] → [5,6,13]) не перезапускає запит, і екран мовчки
   * показує попередній набір. Тому тут `scopeKey` — рядок з УСІХ обраних id.
   *
   * Твердження не послаблене, а посилене: раніше воно вимагало один скалярний
   * teamId, тепер — ключ, що змінюється на будь-якій зміні обсягу.
   */
  assert.ok(/\[mode, selectedPeriod\.from, selectedPeriod\.to, scopeKey, retryNonce/.test(eff),
    "🔴 у залежностях ефекту немає меж діапазону або ключа обсягу — зміна дат чи набору "
    + "команд не перезапустить запит (рівно та поломка, через яку «Період» не працював)");
  assert.equal(/selectedPeriod\.to, teamId,/.test(eff), false,
    "🔴 у залежностях знову скалярний `teamId` — при 2+ командах він завжди \"\" і зміну обсягу не видно");
});

