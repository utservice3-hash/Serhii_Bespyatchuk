import { test } from "node:test";
import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import path from "node:path";

/**
 * 🗣 #278–#278b — ПОМИЛКА СЕРВЕРА НА ЕКРАНІ ПЛАНІВ ВИДИМА ЛЮДИНІ (борг 15).
 *
 * 🔴 ПРИВІД, І ВІН НЕ ГІПОТЕТИЧНИЙ. `doApprove`/`doSubmit` не мали `catch` ЖОДНОГО, а
 * четвертий аргумент `btn` — це `solid`, а не `off`, тож кнопка лишалась клікабельною.
 * Людина тисне, запит падає, на екрані НЕ ВІДБУВАЄТЬСЯ НІЧОГО. Саме так виглядала межа
 * 30 000 на «Змінити»: власник тиснув і не отримував жодного повідомлення, а ми пів дня
 * шукали «зламану кнопку».
 *
 * ⚠️ Зняття межі прибрало РІВНО ОДНУ 400 із десяти відмов роуту (заміряно: 7×400,
 * 2×403 за скоупом, 1×409). Лікуємо не конкретну відмову, а МОВЧАННЯ.
 */

const FE = path.join(import.meta.dirname, "..", "..", "..",
  "frontend/src/pages/dashboard/sections/PlanFormationSection.tsx");
const raw = (): string => readFileSync(FE, "utf8");
const stripComments = (s: string): string =>
  s.replace(/\/\*[\s\S]*?\*\//g, " ").replace(/(^|[^:])\/\/[^\n]*/g, "$1 ");

test("#278 ОБИДВІ ДІЇ ЛОВЛЯТЬ ПОМИЛКУ, і жодна не мовчить", () => {
  const code = stripComments(raw());
  /**
   * Твердження ЗМІСТОВЕ: обидві дії йдуть через спільну обгортку, яка кладе текст
   * помилки у стан. Не «є слово catch» — catch буває й порожнім.
   */
  assert.ok(/const\s+guard\s*=\s*async\s*\([\s\S]{0,200}?catch[\s\S]{0,80}?setErr\(/.test(code),
    "🔴 обгортка не кладе текст помилки у стан — помилка знову летить у порожнечу");
  for (const fn of ["doSubmit", "doApprove"]) {
    assert.ok(new RegExp(`const\\s+${fn}\\s*=\\s*\\(\\)\\s*=>\\s*guard\\(`).test(code),
      `🔴 «${fn}» більше не йде через обгортку — саме ця дія знову стане німою`);
  }
  // Стан помилки ОЧИЩАЄТЬСЯ перед новою спробою: інакше вона застрягне після успіху.
  assert.ok(/setBusy\(true\);\s*setErr\(null\)/.test(code),
    "🔴 попередня помилка не скидається — людина бачитиме її після вдалої дії");
});

test("#278b 🪞 ТЕКСТ ДОХОДИТЬ ДО ЕКРАНА, а не лише до стану", () => {
  /**
   * Без цієї половини гейт зеленів би на коді, який ловить помилку й нікуди її не малює —
   * тобто рівно на теперішньому дефекті, лише з `catch` для вигляду.
   */
  const src = raw();
  assert.ok(/\{err && \(/.test(stripComments(src)),
    "🔴 стан помилки ніде не рендериться — спіймали й сховали");
  assert.ok(/role="alert"/.test(src),
    "🔴 рядок помилки без role=\"alert\" — його не побачить ні читалка екрана, ні гейт");
  assert.ok(/\{err\}/.test(src), "🔴 у рядок не підставляється сам текст помилки");
  // І текст береться з ВІДПОВІДІ сервера, а не вигадується сталою.
  assert.ok(/response[\s\S]{0,120}?data[\s\S]{0,60}?error/.test(stripComments(src)),
    "🔴 текст не читається з відповіді сервера — людина побачить загальну фразу замість причини");
});
