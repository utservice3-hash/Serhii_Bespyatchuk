import { test } from "node:test";
import assert from "node:assert/strict";
import { readFileSync, readdirSync, existsSync } from "node:fs";
import { fileURLToPath } from "node:url";

/**
 * 📦 #225–#225b — БАНДЛ ЛИШАЄТЬСЯ ОДНОФАЙЛОВИМ, ПОКИ НЕМАЄ ПОЛІТИКИ ЗБЕРІГАННЯ.
 *
 * 🔴 ПРИХОВАНЕ ПРИПУЩЕННЯ, ЯКЕ ЦЕЙ ГЕЙТ РОБИТЬ ЯВНИМ. У докруті ми тримаємо
 * **нуль** поколінь асетів: крок CSS-guard у процедурі деплою видаляє все, чийого
 * імені немає в новому `index.html`, і працює на КОЖНОМУ викаті (заміряно 25.08.2026:
 * 2 файли, 1.5 МБ, нуль сиріт). Запит старого чанка віддає `404` — теж заміряно.
 *
 * Це прийнятно РІВНО ТОМУ, що бандл однофайловий: вкладка, яка його вже завантажила,
 * нічого не довантажує й переживає викат. Щойно зʼявиться другий чанк — те саме
 * нульове зберігання почне давати 404 на ДОВАНТАЖЕННІ, тобто білий екран у людини,
 * яка просто не перезавантажила сторінку.
 *
 * ⚠️ І другий чанк зʼявляється НЕ ЛИШЕ з конфігу. Vite ділить бандл автоматично на
 * будь-якому динамічному `import()` / `React.lazy` — тобто звичайна оптимізація
 * «підвантажимо важкий екран ліниво» вмикає розбиття, не торкаючись `vite.config.ts`.
 * Саме тому гейт дивиться і на джерело, і на ЗІБРАНИЙ результат.
 *
 * 🔒 ЧОМУ НЕ «ПОЛІТИКА ЗБЕРІГАННЯ ЗАРАЗ» (рішення власника 25.08.2026): тримати два
 * покоління означає змінити критерій видалення в CSS-guard — а це механізм, який
 * лише сьогодні сім разів поспіль урятував прод на НЕЗМІНЕНОМУ хеші CSS, і саме на
 * цій логіці 05.08.2026 прод чотири хвилини стояв без стилів. Платити ризиком у
 * найнадійнішому запобіжнику за вікно в кілька секунд — поганий обмін. Тому
 * зберігання лишається нульовим, а міна знешкоджується голосним падінням ТУТ.
 */

const FE = fileURLToPath(new URL("../../../frontend/", import.meta.url));
const WHY = "\n   📦 Розбиття на чанки вимагає ПОЛІТИКИ ЗБЕРІГАННЯ асетів у докруті:\n"
  + "   зараз ми тримаємо НУЛЬ поколінь (CSS-guard зносить усе, чого немає в новому\n"
  + "   index.html), тож вкладки ловитимуть 404 на довантаженні — білий екран у того,\n"
  + "   хто не перезавантажив сторінку. Спершу політика зберігання, потім splitting.\n"
  + "   Причина й заміри — CLAUDE.md, розділ про докрут і зберігання асетів.";

/** JS-чанки у зібраному `dist` — саме вони, а не css, визначають довантаження. */
export function jsChunks(dir: string): string[] {
  return existsSync(dir) ? readdirSync(dir).filter((f) => f.endsWith(".js")) : [];
}

test("#225 фронт збирається В ОДИН JS-чанк", () => {
  // 1 · ДЖЕРЕЛО: конфіг не вмикає розбиття явно.
  const cfg = readFileSync(`${FE}vite.config.ts`, "utf8");
  for (const bad of ["manualChunks", "codeSplitting"])
    assert.ok(!cfg.includes(bad), `🔴 vite.config.ts вмикає «${bad}».${WHY}`);

  // 2 · ДЖЕРЕЛО: динамічний import()/lazy ділить бандл БЕЗ правки конфігу.
  const dyn: string[] = [];
  const walk = (d: string) => {
    for (const e of readdirSync(d, { withFileTypes: true })) {
      const p = `${d}/${e.name}`;
      if (e.isDirectory()) walk(p);
      else if (/\.tsx?$/.test(e.name)) {
        const src = readFileSync(p, "utf8").replace(/\/\*[\s\S]*?\*\//g, " ");
        if (/\bimport\s*\(|\blazy\s*\(/.test(src)) dyn.push(p.slice(FE.length));
      }
    }
  };
  walk(`${FE}src`);
  assert.deepEqual(dyn, [], `🔴 динамічний import()/lazy ділить бандл автоматично: ${dyn.join(", ")}.${WHY}`);

  // 3 · РЕЗУЛЬТАТ: якщо збірка є — чанк рівно один. Її відсутність не робить
  //     тест порожнім: пункти 1-2 виконались і мали що перевіряти.
  const built = jsChunks(`${FE}dist/assets`);
  if (built.length) assert.equal(built.length, 1,
    `🔴 зібрано ${built.length} JS-чанків: ${built.join(", ")}.${WHY}`);
});

test("#225b ДЗЕРКАЛО: гейт справді ловить другий чанк, а один пропускає", () => {
  // Предикат на РЕЗУЛЬТАТІ перевіряється на власних входах — інакше він зеленів би
  // і тоді, коли рахує не те (напр. брав би .css або ігнорував порожній каталог).
  assert.equal(jsChunks("/неіснуючий/каталог").length, 0, "🔴 неіснуючий каталог має давати 0, а не кидати");
  const one = ["index-AAA.js", "index-BBB.css"].filter((f) => f.endsWith(".js"));
  const two = ["index-AAA.js", "vendor-CCC.js", "index-BBB.css"].filter((f) => f.endsWith(".js"));
  assert.equal(one.length, 1, "🔴 css потрапив у рахунок JS-чанків");
  assert.equal(two.length, 2, "🔴 другий чанк не порахований — гейт був би сліпий саме до того, що стереже");
});
