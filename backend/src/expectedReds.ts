/**
 * 🏷 РЕЄСТР ОЧІКУВАНИХ ЧЕРВОНИХ — щоб «зелене приймання» став машинним вироком.
 *
 * 📐 ПРИВІД, ЗАМІРЯНИЙ 02.09.2026. `lockRelease` УЖЕ стоїть кроком одразу за
 * `accept`, тобто ланцюг давно вміє віддавати замок сам. Не віддавав він з однієї
 * причини: `accept` червонів на падіннях, які ми ЗАЗДАЛЕГІДЬ називали очікуваними
 * вголос у чаті — а вголос ланцюг не чує. За журналом замка того дня: холд 24 хв
 * при роботі ~20 хв у мене і 184 хв із перехопленням по TTL в іншого чату.
 *
 * 🔴 ЧОМУ ЦЕ МОЖЛИВО САМЕ ЗАРАЗ. Вироки не машинні, а ІМЕНА — машинні: `testRunGate`
 * друкує їх власним маркером `FAIL-GATE:` з подій раннера, а не із символа репортера
 * (`#270`). Отже критерій будується на іменах, і нічого нового вигадувати не треба.
 *
 * ⚖️ КРИТЕРІЙ: зелено ⇔ множина падінь ⊆ реєстру І жодного нового імені.
 *
 * 🔴 І ДЗЕРКАЛО, БЕЗ ЯКОГО ЦЕ БУВ БИ ВИМИКАЧ, А НЕ КРИТЕРІЙ. Запис на гейт, який
 * НАСПРАВДІ ПРОЙШОВ, — дефект реєстру, а не порядок. Інакше реєстр стає ковдрою:
 * під мертвим записом наступне СПРАВЖНЄ падіння того самого імені пройде мовчки.
 * Точно так само влаштований `acceptRetired` у `testManifest.ts`, і не випадково:
 * це той самий клас помилки, тільки про інший бік прогону.
 *
 * ⚠️ МЕЖІ, НАЗВАНІ ВГОЛОС І НАВМИСНО ВУЗЬКІ:
 *   · збіг ЛИШЕ за ПОВНИМ іменем — ні масок, ні префіксів, ні «починається з». Маска
 *     накрила б сусіда, якого ніхто не розглядав;
 *   · НЕДОБІР (`виконалось < обовʼязкових`) цим реєстром НЕ покривається взагалі —
 *     то окремий СТОП, і він лишається окремим: червоне каже «зламано», недобір каже
 *     «ми не дивились», і друге гірше;
 *   · порожній перелік імен при `падінь > 0` — ПРОВАЛ, ніколи не зелене: це рівно
 *     «порожній результат = провал», і саме так один чат отримав 11 «зелених» саботажів;
 *   · `decidedBy` заповнює той, ЧИЄ це рішення. Вписати самому за себе — те саме, що
 *     самому собі підписати приймання.
 */

export interface ExpectedRed {
  /** ПОВНЕ імʼя тесту, як його друкує `FAIL-GATE:`. */
  name: string;
  /** Коли внесено — щоб було видно, що запис протух. */
  since: string;
  /** Чому це падіння очікуване. Без причини запис не відповідає на єдине питання. */
  reason: string;
  /** Чиє це рішення. «Ми домовились» — не рішення. */
  decidedBy: string;
}

/**
 * 🔴 РЕЄСТР ПОЧИНАЄТЬСЯ ПОРОЖНІМ, І ЦЕ СВІДОМО. Заповнює його той, чиє рішення,
 * своїм проходом. Якби я вписав сюди сьогоднішні `#124`/`#125`/`#181`/`#175` сам,
 * це був би рівно той випадок, від якого стереже `decidedBy`: механізм, який
 * дозволяє собі ж і призначити виняток.
 */
export const EXPECTED_REDS: ExpectedRed[] = [];

export interface RedsVerdict {
  ok: boolean;
  /** Падіння, яких у реєстрі немає, — саме вони роблять приймання червоним. */
  uncovered: string[];
  /** Дефекти самого реєстру: мертві записи, записи без причини/дати/автора. */
  registryProblems: string[];
  /** Рядки для звіту: коротко й поіменно. */
  lines: string[];
}

/**
 * Вирок приймання за іменами.
 *
 * @param failed імена падінь цього прогону (з `failureNames`)
 * @param passed імена тестів із РЕЄСТРУ, які цього прогону ПРОЙШЛИ (з `expectedPassNames`).
 *   🔴 Це і є дані дзеркала, і друкує їх гейт прогону — той, хто єдиний бачить події
 *   раннера. Виводити «пройшов» із малюнка репортера не можна: рівно на цьому
 *   01.09.2026 один чат отримав одинадцять «зелених» саботажів. Повний список
 *   виконаних тут не потрібен і навмисно не збирається — дзеркалу досить тих імен,
 *   про які реєстр щось стверджує.
 */
export function acceptExpectedReds(
  failed: readonly string[],
  passed: readonly string[],
  registry: readonly ExpectedRed[] = EXPECTED_REDS,
): RedsVerdict {
  const failedSet = new Set(failed);
  const passedSet = new Set(passed);
  const registryProblems: string[] = [];
  const allowed = new Set<string>();

  for (const r of registry) {
    if (!r.name.trim()) { registryProblems.push("🔴 запис без ІМЕНІ — накрити може будь-що"); continue; }
    if (!r.reason.trim()) {
      registryProblems.push(`🔴 «${r.name}» без ПРИЧИНИ — реєстр без причини не відповідає на питання, заради якого існує`);
      continue;
    }
    if (!r.since.trim()) {
      registryProblems.push(`🔴 «${r.name}» без ДАТИ — без неї не видно, що запис протух`);
      continue;
    }
    if (!r.decidedBy.trim()) {
      registryProblems.push(`🔴 «${r.name}» без АВТОРА РІШЕННЯ — виняток, який ніхто не ухвалював`);
      continue;
    }
    // 🪞 ГЛУШНИК: запис живе, а гейт цього прогону ПРОЙШОВ. Мовчазний виняток на
    // здоровому тесті — це вимкнений гейт, і наступне справжнє падіння він проковтне.
    if (!failedSet.has(r.name) && passedSet.has(r.name)) {
      registryProblems.push(`🔴 «${r.name}» очікується червоним, а тест ПРОЙШОВ — запис став глушником, прибери його`);
      continue;
    }
    allowed.add(r.name);
  }

  const uncovered = failed.filter((n) => !allowed.has(n));
  const ok = uncovered.length === 0 && registryProblems.length === 0;

  const lines: string[] = [];
  if (uncovered.length) {
    lines.push(`🔴 НОВІ ІМЕНА (${uncovered.length}) — у реєстрі їх немає:`);
    for (const n of uncovered) lines.push(`   ﹣ ${n}`);
  }
  for (const p of registryProblems) lines.push(`   ${p}`);
  if (ok && failed.length) {
    lines.push(`✅ падінь ${failed.length}, усі очікувані поіменно:`);
    for (const n of failed) lines.push(`   ﹣ ${n}`);
  }
  return { ok, uncovered, registryProblems, lines };
}
