export interface Verdict { ok: boolean; ran: number; required: number; declared: number; unexpected: string[]; report: string }

export function modeName(env: NodeJS.ProcessEnv = process.env): string {
  return env.TEST_MATRIX === "1" ? "test:matrix" : env.TEST_AI === "1" ? "test:ai" : "test:prod";
}

/**
 * Чистий вирок по прогону — щоб його можна було перевірити ТЕСТОМ, а не лише
 * саботажем усього приймання. Нічого не мутує і не читає глобального стану.
 *
 * 🔴 `declared` МУСИТЬ ПРИЙТИ ЗЗОВНІ (з маніфесту). Спершу я рахував
 * `expected = ran + дозволені скіпи` — і ворота бадьоро надрукували «виконалось
 * 18 із 18», коли не виконалось НІЧОГО: всі файли впали на імпорті. Це рівно та
 * циклічна перевірка «A = B», де B — те, чим щойно означили A. Маніфест каже,
 * скільки тестів МАЄ існувати, і не залежить від того, скільки сьогодні відпрацювало.
 */
export function evaluateRun(t: RunTally, declared: number, env: NodeJS.ProcessEnv = process.env): Verdict {
  const allowed = allowedSkips(env);
  /**
   * 🔴 ЗЛАМАНЕ ОТОЧЕННЯ БʼЄ РЕЄСТР. `ALLOWED_PROD_SKIPS` звіряє ІМʼЯ тесту — і саме
   * тому на проді скіп «тут немає PostgreSQL» (норма) та скіп «диск помер» падали в
   * ОДНУ дозволену клітинку. Тепер дозвіл знімається з будь-якого скіпу, чия причина
   * несе маркер: право пропустити дається за ПРИРОДОЮ перешкоди, а не за іменем.
   */
  const broken = t.broken ?? [];
  const brokenNames = new Set(broken.map((b) => b.name));
  /**
   * 🈳 ДРУГИЙ ДОЗВІЛ — ДВОСКЛАДОВИЙ, І САМЕ ЦЕ РОБИТЬ ЙОГО НЕ КОВДРОЮ.
   * Гейт мусить бути НАЗВАНИЙ у `EMPTY_PERIOD_SKIPS` І його причина мусить нести
   * маркер. Одного імені мало: інакше той самий запис покрив би скіп із будь-якої
   * іншої причини — рівно та діра, яку `BROKEN_ENV_MARK` уже одного разу закривав.
   */
  const emptyNamed = new Set(EMPTY_PERIOD_SKIPS.map((s) => s.name));
  const emptyMarked = new Set((t.emptyPeriod ?? []).map((e) => e.name));
  const emptyOk = (n: string): boolean => emptyNamed.has(n) && emptyMarked.has(n);
  const unexpected = t.skipped.filter((n) => !(allowed.has(n) || emptyOk(n)) || brokenNames.has(n));
  const okSkips = t.skipped.length - unexpected.length;
  // Діти дозволено-скіпнутих батьків фізично не можуть зʼявитись у виводі.
  const skippedSet = new Set(t.skipped);
  const absentChildren = Object.entries(PROD_SKIP_CHILDREN)
    .filter(([parent]) => skippedSet.has(parent) && allowed.has(parent))
    .reduce((n, [, kids]) => n + kids.length, 0);
  const required = declared - okSkips - absentChildren;   // стільки МАЄ виконатись у цьому режимі
  const ok = unexpected.length === 0 && t.ran >= required;
  const mode = modeName(env);

  let report = "\n"
    + (broken.length
      ? `🔴 ОТОЧЕННЯ ЗЛАМАНЕ — ${broken.length} гейт(ів) не виконались НЕ ЧЕРЕЗ РЕЖИМ:\n`
        + broken.map((b) => `   ﹣ ${b.name}\n     ${b.reason.replace(BROKEN_ENV_MARK, "").trim()}\n`).join("")
        + "   Це НЕ дозволений пропуск: перевірка не виконалась, і «0 падінь» тут\n"
        + "   означало б «нічого не перевірено». Полагодь оточення й повтори.\n"
      : "")
    + `🔒 РЕЖИМ ${mode}: ВИКОНАЛОСЬ ${t.ran} із ${required} обовʼязкових `
    + `(оголошено в маніфесті ${declared}, дозволених скіпів ${okSkips}`
    + (absentChildren ? `, підтестів скіпнутих батьків ${absentChildren}` : "")
    + `, несподіваних ${unexpected.length}, падінь ${t.failed})\n`
    /**
     * 🔴 ПРОПУЩЕНІ — ОКРЕМИМ РЯДКОМ, А НЕ РІЗНИЦЕЮ МІЖ ДВОМА ЧИСЛАМИ
     * (вимога власника 07.08.2026).
     *
     * Було: підсумок друкував «tests 237 · pass 220», і щоб дізнатись, що 17
     * тестів не виконались, треба було відняти одне від другого — а до того
     * ще й здогадатись, що це варто зробити. Пропущений тест виглядає як
     * зелений рядок, хоча не перевірив НІЧОГО: та сама пастка, що й
     * «порожній результат = зелено».
     *
     * Тому кількість тепер названа, і поруч — ЧИМ її подивитись поіменно.
     */
    + `﹣ ПРОПУЩЕНО: ${t.skipped.length} (усі дозволені; перелік — рядки з «﹣» у виводі)\n`;
  if (!ok) {
    report += "🔴 ПРОГІН НЕ ЗАРАХОВАНО: виконалось менше, ніж вимагає режим.\n"
      + "   «0 падінь» тут НЕ означає «перевірено» — саме так приймання одного разу\n"
      + "   надрукувало зелене при 72 тихо пропущених.\n"
      + (unexpected.length
        ? "   Несподівані скіпи:\n" + unexpected.map((n) => `   ﹣ ${n}\n`).join("")
        : `   Скіпів немає, але не дорахувались ${required - t.ran} тестів — значить\n`
          + "   частина файлів не завантажилась (падіння на імпорті) або глоб їх не знайшов.\n")
      /**
       * 🔴 НЕ ПОСИЛАТИ ПО .env, КОЛИ ФАЙЛИ ПОМЕРЛИ. Заміряно 25.08.2026: прогін
       * дав недобір 16 тестів, вартовий чесно відмовив — але порадою «оточення не
       * потрапило в процес» відправив читача перевіряти `.env`, хоча вмерли шість
       * файлів за лімітом памʼяті. Відмова була правильна, ПІДКАЗКА — хибна, і саме
       * підказку читають першою.
       */
      + (t.silentDeaths?.length
        ? `   💀 Але ${t.silentDeaths.length} файл(ів) померли БЕЗ діагностики (перелік вище) —\n`
          + "   найімовірніше саме через це недобір. Спершу дивись туди, а НЕ в .env.\n"
        : "   Найчастіша причина: оточення не потрапило в процес. Воно лежить у\n"
          + "   backend/.env (НЕ ../.env):\n"
          + `   cd backend && set -a && . ./.env && set +a && API_BASE=… npm run ${mode}\n`);
  }
  return { ok, ran: t.ran, required, declared, unexpected, report };
}

interface TestEvent {
  type: string;
  data: { name?: string; skip?: boolean | string; details?: { error?: { cause?: unknown } } };
}

/** Скіп через зламане оточення — за маркером у причині, а не за здогадом по тексту. */
export const isBrokenEnvSkip = (skip: boolean | string | undefined): boolean =>
  typeof skip === "string" && skip.includes(BROKEN_ENV_MARK);

/** Скіп «у періоді немає даних» — законна ВІДСУТНІСТЬ, а не зламане оточення. */
export const isEmptyPeriodSkip = (skip: unknown): boolean =>
  typeof skip === "string" && skip.includes(EMPTY_PERIOD_MARK);

export default async function* runGate(source: AsyncIterable<TestEvent>) {
  const tally: RunTally = { ran: 0, failed: 0, skipped: [], broken: [], emptyPeriod: [] };
  for await (const ev of source) {
    if (ev.type !== "test:pass" && ev.type !== "test:fail") continue;
    // `skip` приходить або true, або текстом причини — обидва означають «не виконався».
    if (ev.data.skip === true || typeof ev.data.skip === "string") {
      const name = ev.data.name ?? "";
      tally.skipped.push(name);
      if (isBrokenEnvSkip(ev.data.skip)) tally.broken!.push({ name, reason: String(ev.data.skip) });
      else if (isEmptyPeriodSkip(ev.data.skip)) tally.emptyPeriod!.push({ name, reason: String(ev.data.skip) });
    }
    else {
      tally.ran++;
      if (ev.type === "test:fail") {
        tally.failed++;
        (tally.failures ??= []).push(ev.data.name ?? "?");
        // 💀 Контейнер файлу впав без причини — запамʼятовуємо ПОІМЕННО.
        if (isSilentFileDeath(ev.data.name ?? "", ev.data.details?.error?.cause))
          (tally.silentDeaths ??= []).push(ev.data.name ?? "?");
      }
    }
  }

  /**
   * 💀 ГУЧНИЙ ДІАГНОЗ — ДО решти вироку і НЕЗАЛЕЖНО від режиму.
   * У деві вартовий виходить раніше (скіпи там законні), але мовчазна смерть файлу
   * незаконна ВСЮДИ: у `npm test` вона так само лишає перевірки невиконаними.
   */
  if (tally.silentDeaths?.length) {
    yield "\n💀 ФАЙЛ ПОМЕР БЕЗ ДІАГНОСТИКИ — це не «загадковий збій у тестах»:\n"
      + tally.silentDeaths.map((n) => `   ﹣ ${n}\n`).join("")
      + "   Контейнер файлу впав, а причини немає: підтести могли бути ВСІ зелені.\n"
      + "   Найімовірніше процес убито ядром за лімітом памʼяті (на проді це LVE).\n"
      + "   📐 Заміряно 25.08.2026: `nproc` віддає 48 ХОСТОВИХ ядер, тож `node --test`\n"
      + "   піднімає до 48 процесів, а пʼять файлів тягнуть компілятор TypeScript\n"
      + "   (~50 МБ кожен). Поріг: 12 паралельно чисто, 16 → 2 смерті, 24 → 12.\n"
      + "   ⚙️ Лікується `--test-concurrency` у скриптах; якщо він уже стоїть, а смерть\n"
      + "   сталась — шукай ІНШУ причину (пізня unhandledRejection, чужий OOM), і не\n"
      + "   списуй на памʼять за звичкою.\n";
  }
  /**
   * 🏷 ПЕРЕЛІК ПАДІНЬ ПОІМЕННО — В ОБОХ РЕЖИМАХ І НЕЗАЛЕЖНО ВІД РЕПОРТЕРА (#272).
   * Друкується ДО будь-якого раннього виходу: розбір не має залежати ні від режиму,
   * ні від того, чим показують вивід. Порядок — як у прогоні, без сортування.
   */
  if (tally.failures?.length) {
    yield "\n" + tally.failures.map((n) => `${FAIL_MARK} ${n}\n`).join("");
  }

  /**
   * 🔴 НУЛЬ ВИКОНАНИХ НАЗИВАЄ СЕБЕ — У БУДЬ-ЯКОМУ РЕЖИМІ (#273).
   *
   * `#19c` стереже це для ПОВНОГО набору, але разові команди (`node --test dist/x.test.js`)
   * сторожа не мали: файл, що не зібрався або відсіявся глобом, друкує «pass 0, fail 0»
   * і виходить нулем — тобто найнебезпечніший стан у цьому проєкті виглядає як успіх.
   *
   * ⚠️ ДВІ ПРИЧИНИ РОЗРІЗНЯЮТЬСЯ, бо ведуть у різні боки: «усе скіпнуто» — це питання до
   * оточення (немає БД, немає API), «нічого не знайдено» — це зламаний шлях або збірка.
   * Спільний підпис для двох різних відмов ми вже одного разу купили дорого.
   */
  if (tally.ran === 0) {
    process.exitCode = 1;
    yield tally.skipped.length > 0
      ? `\n🔴 НІЧОГО НЕ ВИКОНАЛОСЬ: усі ${tally.skipped.length} тест(ів) СКІПНУТО.\n`
        + "   «0 падінь» тут означає «нічого не перевірено», а не «все гаразд».\n"
        + "   Оточення не дає їм побігти — дивись причини скіпів вище.\n"
      : "\n🔴 НІЧОГО НЕ ВИКОНАЛОСЬ: раннер не знайшов ЖОДНОГО тесту.\n"
        + "   Найчастіше це не зібраний `dist`, помилка в шляху або глоб, що нічого не збіг.\n"
        + "   Порожній прогін — це ПРОВАЛ, доки не доведено, що перевіряти БУЛО що.\n";
  }

  /**
   * 🔴 ЛОКАЛЬНИЙ `npm test` БІЛЬШЕ НЕ МОВЧИТЬ ПРО ЗЛАМАНЕ ОТОЧЕННЯ (Б2).
   *
   * Решта скіпів у деві законна (немає БД, немає API) — це режим, а не поломка, і
   * вартовий їх, як і раніше, не чіпає. Але скіп через ЗЛАМАНЕ оточення законним не
   * буває ніде: саме він двічі за добу тихо вимкнув 41 гейт, і обидва рази числа
   * знімали з набору, який їх не виконував.
   */
  if (tally.broken!.length > 0) {
    process.exitCode = 1;
    yield "\n🔴 ПРОГІН НЕ ЗАРАХОВАНО: ОТОЧЕННЯ ЗЛАМАНЕ\n"
      + tally.broken!.map((b) => `   ﹣ ${b.name}\n     ${b.reason.replace(BROKEN_ENV_MARK, "").trim()}\n`).join("")
      + `   Не виконалось ${tally.broken!.length} гейт(ів). «0 падінь» тут означає\n`
      + "   «нічого не перевірено», а не «все гаразд».\n";
    if (process.env.TEST_SCOPE !== "prod") return;
  }
  if (process.env.TEST_SCOPE !== "prod") return;    // локальний `npm test`: решта скіпів законна

  const { MANIFEST_TESTS, MANIFEST_SECURITY_TABLES } = await import("./testManifest.js");
  const v = evaluateRun(tally, MANIFEST_TESTS.length + MANIFEST_SECURITY_TABLES.length);
  if (!v.ok) process.exitCode = 1;
  yield v.report;
}
