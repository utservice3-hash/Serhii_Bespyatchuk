import { Pool } from "pg";
import { config } from "../config.js";
import { assertTestHarnessReadOnly } from "./readOnlyGuard.js";

// 🔒 Тестовий режим не сміє відкрити пул до бойової БД повз роль `test_readonly`.
// У бойовому процесі (`TEST_SCOPE` не виставлено) — no-op: див. readOnlyGuard.ts.
// Стоїть ПЕРЕД `new Pool`, щоб падіння сталося ДО першого запиту, а не після нього.
assertTestHarnessReadOnly();

/**
 * 🔴 Обмеження пулу (2 ГБ shared-акаунт adm.tools, crash-loop 15.07.2026): дефолт pg =
 * 10 конекшенів/процес. Під час crash-loop кожен убитий (SIGKILL) процес НЕ кликав
 * `pool.end()` → відкриті конекшени до Neon накопичувались і компаундили тиск на
 * памʼять/квоту. Тримаємо мінімум конекшенів і швидко відпускаємо idle. Ліміт конекту
 * 10с — щоб буут не завис на Neon, а впав швидко й чисто (Supervisor підніме).
 */
export const pool = new Pool({
  connectionString: config.databaseUrl,
  // 🔴 6 → 15 (рішення власника 05.08.2026, заміряно).
  // `/overview` робить **35 запитів** на один запит екрана. При `max: 6` четверо
  // одночасних користувачів ставили 140 запитів у чергу на 6 зʼєднань — саме тому
  // час подвоювався під навантаженням (1 користувач 8 с → 4 користувачі 16 с), а
  // не через «важкий запит». Ліміт Neon для нашого компʼюта — `max_connections=901`
  // (заміряно), тож 15 не наближає нас до нього навіть близько.
  //
  // ⚠️ ЧОМУ НЕ ПЕРЕХОДИМО НА POOLED-ЕНДПОІНТ NEON, хоч це «канонічна» відповідь на
  // багато зʼєднань: пулер працює в transaction mode, а наш read-only запобіжник
  // стоїть на `PGOPTIONS=-c role=test_readonly` у СТАРТОВОМУ пакеті зʼєднання.
  // Через пулер сесійні опції не гарантовані — тобто ми проміняли б доведений
  // запобіжник на економію зʼєднань, яких у нас 901. Лишаємось на прямому.
  max: 15,
  idleTimeoutMillis: 30_000,
  connectionTimeoutMillis: 10_000,
});
