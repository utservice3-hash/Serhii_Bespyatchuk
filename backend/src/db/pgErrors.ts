/**
 * 🔒 РОЗПІЗНАВАЧ «НЕДОСТАТНЬО ПРАВ» (SQLSTATE 42501) — щоб читання не гинуло від
 * побічного запису.
 *
 * 📐 АВАРІЯ, ЯКА ЦЕ КУПИЛА (14.09.2026, гейт `#211f`). GET-роут Звіту тягне тижневі
 * плани, а `weekPlansForMonth` ПОБІЧНО морозить знімки, яких ще немає
 * (`INSERT INTO weekly_plan_snapshots`). Приймання ходить роллю `test_readonly`,
 * тож на новому періоді, коли знімок відсутній, INSERT падав 42501 — і разом із ним
 * падав УВЕСЬ read-роут, хоча числа для відповіді вже були пораховані. Гейт червонів
 * три викати поспіль без жодної правки в його зоні: міна на календарі, а не регресія.
 *
 * Правило: знімок — ІСТОРІЯ, а не відповідь. Не змогли записати історію — віддаємо
 * відповідь і кажемо про це в лог. Будь-яка ІНША помилка запису лишається помилкою:
 * ковтати все підряд означало б сховати справжні поломки під тим самим підписом.
 */
export function isInsufficientPrivilege(e: unknown): boolean {
  return typeof e === "object" && e !== null && (e as { code?: unknown }).code === "42501";
}
