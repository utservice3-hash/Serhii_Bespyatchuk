/**
 * МОВЧАЗНІ ДВЕРІ 1×1: порожня відповідь — це не відмова.
 *
 * 🔴 Привід — скарга власника й замір за нею (27.08.2026). КВП відкривав екран 1×1 і
 * бачив НІЧОГО: `/subjects` і `/record` віддавали 403, а `/meetings`, `/stats/scores`
 * і `/enps` — чесні `200` з порожнім тілом. Причина одна (немає права `view_all_1x1`),
 * а на екрані це читалось як поломка продукту, і людина принесла це як баг, а не як
 * брак доступу.
 *
 * 🔴 Видача прав КВП і адміну цей КЛАС не закриває. Заміряно: з екраном `oneonone` і
 * БЕЗ права лишаються `financier` і `team_lead` — це 1 фінансист і 6 тімлідів. Вони
 * побачать рівно те саме. Тому двері мусять відповідати словами.
 *
 * ⚠️ `/conduct-types` НАВМИСНО лишається `200` навіть із порожнім `types`. Це
 * endpoint-довідка, з якої фронт дізнається, що саме людині можна; віддати там 403
 * означало б зламати екран усім, хто прав не має, замість того щоб пояснити причину.
 * Тобто рівно одне місце має право відповідати порожнечею — те, чия відповідь і є
 * «вам доступно ось стільки».
 */

/** Текст відмови. Одна константа, бо його звіряє гейт — і бачить людина. */
export const ONE_ON_ONE_DENY =
  "Немає доступу до 1×1 цього типу: потрібне право наскрізного перегляду (view_all_1x1) " +
  "або власні проведені зустрічі цього типу.";

/**
 * `null` = показувати дані. Рядок = віддати 403 із цим текстом.
 *
 * Логіка навмисно вузька: відмовляємо ЛИШЕ тоді, коли вибірка не може бути
 * непорожньою в принципі — немає наскрізного перегляду І немає права проводити
 * цей тип, тобто предикат `conducted_by = я` не збігається ні з чим ніколи.
 * Тімлід, який проводить тип A, і далі бачить свої зустрічі — його не зачіпає.
 */
export function viewDenied(hasCrossview: boolean, canConductThisType: boolean): string | null {
  return hasCrossview || canConductThisType ? null : ONE_ON_ONE_DENY;
}
