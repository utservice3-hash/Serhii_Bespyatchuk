/**
 * 🗓 РОЗВ'ЯЗАННЯ ПЕРІОДУ — КОДОМ, А НЕ ПРОХАННЯМ У ПРОМТІ.
 *
 * НАВІЩО. Гейт 31.07.2026 спіймав: на питання «звіт по клієнту за червень» модель
 * один прогін із семи взяла **червень 2025** замість 2026 і тихо видала 43 500 ₴
 * замість 77 220 ₴. Правило про рік жило лише текстом у промті — тобто трималось на
 * тому, що модель його щоразу згадає. Не згадала.
 *
 * ПРАВИЛО (рішення власника 31.07.2026): місяць названо БЕЗ року → береться
 * **НАЙБЛИЖЧЕ МИНУЛЕ входження** цього місяця відносно сьогодні.
 *   • сьогодні липень 2026, питають «червень»  → червень 2026
 *   • сьогодні січень 2027, питають «грудень»  → грудень 2026 (а НЕ грудень 2027)
 *   • питають поточний місяць                  → поточний, позначений неповним
 *
 * ⚠️ Чому не «поточний рік»: у січні спитають про грудень — і «поточний рік» дасть
 * грудень МАЙБУТНІЙ, тобто порожній період. Найближче минуле входження цього не має.
 *
 * `today` передається аргументом (не читається всередині) саме щоб крайні випадки
 * тестувались підстановкою дати, а не чеканням січня.
 */

/** Називний і родовий відмінки + латиниця/цифри — усе, чим модель може назвати місяць. */
const MONTH_FORMS: Record<string, number> = {
  "січень": 1, "січня": 1, "january": 1, "jan": 1,
  "лютий": 2, "лютого": 2, "february": 2, "feb": 2,
  "березень": 3, "березня": 3, "march": 3, "mar": 3,
  "квітень": 4, "квітня": 4, "april": 4, "apr": 4,
  "травень": 5, "травня": 5, "may": 5,
  "червень": 6, "червня": 6, "june": 6, "jun": 6,
  "липень": 7, "липня": 7, "july": 7, "jul": 7,
  "серпень": 8, "серпня": 8, "august": 8, "aug": 8,
  "вересень": 9, "вересня": 9, "september": 9, "sep": 9,
  "жовтень": 10, "жовтня": 10, "october": 10, "oct": 10,
  "листопад": 11, "листопада": 11, "november": 11, "nov": 11,
  "грудень": 12, "грудня": 12, "december": 12, "dec": 12,
};

const MONTH_UK = ["січень", "лютий", "березень", "квітень", "травень", "червень",
  "липень", "серпень", "вересень", "жовтень", "листопад", "грудень"];

export interface ResolvedPeriod {
  from: string;
  to: string;
  /** Людський підпис — модель ЗОБОВ'ЯЗАНА назвати його у відповіді («червень 2026»). */
  label: string;
  /** Поточний місяць ще не завершився — цифри неповні. */
  incomplete: boolean;
  /** Пояснення, якщо код виправив те, що передала модель. Мовчазних правок не робимо. */
  correction?: string;
}

/** Номер місяця з назви («червень», «червня», «June», «6», «06») або null. */
export function parseMonth(input: string | number): number | null {
  if (typeof input === "number") return input >= 1 && input <= 12 ? input : null;
  const s = String(input).trim().toLowerCase();
  if (/^\d{1,2}$/.test(s)) { const n = +s; return n >= 1 && n <= 12 ? n : null; }
  return MONTH_FORMS[s] ?? null;
}

const pad = (n: number) => String(n).padStart(2, "0");
const lastDay = (y: number, m: number) => new Date(Date.UTC(y, m, 0)).getUTCDate();

/**
 * Місяць без року → найближче МИНУЛЕ входження (поточний місяць вважається «своїм»).
 * @param today київська дата «YYYY-MM-DD»
 */
export function resolveNamedMonth(monthInput: string | number, today: string): ResolvedPeriod | null {
  const m = parseMonth(monthInput);
  if (m == null) return null;
  const ty = +today.slice(0, 4), tm = +today.slice(5, 7);
  // Місяць пізніший за поточний ще НЕ настав цього року → беремо торішній.
  const y = m > tm ? ty - 1 : ty;
  const incomplete = y === ty && m === tm;
  return {
    from: `${y}-${pad(m)}-01`,
    to: `${y}-${pad(m)}-${pad(lastDay(y, m))}`,
    label: `${MONTH_UK[m - 1]} ${y}`,
    incomplete,
  };
}

/**
 * Страхувальна сітка для випадку, коли модель ПОРАХУВАЛА дати сама. Період, що
 * цілком лежить у майбутньому, не може бути тим, що просив користувач: даних там
 * нема за визначенням. Зсуваємо на рік назад і ГУЧНО про це повідомляємо — мовчазна
 * правка періоду гірша за помилку, бо її не видно.
 */
export function guardFuturePeriod(from: string | null | undefined, to: string | null | undefined, today: string): ResolvedPeriod | null {
  if (!from || !to || from > to) return null;
  if (from <= today) return null; // період уже почався — не наша справа
  const shift = (d: string) => `${+d.slice(0, 4) - 1}${d.slice(4)}`;
  const nf = shift(from), nt = shift(to);
  const m = +nf.slice(5, 7);
  return {
    from: nf, to: nt,
    label: nf.slice(0, 7) === nt.slice(0, 7) ? `${MONTH_UK[m - 1]} ${nf.slice(0, 4)}` : `${nf} … ${nt}`,
    incomplete: false,
    correction: `запитаний період ${from}…${to} цілком у майбутньому (сьогодні ${today}) — узято ${nf}…${nt}`,
  };
}
