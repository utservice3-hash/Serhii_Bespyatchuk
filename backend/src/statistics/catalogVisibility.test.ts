import { test } from "node:test";
import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import path from "node:path";
import { CATALOG, HIDDEN_DEPARTMENTS, visibleDepartments, getMetric } from "./catalog.js";

/**
 * 👁 #363 / #363b — ЩО САМЕ СХОВАНО В СТАТИСТИКАХ, І ЧОМУ ЦЕ ДВА РІЗНІ ЕКРАНИ.
 *
 * 🔴 ЦЕЙ ФАЙЛ ЗАМІНЮЄ `#355`, ЯКИЙ СТВЕРДЖУВАВ ПРОТИЛЕЖНЕ. `#355` вимагав, щоб
 * `finance` і `hr` ЗНИКЛИ з видачі. Заміряно 08.09.2026, що вказівку власника тоді
 * розвʼязали проти НЕ ТОГО розділу: він показував на вкладку **«Ручні»** (✍️) у розділі
 * «Статистики», а сховали два ВІДДІЛИ в «Статистиках (відділах)». Ціна: названу ціль не
 * зачепили, зате прибрали 26 метрик, з яких 18 не було видно ніде, і випустили новину,
 * яку можна спростувати двома кліками.
 *
 * ⚠️ Правило 13 забороняє «уточнити назву»: змінилось твердження — новий номер. Тому
 * `#355` знято записом у `RETIRED_GATES`, а не переписано на місці.
 *
 * 🔴 ЧОМУ ГЕЙТІВ ДВА, А НЕ ОДИН. Розділи різні, і предмети різні: `#363` стереже, що
 * СЕРВЕР більше нікого не ховає, `#363b` — що ФРОНТ не показує вхід у ручний ввід.
 * Один гейт на обидва зеленів би, поки виконана хоч одна половина, — а помилка 07.09
 * була саме в тому, що зробили одну половину замість іншої.
 */

/** Читання ДЖЕРЕЛА фронта — той самий прийом, що `#24d`/`#52b`/`#107`. */
const SRC_ROOTS = [
  path.join(import.meta.dirname, "..", ".."),
  path.join(import.meta.dirname, "..", "..", ".."),
  path.join(import.meta.dirname, "..", "..", "..", ".."),
];
function readSrc(rel: string): string {
  for (const r of SRC_ROOTS) {
    try { return readFileSync(path.join(r, rel), "utf8"); } catch { /* далі */ }
  }
  assert.fail(`не знайдено ${rel} — перевірка не має права мовчки пропускатись`);
}

test("#363 каталог відділів віддається ЦІЛКОМ — сховано нікого", () => {
  assert.deepEqual([...HIDDEN_DEPARTMENTS], [],
    `🔴 знову щось ховаємо: ${HIDDEN_DEPARTMENTS.join(", ")}. Рішення власника 08.09.2026 — `
    + "не ховати жодного відділу; ховається ВКЛАДКА «Ручні» у сусідньому розділі (#363b)");

  const shown = visibleDepartments().map((d) => d.key);
  assert.deepEqual(shown, CATALOG.map((d) => d.key),
    "🔴 видача розійшлась із каталогом — зʼявився фільтр повз `HIDDEN_DEPARTMENTS`");

  // 🎯 Поіменно саме ті два, які колись сховали помилково. Без цього гейт лишився б
  //    зеленим, якби `finance`/`hr` прибрали з КАТАЛОГУ замість списку схованих —
  //    видача й далі дорівнювала б каталогу, тільки вже урізаному.
  for (const back of ["finance", "hr"]) {
    assert.ok(shown.includes(back),
      `🔴 «${back}» знову не на екрані. 08.09.2026 його повернули свідомо: сховали його `
      + "07.09 через те, що вказівку про вкладку «Ручні» розвʼязали проти іншого розділу");
  }

  // 🪞 Дзеркало проти порожнечі: рівність «видача == каталог» істинна і на двох
  //    порожніх списках, тобто на екрані, який не показує нічого.
  assert.ok(shown.length >= 4,
    `🔴 у каталозі лишилось ${shown.length} відділів — рівність вище перевіряє порожнечу`);

  // Довідник цілий: метрика схованого колись відділу знаходиться (ручний запис і
  // CSV-імпорт спираються на `csvIndexMonth`/`csvIndexWeek` саме в цих метриках).
  const fin = CATALOG.find((d) => d.key === "finance");
  assert.ok(fin && getMetric("finance", fin.metrics[0]!.key),
    "🔴 метрика «Фінансів» більше не знаходиться — зламається CSV-імпорт");
});

test("#363b вкладка «Ручні» не має входу на екрані, але запис у каталозі цілий", () => {
  const src = readSrc(path.join("frontend", "src", "pages", "dashboard", "sections", "StatisticsChartsSection.tsx"));

  // ① Вхід прибрано: панель вкладок відсіює `manualForm`.
  assert.match(src, /CATS\.filter\(\(c\) => !c\.manualForm\)\.map\(/,
    "🔴 вкладка «Ручні» знову в панелі — саме її власник просив прибрати 07.09.2026, "
    + "і саме її тоді НЕ прибрали, сховавши натомість два чужі відділи");

  // ② 🪞 Дзеркало: сам запис ЛИШИВСЯ. Видалення впало б на `CATS.find(...)!` у
  //    `ManualForm`, і «сховали» перетворилось би на «зламали».
  assert.match(src, /key: "manual",[^\n]*manualForm: true/,
    "🔴 запис `manual` зник із CATS — `ManualForm` читає його через `!`, тобто екран впаде. "
    + "Ховаємо подачу, а не зміст");

  // ③ Межа названа: це фронт, і роут ручного запису лишається живим для адміна.
  //    Гейт стереже, що межу не забули задокументувати — інакше через півроку її
  //    приймуть за «ручний ввід прибрано зовсім».
  assert.match(src, /POST \/statistics\/manual` лишається|\/statistics\/manual`? лишається/,
    "🔴 зник коментар про те, що роут ручного запису живий: «сховано з екрана» почнуть "
    + "читати як «прибрано зовсім», і наступний закриє роут, не знаючи, що це нове рішення");
});
