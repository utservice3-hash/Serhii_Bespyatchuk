/**
 * Гейти двох когортних конверсій (01.09.2026).
 *
 *   #24z — чисельник і знаменник із ОДНІЄЇ когорти (саме це ламає старі поля з листа);
 *   #24t — поріг ≥10 віддає «—», а не нуль, і перевірено ОБИДВА боки межі;
 *   #24u — значення приходить із ядра, а не з власної копії SQL у писарі.
 *
 * 🪤 ПРО САБОТАЖ, І ЦЕ ВАЖЛИВІШЕ ЗА САМІ ГЕЙТИ. Минулого проходу я спроєктував
 * саботаж СИНФАЗНИМ: зламав ядро там, де обидві сторони рівності приходять з
 * одного виклику, — і гейт лишився зеленим. Це «саботаж не в те місце», а НЕ
 * «беззубий гейт»; плутати не можна, бо перший висновок веде переписувати
 * робочий гейт. Тут пастка обійдена за побудовою: жоден із трьох гейтів не
 * порівнює ядро САМЕ ІЗ СОБОЮ.
 *   · #24z стверджує ВЛАСТИВІСТЬ (`won ⊆ entered`), а не рівність двох викликів,
 *     тож ламається саме тоді, коли чисельник перестає бути підмножиною;
 *   · #24t — чиста функція на фікстурі, ядро тут ні до чого;
 *   · #24u читає ДЖЕРЕЛО писаря, а не його вивід.
 */

test("#24z ОДНА КОГОРТА: чисельник — підмножина знаменника, а не окреме число", needsDb(), async () => {
  const m = await import("../core/metrics.js");

  for (const kind of ["new", "leadgen"] as const) {
    const rows = await m.conversionCohortByBucket(kind, "month", "2026-01-01");

    // ⚠️ Спершу доводимо, що перевірці БУЛО що знаходити: порожній набір
    // задовольнив би «won ≤ entered» тривіально.
    assert.ok(rows.length >= 3,
      `🔴 ${kind}: бакетів ${rows.length} — замало, щоб щось довести`);

    for (const r of rows) {
      assert.ok(r.won <= r.entered,
        `🔴 ${kind} ${r.bucket}: дійшли ${r.won} > увійшли ${r.entered}. Чисельник рахується `
        + "НЕ по тій самій когорті — це рівно хвороба полів із листа, де чисельник і "
        + "знаменник є двома незалежними числами й можуть стосуватись різних угод");
      assert.ok(r.won >= 0 && r.entered >= 0, `🔴 ${kind} ${r.bucket}: відʼємні лічильники`);
    }

    // Дзеркало: набір не вироджений. Якби won був завжди 0 або завжди == entered,
    // «підмножина» була б істинною й ні про що не свідчила.
    const meaningful = rows.filter((r) => r.won > 0 && r.won < r.entered);
    assert.ok(meaningful.length > 0,
      `🔴 ${kind}: у жодному бакеті немає 0 < дійшли < увійшли — когорта вироджена, `
      + "і властивість підмножини нічого не доводить");
  }
});

test("#24t ПОРІГ ≥10 ВІДДАЄ «—», А НЕ НУЛЬ — обидва боки межі", async () => {
  const m = await import("../core/cohortRule.js"); // 🔴 БЕЗ metrics.js: він тягне config і JWT_SECRET
  assert.equal(m.COHORT_MIN_ENTERED, 10, "🔴 поріг зрушив — це рішення власника, не наше");

  // 🔴 ОБИДВА БОКИ, інакше фікстура доводить лише те, що функція щось повертає.
  assert.equal(m.cohortPct(5, 9), null,
    "🔴 при знаменнику 9 повернулось число — «замало даних» подано як вимір");
  assert.notEqual(m.cohortPct(5, 10), null,
    "🔴 при знаменнику 10 повернувся null — поріг зрушив угору й ховає справжні виміри");
  assert.equal(m.cohortPct(5, 10), 50, "🔴 арифметика відсотка зламалась");

  // 🔴 І окремо: нижче порога це саме `null`, а НЕ нуль. Нуль falsy й читається
  // як «конверсія нульова» — стверджує вимір, якого не робили.
  assert.notEqual(m.cohortPct(0, 9), 0,
    "🔴 нижче порога віддано 0 замість null — «немає даних» перетворилось на «нуль відсотків»");
  assert.equal(m.cohortPct(0, 10), 0,
    "🔴 чесний нуль на достатньому знаменнику зник — це вже втрата виміру");
});

test("#24u ПИСАР КЛИЧЕ ЯДРО — власного SQL у ньому немає", async () => {
  const fs = await import("node:fs/promises");
  const url = await import("node:url");
  const src = await fs.readFile(
    url.fileURLToPath(new URL("../../src/statistics/computeAuto.js".replace(".js", ".ts"), import.meta.url)),
    "utf8");

  // 🔴 Межа зрізу СЕМАНТИЧНА: від оголошення писаря до кінця файла. Зріз по
  // довжині вже одного разу зробив гейт беззубим — саботаж не потрапляв у вікно.
  const from = src.indexOf("export async function computeCohortConversions");
  assert.ok(from > 0, "🔴 не знайдено писаря — гейт втратив предмет");
  const body = src.slice(from);

  assert.match(body, /conversionCohortByBucket\(/,
    "🔴 писар не кличе ядрову `conversionCohortByBucket` — означення переїхало кудись іще");
  assert.doesNotMatch(body, /pool\.query/,
    "🔴 у писарі зʼявився власний SQL. Така копія зійдеться з копією, а не з правилом, "
    + "і розійдеться з Оглядом через місяці — рівно так розійшлись поля з Google-листа");
  assert.doesNotMatch(body, />=\s*10|COHORT_MIN_ENTERED\s*=/,
    "🔴 поріг продубльовано в писарі — він мусить бути в ЯДРІ одним місцем");
});

/**
 * 🏷 #24a — ПІДПИС ПРО ДРЕЙФ СТОЇТЬ РІВНО ТАМ, ДЕ ДРЕЙФ.
 *
 * Дві сусідні колонки поводяться по-різному, і це не дрібниця оформлення:
 *   · `conversion_new_crm` РУХОМА. Сегмент «новий» визначається за ПОТОЧНИМ
 *     станом попередніх угод клієнта: стара угода стає оплаченою — і серпнева
 *     виходить зі знаменника. Чисельник теж поточний і росте. Заміряно
 *     01.09.2026: за 12 годин 1670→1664 і 199→201, тобто те саме «за серпень»
 *     завтра буде іншим;
 *   · `conversion_leadgen_crm` НЕ рухома — `lead_channel` статичний, і замір у
 *     ті самі дві миті дав 456/82 обидва рази, до одиниці.
 *
 * 🔴 ТОМУ ГЕЙТ ДВОБІЧНИЙ, і друга половина важливіша. Поставити той самий підпис
 * обом колонкам — брехня в ІНШИЙ бік: читач почне не довіряти числу, яке насправді
 * стабільне. Односторонній гейт («у рухомої підпис є») зеленів би й тоді, коли
 * підпис навішено на все підряд.
 *
 * Прецедент підпису — наш власний: «Дебіторка (знімок), грн». Знімок і рухоме
 * число мусять називати себе В КОЛОНЦІ, а не лише в підказці, бо підказку
 * читають після того, як уже повірили числу.
 */
test("#24a ПІДПИС ПРО ДРЕЙФ — рівно на рухомій колонці, і ні на якій іншій", async () => {
  const { getMetric } = await import("./catalog.js");
  const DRIFT = /заднім числом/;

  const moving = getMetric("marketing", "conversion_new_crm");
  assert.ok(moving, "🔴 метрики conversion_new_crm у каталозі немає — гейт втратив предмет");
  assert.match(moving.label, DRIFT,
    `🔴 рухома колонка не називає свою властивість у ПІДПИСІ: «${moving.label}». `
    + "Число за серпень завтра буде іншим, і читач мусить дізнатись про це з колонки, "
    + "а не з підказки, яку відкривають уже повіривши числу");

  const stable = getMetric("marketing", "conversion_leadgen_crm");
  assert.ok(stable, "🔴 метрики conversion_leadgen_crm у каталозі немає");
  assert.doesNotMatch(stable.label, DRIFT,
    `🔴 підпис про дрейф навішено на СТАБІЛЬНУ колонку: «${stable.label}». `
    + "lead_channel статичний, число не рухається — це брехня в інший бік");
});
