import { test } from "node:test";
import assert from "node:assert/strict";
import { CATALOG, getMetric } from "./catalog.js";

/**
 * 🏷 ПІДПИС НА ЕКРАНІ КАЖЕ ПРАВДУ (01.09.2026, продовження заміру Статистик).
 *
 * Чотири твердження, і всі — про те, що людина бачить, не про внутрішній устрій:
 *   #26a — знімок називає себе, І ТІЛЬКИ знімок (двобічно);
 *   #26g — колонка, що не рахує обіцяного, каже про це (мітка звʼязана зі станом джоби);
 *   #26k — підпис несе ОБИДВА застереження, і жодне не зʼїло назву показника;
 *   #26e — `ad_leads` більше не рахується-і-викидається.
 *
 * 🪤 Про синфазний саботаж (ловив себе двічі): жоден гейт тут не порівнює каталог
 * сам із собою. `#26a` звіряє ПЕРЕЛІК знімків із підписами; `#26g` звіряє підпис
 * із КОДОМ джоби. Зламати спільне джерело обох сторін нема де.
 *
 * 🪦 `#26c`/`#26d` знято 02.09.2026 через `RETIRED_GATES`: обидва стверджували, що
 * «поставлені» дорівнюють «успішним», а після виправлення означення це неправда.
 */

/**
 * Ті метрики, що рахуються БЕЗ фільтра дати й кладуться в поточний бакет.
 * Перелік — від предмета, а не від слівця в підписі: саме так `recomputeStatistics`
 * і пише їх (запит `snap` + `managers_count`), і це перевіряє `#26d`.
 */
const ЗНІМКИ = ["payment_received", "invoiced_amount", "managers_count", "machines_dispatched"] as const;
/** Справжні періодні метрики продажів — контроль до другої половини `#26a`. */
const ПЕРІОДНІ = ["revenue_won", "machines_success", "cash_deals_amount", "calls"] as const;
const МІТКА = /знімок/i;

test("#26a ЗНІМОК НАЗИВАЄ СЕБЕ — і мітка не стоїть на справжньому періоді", () => {
  for (const key of ЗНІМКИ) {
    const m = getMetric("sales", key);
    assert.ok(m, `🔴 метрики ${key} у каталозі немає — гейт втратив предмет`);
    assert.match(m.label, МІТКА,
      `🔴 «${m.label}» — знімок, підписаний як період. Рядок «липень» для нього означає `
      + "не липень, а стан бази в останню годину липня; читач цього не дізнається");
  }

  // 🔴 ДРУГА ПОЛОВИНА, І ВОНА ВАЖЛИВІША. Односторонній гейт зеленів би й тоді,
  // коли мітку навісили на все підряд — а це брехня в інший бік: читач перестав
  // би довіряти числу, яке насправді рахує період.
  for (const key of ПЕРІОДНІ) {
    const m = getMetric("sales", key);
    assert.ok(m, `🔴 метрики ${key} у каталозі немає`);
    assert.doesNotMatch(m.label, МІТКА,
      `🔴 «${m.label}» рахує ПЕРІОД (анкер closed_at_kommo або власний синк), але підписаний знімком`);
  }

  // І дзеркало до дзеркала: мітка взагалі десь стоїть. Порожній перелік знімків
  // зробив би першу половину істинною тривіально.
  const усі = CATALOG.flatMap((d) => d.metrics);
  assert.ok(усі.filter((m) => МІТКА.test(m.label)).length >= ЗНІМКИ.length,
    "🔴 мітки «знімок» немає в каталозі взагалі — перевіряти нема чого");
});

test("#26e AD_LEADS БІЛЬШЕ НЕ РАХУЄТЬСЯ-І-ВИКИДАЄТЬСЯ", async () => {
  const fs = await import("node:fs/promises");
  const url = await import("node:url");
  const src = await fs.readFile(
    url.fileURLToPath(new URL("../../src/statistics/computeAuto.ts", import.meta.url)), "utf8");

  // Ключ і далі вимкнений — це рішення власника (наше означення розходиться з
  // листом на ~30%), і гейт його НЕ переглядає, лише фіксує.
  // 🔴 Читаємо БІЛИЙ СПИСОК ІЗ ДЖЕРЕЛА, а не імпортом: `computeAuto.js` тягне
  // `db/pool` → `config` → `JWT_SECRET`, і гейт падав би в кожному оточенні без
  // `.env` — і в контейнері, і в стенді. Той самий урок, що `core/cohortRule.ts`.
  const whitelist = src.slice(src.indexOf("DEPT_AUTO_ENABLED"), src.indexOf("]);", src.indexOf("DEPT_AUTO_ENABLED")));
  assert.ok(whitelist.length > 0, "🔴 не знайдено білого списку — гейт втратив предмет");
  assert.doesNotMatch(whitelist, /marketing\|ad_leads/,
    "🔴 ad_leads увімкнули без рішення власника — означення розходиться з листом на ~30%");

  // 🔴 А ось запиту бути не має: рахувати щогодини й викидати — це не обережність,
  // це витрата. Повний прохід по deals із корельованим предикатом, двічі на годину.
  assert.doesNotMatch(src, /set\((?:\s|\n)*"marketing",[^)]*"ad_leads"/,
    "🔴 ad_leads знову рахується й одразу відкидається `set()` — саме це ми й прибрали");
  // 🔴 ПРЕДИКАТ ПО МЕХАНІЗМУ, А НЕ ПО ПРОЗІ. Перша редакція шукала слово
  // `adDealSql` будь-де у файлі — і червоніла на КОМЕНТАРІ, який пояснює, чому
  // запит прибрано. Заборонити пояснення — не те, чого ми хочемо; важить факт
  // ІМПОРТУ: він означає, що предикат знову хтось виконує.
  const importLine = src.split("\n").find((l) => l.startsWith("import") && l.includes("core/metrics.js")) ?? "";
  assert.ok(importLine.length > 0, "🔴 не знайдено імпорту з ядра — гейт втратив предмет");
  assert.doesNotMatch(importLine, /adDealSql/,
    "🔴 у computeAuto повернувся імпорт adDealSql — єдиним його читачем був викинутий запит ad_leads");
});

test("#26f ЗАМОРОЖЕНЕ ДЖЕРЕЛО ПОЗНАЧЕНЕ — і мітка знімається разом із розморожуванням", async () => {
  const fs = await import("node:fs/promises");
  const url = await import("node:url");
  const src = await fs.readFile(
    url.fileURLToPath(new URL("../../src/statistics/computeAuto.ts", import.meta.url)), "utf8");

  const whitelist = src.slice(src.indexOf("DEPT_AUTO_ENABLED"), src.indexOf("]);", src.indexOf("DEPT_AUTO_ENABLED")));
  assert.ok(whitelist.length > 0, "🔴 не знайдено білого списку — гейт втратив предмет");
  const живе = /marketing\|ad_leads/.test(whitelist);

  const m = getMetric("marketing", "ad_leads");
  assert.ok(m, "🔴 метрики ad_leads у каталозі немає");
  const МІТКА_ЗАМОРОЗКИ = /не оновлюється/i;

  /**
   * 🔴 ПІДПИС ЗВʼЯЗАНИЙ ЗІ СТАНОМ, А НЕ З ПАМʼЯТТЮ. Дати в мітці немає свідомо:
   * зашите «заморожено 06.2026» протухло б МОВЧКИ, щойно джерело зʼявиться, і
   * ми знову показували б неправду — лише в інший бік. Тому мітка перевіряється
   * ПРОТИ БІЛОГО СПИСКУ: доки ключ вимкнений, вона мусить стояти; щойно його
   * увімкнуть — мусить зникнути, і гейт цього вимагатиме сам.
   */
  if (живе) {
    assert.doesNotMatch(m.label, МІТКА_ЗАМОРОЗКИ,
      `🔴 ad_leads УВІМКНЕНО в DEPT_AUTO_ENABLED, але підпис «${m.label}» досі каже, що не `
      + "оновлюється. Мітка пережила свою причину — це брехня в інший бік");
  } else {
    assert.match(m.label, МІТКА_ЗАМОРОЗКИ,
      `🔴 ad_leads НЕ рахується (ключа немає в білому списку), а підпис «${m.label}» цього не `
      + "каже. Читач бачить старе число як поточне — джерелом істини стане рекламний кабінет "
      + "через API, а до того колонка мусить називати себе замороженою");
  }

  // Дзеркало: мітка не розповзлась на живі метрики того самого відділу.
  for (const key of ["non_target_leads", "ad_budget_total"]) {
    const live = getMetric("marketing", key);
    assert.ok(live, `🔴 метрики ${key} немає`);
    assert.doesNotMatch(live.label, МІТКА_ЗАМОРОЗКИ,
      `🔴 «${live.label}» рахується щогодини, але підписана як заморожена`);
  }
});

test("#26g КОЛОНКА, ЩО НЕ РАХУЄ ОБІЦЯНОГО, КАЖЕ ПРО ЦЕ — і мітка знімається разом із виправленням", async () => {
  /**
   * 🔴 ЧОМУ ЦЕ ОКРЕМИЙ ГЕЙТ, А НЕ ДРУГЕ ТВЕРДЖЕННЯ В `#26c`. Вони кажуть різне.
   * `#26c` фіксує ФАКТ: дві колонки показують одне число. Він і далі правдивий.
   * `#26g` фіксує, що цей факт — ДЕФЕКТ, а не задум: власник 01.09.2026 означив
   * «відправлені» як «створені в цьому місяці ∧ поїхали ∧ оплата ще НЕ зайшла»,
   * тобто рівно тих, кого нинішня колонка виключає. Перетин нинішнього й
   * правильного населення — нуль за побудовою (заміряно: серпень 955 проти
   * 213–310, липень 1 004 проти 79–150).
   *
   * 🔴 МІТКА ЗВʼЯЗАНА ЗІ СТАНОМ, А НЕ З ПАМʼЯТТЮ — той самий устрій, що в `#26f`.
   * Доки джоба пише `machines_dispatched` із числа успішних, мітка мусить стояти;
   * щойно підміну приберуть — мусить зникнути, і гейт цього вимагатиме сам. Дата
   * в підписі протухла б мовчки, а «прибрати мітку» ніхто б не згадав.
   */
  const fs = await import("node:fs/promises");
  const url = await import("node:url");
  const job = await fs.readFile(
    url.fileURLToPath(new URL("../../src/jobs/recomputeStatistics.ts", import.meta.url)), "utf8");
  const підмінено = /add\(ptype, r\.bucket, lead, "machines_dispatched", Number\(r\.succ\)\)/.test(job);

  const disp = getMetric("sales", "machines_dispatched");
  assert.ok(disp, "🔴 machines_dispatched зник із каталогу — гейт втратив предмет");
  const МІТКА_ПІДМІНИ = /означення не реалізовано/i;

  if (підмінено) {
    assert.match(disp.label, МІТКА_ПІДМІНИ,
      `🔴 «${disp.label}» обіцяє «поставлені машини», а джоба кладе туди кількість УСПІШНИХ — `
      + "тобто рівно тих, у кого оплата вже зайшла, при означенні «оплата ще НЕ зайшла». "
      + "Читач бачить 955 там, де правильне число 213–310, і колонка про це мовчить");
  } else {
    assert.doesNotMatch(disp.label, МІТКА_ПІДМІНИ,
      `🔴 підміну в джобі прибрано, а підпис «${disp.label}» досі каже, що означення не `
      + "реалізовано. Мітка пережила свою причину — це брехня в інший бік");
  }

  // 🔴 ДРУГА ПОЛОВИНА: мітка стоїть РІВНО на одній метриці всього каталогу.
  // Без неї гейт зеленів би й тоді, коли «не реалізовано» навісили на все підряд —
  // а тоді підпис перестає щось означати саме тому, що стоїть скрізь.
  const усі = CATALOG.flatMap((d) => d.metrics).filter((m) => МІТКА_ПІДМІНИ.test(m.label));
  assert.deepEqual(усі.map((m) => m.key), підмінено ? ["machines_dispatched"] : [],
    `🔴 мітку «означення не реалізовано» несуть ${усі.map((m) => m.key).join(", ") || "жодна"} — `
    + "а мусить рівно та колонка, чия підміна доведена заміром");
});

test("#26k ПІДПИС НЕСЕ ОБИДВА ЗАСТЕРЕЖЕННЯ — і жодне не зʼїло назву показника", () => {
  /**
   * 🔴 ДВА ЗАСТЕРЕЖЕННЯ, І ВОНИ НЕ ПРО ОДНЕ Й ТЕ САМЕ — тому одного замало, і одне
   * не заміняє друге:
   *   «знімок»      — число показує стан НА СЬОГОДНІ, тому місяці не порівнюються
   *                   між собою (заміряно: серпень 250, грудень 2025 — 3);
   *   «з 07.2026»   — до липня 2026 в цій колонці лежить ІНША величина (копія
   *                   «успішних»), і вона не перерахується ніколи: джоба бачить
   *                   лише останні 75 днів.
   * Читач, що знає лише перше, порівняє червень із серпнем і побачить обвал; читач,
   * що знає лише друге, візьме липневе число за підсумок липня.
   *
   * 🔴 І ТРЕТЯ ПОЛОВИНА — ПРО ТЕ, ЧОГО МИ ВЖЕ ОДНОГО РАЗУ ЗАЗНАЛИ: підпис, що виріс,
   * витісняє з заголовка сам показник. Тому гейт вимагає, щоб НАЗВА стояла попереду
   * й лишалась читаною, а застереження — після неї й у межах довжини заголовка.
   */
  const m = getMetric("sales", "machines_dispatched");
  assert.ok(m, "🔴 machines_dispatched зник із каталогу — гейт втратив предмет");

  const ЗНІМОК = /знімок/i, ОЗНАЧЕННЯ = /означення з \d{2}\.\d{4}/i;
  assert.match(m.label, ЗНІМОК,
    `🔴 «${m.label}» не каже, що це стан на сьогодні. Рядок «грудень» для нього означає `
    + "не грудень, а те, що з грудневих угод висить неоплаченим ЗАРАЗ, — заміряно 3 проти 897 у листі");
  assert.match(m.label, ОЗНАЧЕННЯ,
    `🔴 «${m.label}» не каже, з якого місяця чинне нове означення. До 07.2026 в колонці лежить `
    + "копія «успішних угод» (~700-1000), і вона не перерахується: RECENT_DAYS = 75 днів");

  // 🔴 НАЗВА ПОКАЗНИКА ВИЖИЛА. Без цієї половини гейт зеленів би на підписі, що
  // складається з самих застережень, — тобто на колонці, яку неможливо впізнати.
  const назва = m.label.split("(")[0].trim();
  assert.ok(назва.length >= 8,
    `🔴 від назви показника лишилось «${назва}» — застереження зʼїли те, що підписують`);
  assert.ok(m.label.length <= 60,
    `🔴 підпис ${m.label.length} символів: заголовок колонки такої довжини розсуває таблицю, `
    + "і застереження перестають читатись разом із числом. Довге пояснення живе в note (title)");

  // 🪞 І дзеркало: обидві мітки стоять РІВНО на цій колонці серед метрик продажів —
  // мітка, що розповзлась, перестає щось означати саме тому, що стоїть скрізь.
  const продажі = CATALOG.find((d) => d.key === "sales")?.metrics ?? [];
  assert.ok(продажі.length > 0, "🔴 відділу «продажі» немає — гейт втратив предмет");
  assert.deepEqual(продажі.filter((x) => ОЗНАЧЕННЯ.test(x.label)).map((x) => x.key), ["machines_dispatched"],
    "🔴 мітку «означення з …» несе не рівно та колонка, чиє означення справді змінилось");
});

test("#26i «ВІДПРАВЛЕНО» РАХУЄ ЯДРО — джоба не має власного предиката", async () => {
  /**
   * 🔴 DoD п.1 у своєму вигляді для цієї метрики. Свій SQL по якорю всередині джоби
   * розійдеться з ядром через місяці й нікому про це не скаже — рівно так і виник
   * дефект, який ми лагодимо: `machines_dispatched` писався як `Number(r.succ)`,
   * тобто мав ВЛАСНЕ означення, і воно було чуже колонці.
   */
  const fs = await import("node:fs/promises");
  const url = await import("node:url");
  const job = await fs.readFile(
    url.fileURLToPath(new URL("../../src/jobs/recomputeStatistics.ts", import.meta.url)), "utf8");
  const { DISPATCH_ANCHOR } = await import("../core/dispatched.js");

  assert.match(job, /dispatchedWhere\(/,
    "🔴 джоба не кличе предикат ядра — означення «відправлено» знову живе у двох місцях");
  assert.doesNotMatch(job, new RegExp(DISPATCH_ANCHOR),
    `🔴 у джобі зʼявився власний SQL по «${DISPATCH_ANCHOR}» — умову «поїхала» тепер задають двоє, `
    + "і розійдуться вони мовчки");
  /**
   * 🔴 ПЕРША РЕДАКЦІЯ ЛОВИЛА ЛІТЕРАЛ `Number(r.succ)` І БУЛА БЕЗЗУБА — знайдено
   * власним саботажем 02.09.2026: підміна, дописана як `Number(r.succ ?? r.n)`,
   * пройшла повз, і гейт лишився зеленим. Той самий клас, що `#26e` («предикат по
   * механізму, а не по прозі»), тільки навпаки: там прозу читали як механізм, тут
   * механізм звузили до одного написання.
   *
   * Тепер твердження про САМ ЗАПИС: він рівно один, і в ньому не згадується число
   * успішних у жодному вигляді. Будь-яке повернення підміни змінює цей рядок.
   */
  const записи = job.split("\n").filter((l) => l.includes('"machines_dispatched"'));
  assert.equal(записи.length, 1,
    `🔴 у колонку пишуть ${записи.length} місць — означення знову існує в кількох, і розійдуться `
    + "вони мовчки:\n   " + записи.join("\n   "));
  assert.doesNotMatch(записи[0], /succ/,
    `🔴 у запис колонки повернулось число УСПІШНИХ: «${записи[0].trim()}». Це рівно ті угоди, `
    + "у кого оплата ЗАЙШЛА, тобто ті, кого означення «відправлено» виключає");
});
