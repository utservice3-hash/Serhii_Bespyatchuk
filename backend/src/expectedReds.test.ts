import test from "node:test";
import assert from "node:assert/strict";
import { acceptExpectedReds, type ExpectedRed } from "./expectedReds.js";

/**
 * 🛑 #315/#315b — «ЗЕЛЕНЕ ПРИЙМАННЯ» СТАЄ МАШИННИМ ВИРОКОМ.
 *
 * 📐 ПРИВІД, ЗАМІРЯНИЙ 02.09.2026 за журналом замка. `lockRelease` УЖЕ стоїть кроком
 * одразу за `accept` — ланцюг умів віддавати замок сам. Не віддавав тому, що `accept`
 * червонів на падіннях, які ми називали очікуваними ВГОЛОС У ЧАТІ, а вголос ланцюг не
 * чує. Ціна: мій холд 24 хв при роботі ~20 хв, чужий — 184 хв із перехопленням по TTL.
 *
 * 🔴 ЧОМУ ДЗЕРКАЛО ТУТ ОБОВʼЯЗКОВЕ, А НЕ БАЖАНЕ. Односторонній критерій («падіння з
 * реєстру не рахуємо») — це ВИМИКАЧ, а не критерій: мертвий запис тихо проковтне
 * наступне СПРАВЖНЄ падіння того самого імені. Тому запис на гейт, який ПРОЙШОВ, сам
 * є дефектом. Той самий устрій, що в `acceptRetired`, і не випадково.
 */

const R = (over: Partial<ExpectedRed> = {}): ExpectedRed => ({
  name: "#124 G3 Σ 1С == Σ БАЗИ, Δ0 (і РЯДКИ, і сума)",
  since: "2026-09-02",
  reason: "розбіжність 1С проти бази, борг чужого проходу",
  decidedBy: "Основний",
  ...over,
});

test("#315 падіння, назване в реєстрі поіменно, дає ЗЕЛЕНИЙ вирок", () => {
  const reg = [R(), R({ name: "#125 G3b ЖИВІ НОТАТКИ НЕ ВТРАТИЛИ ПАРИ" })];
  const v = acceptExpectedReds(
    ["#124 G3 Σ 1С == Σ БАЗИ, Δ0 (і РЯДКИ, і сума)", "#125 G3b ЖИВІ НОТАТКИ НЕ ВТРАТИЛИ ПАРИ"],
    [], reg);
  assert.equal(v.ok, true, "🔴 обидва падіння в реєстрі, а вирок червоний — замок знову триматиме людина");
  assert.deepEqual(v.uncovered, []);
  assert.deepEqual(v.registryProblems, []);

  // 🔴 НОВЕ ІМʼЯ ЛИШАЄ ВИРОК ЧЕРВОНИМ і називає себе — інакше воно розчиниться в числі.
  const v2 = acceptExpectedReds(
    ["#124 G3 Σ 1С == Σ БАЗИ, Δ0 (і РЯДКИ, і сума)", "#999 щось геть нове"], [], reg);
  assert.equal(v2.ok, false, "🔴 незнайоме падіння прийнято за очікуване — це і є глушник");
  assert.deepEqual(v2.uncovered, ["#999 щось геть нове"]);
  assert.ok(v2.lines.join("\n").includes("#999 щось геть нове"),
    "🔴 нове імʼя не названо у звіті — його шукатимуть очима в лозі");

  // 🔴 ЗБІГ ЛИШЕ ЗА ПОВНИМ ІМЕНЕМ. Маска накрила б сусіда, якого ніхто не розглядав.
  const v3 = acceptExpectedReds(["#124"], [], reg);
  assert.equal(v3.ok, false, "🔴 префікс «#124» зарахований як повне імʼя — реєстр став маскою");
});

test("#315b 🪞 ДЗЕРКАЛО: реєстр не сміє ковтати те, що пройшло, і мовчати без причини", () => {
  // 🔴 ГЛУШНИК. Запис живий, а тест цього прогону ПРОЙШОВ — виняток висить на
  // здоровому гейті й проковтне наступне справжнє падіння того самого імені.
  const glushnyk = acceptExpectedReds([], ["#124 G3 Σ 1С == Σ БАЗИ, Δ0 (і РЯДКИ, і сума)"], [R()]);
  assert.equal(glushnyk.ok, false,
    "🔴 запис на ЗЕЛЕНИЙ гейт визнано порядком — ми зробили собі вимикач замість критерію");
  assert.match(glushnyk.registryProblems.join("\n"), /глушник/,
    "🔴 дефект реєстру не названо словом — його не відрізнять від звичайного падіння");

  // Дефекти самого запису: кожен окремо, бо спільна перевірка пропустила б один.
  for (const [field, over] of [
    ["ПРИЧИНА", { reason: "  " }], ["ДАТА", { since: "" }], ["АВТОР", { decidedBy: "" }],
  ] as const) {
    const v = acceptExpectedReds(["#124 G3 Σ 1С == Σ БАЗИ, Δ0 (і РЯДКИ, і сума)"], [], [R(over)]);
    assert.equal(v.ok, false, `🔴 запис без поля ${field} прийнято — виняток, якого ніхто не ухвалював`);
    // І таке падіння НЕ вважається покритим: дефектний запис нічого не накриває.
    assert.deepEqual(v.uncovered, ["#124 G3 Σ 1С == Σ БАЗИ, Δ0 (і РЯДКИ, і сума)"],
      `🔴 дефектний запис (${field}) усе одно накрив падіння`);
  }

  // 🔴 ПОРОЖНІЙ РЕЄСТР — НЕ ІНДУЛЬГЕНЦІЯ. Жодне падіння без запису не проходить.
  assert.equal(acceptExpectedReds(["#124 G3 Σ 1С == Σ БАЗИ, Δ0 (і РЯДКИ, і сума)"], [], []).ok, false,
    "🔴 при порожньому реєстрі падіння визнано очікуваним — критерій вимкнено цілком");

  // Дзеркало свіжості: прогін БЕЗ падінь зелений і тоді, коли реєстр не порожній.
  assert.equal(acceptExpectedReds([], [], [R()]).ok, true,
    "🔴 чистий прогін визнано червоним — тоді замок не віддавався б ніколи");
});
