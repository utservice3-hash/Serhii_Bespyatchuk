/**
 * 🔢 НОМЕР ГЕЙТА — ЦЕ АДРЕСА. ДВА ГЕЙТИ НА ОДНІЙ АДРЕСІ = ЗЛАМАНА ДІАГНОСТИКА.
 *
 * 🔴 ПРИВІД: за одну добу 25.08.2026 сталося ШІСТЬ зіткнень номерів між чатами.
 * Блок `#180`-`#199` виявився зайнятий 20 із 20, а `#200`-`#203` мали ТРЕТЬОГО
 * власника, якого не бачив ніхто. Руками це більше не тримається.
 *
 * ЧОМУ ЦЕ НЕ КОСМЕТИКА: у виводі падіння тест називається НОМЕРОМ. Коли номер
 * має двох власників, «впав #30c» перестає вказувати на щось конкретне — і на
 * цьому вже втрачали прохід (записано в CLAUDE.md).
 *
 * ⚠️ ТОКЕН ЧИТАЄТЬСЯ ДО ПЕРШОГО ПРОБІЛУ, і це не дрібниця. Наївне `#\d+[a-z]*`
 * ріже `#5.1` до `#5`, а `#99b2` до `#99b` — і дає 16 ФАЛЬШИВИХ зіткнень проти
 * 10 справжніх. Гейт на такій токенізації червонів би з першого дня, тобто його
 * б вимкнули. Саме тому тут `\S+`.
 */
export function collidingNumbers(names: readonly string[]): Map<string, string[]> {
  const byToken = new Map<string, string[]>();
  for (const n of names) {
    const m = /^(#\S+)\s/.exec(n);
    if (!m) continue;
    const list = byToken.get(m[1]) ?? [];
    list.push(n);
    byToken.set(m[1], list);
  }
  return new Map([...byToken].filter(([, v]) => v.length > 1));
}

