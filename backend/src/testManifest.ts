export interface RetireVerdict {
  /** Зникнення, ЯКИХ РЕЄСТР НЕ ПОКРИВАЄ. Непорожньо — ланцюг стоїть. */
  unaccounted: string[];
  /** Дефекти САМОГО реєстру. Непорожньо — ланцюг стоїть, і це не те саме, що зверху. */
  problems: string[];
  /** Прийняті поіменно — щоб звіт називав, ЩО саме дозволено, а не «все гаразд». */
  accepted: string[];
}

/**
 * Розбирає зниклі гейти на «дозволено поіменно» й «ні», і окремо перевіряє сам реєстр.
 *
 * `alive` — імена гейтів, що Є в дереві ЗАРАЗ. Саме проти них ловиться найгірший
 * стан: запис, який оголошує знятим гейт, що досі живий.
 */
export function acceptRetired(
  lost: readonly string[], alive: readonly string[], registry: readonly RetiredGate[] = RETIRED_GATES,
): RetireVerdict {
  const problems: string[] = [];
  const liveNames = new Set(gateNames(alive));
  const allowed = new Set<string>();
  for (const r of registry) {
    if (!r.reason.trim()) {
      problems.push(`🔴 запис «${r.name}» без ПРИЧИНИ — реєстр без причини не відповідає на єдине питання, заради якого існує`);
      continue;
    }
    if (!r.since.trim()) {
      problems.push(`🔴 запис «${r.name}» без ДАТИ — без неї не видно, що борг протух`);
      continue;
    }
    if (liveNames.has(r.name)) {
      problems.push(`🔴 «${r.name}» оголошено знятим, але гейт ЖИВИЙ і зараз у дереві — `
        + "реєстр став би ковдрою: під цим записом наступне СПРАВЖНЄ зникнення пройшло б мовчки");
      continue;
    }
    allowed.add(r.name);
  }
  return {
    unaccounted: lost.filter((n) => !allowed.has(n)),
    problems,
    accepted: lost.filter((n) => allowed.has(n)),
  };
}

export function diffGates(before: readonly string[], after: readonly string[]): {
  onlyBefore: string[]; onlyAfter: string[]; countBefore: number; countAfter: number;
} {
  const a = new Set(gateNames(before)), b = new Set(gateNames(after));
  return {
    onlyBefore: [...a].filter((n) => !b.has(n)),
    onlyAfter: [...b].filter((n) => !a.has(n)),
    countBefore: a.size, countAfter: b.size,
  };
}
