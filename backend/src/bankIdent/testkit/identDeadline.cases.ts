// Тести пакета `tests/identDeadline.test.ts` ДОСЛІВНО; змінено лише імпорти (прокладка vitest → node:test).
import { describe, expect, it } from '../../cargo/testkit/shim.js';
import { HOUR, identDeadline, isWorkday, kyiv, kyivParts, parseHolidays, startOf, workBetween } from '../identDeadline.js';

const K = (y: number, m: number, d: number, hh = 0, mm = 0) => kyiv(y, m, d, hh, mm);
const show = (ms: number) => { const p = kyivParts(ms); return `${['нд', 'пн', 'вт', 'ср', 'чт', 'пт', 'сб'][p.wd]} ${p.d}.${p.m} ${String(p.hh).padStart(2, '0')}:${String(p.mm).padStart(2, '0')}`; };

describe('строк 48 год без суботи й неділі (Київ)', () => {
  // жовтень 2026: 22 — чт, 23 — пт, 24 — сб, 25 — нд (перехід на зимовий час), 26 — пн, 27 — вт
  it.each([
    ['пт 15:00 → вт 15:00 (слова Сергія: «пʼятниця прихід — вихідні пропускаються по часу»)', K(2026, 10, 23, 15), K(2026, 10, 27, 15)],
    ['пт 10:05 → вт 10:05', K(2026, 10, 23, 10, 5), K(2026, 10, 27, 10, 5)],
    ['сб 11:20 → відлік з пн → кінець вт (ср 00:00)', K(2026, 10, 24, 11, 20), K(2026, 10, 28)],
    ['нд 16:40 → кінець вт', K(2026, 10, 25, 16, 40), K(2026, 10, 28)],
    ['чт 17:30 → пн 17:30', K(2026, 10, 22, 17, 30), K(2026, 10, 26, 17, 30)],
    ['чт 00:00 → кінець пт', K(2026, 10, 22), K(2026, 10, 24)],
    ['пн 09:00 → ср 09:00', K(2026, 10, 26, 9), K(2026, 10, 28, 9)],
    ['ср 23:59 → пт 23:59', K(2026, 10, 28, 23, 59), K(2026, 10, 30, 23, 59)],
    ['пт 23:30 → вт 23:30', K(2026, 10, 23, 23, 30), K(2026, 10, 27, 23, 30)],
    ['літній час: пт 27.03 15:00 → вт 31.03 15:00', K(2026, 3, 27, 15), K(2026, 3, 31, 15)],
    ['літній час: сб 28.03 → кінець вт 31.03', K(2026, 3, 28, 12), K(2026, 4, 1)],
    ['новий рік: ср 30.12 10:00 → пт 01.01 10:00 (свят немає)', K(2026, 12, 30, 10), K(2027, 1, 1, 10)],
  ])('%s', (_n, start, want) => {
    expect(show(identDeadline(start))).toBe(show(want));
    expect(identDeadline(start)).toBe(want);
  });

  it('відлік — від пізнішого: банк пт 15:00, у виписці сб 09:00 → кінець вт', () => {
    expect(identDeadline(K(2026, 10, 23, 15), K(2026, 10, 24, 9))).toBe(K(2026, 10, 28));
    expect(startOf(K(2026, 10, 26, 9), K(2026, 10, 26, 9, 10))).toBe(K(2026, 10, 26, 9, 10));
    expect(startOf(K(2026, 10, 26, 9), null)).toBe(K(2026, 10, 26, 9));
  });

  it('свята пропускаються (на випадок, якщо зʼявляться)', () => {
    expect(identDeadline(K(2026, 10, 23, 15), null, { holidays: parseHolidays('2026-10-26') })).toBe(K(2026, 10, 28, 15));
    expect(isWorkday(K(2026, 10, 26, 12), new Set(['2026-10-26']))).toBe(false);
  });

  it('інший строк у годинах', () => {
    expect(identDeadline(K(2026, 10, 23, 15), null, { hours: 24 })).toBe(K(2026, 10, 26, 15));
  });

  it('робочий час між моментами', () => {
    expect(workBetween(K(2026, 10, 27, 13, 30), K(2026, 10, 27, 15)) / HOUR).toBe(1.5);
    expect(workBetween(K(2026, 10, 24, 12), K(2026, 10, 27, 15)) / HOUR).toBe(39);
    expect(workBetween(K(2026, 10, 25, 1), K(2026, 10, 25, 23)) / HOUR).toBe(0);
    expect(workBetween(K(2026, 10, 27, 15), K(2026, 10, 27, 13))).toBe(0);
  });

  it('500 випадкових моментів: між початком і строком рівно 48 робочих год, строк — у будній день або рівно опівночі після нього', () => {
    let seed = 7;
    const rnd = () => (seed = (seed * 16807) % 2147483647) / 2147483647;
    for (let i = 0; i < 500; i++) {
      const s = K(2026, 1, 1) + Math.floor(rnd() * 360 * 24 * 60) * 60_000;
      const d = identDeadline(s);
      expect(workBetween(startOf(s), d)).toBe(48 * HOUR);
      expect(isWorkday(d - 1)).toBe(true);
    }
  });

  it('свята: некоректна дата — помилка, а не мовчання', () => {
    expect(() => parseHolidays('01.01.2027')).toThrow(/РРРР-ММ-ДД/);
    expect([...parseHolidays(' 2027-01-01, 2027-05-01 ;')]).toEqual(['2027-01-01', '2027-05-01']);
  });
});
