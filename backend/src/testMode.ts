import { EMPTY_PERIOD_MARK } from "./testRunGate.js";
import { kyivToday, kyivMonthBounds, withinPlanGrace } from "./core/dates.js";
/**
 * РЕЖИМИ ОДНОГО НАБОРУ ТЕСТІВ. Точка входу одна — `npm test` (`node --test dist/`).
 * Різні перевірки вимагають різного оточення, і це вирішується РЕЖИМОМ, а не другим
 * паралельним механізмом: дві культури тестів через місяць розходяться, і в підсумку
 * ніхто не знає, що саме зелене.
 *
 *   npm test        — усе, що можна без зовнішніх залежностей + БД, якщо є DATABASE_URL
 *   npm run test:prod — додає перевірки проти ЖИВОГО API (приймання після деплою)
 *   npm run test:ai   — додає гейти, що звертаються до моделі (коштують грошей)
 *
 * Тест, якому оточення не вистачає, ПРОПУСКАЄТЬСЯ з видимою причиною, а не падає і не
 * робить вигляд, що пройшов. `node --test` показує skip окремо від pass — саме тому
 * тут `{ skip: "..." }`, а не мовчазний `return`.
 */

export const HAS_DB = Boolean(process.env.DATABASE_URL);
/** `prod` вмикає перевірки проти живого HTTP-API. */
export const SCOPE = process.env.TEST_SCOPE ?? "local";
export const IS_PROD_SCOPE = SCOPE === "prod";
/** Гейти з викликами моделі — платні, тому лише за явним прапорцем. */
export const AI_ENABLED = process.env.TEST_AI === "1";
export const API_BASE = process.env.API_BASE ?? "http://127.0.0.1:3000";

type Opts = { skip?: string };

/** Потрібна БД. */
export const needsDb = (): Opts =>
  HAS_DB ? {} : { skip: "потрібен DATABASE_URL (npm test без БД пропускає)" };

/**
 * Потрібне ОТОЧЕННЯ БЕКЕНДА, а не лише БД.
 *
 * 🔴 НАВІЩО ОКРЕМО ВІД `needsDb`. Гейт, що кличе обробник роуту в процесі,
 * імпортує `routes/dashboard.js` → `config.js`, а той кидає `Missing required
 * env var: JWT_SECRET` ЩЕ НА ІМПОРТІ. `DATABASE_URL` у контейнері є (роль
 * `kk_ro`), а `JWT_SECRET` — ні, тож `needsDb()` пропускає такий гейт до
 * виконання, і той падає не на дефекті, а на оточенні.
 *
 * ⚠️ Наявні `#150c`/`#157`/`#158` живуть саме так — вони в числі відомих падінь
 * контейнера. Переводити ЇХ на цей гейт означало б змінити базу порівняння
 * падінь у чужому проході; тому guard додано, а старих не чіпано. Нові гейти
 * до цієї родини не дописуються.
 */
export const needsBackendEnv = (): Opts =>
  !HAS_DB ? { skip: "потрібен DATABASE_URL" }
    : process.env.JWT_SECRET ? {}
      : { skip: "потрібен JWT_SECRET: гейт кличе обробник роуту, а `config` кидає ще на імпорті" };

/** Потрібне живе API: `TEST_SCOPE=prod` + доступний API_BASE. */
export const needsApi = (): Opts =>
  IS_PROD_SCOPE
    ? (HAS_DB ? {} : { skip: "потрібен DATABASE_URL" })
    : { skip: "лише в режимі TEST_SCOPE=prod (npm run test:prod)" };

/**
 * Повний зліпок доступу (#11): 177 роутів × ролі ≈ 1024 проби, ~7-8 хв.
 * ⏱ Тому окремий режим: `npm test` і `npm run test:prod` його ПРОПУСКАЮТЬ,
 * `npm run test:matrix` — вмикає. Це не «зазвичай ганяємо шматок», а названий поділ:
 * швидкий набір на кожен деплой, повна матриця — перед злиттям у прод-гілку.
 */
export const MATRIX_ENABLED = process.env.TEST_MATRIX === "1";
export const needsMatrix = (): Opts =>
  MATRIX_ENABLED
    ? (IS_PROD_SCOPE && HAS_DB ? {} : { skip: "потрібні TEST_SCOPE=prod + DATABASE_URL" })
    : { skip: "повний зліпок доступу — окремий режим (npm run test:matrix)" };

/**
 * Живе API, але БЕЗ матричного режиму — для гейтів, що міряють ЧАС.
 *
 * 🔴 ЧОМУ ЦЕ НЕ ПОСЛАБЛЕННЯ. `#11` заливає сервер 1024 пробами; будь-який замір
 * часу, зроблений одночасно з цим, міряє ЗАЛИВКУ, а не ендпоінт. Заміряно того
 * самого дня на тому самому коді: чисто 2 432-3 355 мс, у `test:prod` 4 438 мс
 * (полагоджено «найкращим із трьох»), у `test:matrix` — 11 058 мс. Проти
 * останнього «найкращий із трьох» безсилий: повільні ВСІ три.
 *
 * Тому поділ дзеркальний до `#11`: матриця обовʼязкова в `test:matrix` і
 * пропускається в `test:prod`; часовий гейт — навпаки. Кожен режим має рівно ті
 * гейти, які в ньому здатні щось виміряти. Поріг не змінюється в жодному з них.
 *
 * ⚠️ Це НЕ «вимкнути незручний тест»: у `test:prod` він обовʼязковий, і саме
 * `test:prod` ганяється на КОЖЕН деплой.
 */
export const needsApiQuiet = (): Opts =>
  MATRIX_ENABLED
    ? { skip: "гейт ЧАСУ не можна міряти під заливкою #11 (1024 проби) — режим test:prod" }
    : needsApi();

/**
 * Потрібна БД **З ПРАВОМ ЗАПИСУ** — для саботаж-гейтів, що ламають стан у
 * транзакції з `ROLLBACK`.
 *
 * 🔴 ЧОМУ ОКРЕМИЙ РЕЖИМ, А НЕ `needsDb()`. `test:prod` ходить у бойову базу під
 * роллю `test_readonly` (`--import ./dist/testReadOnly.js`), і будь-який `UPDATE`
 * там падає з `permission denied for table …` — навіть усередині транзакції, бо
 * права перевіряються ДО, а не при коміті. Я на цьому спіймався 06.08.2026:
 * чотири нових саботаж-гейти (`#48e`, `#50c`, `#51c`, `#52`) червоніли на проді,
 * і це виглядало як регрес продукту, хоча ламався сам харнес.
 *
 * ⚠️ Це НЕ послаблення. Гейт лишається обовʼязковим у `npm test` (де база своя і
 * запис дозволений); у прод-режимі він СВІДОМО пропускається з названою причиною,
 * бо перевіряти запис у бойовій базі ми й не збираємось — саме цього забороняє
 * правило «тести проти прода ходять тільки read-only».
 */
export const needsDbWritable = (): Opts =>
  IS_PROD_SCOPE
    ? { skip: "саботаж потребує ЗАПИСУ; проти прода набір ходить лише read-only (роль test_readonly)" }
    : needsDb();

/** Потрібні платні виклики моделі. */
export const needsAi = (): Opts =>
  AI_ENABLED
    ? (process.env.ANTHROPIC_API_KEY ? {} : { skip: "немає ANTHROPIC_API_KEY" })
    : { skip: "платний гейт — вмикається TEST_AI=1 (npm run test:ai)" };

/**
 * 🈳 ГУЧНИЙ СКІП ЗАМІСТЬ ПАДІННЯ НА ПОРОЖНЬОМУ ПЕРІОДІ.
 *
 * 🔴 ЩО САМЕ ЛІКУЄМО. Гейт, який перевіряє ВЛАСТИВІСТЬ живих даних, на порожньому
 * періоді не має що перевіряти — і падав. Заміряно 01.09.2026: одинадцять таких
 * падінь із сімнадцяти, тобто на кожній межі місяця приймання блокує викати всім.
 * Але просто «пропустити» не можна: скіп, що ковтає СПРАВЖНІЙ дефект, гірший за
 * падіння. Тому дозвіл двоскладовий (імʼя в `EMPTY_PERIOD_SKIPS` + цей маркер), а
 * причина зобовʼязана НАЗВАТИ предмет і число.
 *
 * ⚠️ Кличеться ЛИШЕ там, де нуль — законний стан світу (початок місяця, ще не
 * заведені плани). Якщо нуль означає поломку — це падіння, і його не маскують.
 *
 * Повертає причину для `t.skip(...)`, або `null`, якщо дані є і гейт мусить бігти.
 */
export function emptyPeriodSkip(subject: string, count: number, ctx: string): string | null {
  if (count > 0) return null;
  return `${EMPTY_PERIOD_MARK} у періоді немає даних: ${subject} = 0 (${ctx}). `
    + "Це законна ВІДСУТНІСТЬ, а не «перевірено». Щойно дані зʼявляться, гейт побіжить сам.";
}

/**
 * 🗓 ПОРОЖНЬО, БО ПЛАНІВ ЩЕ НЕ ЗАВЕЛИ — СКІП ЛИШЕ В ПЕРШІ ДВА РОБОЧІ ДНІ.
 *
 * 🔴 ДОМЕННИЙ ФАКТ ВЛАСНИКА, дослівно: «плани у нас виставляються на протязі 2х
 * днів, це норма». Звідси випливає межа, якої немає в інших порожніх періодах:
 * після вікна нуль планів — це вже не норма, а **аварія «плани забули завести»**,
 * і глухий скіп сховав би саме її. Різниця тут не в даних, а в ДАТІ.
 *
 * `null` означає «не скіпаємо» — і тоді гейт біжить далі й падає власним вироком.
 */
export function planGraceSkip(subject: string, count: number, today: string = kyivToday()): string | null {
  if (count > 0) return null;
  if (!withinPlanGrace(today)) return null;   // вікно минуло → це справжнє червоне
  const { ym } = kyivMonthBounds(today);
  return `${EMPTY_PERIOD_MARK} ${subject} = 0, і сьогодні ${today} — у вікні заведення планів `
    + `на ${ym} (перші 2 робочі дні, норма за рішенням власника). `
    + "ПІСЛЯ вікна той самий нуль буде ПАДІННЯМ, а не скіпом.";
}

/**
 * 📉 ВИБІРКА ЗАМАЛА ДЛЯ ПЕРЕВІРКИ — теж законний стан світу, а не дефект.
 *
 * 🔴 РІШЕННЯ ВЛАСНИКА, дослівно: **«може бути і 2 ліди, це не проблема»**. Отже гейт,
 * який вимагав ≥20, падав на НОРМАЛЬНОМУ стані — і за нашою ж доктриною це гучний
 * скіп, а не червоне.
 *
 * ⚠️ ЩО САМЕ ОЗНАЧАЄ ПОРІГ, І ЦЕ МУСИТЬ БУТИ В ТЕКСТІ, А НЕ В ПАМʼЯТІ. `need` — це
 * межа **придатності ПЕРЕВІРКИ**, а не вимога до менеджера: на двох лідах частка
 * `slow/n` збігається з контролем ВИПАДКОВО, тож зелене нічого не доводило б. Через
 * півроку цей рядок читатимуть без нас — і не має прочитати його як план продажів.
 *
 * 🪞 МЕЖА: скіп лише коли вибірки НЕ ВИСТАЧАЄ. Щойно її досить — `null`, гейт біжить
 * і падає на порушенні. Скіп, що ковтає справжній дефект, гірший за падіння.
 */
export function smallSampleSkip(subject: string, best: number, need: number, ctx: string): string | null {
  if (best >= need) return null;
  return `${EMPTY_PERIOD_MARK} вибірка замала для ПЕРЕВІРКИ: ${subject} = ${best}, а щоб `
    + `перевірка щось доводила, треба ${need} (${ctx}). Це межа придатності ГЕЙТА, а НЕ вимога `
    + "до менеджера: власник прямо сказав, що і два ліди — нормально. "
    + "Щойно вибірки вистачить, гейт побіжить сам.";
}
